#!/usr/bin/env python3
"""Generate tests/helpers/include/matmul_pack_tables.h from llk_pack_block of the metal API (tt_metal/hw/ckernels/blackhole/metal/llk_api/llk_pack_tile_api.h):
the form tables, the matmul masks, llk_pack_block_class and llk_pack_block_form as constexpr functions of plain values instead of an output id.
usage: gen_matmul_pack_tables.py [--write]   (without --write: exit 1 when the committed header differs from the generated one)"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
API = HERE.parents[2] / "hw/ckernels/blackhole/metal/llk_api/llk_pack_tile_api.h"
OUT = HERE.parent / "helpers/include/matmul_pack_tables.h"


def _func(src, head):
    a = src.index(head)
    depth = 0
    i = src.index("{", a)
    for j in range(i, len(src)):
        depth += src[j] == "{"
        depth -= src[j] == "}"
        if depth == 0:
            return src[a : j + 1]
    raise SystemExit("unterminated " + head)


def _sub(text, old, new, count=None):
    n = text.count(old)
    if n == 0 or (count is not None and n != count):
        raise SystemExit(f"generator out of date: {old!r} found {n} times")
    return text.replace(old, new)


def generate():
    s = API.read_text()
    a = s.index("constexpr char llk_pack_init_form[")
    t = s.index("constexpr std::uint64_t llk_pack_mm_take_w")
    tables = s[a : s.index("\n};\n", t) + 4]
    cls = _func(s, "inline std::uint32_t llk_pack_block_class(")
    cls = _sub(cls, "inline std::uint32_t llk_pack_block_class(const std::uint32_t output_id)", "constexpr std::uint32_t llk_pack_block_class_k(const std::uint32_t rows, const std::uint32_t faces, const bool bfpa, const bool bfp, const bool bfp8, const bool wide)", 1)
    cls = _sub(cls, "    const std::uint32_t rows = get_output_face_r_dim(output_id);\n", "", 1)
    for old, new in (("get_output_num_faces(output_id)", "faces"), ("llk_pack_dst_is_bfpa(output_id)", "bfpa"), ("llk_pack_dst_is_bfp8(output_id)", "bfp8"), ("llk_pack_dst_is_bfp(output_id)", "bfp"), ("llk_pack_dst_is_wide(output_id)", "wide")):
        cls = _sub(cls, old, new)
    form = _func(s, "inline char llk_pack_block_form(")
    head = "inline char llk_pack_block_form(const std::uint32_t output_id, const std::uint32_t ntiles, const char (*table)[4][17], const bool next)"
    form = _sub(form, head, "constexpr char llk_pack_block_form_k(const std::uint32_t row, const std::uint32_t ntiles, const char (*table)[4][17], const bool next, const bool sync_full, const bool src32, const bool int8)", 1)
    form = _sub(form, "    const std::uint32_t row = llk_pack_block_class(output_id);\n", "", 1)
    form = _sub(form, "DST_SYNC_MODE == DstSync::SyncFull", "sync_full", 1)
    form = _sub(form, "llk_pack_dst_is_int8(output_id)", "int8", 1)
    form = _sub(form, "constexpr std::uint32_t family = llk_pack_src32_family<is_fp32_dest_acc_en> ? 1 : 0;", "const std::uint32_t family = (is_fp32_dest_acc_en && src32) ? 1 : 0;", 1)
    assert "output_id" not in form and "output_id" not in cls
    return (
        "// SPDX-FileCopyrightText: © 2026 Tenstorrent AI ULC\n// SPDX-License-Identifier: Apache-2.0\n#pragma once\n\n"
        "// GENERATED by tests/python_tests/gen_matmul_pack_tables.py from llk_pack_tile_api.h; do not edit. hardware_free/kernels/test_matmul_pack_tables.py fails when it differs.\n\n"
        "#include <cstdint>\n#include \"llk_defs.h\"\n\nnamespace matmul_pack_tables\n{\nusing namespace ckernel;\n\n"
        + tables + "\n"
        + "template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>\n" + form + "\n\n"
        + cls + "\n} // namespace matmul_pack_tables\n"
    )


if __name__ == "__main__":
    text = generate()
    if "--write" in sys.argv:
        OUT.write_text(text)
        print("wrote", OUT)
    elif not OUT.exists() or OUT.read_text() != text:
        print("matmul_pack_tables.h differs from llk_pack_tile_api.h: run gen_matmul_pack_tables.py --write")
        sys.exit(1)
    else:
        print("matmul_pack_tables.h matches llk_pack_tile_api.h")

def perf_gate_selection(params, key, family, ident) -> frozenset:
    """ident(p) of every production block (key(p)) and of the first p of each family that has none."""
    params = list(params)
    covered = {family(p) for p in params if key(p)}
    keep = set()
    for p in params:
        f = family(p)
        if key(p) or f not in covered:
            covered.add(f)
            keep.add(ident(p))
    return frozenset(keep)



def main():
    bad = 0
    for x, y, z, want in VECTORS:
        got = fma_model_bh(Concrete, x, y, z)
        if got != want:
            print("FAIL fma(%08x,%08x,%08x) got %08x want %08x" % (x, y, z, got, want))
            bad += 1
    assert not bad, "%d fma golden mismatches" % bad
    print("fma concrete: %d/%d golden vectors OK" % (len(VECTORS), len(VECTORS)))

    import z3

    xs, ys, zs = z3.BitVecs("x y z", 32)
    expr = fma_model_bh(Symbolic, xs, ys, zs)
    random.seed(3)
    for _ in range(25):
        cx, cy, cz = (random.getrandbits(32) for _ in range(3))
        ev = z3.simplify(
            z3.substitute(
                expr,
                (xs, z3.BitVecVal(cx, 32)),
                (ys, z3.BitVecVal(cy, 32)),
                (zs, z3.BitVecVal(cz, 32)),
            )
        ).as_long()
        assert ev == fma_model_bh(Concrete, cx, cy, cz)
    print("fma symbolic == concrete on 25 points OK")

    s = z3.BitVec("d_0_0_g0", 16)
    a = z3.ZeroExt(16, s) * z3.BitVecVal(3, 32)
    b = z3.ZeroExt(16, s) + (z3.ZeroExt(16, s) << 1)
    n, witness_x = exhaustive16(a, b, "d_0_0_g0")
    assert n == 0, witness_x
    c = z3.If(s == z3.BitVecVal(0x1234, 16), z3.ZeroExt(16, s) + 1, z3.ZeroExt(16, s))
    n, witness_x = exhaustive16(c, z3.ZeroExt(16, s), "d_0_0_g0")
    assert n == 1 and witness_x["inputs"]["d_0_0_g0"] == 0x1234, (n, witness_x)
    print("exhaustive16 compiler OK")
    print("SELFTEST PASS")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate visible_issue_table.h (included by issue.h): decode a Blackhole Tensix instruction word into its fields and issue it
through the compiler's per-instruction builtin.  Inputs: common/inc/ckernel_ops.h (encodings, field widths) and the
SFPI compiler's tensix_builtins.def (builtin names, arity, return type).

Usage: gen_visible_issue_table.py <tt_llk_blackhole/common/inc/ckernel_ops.h> <sfpi/include/tensix_builtins.def> <out.h>

Check after regenerating: every builtin must encode exactly like its TT_OP_* macro (compile each with field patterns,
all -mtt-tensix-* passes off, and compare the words), and CONSTRAINTS must list every field value a builtin rejects."""
import re, sys

ops_h, defs, out = sys.argv[1], sys.argv[2], sys.argv[3]
src = re.sub(r'\\\n', ' ', open(ops_h).read())
ops = {}
for m in re.finditer(r'#define TT_OP_(\w+)(?:\(([^)]*)\))?\s+TT_OP\(\s*(0x[0-9a-fA-F]+)\s*,\s*(.*)\)\s*$', src, re.M):
    name, params, opc, body = m.group(1), m.group(2), int(m.group(3), 16), m.group(4)
    params = [p.strip() for p in params.split(',')] if params else []
    shifts = []
    for p in params:
        mm = re.search(r'\(\(' + re.escape(p) + r'\)\s*<<\s*(\d+)\)', body)
        shifts.append(int(mm.group(1)))
    ops[name] = (opc, params, shifts)
widths = {}
for m in re.finditer(r'#define TT_(\w+)_VALID\(([^)]*)\)\s+(.*)$', src, re.M):
    widths[m.group(1)] = {k: int(v) for k, v in re.findall(r'is_valid\((\w+),\s*(\d+)\)', m.group(3))}
builtins = {}
for m in re.finditer(r'^(\w+)\s+__builtin_rvtt_(\w+)\s*\(([^)]*)\)', open(defs).read(), re.M):
    builtins.setdefault(m.group(2), (m.group(1), len([a for a in m.group(3).split(',') if a.strip()])))

norm = lambda s: re.sub(r'[^a-z0-9]', '', s.lower())
by_norm = {}
for k in builtins:
    by_norm.setdefault(norm(k), []).append(k)
# Instructions that stay opaque: REPLAY changes what the following instructions mean (record vs execute) and is issued
# through lltt where the compiler sees it; the rest have no per-instruction builtin.
EXCLUDE = {'REPLAY'}
# Field values the builtins reject (found by compiling each builtin with every single-bit value of every field, see
# the check above): {instruction: {field index: (forbidden bits, maximum value or None)}}. ThreadOverride
# bits are forbidden (the compiler rejects constant writes to another thread's counters); a word that sets them, or
# exceeds a maximum, stays opaque.
CONSTRAINTS_PROBED = {'SHIFTXA': {0: (0, 262143)}, 'SETIBRWC': {0: (0, 15)}, 'PACR': {7: (1, None)}, 'SETADC': {3: (196608, None)}, 'SETADCXY': {1: (24, None)}, 'INCADCXY': {1: (24, None)}, 'ADDRCRXY': {1: (24, None)}, 'SETADCZW': {1: (24, None)}, 'INCADCZW': {1: (24, None)}, 'ADDRCRZW': {1: (24, None)}, 'SETDVALID': {0: (0, 65535)}, 'ADDDMAREG': {1: (0, 63)}, 'SUBDMAREG': {1: (0, 63)}, 'MULDMAREG': {1: (0, 63)}, 'ATSWAP': {1: (0, 255)}, 'ATCAS': {1: (0, 15)}}
# UNPACR's OvrdThreadId is rejected only together with other fields; require it clear.
CONSTRAINTS = dict(CONSTRAINTS_PROBED)  # UNPACR OvrdThreadId: accepted by the builtin (checked 2026-11-19)
# Builtins that return void (no word to store in the instruction buffer).
VOID = {'rareb', 'trnspsrca'}
table = []
for name, (opc, params, shifts) in sorted(ops.items(), key=lambda kv: kv[1][0]):
    if name in EXCLUDE:
        continue
    cands = [c for pre in ('bh', '', 'tt') for c in by_norm.get(pre + norm(name), [])
             if builtins[c][1] == len(params) and builtins[c][0] in ('unsigned', 'void')]
    if len(cands) > 1:
        cands = [c for c in cands if builtins[c][0] == 'unsigned']
    if len(cands) != 1:
        continue
    w = widths.get(name, {})
    table.append((name, opc, params, shifts, [w[p] for p in params], cands[0], cands[0] in VOID))
opcodes = [t[1] for t in table]
assert len(opcodes) == len(set(opcodes)), 'two instructions share an opcode'

L = []
L.append('// SPDX-FileCopyrightText: © 2026 Tenstorrent AI ULC\n//\n// SPDX-License-Identifier: Apache-2.0\n')
L.append('// Generated by gen_visible_issue_table.py from common/inc/ckernel_ops.h and the SFPI compiler\'s')
L.append('// tensix_builtins.def. Do not edit; rerun the script.\n')
L.append('#pragma once\n\n#include <cstdint>\n\n#include "ckernel_ops.h"\n#include "llk_assert.h"\n\nextern volatile std::uint32_t __instrn_buffer[];\n')
L.append('namespace hal::detail::visible\n{\n')


def fields_of(shifts, ws, word='w'):
    return [f'({word} >> {s}) & 0x{(1 << wd) - 1:x}u' for s, wd in zip(shifts, ws)]


def constraints_of(name, names):
    conds = []
    for i, (forbid, mx) in sorted(CONSTRAINTS.get(name, {}).items()):
        if forbid:
            conds.append(f'({names[i]} & 0x{forbid:x}u) == 0')
        if mx is not None:
            conds.append(f'{names[i]} <= {mx}u')
    return conds


# Everything below works on scalars only (no aggregate of fields): a field struct passed through always_inline
# functions costs the compiler one memory load per field per switch case at every call site until the word becomes a
# constant, and the early optimisers then spend most of the build walking those loads.
L.append('/** @brief Opcode + 1 of a compile-time word when a builtin covers it and the word round-trips through its')
L.append(' *         instruction\'s fields (and meets the builtin\'s field constraints); 0 otherwise. Constant evaluation only. */')
L.append('inline constexpr std::uint32_t id_of(const std::uint32_t w)\n{\n    switch (w >> 24)\n    {')
for name, opc, params, shifts, ws, b, void in table:
    fn = [f'f{i}' for i in range(len(params))]
    re_enc = f'TT_OP_{name}(' + ', '.join(fn) + ')' if params else f'TT_OP_{name}'
    L.append(f'#if __has_builtin(__builtin_rvtt_{b})')
    L.append(f'        case 0x{opc:02x}: // {name}')
    L.append('        {')
    if params:
        L.append('            const std::uint32_t ' + ', '.join(f'{n} = {e}' for n, e in zip(fn, fields_of(shifts, ws))) + ';')
    conds = [f'static_cast<std::uint32_t>({re_enc}) == w'] + constraints_of(name, fn)
    L.append(f'            return ' + ' && '.join(conds) + f' ? 0x{opc + 1:x}u : 0u;')
    L.append('        }')
    L.append('#endif')
L.append('        default:\n            return 0u;\n    }\n}\n')
L.append('/** @brief Issue the instruction of id through its builtin: run(fields...) with the fields as operands, word<W>()')
L.append(' *         with the fields of the compile-time word W. */')
L.append('template <std::uint32_t Id>\nstruct Emit;\n')
for name, opc, params, shifts, ws, b, void in table:
    fn = [f'f{i}' for i in range(len(params))]
    L.append(f'#if __has_builtin(__builtin_rvtt_{b})')
    L.append(f'template <>\nstruct Emit<0x{opc + 1:x}u> // {name}\n{{')
    L.append('    static inline __attribute__((always_inline)) void run(' + ', '.join(f'const std::uint32_t {n}' for n in fn) + ')\n    {')
    L.append(f'        __builtin_rvtt_{b}({", ".join(fn)});' if void else f'        ::__instrn_buffer[0] = __builtin_rvtt_{b}({", ".join(fn)});')
    L.append('    }\n')
    L.append('    template <std::uint32_t W>\n    static inline __attribute__((always_inline)) void word()\n    {')
    L.append('        run(' + ', '.join(fields_of(shifts, ws, 'W')) + ');')
    L.append('    }\n};\n#endif\n')
L.append('/** @brief Issue w through the builtin of its instruction. Returns false, with nothing issued, when no builtin')
L.append(' *         covers it; the caller then issues the word opaquely.')
L.append(' *')
L.append(' * whole_word_constant: w folds to a constant. It is then issued through its builtin only when it round-trips')
L.append(' * through the instruction\'s fields and meets the builtin\'s field constraints. Otherwise only the opcode is')
L.append(' * known: the builtin gets run-time field operands, provided the constraints fold to true (a word the HAL encodes')
L.append(' * with TT_OP_* always round-trips; LLK_ASSERT checks it).')
L.append(' *')
L.append(' * @note Call only where w >> 24 folds to a constant, so that one case remains. */')
L.append('inline __attribute__((always_inline)) bool issue_word(const std::uint32_t w, const bool whole_word_constant)\n{\n    switch (w >> 24)\n    {')
for name, opc, params, shifts, ws, b, void in table:
    fn = [f'f{i}' for i in range(len(params))]
    re_enc = f'TT_OP_{name}(' + ', '.join(fn) + ')' if params else f'TT_OP_{name}'
    L.append(f'#if __has_builtin(__builtin_rvtt_{b})')
    L.append(f'        case 0x{opc:02x}: // {name}')
    L.append('        {')
    if params:
        L.append('            const std::uint32_t ' + ', '.join(f'{n} = {e}' for n, e in zip(fn, fields_of(shifts, ws))) + ';')
    L.append(f'            const bool exact = static_cast<std::uint32_t>({re_enc}) == w;')
    cons = constraints_of(name, fn)
    if cons:
        L.append('            const bool allowed = ' + ' && '.join(cons) + ';')
        L.append('            if (whole_word_constant ? (exact && allowed) : (__builtin_constant_p(allowed) && allowed))')
    else:
        L.append('            if (!whole_word_constant || exact)')
    L.append('            {')
    L.append('                LLK_ASSERT(exact, "run-time instruction word has bits outside its instruction\'s fields");')
    L.append(f'                Emit<0x{opc + 1:x}u>::run({", ".join(fn)});')
    L.append('                return true;')
    L.append('            }')
    L.append('            return false;')
    L.append('        }')
    L.append('#endif')
L.append('        default:\n            return false;\n    }\n}\n')
L.append('} // namespace hal::detail::visible')
open(out, 'w').write('\n'.join(L) + '\n')
print(f'{len(table)} instructions', file=sys.stderr)
print('opaque (no builtin):', sorted(set(ops) - {t[0] for t in table}), file=sys.stderr)

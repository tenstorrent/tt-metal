// One table cell's form, the Int8 rule aside; compile time only, into llk_pack_form_words.
template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>
constexpr char llk_pack_block_form_of(
    const std::uint32_t row, const std::uint32_t ntiles, const char (*table)[4][17], const std::uint32_t state, const std::uint32_t ctx)
{
    const std::uint32_t column     = (DST_SYNC_MODE == DstSync::SyncFull ? 2 : 0) + (is_fp32_dest_acc_en ? 1 : 0);
    const std::uint32_t count      = (ntiles < 16 ? ntiles : 16) - 1;
    const char form                = table[row][column][count];
    constexpr std::uint32_t family = llk_pack_src32_family<is_fp32_dest_acc_en> ? 1 : 0;
    // with the K given the caller vouches for matmul math
    constexpr std::uint32_t group       = MATH_FIDELITY != MathFidelity::LoFi ? 3 : (matmul_kt == 0 ? 0 : (matmul_kt == 1 ? 1 : 2));
    constexpr std::uint32_t group_other = MATH_FIDELITY != MathFidelity::LoFi ? 5 : 4;
    const std::uint32_t mask_group      = (matmul_kt != 0 || ctx != 0) ? group : group_other;
    const std::uint32_t bit             = column * 16 + count;
    char out                            = form;
    constexpr std::uint32_t drop_group  = group == 3 ? 1 : 0;
    const std::uint64_t keep_w          = ctx != 0 && (group == 0 || group == 3) ? ~llk_pack_mm_drop_no_w[family][drop_group][state][row] : ~0ULL;
    const std::uint64_t keep_b          = ctx != 0 && (group == 0 || group == 3) ? ~llk_pack_mm_drop_no_block[family][drop_group][state][row] : ~0ULL;
    const std::uint64_t tail_w          = ctx == 2 ? llk_pack_mm_tail_no_w[family][group][state][row] : 0;
    const std::uint64_t tail_b          = ctx == 2 ? llk_pack_mm_tail_no_block[family][group][state][row] : 0;
    if (out == 'W' && ((((llk_pack_mm_no_w[family][mask_group][state][row] & keep_w) | tail_w) >> bit) & 1) != 0)
    {
        out = 'B';
    }
    if (out == 'B' && ((((llk_pack_mm_no_block[family][mask_group][state][row] & keep_b) | tail_b) >> bit) & 1) != 0)
    {
        out = 'T';
    }
    if constexpr (matmul_kt != 0)
    {
        if (state == 2 && out != 'W' && (((llk_pack_mm_take_w[family][group - 1][row] & ~tail_w) >> bit) & 1) != 0)
        {
            out = 'W';
        }
        if (state == 2 && out == 'T' && (((llk_pack_mm_take_b[family][group - 1][row] & ~tail_b) >> bit) & 1) != 0)
        {
            out = 'B';
        }
    }
    // Half sync, 16-bit DEST, no 32-bit CB, LoFi, Float16_b, three tiles or more: the table's block forms. With the copy and the unpacker
    // on the datacopy stack the pack binds there, and a per-tile pack pays main's destination word write per tile.
    if (llk_pack_src32_mask(0) == 0 && llk_pack_src32_mask(32) == 0 && column == 0 && MATH_FIDELITY == MathFidelity::LoFi && row == 10 && count >= 2)
    {
        return form;
    }
    constexpr std::uint32_t fam_bit = family == 0 ? 1 : (llk_pack_unpack_to_dest ? 4 : 2);
    constexpr std::uint32_t fid_bit =
        MATH_FIDELITY == MathFidelity::LoFi ? 1 : (MATH_FIDELITY == MathFidelity::HiFi2 ? 2 : (MATH_FIDELITY == MathFidelity::HiFi3 ? 4 : 8));
    constexpr std::uint32_t k_bit = matmul_kt == 0 ? 1 : (matmul_kt == 1 ? 2 : (matmul_kt == 2 ? 4 : (matmul_kt == 4 ? 8 : (matmul_kt == 8 ? 16 : 32))));
    const std::uint32_t cell      = (state << 16) | (row << 18) | (column << 22) | (count << 24);
    for (std::uint32_t i = llk_pack_form_cells_at.at[state * 12 + row]; i < llk_pack_form_cells_at.at[state * 12 + row + 1]; i++)
    {
        const std::uint32_t e = llk_pack_form_cells[i];
        if ((e & fam_bit) != 0 && ((e >> 3) & fid_bit) != 0 && ((e >> 7) & k_bit) != 0 && ((e >> 13) & (1u << ctx)) != 0 && (e & 0x0FFF0000u) == cell)
        {
            out = "TBW"[(e >> 28) & 3];
        }
    }
    return out;
}

template <bool is_fp32_dest_acc_en>
constexpr const char (*llk_pack_form_table(const char (*u)[4][17], const char (*dc)[4][17]))[4][17]
{
    return llk_pack_src32_family<is_fp32_dest_acc_en> && llk_pack_unpack_to_dest ? u : dc;
}

// Every row's forms per count, three states, nctx contexts, two bits each (T 0, B 1, W 2): a lookup reads one word.
template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt, std::uint32_t ctx0, std::uint32_t nctx, std::uint32_t step>
struct llk_pack_form_words_t
{
    std::uint32_t w[nctx][3][12];

    constexpr llk_pack_form_words_t() : w()
    {
        const char(*tables[3])[4][17] = {
            llk_pack_form_table<is_fp32_dest_acc_en>(llk_pack_init_form, llk_pack_init_form_dc),
            llk_pack_form_table<is_fp32_dest_acc_en>(llk_pack_reconf_form, llk_pack_reconf_form_dc),
            llk_pack_form_table<is_fp32_dest_acc_en>(llk_pack_next_form, llk_pack_next_form_dc)};
        for (std::uint32_t ctx = 0; ctx < nctx; ctx++)
        {
            for (std::uint32_t state = 0; state < 3; state++)
            {
                for (std::uint32_t row = 0; row < 12; row++)
                {
                    for (std::uint32_t n = 1; n <= 16; n++)
                    {
                        const char f = llk_pack_block_form_of<is_fp32_dest_acc_en, matmul_kt>(row, n, tables[state], state, ctx0 + ctx * step);
                        w[ctx][state][row] |= static_cast<std::uint32_t>(f == 'T' ? 0 : (f == 'B' ? 1 : 2)) << (2 * (n - 1));
                    }
                }
            }
        }
    }
};

// Contexts 0 and 2, the 288 bytes a variable block reads at most, and context 1, read only where the forms fold.
template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>
inline constexpr llk_pack_form_words_t<is_fp32_dest_acc_en, matmul_kt, 0, 2, 2> llk_pack_form_words {};
template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>
inline constexpr llk_pack_form_words_t<is_fp32_dest_acc_en, matmul_kt, 1, 1, 1> llk_pack_form_words_mm {};

// state: 0 init, 1 reconfigure, 2 next.
template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>
__attribute__((always_inline)) inline char llk_pack_block_form(
    const std::uint32_t output_id, const std::uint32_t ntiles, const std::uint32_t state, const std::uint32_t ctx = llk_pack_context<matmul_kt>())
{
    if (!is_fp32_dest_acc_en && llk_pack_dst_is_int8(output_id))
    {
        return 'T';
    }
    const std::uint32_t row   = llk_pack_block_class(output_id);
    const std::uint32_t count = (ntiles < 16 ? ntiles : 16) - 1;
    // Context 0 is not behind matmul math, whatever the K says.
    const auto& words_0      = llk_pack_form_words<is_fp32_dest_acc_en, 0>.w;
    const auto& words        = llk_pack_form_words<is_fp32_dest_acc_en, matmul_kt>.w;
    const auto& words_mm     = llk_pack_form_words_mm<is_fp32_dest_acc_en, matmul_kt>.w;
    const std::uint32_t code = ((ctx == 0 ? words_0[0][state][row] : (ctx == 2 ? words[1][state][row] : words_mm[0][state][row])) >> (2 * count)) & 3;
    return code == 0 ? 'T' : (code == 1 ? 'B' : 'W');
}

// The forms of the three states as a mask: 1 per tile, 2 block, 4 W offset.
template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>
__attribute__((always_inline)) inline std::uint32_t llk_pack_block_forms(const std::uint32_t output_id, const std::uint32_t ntiles, const std::uint32_t ctx)
{
    const char init   = llk_pack_block_form<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 0, ctx);
    const char reconf = llk_pack_block_form<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 1, ctx);
    const char next   = llk_pack_block_form<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 2, ctx);
    return (init == 'T' || reconf == 'T' || next == 'T' ? 1 : 0) | (init == 'B' || reconf == 'B' || next == 'B' ? 2 : 0) |
           (init == 'W' || reconf == 'W' || next == 'W' ? 4 : 0);
}

// The per-tile packs of a block that takes none of the block forms: main's loop, which reads no pack flag.
template <bool is_fp32_dest_acc_en>
__attribute__((always_inline)) inline void llk_pack_block_per_tile(
    const std::uint32_t start_tile_index, const std::uint8_t output_id, const std::uint32_t ntiles)
{
    if constexpr (llk_pack_pre_on<is_fp32_dest_acc_en, PackMode::Default>())
    {
        // Only the first tile can find its destination written, and only the last sets the next: no per-tile bookkeeping.
        std::uint32_t pack_tile_addr = get_output_tile_address<false, PackMode::Default>(output_id, 0);
        llk_pack_tile_of_output<is_fp32_dest_acc_en, PackMode::Default, false>(start_tile_index, pack_tile_addr, output_id);
        for (std::uint32_t tile_index = start_tile_index + 1; tile_index < start_tile_index + ntiles; tile_index++)
        {
            pack_tile_addr = get_output_tile_address<false, PackMode::Default>(output_id, 0);
            llk_pack_impl<is_fp32_dest_acc_en, PackMode::Default, false>(tile_index, pack_tile_addr);
        }
        llk_pack_pre_set<is_fp32_dest_acc_en>(pack_tile_addr + get_local_cb_interface(output_id).fifo_page_size);
    }
    else
    {
        for (std::uint32_t tile_index = start_tile_index; tile_index < start_tile_index + ntiles; tile_index++)
        {
            std::uint32_t pack_tile_addr = get_output_tile_address<false, PackMode::Default>(output_id, 0);
            llk_pack_tile_of_output<is_fp32_dest_acc_en, PackMode::Default, false>(tile_index, pack_tile_addr, output_id);
        }
    }
}

// A per-tile block of three tiles or more, to an output the W offset reaches: one destination write, then each tile closed as
// main's and the next moved by the W counters (_llk_pack_block_closed_), not three byte writes and a SETADC per tile.
// Not at half sync with fp32 DEST and an unpack to DEST, where the per-tile pack keeps its slower destination write, nor
// for 4 byte outputs, which read slower closed.
template <bool is_fp32_dest_acc_en, std::uint32_t ntiles, bool guard_dest_straddle>
__attribute__((always_inline)) inline void llk_pack_block_tiles(const std::uint32_t start_tile_index, const std::uint8_t output_id)
{
    if constexpr (ntiles > 2 && llk_pack_rmw_per_tile<is_fp32_dest_acc_en, PackMode::Default> && !pack_fast_untilize_linked<DST_SYNC_MODE>)
    {
        const bool straddle = guard_dest_straddle && IS_BFP_FORMAT(pack_dst_format[output_id]) && ntiles == 2 && (start_tile_index & 3) == 3;
        if (llk_pack_block_is_closable(output_id) && !llk_pack_dst_is_wide(output_id) && !llk_pack_dst_is_int8(output_id) && !straddle &&
            !LLK_PACK_OTHER_PROGRAM_ACTIVE() &&
            !(DST_SYNC_MODE == DstSync::SyncHalf && LLK_PACK_L1_ACC_ACTIVE()))
        {
            const std::uint32_t page_size = get_local_cb_interface(output_id).fifo_page_size;
            const std::uint32_t pack_tile_addr = get_local_cb_interface(output_id).fifo_wr_ptr + get_local_cb_interface(output_id).fifo_wr_tile_ptr - 1;
            get_local_cb_interface(output_id).fifo_wr_tile_ptr += page_size * ntiles;
            _llk_pack_block_closed_<DST_SYNC_MODE, is_fp32_dest_acc_en, true, false>(
                start_tile_index, pack_tile_addr, ntiles, page_size << 4, get_output_num_faces(output_id));
            llk_pack_pre_set<is_fp32_dest_acc_en>(0);
            return;
        }
    }
    if constexpr (ntiles == 2 && llk_pack_rmw_per_tile<is_fp32_dest_acc_en, PackMode::Default>)
    {
        // The second tile's address is in hand with the first's: its high byte is written only if it differs.
        const std::uint32_t addr0 = get_output_tile_address<false, PackMode::Default>(output_id, 0);
        llk_pack_tile_of_output<is_fp32_dest_acc_en, PackMode::Default, false>(start_tile_index, addr0, output_id);
        const std::uint32_t addr1 = get_output_tile_address<false, PackMode::Default>(output_id, 0);
        _llk_pack_next_<DST_SYNC_MODE, false>(start_tile_index + 1, addr1, addr0);
        llk_pack_pre_set<is_fp32_dest_acc_en>(addr1 + get_local_cb_interface(output_id).fifo_page_size);
        return;
    }
    llk_pack_block_per_tile<is_fp32_dest_acc_en>(start_tile_index, output_id, ntiles);
}

// The contexts a block can pack in: 0 always, 1 and 2 only in a kernel with a matmul API, 2 only with a pack-thread
// SFPU header too.
template <std::uint32_t matmul_kt>
constexpr bool llk_pack_context_reach(const std::uint32_t ctx)
{
    constexpr bool matmul = llk_pack_matmul_kernel<matmul_kt>();
    return ctx == 0 || (ctx == 1 ? matmul : matmul && llk_pack_sfpu_kernel<matmul_kt>());
}

// Counts at which some output of the kernel packs per tile in some state or reachable context (bit n - 1, above 16 the
// bit of 16): a block of such a count with a variable output packs per tile, so it never reaches a per-tile pack at run
// time.
template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>
struct llk_pack_per_tile_counts_t
{
    std::uint32_t counts;

    constexpr llk_pack_per_tile_counts_t() : counts(0)
    {
        const auto& words_0  = llk_pack_form_words<is_fp32_dest_acc_en, 0>.w;
        const auto& words    = llk_pack_form_words<is_fp32_dest_acc_en, matmul_kt>.w;
        const auto& words_mm = llk_pack_form_words_mm<is_fp32_dest_acc_en, matmul_kt>.w;
        for (std::uint32_t i = 0; i < sizeof(pack_dst_format); i++)
        {
            const std::uint32_t fmt = pack_dst_format[i];
            if (fmt == static_cast<std::uint32_t>(DataFormat::Invalid))
            {
                continue;
            }
            const bool int8 = fmt == static_cast<std::uint32_t>(DataFormat::Int8) || fmt == static_cast<std::uint32_t>(DataFormat::UInt8);
            if (!is_fp32_dest_acc_en && int8)
            {
                counts = 0xFFFF;
                continue;
            }
            const std::uint32_t row = llk_pack_class_tab.row[i];
            for (std::uint32_t state = 0; state < 3; state++)
            {
                const std::uint32_t w[3] = {words_0[0][state][row], words_mm[0][state][row], words[1][state][row]};
                for (std::uint32_t c = 0; c < 3; c++)
                {
                    for (std::uint32_t bit = 0; bit < 16 && llk_pack_context_reach<matmul_kt>(c); bit++)
                    {
                        if (((w[c] >> (2 * bit)) & 3) == 0)
                        {
                            counts |= 1u << bit;
                        }
                    }
                }
            }
        }
    }
};

template <bool is_fp32_dest_acc_en, std::uint32_t matmul_kt>
inline constexpr llk_pack_per_tile_counts_t<is_fp32_dest_acc_en, matmul_kt> llk_pack_per_tile_counts {};

// guard_dest_straddle: block-float tiles at DEST 3 and 4 read 6 cycles slower closed: a variable start packs per tile.
// matmul_kt: K tiles per output block of the matmul that filled DEST, if known; 0 takes the forms no K reads slower.
// arm_form: a test arm's form ('T', 'B' or 'W'), run as a constant output whose every state takes it; 0 the tables.
template <std::uint32_t ntiles, bool is_fp32_dest_acc_en, bool guard_dest_straddle = false, std::uint32_t matmul_kt = 0, char arm_form = 0>
__attribute__((always_inline)) inline void llk_pack_block(std::uint32_t start_tile_index, std::uint32_t output)
{
    static_assert(ntiles > 0, "pack_block packs at least one tile");
    if constexpr (ntiles == 1)
    {
        pack_short_block = true;
    }
    std::uint8_t output_id = get_output_id(output);

    LLK_ASSERT_BLOCK(are_packers_configured_correctly(pack_src_format[output_id], pack_dst_format[output_id]));
    LLK_ASSERT(
        ((start_tile_index + ntiles - 1) < get_pack_dest_max_tiles<DST_SYNC_MODE>()),
        "Dst tile exceeds packer destination capacity for the configured W-stride.");

    SAN_HOOK(execute<OperationPack>(
        StateVal<Operand<Exu::Pack>::DestWidth32>(is_fp32_dest_acc_en),
        StateVal<Operand<Exu::Pack>::InputFormat>(pack_src_format[output_id]),
        StateVal<Operand<Exu::Pack>::OutputFormat>(pack_dst_format[output_id]),
        StateVal<Operand<Exu::Pack>::FaceHeight>(get_output_face_r_dim(output_id)),
        StateVal<Operand<Exu::Pack>::TileWidth>(get_output_tile_c_dim(output_id)),
        StateVal<Operand<Exu::Pack>::NumFaces>(get_output_num_faces(output_id)),
        StateDiscard<std::uint32_t>(start_tile_index),
        StateDiscard<std::uint32_t>(ntiles)));

    // A constant output folds the forms of every state and reachable context (0 otherwise). A block that can pack per
    // tile in one of them packs per tile in all: a per-tile pack never pays a run-time form choice, and keeps no state.
    std::uint32_t forms = 0;
    if constexpr (arm_form != 0)
    {
        forms = arm_form == 'T' ? 1 : (arm_form == 'B' ? 2 : 4);
    }
    else if (__builtin_constant_p(output_id))
    {
        std::uint32_t any = 0;
        if constexpr (llk_pack_context_reach<matmul_kt>(0))
        {
            any |= llk_pack_block_forms<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 0);
        }
        if constexpr (llk_pack_context_reach<matmul_kt>(1))
        {
            any |= llk_pack_block_forms<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 1);
        }
        if constexpr (llk_pack_context_reach<matmul_kt>(2))
        {
            any |= llk_pack_block_forms<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 2);
        }
        forms = (any & 1) != 0 ? 1 : any;
    }
    else if constexpr (((llk_pack_per_tile_counts<is_fp32_dest_acc_en, matmul_kt>.counts >> ((ntiles < 16 ? ntiles : 16) - 1)) & 1) != 0)
    {
        forms = 1;
    }
    // Still marks the last output: these packs move the output base without invalidating another output's W offset.
    if (forms == 1)
    {
        llk_pack_state_set_half(output_id + 1);
        llk_pack_block_tiles<is_fp32_dest_acc_en, ntiles, guard_dest_straddle>(start_tile_index, output_id);
        return;
    }
    // A block of one folded form packs as main: it reads no state, so it closes no fast untilize either.
    const bool one_form = forms != 0 && (forms & (forms - 1)) == 0;

    // The block forms run the default pack program, so after a tilize, untilize or pack rows init they pack per tile;
    // so too under half-sync L1 accumulation, where a block behind matmul math reads up to 64 cycles slower.
    if (LLK_PACK_OTHER_PROGRAM_ACTIVE() || (DST_SYNC_MODE == DstSync::SyncHalf && LLK_PACK_L1_ACC_ACTIVE()))
    {
        if (!one_form)
        {
            _llk_pack_close_fast_untilize_<DST_SYNC_MODE>();
        }
        LLK_PACK_W_INVALIDATE();
        llk_pack_block_per_tile<is_fp32_dest_acc_en>(start_tile_index, output_id, ntiles);
        return;
    }

    // Last output and reconfigure mark in one halfword: a continuing block reads output_id + 1, W bit or not.
    const std::uint32_t state = llk_pack_state_half();
    const bool first_block    = (state & ~static_cast<std::uint32_t>(LLK_PACK_STATE_W)) != output_id + 1u;
    const bool reconfigured   = (state >> 8) != 0;
    // Constant or variable, a block reads each state's word at a constant index in the folded path's context, so a late
    // constant still folds and both paths pick the same form.
    const char form = arm_form != 0 ? arm_form
                      : forms == 2  ? 'B'
                                    : (first_block ? (reconfigured ? llk_pack_block_form<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 1)
                                                                   : llk_pack_block_form<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 0))
                                                   : llk_pack_block_form<is_fp32_dest_acc_en, matmul_kt>(output_id, ntiles, 2));
    // A fast untilize left open marks the last output, so only a first block closes it.
    if (!one_form && first_block)
    {
        _llk_pack_close_fast_untilize_<DST_SYNC_MODE>();
    }
    const bool straddle = guard_dest_straddle && IS_BFP_FORMAT(pack_dst_format[output_id]) && ntiles == 2 && (start_tile_index & 3) == 3;
    const bool take_w =
        form == 'W' && (forms == 0 || (forms & 4) != 0) && (llk_pack_block_is_contiguous(output_id) || (llk_pack_block_is_closable(output_id) && !straddle));
    // A W offset block stores the state in llk_pack_w_take, after it reads it.
    if (!take_w)
    {
        llk_pack_state_set_half(output_id + 1);
    }
    if (form == 'T')
    {
        llk_pack_block_tiles<is_fp32_dest_acc_en, ntiles, guard_dest_straddle>(start_tile_index, output_id);
        return;
    }
    llk_pack_pre_set<is_fp32_dest_acc_en>(0);
    if (llk_pack_block_is_contiguous(output_id))
    {
        std::uint32_t pack_tile_addr = get_local_cb_interface(output_id).fifo_wr_ptr + get_local_cb_interface(output_id).fifo_wr_tile_ptr - 1;
        get_local_cb_interface(output_id).fifo_wr_tile_ptr += get_local_cb_interface(output_id).fifo_page_size * ntiles;
        std::uint32_t out_tile = 0;
        if (take_w)
        {
            llk_pack_w_take(output_id, pack_tile_addr, get_local_cb_interface(output_id).fifo_page_size, ntiles, out_tile);
            _llk_pack_block_w_<DST_SYNC_MODE, is_fp32_dest_acc_en>(start_tile_index, out_tile, ntiles);
        }
        else
        {
            _llk_pack_block_<DST_SYNC_MODE, is_fp32_dest_acc_en, PackMode::Default, llk_pack_rmw_tile<PackMode::Default>, false>(
                start_tile_index, pack_tile_addr, ntiles);
        }
    }
    else if (llk_pack_block_is_closable(output_id) && !straddle)
    {
        const std::uint32_t page_size = get_local_cb_interface(output_id).fifo_page_size;
        std::uint32_t pack_tile_addr  = get_local_cb_interface(output_id).fifo_wr_ptr + get_local_cb_interface(output_id).fifo_wr_tile_ptr - 1;
        get_local_cb_interface(output_id).fifo_wr_tile_ptr += page_size * ntiles;
        std::uint32_t out_tile = 0;
        if (take_w)
        {
            llk_pack_w_take(output_id, pack_tile_addr, page_size, ntiles, out_tile);
            _llk_pack_block_closed_w_mop_<DST_SYNC_MODE, is_fp32_dest_acc_en>(start_tile_index, out_tile, ntiles, get_output_num_faces(output_id));
        }
        else
        {
            _llk_pack_block_closed_<DST_SYNC_MODE, is_fp32_dest_acc_en, llk_pack_rmw_tile<PackMode::Default>, false>(
                start_tile_index, pack_tile_addr, ntiles, page_size << 4, get_output_num_faces(output_id));
        }
    }
    else
    {
        llk_pack_block_per_tile<is_fp32_dest_acc_en>(start_tile_index, output_id, ntiles);
    }
}

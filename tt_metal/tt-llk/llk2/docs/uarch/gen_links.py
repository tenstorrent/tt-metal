"""Append pinned GitHub links for the code tags in the LLK 2.0 uarch docs, and print each tag's source line.

usage: python3 -I gen_links.py <demo checkout root> <doc.md>...
A tag is a shortcut reference link such as [tensor.h:344] or [api/dest.h:56-64]. The generated block at the end of
each doc is replaced on every run.
"""

import re
import sys

SHA = "972eb4de3392481e56c7509f58870c754019ed01"
BASE = f"https://github.com/tenstorrent/tt-metal/blob/{SHA}/tt_metal/tt-llk/"
PREFIX = {
    "tensor.h": "llk2/inc/common/tensor/tensor.h",
    "thread.h": "llk2/inc/common/llk_lib/thread.h",
    "settings.h": "llk2/inc/common/kernel_settings.h",
    "kernel.cpp": "llk2/kernels/bmm_large_block_zm_fused_bias_activation.cpp",
    "README.md": "llk2/README.md",
    "api/": "llk2/inc/common/compute_api/",
    "lib/": "llk2/inc/blackhole/llk_lib/",
    "res/": "llk2/inc/common/resolver/",
    "bh-res/": "llk2/inc/blackhole/resolver/",
    "tests/": "llk2/tests/python_tests/",
    "hal/": "tt_llk_blackhole/llk_lib/hal/",
}
TAG = re.compile(r"(?<![\]\w])\[((?:api|lib|res|bh-res|tests|hal)/[\w./-]+|tensor\.h|thread\.h|settings\.h|kernel\.cpp|README\.md):(\d+)(?:-(\d+))?\](?![\[(:])")
MARK = "<!-- Links below are generated by gen_links.py; do not edit by hand. -->"


def path_of(name):
    for p, full in PREFIX.items():
        if name == p or (p.endswith("/") and name.startswith(p)):
            return full + name[len(p):] if p.endswith("/") else full
    raise KeyError(name)


root = sys.argv[1]
bad = 0
for doc in sys.argv[2:]:
    text = open(doc).read().split(MARK)[0].rstrip() + "\n"
    defs = {}
    for m in TAG.finditer(text):
        name, a, b = m.group(1), int(m.group(2)), m.group(3)
        full = path_of(name)
        try:
            lines = open(f"{root}/tt_metal/tt-llk/{full}").read().split("\n")
            src = lines[a - 1].strip() if a <= len(lines) else "<<PAST END>>"
            if b and int(b) > len(lines):
                src += "  <<RANGE PAST END>>"
        except FileNotFoundError:
            src = "<<NO FILE>>"
        if "<<" in src or not src:
            bad += 1
        print(f"{doc.split('/')[-1]}: [{m.group(0)[1:-1]}]  {src[:110]}")
        anchor = f"#L{a}" + (f"-L{b}" if b else "")
        defs[m.group(0)[1:-1]] = BASE + full + anchor
    out = text + "\n" + MARK + "\n\n[PR]: https://github.com/tenstorrent/tt-metal/pull/62961\n"
    out += "".join(f"[{k}]: {v}\n" for k, v in sorted(defs.items()))
    open(doc, "w").write(out)
print(f"{bad} suspicious tags", file=sys.stderr)

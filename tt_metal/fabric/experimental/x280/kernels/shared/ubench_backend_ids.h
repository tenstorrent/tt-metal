/*
 * Backend identities: the value each benchmark backend publishes in its
 * result's backend_id, which the host checks against the placement it chose
 * and records.
 */
#ifndef X280_UBENCH_BACKEND_IDS_H
#define X280_UBENCH_BACKEND_IDS_H

/* Bits 31..28 name the core family the backend runs on, bits 27..20 the suite,
 * and the low bits the member within the suite. The values are recorded and
 * tools/tabulate_suites.py selects tables by them, so a change here changes
 * that file in the same commit. */
#define UBENCH_BACKEND_ID(core_class, suite, member) (((core_class) << 28) | ((suite) << 20) | (member))
#define UBENCH_BACKEND_ID_CLASS(id) ((id) >> 28)

#define UBENCH_BACKEND_CLASS_X280 0x1u
#define UBENCH_BACKEND_CLASS_TENSIX 0x2u
#define UBENCH_BACKEND_CLASS_ERISC 0x3u
#define UBENCH_BACKEND_CLASS_DRISC 0x4u

#define UBENCH_BACKEND_SUITE_P2P_LATENCY 0x00u
#define UBENCH_BACKEND_SUITE_TRANSPORT_BANDWIDTH 0x01u
#define UBENCH_BACKEND_SUITE_PIPELINE_STAGE 0x02u

#define P2P_LATENCY_BACKEND_ID_X280_X280_SAME_TILE \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_X280, UBENCH_BACKEND_SUITE_P2P_LATENCY, 1u)
#define P2P_LATENCY_BACKEND_ID_X280_X280_PEER_TILE \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_X280, UBENCH_BACKEND_SUITE_P2P_LATENCY, 2u)
#define P2P_LATENCY_BACKEND_ID_TENSIX_TENSIX_PEER_TILE \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_TENSIX, UBENCH_BACKEND_SUITE_P2P_LATENCY, 3u)
#define P2P_LATENCY_BACKEND_ID_ERISC_ERISC_PEER_TILE \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_ERISC, UBENCH_BACKEND_SUITE_P2P_LATENCY, 4u)
#define P2P_LATENCY_BACKEND_ID_DRISC_DRISC_PEER_TILE \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_DRISC, UBENCH_BACKEND_SUITE_P2P_LATENCY, 5u)
#define P2P_LATENCY_BACKEND_ID_X280_METAL_PEER_TILE \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_X280, UBENCH_BACKEND_SUITE_P2P_LATENCY, 6u)

#define TRANSPORT_BW_BACKEND_ID_TENSIX_TO_X280 \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_TENSIX, UBENCH_BACKEND_SUITE_TRANSPORT_BANDWIDTH, 1u)
#define TRANSPORT_BW_BACKEND_ID_X280_TO_TENSIX \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_X280, UBENCH_BACKEND_SUITE_TRANSPORT_BANDWIDTH, 2u)
#define TRANSPORT_BW_BACKEND_ID_ERISC_TO_X280 \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_ERISC, UBENCH_BACKEND_SUITE_TRANSPORT_BANDWIDTH, 3u)

/* pipeline_stage IDs 0x40200003, 0x30200003, 0x40200004 and 0x30200004 are
 * reserved: no member publishes them. */
#define PIPELINE_STAGE_BACKEND_ID_X280_ROUTE_COMPUTE \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_X280, UBENCH_BACKEND_SUITE_PIPELINE_STAGE, 1u)
#define PIPELINE_STAGE_BACKEND_ID_X280_ROUTE_FORWARD \
    UBENCH_BACKEND_ID(UBENCH_BACKEND_CLASS_X280, UBENCH_BACKEND_SUITE_PIPELINE_STAGE, 2u)

#endif /* X280_UBENCH_BACKEND_IDS_H */

#!/usr/bin/env python3
"""Phase-diagram cell generator for the SFPU applicability-bounds sweep.

For one grid cell (variant, degree D, segments N, parity), emits BOTH:
  - kernels/common/bench_lut.h   : the benchmark LUT for (D, N, parity)
  - kernels/compute/adhoc/adhoc.cpp : a specialized kernel for (variant, D)

The driver (bounds_sweep.sh) calls this per cell, builds the adhoc target, runs it,
and records {compiled?, correct?, us} -> the phase diagram. A build/JIT failure is a
DATA POINT (the register-ICE frontier), not an error.

Variants:
  cascade        - per-segment Horner inside each v_if            (the baseline)
  dual           - cascade, 2 DST rows/iter, shared coeff loads   (ILP)
  blend          - cascade overwrites coeff regs; ONE Horner after (select-then-eval)
  blend_dual     - blend + dual (probes the blend+dual register frontier)

parity:
  off  -> dense polynomial (coeffs c0..cD), Horner length D
  on   -> odd polynomial   (coeffs c1,c3,..),  x^2-Horner, half the live coeffs
"""
import numpy as np
import sys
import os

SEED = 20260620
LO, HI = -8.0, 8.0
HERE = os.path.dirname(os.path.abspath(__file__))


def build_bench(D, N, parity):
    rng = np.random.default_rng(SEED + D * 131 + N)
    bounds = np.linspace(LO, HI, N + 1)
    coeffs = np.zeros((N, D + 1))
    for s in range(N):
        for d in range(D + 1):
            if parity and d % 2 == 0:
                continue  # odd parity -> even coeffs zero
            coeffs[s, d] = rng.uniform(-0.5, 0.5) / (HI ** max(d - 1, 0))
    return bounds, coeffs


def emit_bench(D, N, parity):
    bounds, coeffs = build_bench(D, N, parity)
    flat = list(bounds)
    for s in range(N):
        flat += list(coeffs[s])
    n = len(flat)
    path = os.path.join(HERE, "kernels/common/bench_lut.h")
    with open(path, "w") as f:
        f.write("// GENERATED by gen_sweep.py - do not edit\n#pragma once\n#include <array>\n#include <cstdint>\n")
        f.write(f"constexpr uint32_t BENCH_NUM_SEGMENTS = {N};\n")
        f.write(f"constexpr uint32_t BENCH_MAX_DEGREE = {D};\n")
        f.write(f"constexpr float BENCH_RANGE_MIN = {LO}f;\nconstexpr float BENCH_RANGE_MAX = {HI}f;\n")
        f.write(f"constexpr uint32_t BENCH_LUT_SIZE = {n};\n")
        f.write("constexpr std::array<float, %d> BENCH_LUT = {{%s}};\n" % (n, ", ".join(f"{v:.9e}f" for v in flat)))
    # exact reference for the correctness gate
    xs = np.linspace(LO, HI, 262144)
    out = np.empty_like(xs)
    for i, x in enumerate(xs):
        s = min(max(int(np.searchsorted(bounds, x, side="right") - 1), 0), N - 1)
        out[i] = sum(coeffs[s, d] * x**d for d in range(D + 1))
    np.savetxt(
        os.path.join(HERE, "bench_reference.csv"),
        np.c_[xs, out],
        delimiter=",",
        header="input,output",
        comments="",
        fmt="%.9e",
    )


# ---- kernel code generation (specialized per variant + degree) ----

SCAFFOLD_HEAD = """// GENERATED by gen_sweep.py - sweep cell kernel (variant=%(variant)s, D=%(D)d, parity=%(par)d)
#include <cstdint>
#include <array>
#include "api/compute/common.h"
#include "api/compute/tile_move_copy.h"
#include "api/compute/eltwise_unary/eltwise_unary.h"
#include "../../../tutorials/sfpu_optimization/kernels/common/bench_lut.h"
#define EMBEDDED_LUT
constexpr uint32_t POLY_DEGREE = BENCH_MAX_DEGREE;
constexpr uint32_t NUM_SEGMENTS = BENCH_NUM_SEGMENTS;
constexpr uint32_t LUT_SIZE = BENCH_LUT_SIZE;
constexpr auto& LUT_DATA = BENCH_LUT;
#ifdef TRISC_MATH
namespace sfpi {
"""

SCAFFOLD_MAIN = """
}  // namespace sfpi
#endif  // TRISC_MATH
void kernel_main() {
    uint32_t n_tiles = get_arg_val<uint32_t>(0);
    constexpr auto cb_in = tt::CBIndex::c_0;
    constexpr auto cb_out = tt::CBIndex::c_16;
    const auto& lut_ref = LUT_DATA; auto p_lut = &lut_ref;
    init_sfpu(cb_in, cb_out);
    for (uint32_t tile = 0; tile < n_tiles; tile++) {
        cb_wait_front(cb_in, 1); tile_regs_acquire(); copy_tile(cb_in, 0, 0);
        #ifdef TRISC_MATH
        sfpi::piecewise_generic_lut_dispatch<POLY_DEGREE, NUM_SEGMENTS, LUT_SIZE>(*p_lut);
        #endif
        tile_regs_commit(); tile_regs_wait(); cb_reserve_back(cb_out, 1);
        pack_tile(0, cb_out); cb_push_back(cb_out, 1); cb_pop_front(cb_in, 1); tile_regs_release();
    }
}
"""


def horner_eval(D, parity, var, xexpr):
    """Return C++ expression string evaluating the polynomial of degree D at `var`
    using coeff pointer `c` (and t=var*var if parity)."""
    if parity:
        top = D if D % 2 == 1 else D - 1
        if top < 1:
            return "c[1]"  # degenerate
        terms = list(range(top, 0, -2))  # e.g. 7,5,3,1
        e = f"c[{terms[0]}]"
        for k in terms[1:]:
            e = f"({e} * t + c[{k}])"
        return f"({xexpr} * ({e}))"
    else:
        e = f"c[{D}]"
        for k in range(D - 1, -1, -1):
            e = f"({e} * {xexpr} + c[{k}])"
        return e


def gen_kernel(variant, D, parity):
    head = SCAFFOLD_HEAD % {"variant": variant, "D": D, "par": int(parity)}
    cps = "(POLY_DEGREE + 1)"
    base = f"(NUM_SEGMENTS + 1) + S * {cps}"
    t_decl = "vFloat t = x * x;" if parity else ""
    blend_idx = list(range(1, D + 1, 2)) if parity else list(range(0, D + 1))
    body = ""
    if variant in ("cascade", "dual"):
        ev = horner_eval(D, parity, variant, "x")
        seg = f"""template <uint32_t S>
__attribute__((always_inline)) static inline void seg(const std::array<float, LUT_SIZE>& lut, vFloat x, vFloat t, vFloat& r) {{
    if constexpr (S < NUM_SEGMENTS) {{
        const float* c = &lut[{base}];
        v_if (x >= lut[S]) {{ r = {ev}; }} v_endif;
        seg<S + 1>(lut, x, t, r);
    }}
}}"""
        if variant == "cascade":
            disp = f"""template <uint32_t PD, uint32_t NS, uint32_t LS>
inline void piecewise_generic_lut_dispatch(const std::array<float, LS>& lut) {{
    for (int d = 0; d < 32; d++) {{ vFloat x = dst_reg[d]; {t_decl} vFloat r = 0.0f; seg<0>(lut, x, t, r); dst_reg[d] = r; }}
}}"""
            body = seg.replace("vFloat t,", "vFloat t,") + "\n" + disp
            if not parity:
                body = (
                    body.replace(", vFloat t,", ",").replace("(lut, x, t, r)", "(lut, x, r)").replace("{t_decl} ", "")
                )
        else:  # dual: per-segment eval on two rows (no shared-coeff micro-opt for the sweep; tests register frontier)
            evd0 = horner_eval(D, parity, variant, "x0")
            evd1 = horner_eval(D, parity, variant, "x1")
            body = f"""template <uint32_t S>
__attribute__((always_inline)) static inline void seg2(const std::array<float, LUT_SIZE>& lut, vFloat x0, vFloat x1, vFloat t0, vFloat t1, vFloat& r0, vFloat& r1) {{
    if constexpr (S < NUM_SEGMENTS) {{
        const float* c = &lut[{base}];
        {{ vFloat t = t0; v_if (x0 >= lut[S]) {{ r0 = {evd0.replace("t","t0") if parity else evd0}; }} v_endif; }}
        {{ vFloat t = t1; v_if (x1 >= lut[S]) {{ r1 = {evd1.replace("t","t1") if parity else evd1}; }} v_endif; }}
        seg2<S + 1>(lut, x0, x1, t0, t1, r0, r1);
    }}
}}
template <uint32_t PD, uint32_t NS, uint32_t LS>
inline void piecewise_generic_lut_dispatch(const std::array<float, LS>& lut) {{
    for (int d = 0; d < 32; d += 2) {{
        vFloat x0 = dst_reg[d], x1 = dst_reg[d + 1];
        vFloat t0 = x0 * x0, t1 = x1 * x1; vFloat r0 = 0.0f, r1 = 0.0f;
        seg2<0>(lut, x0, x1, t0, t1, r0, r1);
        dst_reg[d] = r0; dst_reg[d + 1] = r1;
    }}
}}"""
    elif variant in ("blend", "blend_dual"):
        # blend: cascade overwrites coeff registers c_<i>; one Horner after.
        decls = ", ".join(f"vFloat& b{ i }" for i in range(len(blend_idx)))
        inits_args = ", ".join(f"b{ i }" for i in range(len(blend_idx)))
        moves = " ".join(f"b{ i } = lut[base + {idx}];" for i, idx in enumerate(blend_idx))
        seg = f"""template <uint32_t S>
__attribute__((always_inline)) static inline void blend(const std::array<float, LUT_SIZE>& lut, vFloat x, {decls}) {{
    if constexpr (S < NUM_SEGMENTS) {{
        const uint32_t base = {base};
        v_if (x >= lut[S]) {{ {moves} }} v_endif;
        blend<S + 1>(lut, x, {inits_args});
    }}
}}"""
        # final Horner over blended regs
        if parity:
            # b's correspond to odd indices high..low? blend_idx ascending [1,3,5,7]; Horner from top
            order = list(range(len(blend_idx) - 1, -1, -1))
            e = f"b{order[0]}"
            for k in order[1:]:
                e = f"({e} * t + b{k})"
            final = f"vFloat t = x * x; vFloat acc = {e}; dst_reg[d] = x * acc;"
        else:
            order = list(range(len(blend_idx) - 1, -1, -1))  # high..low = cD..c0
            e = f"b{order[0]}"
            for k in order[1:]:
                e = f"({e} * x + b{k})"
            final = f"vFloat acc = {e}; dst_reg[d] = acc;"
        binit = " ".join(f"vFloat b{ i } = lut[base0 + {idx}];" for i, idx in enumerate(blend_idx))
        body = (
            seg
            + f"""
template <uint32_t PD, uint32_t NS, uint32_t LS>
inline void piecewise_generic_lut_dispatch(const std::array<float, LS>& lut) {{
    constexpr uint32_t base0 = (NUM_SEGMENTS + 1);
    for (int d = 0; d < 32; d++) {{
        vFloat x = dst_reg[d];
        {binit}
        blend<1>(lut, x, {inits_args});
        {final}
    }}
}}"""
        )
    return head + body + SCAFFOLD_MAIN


if __name__ == "__main__":
    # usage: gen_sweep.py <variant> <D> <N> <parity 0|1>
    variant, D, N, parity = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), bool(int(sys.argv[4]))
    emit_bench(D, N, parity)
    src = gen_kernel(variant, D, parity)
    adhoc = os.path.join(HERE, "../../kernels/compute/adhoc/adhoc.cpp")
    open(os.path.abspath(adhoc), "w").write(src)
    print(f"cell: variant={variant} D={D} N={N} parity={int(parity)} -> bench_lut.h + adhoc.cpp ({len(src)} chars)")

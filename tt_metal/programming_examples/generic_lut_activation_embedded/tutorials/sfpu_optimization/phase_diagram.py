#!/usr/bin/env python3
"""Render the SFPU applicability-bounds phase diagrams from bounds_results.csv.

Emits bounds_phase_diagram.md: per-(variant,parity) grids (degree x segments,
cells = us / ICE / WRONG) and auto-derived plain-English bound statements
(register-ICE frontier per variant, and blend break-even vs the cascade baseline).
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, "bounds_results.csv"))))


def num(s):
    try:
        return float(s)
    except Exception:
        return None


cells = {}  # (variant,parity,D,N) -> (status, us)
for r in rows:
    cells[(r["variant"], r["parity"], int(r["degree"]), int(r["segments"]))] = (r["status"], num(r["us"]))
variants = sorted({r["variant"] for r in rows})
parities = sorted({r["parity"] for r in rows})
degrees = sorted({int(r["degree"]) for r in rows})
segments = sorted({int(r["segments"]) for r in rows})


def cell_str(st, us):
    if st == "OK":
        return f"{us:.1f}" if us else "OK"
    return {"ICE": "ICE", "WRONG": "wrong", "RUN_FAIL": "fail", "GEN_FAIL": "gen?"}.get(st, st)


out = [
    "# SFPU optimization applicability bounds — phase diagrams\n",
    "Generated by `bounds_sweep.sh` + `phase_diagram.py`. Cells = device µs (256 tiles, fp32); "
    "`ICE` = JIT register-spill compiler crash (the register-pressure frontier); `wrong` = failed the 1e-2 gate.\n",
]

for v in variants:
    for p in parities:
        if not any((v, p, D, N) in cells for D in degrees for N in segments):
            continue
        out.append(f"\n## {v}  (parity={'on' if p=='1' else 'off'})\n")
        hdr = "| deg \\ seg | " + " | ".join(str(N) for N in segments) + " |"
        out.append(hdr)
        out.append("|" + "---|" * (len(segments) + 1))
        for D in degrees:
            line = f"| **{D}** | "
            line += " | ".join(cell_str(*cells.get((v, p, D, N), ("-", None))) for N in segments)
            out.append(line + " |")

# --- auto bound statements ---
out.append("\n## Discovered bounds\n")
# ICE frontier per variant x parity: smallest degree with ICE (over any N)
out.append("**Register-ICE frontier** (smallest degree that spills the register file):")
for v in variants:
    for p in parities:
        ice_degs = sorted({D for D in degrees for N in segments if cells.get((v, p, D, N), ("", None))[0] == "ICE"})
        ok_degs = sorted({D for D in degrees for N in segments if cells.get((v, p, D, N), ("", None))[0] == "OK"})
        if ice_degs:
            out.append(
                f"- `{v}` parity={'on' if p=='1' else 'off'}: ICE at degree ≥ **{ice_degs[0]}** "
                f"(max safe degree {max([d for d in ok_degs if d < ice_degs[0]], default='-')})."
            )
        elif ok_degs:
            out.append(f"- `{v}` parity={'on' if p=='1' else 'off'}: no ICE up to degree {max(ok_degs)} (fits).")

# blend break-even vs cascade
out.append("\n**Blend vs cascade break-even** (where select-then-eval beats evaluate-then-select):")
for p in parities:
    for D in degrees:
        wins = []
        for N in segments:
            c = cells.get(("cascade", p, D, N), ("", None))
            b = cells.get(("blend", p, D, N), ("", None))
            if c[0] == "OK" and b[0] == "OK" and c[1] and b[1]:
                wins.append((N, b[1], c[1], c[1] / b[1]))
        if wins:
            winN = [w[0] for w in wins if w[3] > 1.02]
            s = ", ".join(f"N={w[0]}:{w[3]:.2f}x" for w in wins)
            out.append(
                f"- parity={'on' if p=='1' else 'off'} D={D}: {s}"
                + (f"  → blend wins for N≥{min(winN)}" if winN else "  → cascade wins/ties")
            )

open(os.path.join(HERE, "bounds_phase_diagram.md"), "w").write("\n".join(out) + "\n")
print("wrote bounds_phase_diagram.md")

// The kernel is fitted on BF16 data; the SFPU reads DEST in the math thread's SrcB format.
inline bool bf16_dest_hardswish_bw() {
#if defined(TRISC_MATH) || defined(LLK_TRISC_MATH)
    return ckernel::math::src_zero_flag_srcb_fmt == static_cast<std::uint32_t>(DataFormat::Float16_b);
#else
    return false;
#endif
}
template <int ITERATIONS = 8>
inline void calculate_hardswish_bw_bf16() {
    ckernel::sfpu::bf16::calculate_config_tile<ckernel::sfpu::HardswishBwBf16Config, ITERATIONS>();
}
inline void init_hardswish_bw_bf16() {
    if (bf16_dest_hardswish_bw()) {
        ckernel::sfpu::bf16::init_config_tile<ckernel::sfpu::HardswishBwBf16Config>();
    }
}

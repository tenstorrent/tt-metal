"""Generate host/l2cpu/layout.py (the Python mirror of include/l2cpu_boot.h).

Every `#define L2CPU_<NAME> <integer expression>` becomes a Python constant (function-like macros are skipped).
    gen_boot_py.py            write the mirror
    gen_boot_py.py --check    exit 1 if the committed mirror is stale
"""
import argparse
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
HEADER = os.path.join(ROOT, "include", "l2cpu_boot.h")
OUT = os.path.join(ROOT, "host", "l2cpu", "layout.py")
DEFINE_RE = re.compile(r"^\s*#\s*define\s+(L2CPU_[A-Za-z0-9_]+)\s+(.+?)\s*(?:/\*.*)?$")


def parse(path):
    consts, order = {}, []
    for line in open(path):
        m = DEFINE_RE.match(line)
        if not m:
            continue
        name, value = m.group(1), m.group(2)
        expr = re.sub(r"/\*.*?\*/", "", value).strip()
        expr = re.sub(r"\b(0[xX][0-9a-fA-F]+|\d+)([uU]?[lL]{0,2})\b", r"\1", expr).replace("/", "//")
        if not expr or re.search(r"[^0-9A-Za-z_xX+\-*()<>|& /~ ]", expr):
            continue
        try:
            val = eval(expr, {"__builtins__": {}}, dict(consts))
        except Exception:
            continue
        if isinstance(val, int):
            consts[name] = val
            order.append(name)
    return consts, order


def render():
    consts, order = parse(HEADER)
    digest = hashlib.sha256(open(HEADER, "rb").read()).hexdigest()[:16]
    lines = [
        "# SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.",
        "# SPDX-FileCopyrightText: © 2026 Kansei Motoe (kinginu)",
        "# SPDX-License-Identifier: Apache-2.0",
        '"""GENERATED by tools/l2cpu/tools/gen_boot_py.py from tools/l2cpu/include/l2cpu_boot.h. DO NOT EDIT."""',
        "",
        f'HEADER_SHA256_16 = "{digest}"',
        "",
    ]
    lines += [f"{n} = {f'0x{consts[n]:X}' if consts[n] >= 16 else consts[n]}" for n in order]
    lines += ["", "CONSTANTS = {"] + [f'    "{n}": {n},' for n in order] + ["}", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print(f"{OUT} is stale: run {__file__}")
            return 1
        print("layout mirror is current")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Generate a training config for one FSDP/DDP benchmark point.

One generator instead of a directory of near-identical YAML files: every knob that varied in the
study is a flag, the rest is fixed so two configs differ only in what the flags say.

    python make_config.py --model tinyllama --mode fsdp --mesh 8 --samples 1 --overlap > cfg.yaml
    python make_config.py --model llama8b --mode fsdp --tp 4 --mesh 8 --samples 2 --memeff --overlap columns=1

``--samples`` is the number of samples (of 2048 tokens) per device; ``batch_size`` is derived so the
DDP and FSDP points of one mesh size see the same data. Model configs come from the repo
(``configs/model_configs``); ``--memeff`` points at the copies in ``configs/`` here that switch the
block runner to gradient checkpointing (a model config cannot be overridden from the training YAML).
"""

import argparse
import sys

KIT = "${TT_METAL_RUNTIME_ROOT}/tt-train/tools/profiling/fsdp_bench/configs"
MODELS = {
    "tinyllama": {
        "model_config": "${TT_METAL_RUNTIME_ROOT}/tt-train/configs/model_configs/tinyllama_bpe.yaml",
        "memeff_model_config": f"{KIT}/tinyllama_bpe_memeff.yaml",
        "data_path": "data/tokenized_shakespeare_tinyllama.yaml",
        "lr": 3.0e-4,
        "weight_decay": 0.01,
        "beta2": 0.999,
    },
    "llama8b": {
        "model_config": "${TT_METAL_RUNTIME_ROOT}/tt-train/configs/model_configs/llama8b.yaml",
        "memeff_model_config": f"{KIT}/llama8b_memeff.yaml",
        "data_path": "data/tokenized_shakespeare_llama8b.yaml",
        "lr": 1.0e-4,
        "weight_decay": 0.1,
        "beta2": 0.95,
    },
}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", choices=sorted(MODELS), default="tinyllama")
    ap.add_argument("--mode", choices=["fsdp", "ddp"], default="fsdp")
    ap.add_argument("--mesh", type=int, default=8, help="data-parallel axis size")
    ap.add_argument("--tp", type=int, default=1, help="tensor-parallel axis size (second mesh axis)")
    ap.add_argument("--samples", type=int, default=1, help="samples of 2048 tokens per device (per TP group)")
    ap.add_argument("--ga", type=int, default=1, help="gradient accumulation steps")
    ap.add_argument("--steps", type=int, default=12)
    ap.add_argument("--memeff", action="store_true", help="gradient-checkpointing block runner")
    ap.add_argument("--overlap", nargs="?", const="columns=1", default=None, help="e.g. columns=1 or rows=1")
    ap.add_argument("--keep-gathered-gib", type=float, default=None)
    ap.add_argument("--name", default=None)
    args = ap.parse_args()

    m = MODELS[args.model]
    name = args.name or (
        f"{args.model}_{args.mode}{args.mesh}"
        + (f"_tp{args.tp}" if args.tp > 1 else "")
        + f"_s{args.samples}"
        + (f"_ga{args.ga}" if args.ga > 1 else "")
        + ("_memeff" if args.memeff else "")
        + (f"_ovl_{args.overlap.replace('=', '')}" if args.overlap else "")
    )
    device = [f"  mesh_shape: [{args.mesh}, {args.tp}]"]
    device.append("  enable_fsdp: true" if args.mode == "fsdp" else "  enable_ddp: true")
    if args.tp > 1:
        device.append("  enable_tp: true")
    if args.overlap:
        kind, count = args.overlap.split("=")
        if kind not in ("rows", "columns"):
            sys.exit("--overlap takes rows=N or columns=N")
        device.append("  fsdp_overlap_collectives: true")
        device.append(f"  fsdp_ccl_subdevice: {{{kind}: {int(count)}}}")
    if args.keep_gathered_gib is not None:
        device.append(f"  fsdp_keep_gathered_gib: {args.keep_gathered_gib}")

    lines = [
        f"# generated by make_config.py: {' '.join(sys.argv[1:])}",
        "training_config:",
        f'  project_name: "fsdp_bench_{name}"',
        "  seed: 5489",
        "  model_save_interval: 0",
        f"  batch_size: {args.samples * args.mesh}",
        f"  gradient_accumulation_steps: {args.ga}",
        f"  max_steps: {args.steps}",
        "  use_clip_grad_norm: false",
        "  clip_grad_norm_max_norm: 1.0",
        "  tokenizer_type: bpe",
        f'  data_path: "{m["data_path"]}"',
        f'  model_config: "{m["memeff_model_config" if args.memeff else "model_config"]}"',
        "  optimizer:",
        "    type: AdamW",
        f"    lr: {m['lr']}",
        "    beta1: 0.9",
        f"    beta2: {m['beta2']}",
        "    epsilon: 1.0e-8",
        f"    weight_decay: {m['weight_decay']}",
        "device_config:",
        *device,
        "eval_config:",
        "  repetition_penalty: 1.0",
        "  temperature: 0.7",
        "  top_k: 50",
        "  top_p: 1.0",
    ]
    print("\n".join(lines))


if __name__ == "__main__":
    main()

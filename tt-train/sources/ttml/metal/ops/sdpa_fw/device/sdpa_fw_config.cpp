SDPAForwardCbTiles cb_tiles(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks) {
    const uint32_t rows = chunks.rows();
    const uint32_t Sq = chunks.Sq_chunk_t;
    const uint32_t Sk = chunks.Sk_chunk_t;
    uint32_t attn_mask = 0U;
    if (shape.mask_type == AttentionMaskType::Causal) {
        attn_mask = kNumCausalMaskTiles;
    } else if (shape.mask_type == AttentionMaskType::Arbitrary) {
        attn_mask = 2U * Sq * Sk;  // per step, shared by the stacked heads, double-buffered
    }
    return SDPAForwardCbTiles{
        .query = 2U * rows * shape.qWt,
        .key = 2U * Sk * shape.qWt,
        .value = 2U * Sk * shape.vWt,
        .attn_mask = attn_mask,
        .gate = shape.has_gate ? 2U * rows * shape.vWt : 0U,
        .intermediate = shape.return_intermediates ? rows * kIntermediateTiles : 0U,
        // The compute kernel rewrites the attention weights and the stats in place (pop, reserve, pack at
        // the same offsets). That only works while each CB holds exactly one block, so these must stay
        // single-buffered.
        .attention_weights = rows * Sk,
        .stat = rows,
        .mm_out = rows * shape.vWt,
        .output = rows * shape.vWt};
}

uint64_t l1_bytes(const SDPAForwardCbTiles& t) {
    constexpr uint32_t kScalerTiles = 2U;  // reduction scaler + matmul reduce tile
    const uint64_t bf16_tiles =
        t.query + t.key + t.value + t.attn_mask + t.gate + kScalerTiles + 2U * t.stat + t.output;
    const uint64_t fp32_tiles = t.intermediate + t.attention_weights + 3U * t.stat + 2U * t.mm_out;
    return bf16_tiles * kBf16TileBytes + fp32_tiles * kFp32TileBytes;
}

uint32_t num_work_items(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks) {
    const uint32_t num_stacks = shape.batch * shape.q_heads / chunks.heads_per_item;
    return num_stacks * (shape.St / chunks.Sq_chunk_t);
}

uint32_t num_kv_steps(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks, uint32_t item) {
    const uint32_t q_num_chunks = shape.St / chunks.Sq_chunk_t;
    return sdpa_fw_items::num_kv_steps_of_chunk(
        shape.mask_type == AttentionMaskType::Causal,
        shape.St,
        chunks.Sq_chunk_t,
        chunks.Sk_chunk_t,
        sdpa_fw_items::first_row_tile_of(item, q_num_chunks, chunks.Sq_chunk_t));
}

SDPAForwardShape shape_of(
    const ttnn::Tensor& query,
    const ttnn::Tensor& key,
    const ttnn::Tensor& value,
    AttentionMaskType mask_type,
    bool has_gate,
    bool return_intermediates) {
    const auto [qB, qNH, qS, qE] = query.padded_shape().to_array_4D();
    return SDPAForwardShape{
        .batch = qB,
        .q_heads = qNH,
        .kv_heads = key.padded_shape()[1],
        .St = qS / tt::constants::TILE_HEIGHT,
        .qWt = qE / tt::constants::TILE_WIDTH,
        .vWt = value.padded_shape()[-1] / tt::constants::TILE_WIDTH,
        .mask_type = mask_type,
        .has_gate = has_gate,
        .return_intermediates = return_intermediates};
}

uint64_t l1_budget_bytes(const tt::tt_metal::IDevice* device) {
    return device->l1_size_per_core() - device->allocator()->get_base_allocator_addr(tt::tt_metal::HalMemType::L1);
}

std::vector<CoreItemRuns> split_work(
    const SDPAForwardShape& shape, const SDPAForwardChunks& chunks, uint32_t num_cores) {
    const uint32_t total_items = num_work_items(shape, chunks);
    TT_FATAL(num_cores > 0 && num_cores <= total_items, "split_work: need 1..{} cores, got {}", total_items, num_cores);
    // Causal with an even chunk count and enough pairs for every core: heavy/light chunk pairs.
    const uint32_t q_num_chunks = shape.St / chunks.Sq_chunk_t;
    const uint32_t num_stacks = shape.batch * shape.q_heads / chunks.heads_per_item;
    const uint32_t total_pairs = num_stacks * (q_num_chunks / 2U);
    std::vector<CoreItemRuns> per_core_runs;
    if (shape.mask_type == AttentionMaskType::Causal && q_num_chunks % 2U == 0U && total_pairs >= num_cores) {
        per_core_runs = split_items_paired(num_stacks, q_num_chunks, num_cores);
    }
    if (per_core_runs.empty() || !fits_runtime_args(per_core_runs)) {
        per_core_runs = split_items_contiguous(total_items, num_cores);
    }
    return per_core_runs;
}

double predict_us(
    const SDPAForwardShape& shape,
    const SDPAForwardChunks& chunks,
    const std::vector<CoreItemRuns>& per_core_runs,
    uint32_t num_cores) {
    const double step = step_us(shape, chunks, num_cores);
    const double fixed = item_fixed_us(shape, chunks, num_cores);
    double busiest = 0.0;
    for (const auto& runs : per_core_runs) {
        double core_us = 0.0;
        for (const auto& run : runs) {
            for (uint32_t item = run.first_item; item < run.first_item + run.num_items; ++item) {
                core_us += fixed + step * num_kv_steps(shape, chunks, item);
            }
        }
        busiest = std::max(busiest, core_us);
    }
    return busiest;
}

namespace {

// The user's knobs in tiles, 0 = unset; throws on an invalid knob.
SDPAForwardChunks user_chunks(const SDPAForwardProgramConfig& config, const SDPAForwardShape& shape) {
    const uint32_t heads_per_group = shape.q_heads / shape.kv_heads;
    const SDPAForwardChunks user{
        .Sq_chunk_t = chunk_size_to_tiles(config.q_chunk_size, shape.St, "q_chunk_size"),
        .Sk_chunk_t = chunk_size_to_tiles(config.k_chunk_size, shape.St, "k_chunk_size"),
        .heads_per_item = config.heads_per_item};
    TT_FATAL(
        heads_per_group % std::max(user.heads_per_item, 1U) == 0U,
        "heads_per_item ({}) must divide the number of query heads per key/value head ({})",
        user.heads_per_item,
        heads_per_group);
    return user;
}

void check_l1(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks, uint64_t l1_budget_bytes) {
    const uint64_t bytes = l1_bytes(cb_tiles(shape, chunks));
    TT_FATAL(
        bytes <= l1_budget_bytes,
        "SDPA forward circular buffers need {} bytes of L1 per core but only {} are available. Reduce "
        "q_chunk_size ({} rows), k_chunk_size ({} rows) or heads_per_item ({}); 0 = pick.",
        bytes,
        l1_budget_bytes,
        chunks.Sq_chunk_t * tt::constants::TILE_HEIGHT,
        chunks.Sk_chunk_t * tt::constants::TILE_HEIGHT,
        chunks.heads_per_item);
}

}  // namespace

void check_chunks(const SDPAForwardProgramConfig& config, const SDPAForwardShape& shape, uint64_t l1_budget_bytes) {
    const SDPAForwardChunks user = user_chunks(config, shape);
    if (user.Sq_chunk_t != 0U && user.Sk_chunk_t != 0U && user.heads_per_item != 0U) {
        check_l1(shape, user, l1_budget_bytes);
    }
}

SDPAForwardChunks resolve_chunks(
    const SDPAForwardProgramConfig& config,
    const SDPAForwardShape& shape,
    uint64_t l1_budget_bytes,
    uint32_t num_available_cores) {
    const uint32_t heads_per_group = shape.q_heads / shape.kv_heads;
    const SDPAForwardChunks user = user_chunks(config, shape);
    if (user.Sq_chunk_t != 0U && user.Sk_chunk_t != 0U && user.heads_per_item != 0U) {
        check_l1(shape, user, l1_budget_bytes);
        return user;
    }

    // Candidates for the unset knobs: the chunk sizes that divide the sequence, up to the sizes beyond
    // which the gain flattens out; head stacks that divide the group.
    auto candidates = [](uint32_t fixed, std::initializer_list<uint32_t> options, uint32_t divides) {
        std::vector<uint32_t> out;
        if (fixed != 0U) {
            out.push_back(fixed);
            return out;
        }
        for (const uint32_t c : options) {
            if (divides % c == 0U) {
                out.push_back(c);
            }
        }
        return out;
    };
    const auto sq_options = candidates(user.Sq_chunk_t, {1U, 2U, 4U, 8U}, shape.St);
    const auto sk_options = candidates(user.Sk_chunk_t, {1U, 2U, 4U, 8U, 16U}, shape.St);
    const auto h_options = candidates(user.heads_per_item, {1U, 2U, 4U, 8U}, heads_per_group);

    SDPAForwardChunks best{};
    double best_us = std::numeric_limits<double>::infinity();
    uint64_t smallest_l1 = std::numeric_limits<uint64_t>::max();
    for (const uint32_t h : h_options) {
        for (const uint32_t Sq : sq_options) {
            for (const uint32_t Sk : sk_options) {
                const SDPAForwardChunks chunks{.Sq_chunk_t = Sq, .Sk_chunk_t = Sk, .heads_per_item = h};
                const uint64_t bytes = l1_bytes(cb_tiles(shape, chunks));
                smallest_l1 = std::min(smallest_l1, bytes);
                if (bytes > l1_budget_bytes) {
                    continue;
                }
                const uint32_t num_cores = std::min(num_available_cores, num_work_items(shape, chunks));
                const double us = predict_us(shape, chunks, split_work(shape, chunks, num_cores), num_cores);
                if (us < best_us) {
                    best_us = us;
                    best = chunks;
                }
            }
        }
    }
    TT_FATAL(
        best_us < std::numeric_limits<double>::infinity(),
        "SDPA forward circular buffers need at least {} bytes of L1 per core but only {} are available. "
        "Reduce q_chunk_size, k_chunk_size or heads_per_item (0 = pick).",
        smallest_l1,
        l1_budget_bytes);
    log_debug(
        tt::LogOp,
        "sdpa_fw chunks: Sq={} Sk={} heads={} (predicted {:.0f} us on {} cores, L1 budget {} B)",
        best.Sq_chunk_t,
        best.Sk_chunk_t,
        best.heads_per_item,
        best_us,
        num_available_cores,
        l1_budget_bytes);
    return best;
}


SDPAForwardCbTiles cb_tiles(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks) {
    const uint32_t rows = chunks.rows();
    const uint32_t Sq = chunks.Sq_chunk_t;
    const uint32_t Sk = chunks.Sk_chunk_t;
    uint32_t attn_mask = 0U;
    if (shape.mask_type == AttentionMaskType::Causal) {
        attn_mask = kNumCausalMaskTiles;
    } else if (shape.mask_type == AttentionMaskType::Arbitrary) {
        attn_mask = 2U * Sq * Sk;  // per step, shared by the stacked heads, double-buffered
    }
    return SDPAForwardCbTiles{
        .query = 2U * rows * shape.qWt,
        .key = 2U * Sk * shape.qWt,
        .value = 2U * Sk * shape.vWt,
        .attn_mask = attn_mask,
        .gate = shape.has_gate ? 2U * rows * shape.vWt : 0U,
        .intermediate = shape.return_intermediates ? rows * kIntermediateTiles : 0U,
        // The compute kernel rewrites the attention weights and the stats in place (pop, reserve, pack at
        // the same offsets). That only works while each CB holds exactly one block, so these must stay
        // single-buffered.
        .attention_weights = rows * Sk,
        .stat = rows,
        .mm_out = rows * shape.vWt,
        .output = rows * shape.vWt,
        .reduction_scaler = 1U,
        .matmul_reduce = 1U};
}

std::array<SDPAForwardCb, kNumSDPAForwardCbs> cb_plan(const SDPAForwardCbTiles& t) {
    // The inputs, the constant tiles, the max and the output are bf16 like the tensors; the scores, the
    // running sums, the rescale factor, the P @ V accumulator and the lse are fp32. The max can stay bf16
    // although the scores are fp32: P, alpha and the lse all use the same rounded max, so its rounding
    // cancels in O / sum and in the lse.
    constexpr auto bf16 = tt::DataFormat::Float16_b;
    constexpr auto fp32 = tt::DataFormat::Float32;
    return {{
        {kQueryCbIndex, bf16, t.query},
        {kKeyCbIndex, bf16, t.key},
        {kValueCbIndex, bf16, t.value},
        {kAttnMaskCbIndex, bf16, t.attn_mask},
        {kIntermediateCbIndex, fp32, t.intermediate},
        {kReductionScalerCbIndex, bf16, t.reduction_scaler},
        {kMatMulReduceCbIndex, bf16, t.matmul_reduce},
        {kAttentionWeightsCbIndex, fp32, t.attention_weights},
        {kPrevMaxValueCbIndex, bf16, t.stat},
        {kCurMaxValueCbIndex, bf16, t.stat},
        {kExpMaxDiffCbIndex, fp32, t.stat},
        {kPrevSumExpCbIndex, fp32, t.stat},
        {kCurSumExpCbIndex, fp32, t.stat},
        {kPrevMmOutCbIndex, fp32, t.mm_out},
        {kCurMmOutCbIndex, fp32, t.mm_out},
        {kOutputCbIndex, bf16, t.output},
        {kGateCbIndex, bf16, t.gate},
    }};
}

uint64_t l1_bytes(const SDPAForwardCbTiles& tiles) {
    uint64_t bytes = 0U;
    for (const SDPAForwardCb& cb : cb_plan(tiles)) {
        bytes += static_cast<uint64_t>(cb.tiles) * tt::tile_size(cb.format);
    }
    return bytes;
}

uint32_t num_work_items(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks) {
    const uint32_t num_stacks = shape.batch * shape.q_heads / chunks.heads_per_item;
    return sdpa_items::num_items(num_stacks, shape.St / chunks.Sq_chunk_t);
}

SDPAForwardShape shape_of(
    const ttnn::Tensor& query,
    const ttnn::Tensor& key,
    const ttnn::Tensor& value,
    AttentionMaskType mask_type,
    bool has_gate,
    bool return_intermediates) {
    const auto [qB, qNH, qS, qE] = query.padded_shape().to_array_4D();
    return SDPAForwardShape{
        .batch = qB,
        .q_heads = qNH,
        .kv_heads = key.padded_shape()[1],
        .St = qS / tt::constants::TILE_HEIGHT,
        .qWt = qE / tt::constants::TILE_WIDTH,
        .vWt = value.padded_shape()[-1] / tt::constants::TILE_WIDTH,
        .mask_type = mask_type,
        .has_gate = has_gate,
        .return_intermediates = return_intermediates};
}

uint32_t num_kv_steps(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks, uint32_t item) {
    const uint32_t q_num_chunks = shape.St / chunks.Sq_chunk_t;
    return sdpa_items::num_kv_steps_of_chunk(
        shape.mask_type == AttentionMaskType::Causal,
        shape.St,
        chunks.Sq_chunk_t,
        chunks.Sk_chunk_t,
        sdpa_items::first_row_tile_of(item, q_num_chunks, chunks.Sq_chunk_t));
}

std::vector<CoreItemRuns> split_work(
    const SDPAForwardShape& shape, const SDPAForwardChunks& chunks, uint32_t num_cores) {
    const uint32_t total_items = num_work_items(shape, chunks);
    TT_FATAL(num_cores > 0 && num_cores <= total_items, "split_work: need 1..{} cores, got {}", total_items, num_cores);
    std::vector<CoreItemRuns> per_core_runs;
    if (shape.mask_type == AttentionMaskType::Causal) {
        std::vector<uint32_t> item_costs(total_items);
        for (uint32_t item = 0; item < total_items; ++item) {
            item_costs[item] = num_kv_steps(shape, chunks, item);
        }
        per_core_runs = split_items_longest_first(item_costs, num_cores);
    }
    return split_items_contiguous(num_work_items(shape, chunks), num_cores);  // one run per core: always fits
}

namespace {

// The user's knobs in tiles, 0 = unset; throws on an invalid knob.
SDPAForwardChunks user_chunks(const SDPAForwardProgramConfig& config, const SDPAForwardShape& shape) {
    const uint32_t heads_per_group = shape.q_heads / shape.kv_heads;
    const SDPAForwardChunks user{
        .Sq_chunk_t = chunk_size_to_tiles(config.q_chunk_size, shape.St, "q_chunk_size"),
        .Sk_chunk_t = chunk_size_to_tiles(config.k_chunk_size, shape.St, "k_chunk_size"),
        .heads_per_item = config.heads_per_item};
    TT_FATAL(
        heads_per_group % std::max(user.heads_per_item, 1U) == 0U,
        "heads_per_item ({}) must divide the number of query heads per key/value head ({})",
        user.heads_per_item,
        heads_per_group);
    return user;
}

void check_l1(const SDPAForwardShape& shape, const SDPAForwardChunks& chunks, uint64_t l1_budget_bytes) {
    const uint64_t bytes = l1_bytes(cb_tiles(shape, chunks));
    TT_FATAL(
        bytes <= l1_budget_bytes,
        "SDPA forward circular buffers need {} bytes of L1 per core but only {} are available at q_chunk_size {} "
        "rows, k_chunk_size {} rows, heads_per_item {}. Reduce the pinned knobs; 0 = pick.",
        bytes,
        l1_budget_bytes,
        chunks.Sq_chunk_t * tt::constants::TILE_HEIGHT,
        chunks.Sk_chunk_t * tt::constants::TILE_HEIGHT,
        chunks.heads_per_item);
}

}  // namespace

void check_chunks(const SDPAForwardProgramConfig& config, const SDPAForwardShape& shape, uint64_t l1_budget_bytes) {
    const SDPAForwardChunks user = user_chunks(config, shape);
    // The pick only shrinks the unset knobs, down to one tile / one head, so the config fits at all iff it
    // fits with every unset knob at one. With all three pinned this is the final check.
    const SDPAForwardChunks floor{
        .Sq_chunk_t = std::max(user.Sq_chunk_t, 1U),
        .Sk_chunk_t = std::max(user.Sk_chunk_t, 1U),
        .heads_per_item = std::max(user.heads_per_item, 1U)};
    check_l1(shape, floor, l1_budget_bytes);
}

SDPAForwardChunks resolve_chunks(
    const SDPAForwardProgramConfig& config,
    const SDPAForwardShape& shape,
    uint64_t l1_budget_bytes,
    uint32_t num_available_cores) {
    const SDPAForwardChunks user = user_chunks(config, shape);
    if (user.Sq_chunk_t != 0U && user.Sk_chunk_t != 0U && user.heads_per_item != 0U) {
        check_l1(shape, user, l1_budget_bytes);
        return user;
    }

    // Shape rule for the unset knobs, from the chunk sweep on Blackhole (S=2048/4096, D=64/128, every mask
    // mode): four query tile-rows per item and eight K/V tiles per step win or tie everywhere they fit;
    // four K/V tiles do better once the inner dim reaches 128 tiles-wide traffic or with a mask tensor
    // (the step then reads mask tiles on top of K/V). More rows per item only pay off once the work is
    // scheduled by cost rather than paired, so heads_per_item stays 1 unless asked for. The chunks shrink
    // while they do not fit L1 or would leave cores idle.
    constexpr uint32_t kDefaultSqChunkT = 4U;
    const uint32_t default_sk_chunk_t = (shape.qWt >= 4U || shape.mask_type == AttentionMaskType::Arbitrary) ? 4U : 8U;
    SDPAForwardChunks chunks{
        .Sq_chunk_t = user.Sq_chunk_t,
        .Sk_chunk_t = user.Sk_chunk_t,
        .heads_per_item = std::max(user.heads_per_item, 1U)};
    if (chunks.Sq_chunk_t == 0U) {
        chunks.Sq_chunk_t = kDefaultSqChunkT;
        while (chunks.Sq_chunk_t > 1U &&
               (shape.St % chunks.Sq_chunk_t != 0U || num_work_items(shape, chunks) < num_available_cores)) {
            chunks.Sq_chunk_t /= 2U;
        }
    }
    // Shrink the picked (not the pinned) knobs while cores would idle: the rows first, then the stacking.
    const bool can_pair = shape.mask_type == AttentionMaskType::Causal && shape.St % 2U == 0U;
    const auto units_for_balance = [&]() {
        return can_pair ? num_causal_pairs(shape, chunks) : num_work_items(shape, chunks);
    };
    while (units_for_balance() < num_available_cores) {
        if (user.Sq_chunk_t == 0U && chunks.Sq_chunk_t > 1U) {
            chunks.Sq_chunk_t /= 2U;
        } else if (user.heads_per_item == 0U && chunks.heads_per_item > 1U) {
            chunks.heads_per_item /= 2U;
        } else {
            break;
        }
    }
    if (chunks.Sk_chunk_t == 0U) {
        const bool single_head_with_mask = has_mask_tensor && chunks.heads_per_item == 1U;
        chunks.Sk_chunk_t = (shape.qWt >= 4U || single_head_with_mask) ? 4U : 8U;
        while (chunks.Sk_chunk_t > 1U && shape.St % chunks.Sk_chunk_t != 0U) {
            chunks.Sk_chunk_t /= 2U;
        }
    }
    // Shrink the picked (not the pinned) knobs until the circular buffers fit: the K/V step first, then the
    // rows, then the stacking, so the floor is every unset knob at one, as check_chunks assumes.
    while (l1_bytes(cb_tiles(shape, chunks)) > l1_budget_bytes) {
        if (user.Sk_chunk_t == 0U && chunks.Sk_chunk_t > 1U) {
            chunks.Sk_chunk_t /= 2U;
        } else if (user.Sq_chunk_t == 0U && chunks.Sq_chunk_t > 1U) {
            chunks.Sq_chunk_t /= 2U;
        } else if (user.heads_per_item == 0U && chunks.heads_per_item > 1U) {
            chunks.heads_per_item /= 2U;
        } else {
            break;
        }
    }
    check_l1(shape, chunks, l1_budget_bytes);
    return chunks;
}


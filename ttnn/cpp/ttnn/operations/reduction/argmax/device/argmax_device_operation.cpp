/*
 * Generates the output shape for the reduction operation.
 * The output shape is generated by iterating over the input shape and adjusting
 * the output shape for keepdim.
 * @param input_tensor The input tensor on which reduction is performed.
 * @param dim The dimension to reduce on (optional).
 * @param keepdim Whether to keep the reduced dimension.
 * @return The output shape.
 */
ttsl::SmallVector<uint32_t> get_output_shape(const Tensor& input_tensor, const std::optional<int>& dim, bool keepdim) {
    auto input_shape = input_tensor.logical_shape();
    int rank = input_shape.size();
    ttsl::SmallVector<uint32_t> output_shape;

    // If no reduction dims are specified, we reduce all dimensions
    auto all_dim_reduce = not dim.has_value();
    auto red_dim = dim.value_or(0);
    TT_FATAL(
        (rank == 0) or ((red_dim >= -rank) and (red_dim < rank)),
        "Invalid reduction dimension {} for input tensor with rank {}",
        red_dim,
        rank);

    // Adjust negative reduction dimension to positive
    red_dim = normalize_dim(red_dim, rank);

    // Generate output shape
    // Iterate over the input shape and adjust the output shape for keepdim
    for (int d = 0; d < rank; ++d) {
        // If this is in the reduction dims, keep it only if keepdim is true
        bool is_reduction_dim = all_dim_reduce or (d == red_dim);

        if (is_reduction_dim) {
            TT_FATAL(input_shape[d] != 0, "Expected reduction dim {} to have non-zero size", d);
            if (keepdim) {
                output_shape.push_back(1);
            }
        } else {
            // If this is not a reduction dim, we keep the original size
            output_shape.push_back(input_shape[d]);
        }
    }

    return output_shape;
}

ArgMaxDeviceOperation::program_factory_t ArgMaxDeviceOperation::select_program_factory(
    const operation_attributes_t& args, const tensor_args_t& tensor_args) {
    if (args.use_rvv) {
        // Eligibility is enforced in validate_on_program_cache_miss.
        return ArgMaxRvvTileProgramFactory{};
    }
    if (args.use_sfpu) {
        // Eligibility is enforced in validate_on_program_cache_miss.
        return ArgMaxSfpuTileProgramFactory{};
    }
    if (uses_multicore_path(args, tensor_args)) {
        return ArgMaxMultiCoreProgramFactory{};
    }
    return ArgMaxSingleCoreProgramFactory{};
}

void ArgMaxDeviceOperation::validate_on_program_cache_miss(
    const operation_attributes_t& args, const tensor_args_t& tensor_args) {
    const auto& input_tensor_a = tensor_args.input;
    const auto input_layout = input_tensor_a.layout();

    TT_FATAL(
        input_tensor_a.memory_config().memory_layout() == TensorMemoryLayout::INTERLEAVED,
        "Only INTERLEAVED memory layout is supported for inputs, got {}",
        input_tensor_a.memory_config().memory_layout());

    if (input_layout == Layout::ROW_MAJOR) {
        TT_FATAL(
            input_tensor_a.dtype() == DataType::BFLOAT16 || input_tensor_a.dtype() == DataType::FLOAT32 ||
                input_tensor_a.dtype() == DataType::INT32 || input_tensor_a.dtype() == DataType::UINT32 ||
                input_tensor_a.dtype() == DataType::UINT16,
            "Only BFLOAT16, FLOAT32, INT32, UINT32, and UINT16 are supported for inputs with ROW_MAJOR layout, got {}",
            input_tensor_a.dtype());
    } else {
        TT_FATAL(
            input_tensor_a.dtype() == DataType::BFLOAT16 || input_tensor_a.dtype() == DataType::FLOAT32,
            "Only BFLOAT16, FLOAT32 are supported for inputs with TILE layout, got {}",
            input_tensor_a.dtype());

        const auto& input_shape = input_tensor_a.padded_shape();
        auto rank = input_shape.size();
        // With TILE layout, padded shape has always at least 2 dims (i.e., also for 1D input tensors).
        TT_FATAL(rank > 1, "Invalid rank {} for input tensor with TILE layout", rank);
        const uint32_t tile_width = input_tensor_a.tensor_spec().tile().get_width();
        const uint32_t tile_height = input_tensor_a.tensor_spec().tile().get_height();
        TT_FATAL(
            input_shape[rank - 1] % tile_width == 0,
            "Last dimension {} must be divisible by tile width {}",
            input_shape[rank - 1],
            tile_width);
        TT_FATAL(
            input_shape[rank - 2] % tile_height == 0,
            "Second-to-last dimension {} must be divisible by tile height {}",
            input_shape[rank - 2],
            tile_height);
    }

    TT_FATAL(args.output_dtype == DataType::UINT32, "Only UINT32 is supported for outputs, got {}", args.output_dtype);

    TT_FATAL(
        args.output_mem_config.memory_layout() == TensorMemoryLayout::INTERLEAVED,
        "Only INTERLEAVED memory layout is supported for outputs, got {}",
        args.output_mem_config.memory_layout());

    const auto& optional_output_tensor = tensor_args.optional_output_tensor;
    if (optional_output_tensor.has_value()) {
        TT_FATAL(
            optional_output_tensor.value().dtype() == DataType::UINT32,
            "Only UINT32 is supported for outputs, got {}",
            optional_output_tensor.value().dtype());
        TT_FATAL(
            optional_output_tensor.value().memory_config().memory_layout() == TensorMemoryLayout::INTERLEAVED,
            "Only INTERLEAVED memory layout is supported for outputs, got {}",
            optional_output_tensor.value().memory_config().memory_layout());
        TT_FATAL(
            optional_output_tensor.value().layout() == Layout::ROW_MAJOR,
            "Output tensor must have ROW_MAJOR layout, got {}",
            optional_output_tensor.value().layout());
    }

    if (args.dim.has_value()) {
        const int32_t rank = static_cast<int32_t>(input_tensor_a.logical_shape().rank());
        const int32_t normalized_dim = normalize_dim(static_cast<int32_t>(args.dim.value()), rank);
        if (input_layout == Layout::TILE) {
            // Last dim: W, second-to-last: H.
            const bool w_dim = (normalized_dim == rank - 1);
            const bool h_dim = (rank >= 2 && normalized_dim == rank - 2);
            TT_FATAL(
                w_dim or h_dim,
                "TILE: argmax dim must be H (rank-2) or W (last). Got dim={} (normalized={}) for rank {}.",
                args.dim.value(),
                normalized_dim,
                rank);
        } else {
            TT_FATAL(
                normalized_dim == (rank - 1),
                "ROW_MAJOR: only argmax on the last dim is supported. Got dim={} (normalized={}), expected {}",
                args.dim.value(),
                normalized_dim,
                rank - 1);
        }
    } else {
        TT_FATAL(input_layout != Layout::TILE, "For inputs with TILE layout, dim parameter must be specified!");
    }

    if (uses_multicore_path(args, tensor_args)) {
        if (args.sub_core_grids.has_value()) {
            TT_FATAL(
                args.sub_core_grids->ranges().size() <= 2,
                "Multicore argmax only supports up to 2 core grid ranges, but got {} ranges",
                args.sub_core_grids->ranges().size());
        }
        TT_FATAL(
            input_tensor_a.layout() == Layout::ROW_MAJOR,
            "Multicore argmax only supports ROW_MAJOR layout for inputs, got {}. "
            "(ROW_MAJOR tensors reduced along height are converted to TILE internally; that path uses single-core "
            "argmax.)",
            input_tensor_a.layout());
    }

    if (uses_multicore_path(args, tensor_args) && args.sub_core_grids.has_value()) {
        ReduceOpDeviceGridValidationOptions grid_opts;
        grid_opts.sub_grid_contained_in_device_grid = &args.sub_core_grids.value();
        grid_opts.sub_grid_label = "Multicore argmax sub_core_grids";
        validate_reduce_op_tensor(tensor_args.input, "Argmax", "input", &grid_opts);
    }

    // RVV (Zve32f pack-RISC) path eligibility — opt-in, so requesting it with
    // an unsupported configuration is a hard error rather than a silent
    // fallback (keeps A/B measurements unambiguous).
    if (args.use_rvv) {
        TT_FATAL(
            tt::tt_metal::hal::get_arch() == tt::ARCH::BLACKHOLE,
            "argmax use_rvv=true requires a Blackhole device (TRISC vector unit)");
        TT_FATAL(input_layout == Layout::TILE, "argmax use_rvv=true requires TILE layout input, got {}", input_layout);
        TT_FATAL(
            input_tensor_a.dtype() == DataType::BFLOAT16,
            "argmax use_rvv=true requires BFLOAT16 input, got {}",
            input_tensor_a.dtype());
        TT_FATAL(args.dim.has_value(), "argmax use_rvv=true requires an explicit dim (last dim)");
        const int32_t rank = static_cast<int32_t>(input_tensor_a.logical_shape().rank());
        const int32_t normalized_dim = normalize_dim(static_cast<int32_t>(args.dim.value()), rank);
        TT_FATAL(
            normalized_dim == rank - 1,
            "argmax use_rvv=true supports only last-dim reduction, got dim={} (normalized={}) for rank {}",
            args.dim.value(),
            normalized_dim,
            rank);
        const uint32_t tile_w = input_tensor_a.tensor_spec().tile().get_width();
        const uint32_t tile_h = input_tensor_a.tensor_spec().tile().get_height();
        TT_FATAL(tile_w == 32 && tile_h == 32, "argmax use_rvv=true requires standard 32x32 tiles");
        const auto& logical_shape = input_tensor_a.logical_shape();
        TT_FATAL(
            logical_shape[-1] % tile_w == 0,
            "argmax use_rvv=true requires the reduction dim ({}) to be a multiple of the tile width {} "
            "(no width padding)",
            logical_shape[-1],
            tile_w);
    }

    // SFPU TILE last-dim path eligibility — like use_rvv, this is opt-in, so
    // requesting it with an unsupported configuration is a hard error rather
    // than a silent fallback.
    TT_FATAL(!(args.use_rvv && args.use_sfpu), "argmax: use_rvv and use_sfpu are mutually exclusive");
    if (args.use_sfpu) {
        // Blackhole-only for now: the path's special-value semantics (the
        // NaN-as-infinity / flush-to-zero gasket documented in
        // argmax_sfpu_tile_compute.cpp) are silicon-validated on Blackhole.
        // Nothing in the kernels is architecturally Blackhole-specific;
        // enabling Wormhole is a follow-up gated on re-running the
        // special-value battery there.
        TT_FATAL(
            tt::tt_metal::hal::get_arch() == tt::ARCH::BLACKHOLE,
            "argmax use_sfpu=true is currently supported on Blackhole only");
        TT_FATAL(input_layout == Layout::TILE, "argmax use_sfpu=true requires TILE layout input, got {}", input_layout);
        TT_FATAL(
            input_tensor_a.dtype() == DataType::BFLOAT16,
            "argmax use_sfpu=true requires BFLOAT16 input, got {}",
            input_tensor_a.dtype());
        TT_FATAL(args.dim.has_value(), "argmax use_sfpu=true requires an explicit dim (last dim)");
        const int32_t rank = static_cast<int32_t>(input_tensor_a.logical_shape().rank());
        const int32_t normalized_dim = normalize_dim(static_cast<int32_t>(args.dim.value()), rank);
        TT_FATAL(
            normalized_dim == rank - 1,
            "argmax use_sfpu=true supports only last-dim reduction, got dim={} (normalized={}) for rank {}",
            args.dim.value(),
            normalized_dim,
            rank);
        const uint32_t tile_w = input_tensor_a.tensor_spec().tile().get_width();
        const uint32_t tile_h = input_tensor_a.tensor_spec().tile().get_height();
        TT_FATAL(tile_w == 32 && tile_h == 32, "argmax use_sfpu=true requires standard 32x32 tiles");
        const auto& logical_shape = input_tensor_a.logical_shape();
        TT_FATAL(
            logical_shape[-1] % tile_w == 0,
            "argmax use_sfpu=true requires the reduction dim ({}) to be a multiple of the tile width {} "
            "(no width padding)",
            logical_shape[-1],
            tile_w);
    }

    const auto& optional_maxval = tensor_args.optional_maxval_tensor;
    if (optional_maxval.has_value()) {
        TT_FATAL(
            args.use_rvv || args.use_sfpu,
            "argmax max-value output is only produced by the use_rvv=true / use_sfpu=true paths");
        const auto& maxval = optional_maxval.value();
        TT_FATAL(is_device_tensor(maxval), "argmax max-value tensor must be allocated on device");
        // Device affinity: the program is launched from the input tensor, so a
        // maxval buffer on a different device/mesh would have its (foreign)
        // address bound into this device's kernel.
        TT_FATAL(
            maxval.device() == input_tensor_a.device(),
            "argmax max-value tensor must be on the same device/mesh as the input tensor");
        TT_FATAL(
            maxval.dtype() == DataType::BFLOAT16, "argmax max-value tensor must be BFLOAT16, got {}", maxval.dtype());
        TT_FATAL(
            maxval.layout() == Layout::ROW_MAJOR, "argmax max-value tensor must be ROW_MAJOR, got {}", maxval.layout());
        TT_FATAL(
            maxval.memory_config().memory_layout() == TensorMemoryLayout::INTERLEAVED,
            "argmax max-value tensor must be INTERLEAVED, got {}",
            maxval.memory_config().memory_layout());
        const auto expected_shape = ttnn::Shape(get_output_shape(input_tensor_a, args.dim, args.keepdim));
        TT_FATAL(
            maxval.logical_shape() == expected_shape,
            "argmax max-value tensor has shape {}, expected the index output shape {}",
            maxval.logical_shape(),
            expected_shape);
    }
}

tt::tt_metal::TensorSpec ArgMaxDeviceOperation::compute_output_specs(
    const operation_attributes_t& args, const tensor_args_t& tensor_args) {
    if (tensor_args.optional_output_tensor.has_value()) {
        return tensor_args.optional_output_tensor->tensor_spec();
    }

    const auto& input_tensor = tensor_args.input;
    auto output_shape = get_output_shape(input_tensor, args.dim, args.keepdim);
    return tt::tt_metal::TensorSpec(
        ttnn::Shape(output_shape),
        TensorLayout(args.output_dtype, PageConfig(Layout::ROW_MAJOR), args.output_mem_config));
}

Tensor ArgMaxDeviceOperation::create_output_tensors(
    const operation_attributes_t& args, const tensor_args_t& tensor_args) {
    if (tensor_args.optional_output_tensor.has_value()) {
        return tensor_args.optional_output_tensor.value();
    }
    return create_device_tensor(compute_output_specs(args, tensor_args), tensor_args.input.device());
}

ttnn::Tensor argmax(
    const ttnn::Tensor& input,
    tt::tt_metal::DataType output_dtype,
    std::optional<int> dim,
    bool keepdim,
    const std::optional<CoreRangeSet>& sub_core_grids,
    const tt::tt_metal::MemoryConfig& output_mem_config,
    std::optional<ttnn::Tensor> optional_output_tensor,
    bool use_rvv,
    bool use_sfpu,
    std::optional<ttnn::Tensor> optional_maxval_tensor) {
    return ttnn::device_operation::launch<ArgMaxDeviceOperation>(
        ArgMaxDeviceOperation::operation_attributes_t{
            .output_dtype = output_dtype,
            .dim = dim,
            .keepdim = keepdim,
            .sub_core_grids = sub_core_grids,
            .output_mem_config = output_mem_config,
            .use_rvv = use_rvv,
            .use_sfpu = use_sfpu,
        },
        ArgMaxDeviceOperation::tensor_args_t{
            .input = input,
            .optional_output_tensor = std::move(optional_output_tensor),
            .optional_maxval_tensor = std::move(optional_maxval_tensor)});
}


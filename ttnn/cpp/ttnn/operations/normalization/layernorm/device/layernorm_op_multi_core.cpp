// Dataflow buffer identities. Each name carries the role its buffer plays in the layernorm
// pipeline and nothing else: the `dfb::` namespace the kernels see already says these are
// buffers, so no prefix repeats it.
const m2::DFBSpecName IN{"in"};                    // input x, or a for fused pre-add (x = a + b)
const m2::DFBSpecName INB{"inb"};                  // input b for fused pre-add
const m2::DFBSpecName SCALER{"scaler"};            // reduce scaler, generated by the reader
const m2::DFBSpecName EPS{"eps"};                  // epsilon tile, generated by the reader
const m2::DFBSpecName GAMMA{"gamma"};              // gamma (weight) tiles
const m2::DFBSpecName BETA{"beta"};                // beta (bias) tiles
const m2::DFBSpecName OUT{"out"};                  // output
const m2::DFBSpecName EX{"ex"};                    // E[x]
const m2::DFBSpecName EX2{"ex2"};                  // E[(x-E[x])^2]
const m2::DFBSpecName XMM2{"xmm2"};                // (x-E[x])^2
const m2::DFBSpecName EX2PE{"ex2pe"};              // E[(x-E[x])^2] + eps
const m2::DFBSpecName FUSION{"fusion"};            // gamma/beta streaming intermediate
const m2::DFBSpecName X{"x"};                      // x = a + b, the fused pre-add result
const m2::DFBSpecName XMM{"xmm"};                  // x - E[x]
const m2::DFBSpecName RECIPROCALS{"reciprocals"};  // pre-computed reciprocal LUT for Welford
const m2::DFBSpecName ACCUMULATE{"accumulate"};    // large-tensor variance accumulator
const m2::DFBSpecName IN_RM{"in_rm"};              // row-major input staging for in-flight tilize
const m2::DFBSpecName OUT_RM{"out_rm"};            // row-major output staging for the RM writer

// Welford fp32 aliases. Each shares its primary buffer's SRAM under a second index so the
// Welford section can read it with UnpackToDest (full fp32) while the surrounding FPU work keeps
// reading the primary index through SrcA. Present only when the matching alias gate holds;
// otherwise the kernel-side name falls back to the primary buffer's own handle.
const m2::DFBSpecName X_WELFORD{"x_welford"};      // alias of X (fused) or IN (non-fused)
const m2::DFBSpecName EX_WELFORD{"ex_welford"};    // alias of EX
const m2::DFBSpecName EX2_WELFORD{"ex2_welford"};  // alias of EX2

// Tensor parameter identities.
const m2::TensorParamName INPUT{"input"};
const m2::TensorParamName RESIDUAL{"residual"};
const m2::TensorParamName GAMMA_T{"weight"};
const m2::TensorParamName BETA_T{"bias"};
const m2::TensorParamName OUTPUT{"output"};
// Backing store for the RECIPROCALS buffer. No kernel binds an accessor to it: the Welford
// compute kernels reach the LUT through the borrowed buffer's base pointer, so the tensor exists
// in the spec purely to resolve that buffer's address at each enqueue.
const m2::TensorParamName RECIP{"recip"};

void bind_dfb(m2::KernelSpec& kernel, const m2::DFBSpecName& dfb, std::string accessor_name, m2::DFBEndpointType role) {
    kernel.dfb_bindings.push_back(m2::DFBBinding{
        .dfb_spec_name = dfb,
        .accessor_name = std::move(accessor_name),
        .endpoint_type = role,
    });
}

// Bind a buffer the kernel both fills and drains. One accessor name serves both directions, so
// the kernel builds a single DataflowBuffer object for the FIFO.
void bind_self_loop(m2::KernelSpec& kernel, const m2::DFBSpecName& dfb, std::string accessor_name) {
    bind_dfb(kernel, dfb, accessor_name, m2::DFBEndpointType::PRODUCER);
    bind_dfb(kernel, dfb, std::move(accessor_name), m2::DFBEndpointType::CONSUMER);
}

void bind_tensor(m2::KernelSpec& kernel, const m2::TensorParamName& tensor, std::string accessor_name) {
    kernel.tensor_bindings.push_back(m2::TensorBinding{
        .tensor_parameter_name = tensor,
        .accessor_name = std::move(accessor_name),
    });
}

// Make the two members of a legacy two-index circular buffer into an alias clique. Both members
// must name each other, which is what makes the group legal.
void alias_pair(m2::ProgramSpec& spec, const m2::DFBSpecName& first, const m2::DFBSpecName& second) {
    for (auto& dfb : spec.dataflow_buffers) {
        if (dfb.unique_id == first) {
            dfb.advanced_options.alias_with = {second};
        } else if (dfb.unique_id == second) {
            dfb.advanced_options.alias_with = {first};
        }
    }
}

std::optional<tt::DataFormat> dfb_data_format(const m2::ProgramSpec& spec, const m2::DFBSpecName& dfb) {
    for (const auto& candidate : spec.dataflow_buffers) {
        if (candidate.unique_id == dfb) {
            return candidate.data_format_metadata;
        }
    }
    return std::nullopt;
}


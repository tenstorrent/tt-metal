ttnn::device_operation::ProgramArtifacts LayerNormMultiCoreProgramFactory::create_program_artifacts(
    const LayerNormParams& operation_attributes,
    const LayerNormInputs& tensor_args,
    Tensor& tensor_return_value,
    const std::optional<CoreRangeSet>& core_range_set) {
    using namespace CMAKE_UNIQUE_NAMESPACE;

    // Extract from operation_attributes and tensor_args
    const auto& a = tensor_args.input;
    const auto& b = tensor_args.residual_input_tensor;
    const auto& gamma = tensor_args.weight;
    const auto& beta = tensor_args.bias;
    auto& output = tensor_return_value;
    bool rms_norm = operation_attributes.norm_type == LayerNormType::RMSNORM;
    float eps = operation_attributes.eps;
    const auto& compute_kernel_config = operation_attributes.compute_kernel_config;

    // Extract program config
    bool legacy_reduction = false;
    bool legacy_rsqrt = false;
    bool requested_use_welford = false;
    std::visit(
        [&](const auto& program_config) {
            using ProgramConfigType = std::decay_t<decltype(program_config)>;
            if constexpr (std::is_same_v<ProgramConfigType, LayerNormDefaultProgramConfig>) {
                legacy_reduction = program_config.legacy_reduction;
                legacy_rsqrt = program_config.legacy_rsqrt;
                requested_use_welford = program_config.use_welford;
            }
        },
        operation_attributes.program_config);

    const auto& logical_shape = a.logical_shape();
    const auto& padded_shape = a.padded_shape();
    std::uint32_t W = logical_shape[-1];
    const bool input_is_row_major = a.layout() == Layout::ROW_MAJOR;
    std::uint32_t Wp = padded_shape[-1], Hp = padded_shape[-2];
    std::uint32_t HWp = Hp * Wp;
    std::uint32_t NC = a.physical_volume() / HWp;
    // For ROW_MAJOR inputs the tensor height is not padded to tile boundaries.
    // Round Hp up to the next TILE_HEIGHT multiple so that Ht >= 1 for any H < TILE_HEIGHT.
    // HWp and NC are computed above from the original (unpadded) Hp, so they remain correct.
    if (input_is_row_major) {
        Hp = tt::round_up(Hp, TILE_HEIGHT);
    }
    // Total logical (non-padded) row count. Used by RM reader/writer kernels to
    // avoid OOB DRAM reads/writes when H is not a multiple of TILE_HEIGHT.
    const std::uint32_t H_logical = static_cast<std::uint32_t>(NC) * static_cast<std::uint32_t>(logical_shape[-2]);

    // Kernels are configured to support BFLOAT8_B, but bad pcc so we need mixed precision support in compute

    ////////////////////////////////////////////////////////////////////////////
    //                       Device Setup
    //////////////////////////////////////////////////////////////////////////
    // This should allocate a DRAM buffer on the device
    IDevice* device = a.device();

    ////////////////////////////////////////////////////////////////////////////
    //                Dataflow Buffer Data Format Setup
    //////////////////////////////////////////////////////////////////////////
    auto [math_fidelity, math_approx_mode, fp32_dest_acc_en, packer_l1_acc, dst_full_sync_en] =
        get_compute_kernel_config_args(device->arch(), compute_kernel_config);

    const std::uint32_t tile_height = a.tensor_spec().tile().get_height();
    const std::uint32_t tile_width = a.tensor_spec().tile().get_width();

    // Data span in tiles, rounded up to tile boundaries
    std::uint32_t Wt = Wp / tile_width;
    std::uint32_t Ht = Hp / tile_height;

    // Block size that maximizes dest usage depending on
    // whether fp32 accumulation is enabled
    std::uint32_t block_size = fp32_dest_acc_en ? 4 : 8;

    tt::DataFormat in_data_format = tt::tt_metal::datatype_to_dataformat_converter(a.dtype());
    tt::DataFormat out_data_format = tt::tt_metal::datatype_to_dataformat_converter(output.dtype());
    tt::DataFormat interm_data_format = fp32_dest_acc_en ? tt::DataFormat::Float32 : tt::DataFormat::Float16_b;
    tt::DataFormat gamma_data_format = gamma.has_value()
                                           ? tt::tt_metal::datatype_to_dataformat_converter(gamma.value().dtype())
                                           : tt::DataFormat::Float16_b;
    tt::DataFormat beta_data_format = beta.has_value()
                                          ? tt::tt_metal::datatype_to_dataformat_converter(beta.value().dtype())
                                          : tt::DataFormat::Float16_b;
    tt::DataFormat reciprocal_data_format = tt::DataFormat::Float32;

    uint32_t in_single_tile_size = tt::tile_size(in_data_format);
    uint32_t single_tile_size = tt::tile_size(interm_data_format);
    uint32_t out_single_tile_size = tt::tile_size(out_data_format);
    uint32_t bfloat16_tile_size = tt::tile_size(tt::DataFormat::Float16_b);
    tt::DataFormat scaler_data_format = tt::DataFormat::Float16_b;
    uint32_t scaler_tile_size = tt::tile_size(scaler_data_format);
    uint32_t gamma_single_tile_size = tt::tile_size(gamma_data_format);
    uint32_t beta_single_tile_size = tt::tile_size(beta_data_format);

    log_debug(tt::LogOp, "in_data_format: {}", in_data_format);
    log_debug(tt::LogOp, "out_data_format: {}", out_data_format);
    log_debug(tt::LogOp, "interm_data_format: {}", interm_data_format);
    log_debug(tt::LogOp, "gamma_data_format: {}", gamma_data_format);
    log_debug(tt::LogOp, "beta_data_format: {}", beta_data_format);
    log_debug(tt::LogOp, "reciprocal_data_format: {}", reciprocal_data_format);
    log_debug(tt::LogOp, "math_fidelity: {}", math_fidelity);
    log_debug(tt::LogOp, "math_approx_mode: {}", math_approx_mode);
    log_debug(tt::LogOp, "fp32_dest_acc_en: {}", fp32_dest_acc_en);

    tt::DataFormat inb_data_format = tt::DataFormat::Invalid;
    std::uint32_t inb_single_tile_size = 0;
    if (b) {
        inb_data_format = tt::tt_metal::datatype_to_dataformat_converter(b.value().dtype());
        inb_single_tile_size = tt::tile_size(inb_data_format);
    }

    uint32_t num_tile_rows = NC * Ht;

    // The caller may restrict the program to a subset of the grid; otherwise take the whole of it.
    CoreRangeSet requested_cores = core_range_set.has_value() ? core_range_set.value() : default_core_range(device);

    // Use split_work_to_cores to properly distribute tile rows across available cores
    auto
        [num_cores,
         all_cores,
         core_group_1,
         core_group_2,
         num_tile_rows_per_core_group_1,
         num_tile_rows_per_core_group_2] = split_work_to_cores(requested_cores, num_tile_rows, true /* row_wise */);

    std::optional<Tensor> recip_tensor = std::nullopt;
    uint32_t reciprocal_buffer_size_bytes = 0;

    ////////////////////////////////////////////////////////////////////////////
    //                         Parameters Setup
    ////////////////////////////////////////////////////////////////////////////
    auto use_row_major_kernel = (gamma.has_value() and gamma.value().layout() == Layout::ROW_MAJOR) or
                                (beta.has_value() and beta.value().layout() == Layout::ROW_MAJOR);
    // Size the small-kernel buffers to be a multiple of the block size
    uint32_t Wt_next_block_up = tt::round_up(Wt, block_size);
    uint32_t in0_t =
        Wt_next_block_up;  // dfb_x for no pre-add variant, x=a+b for fused pre-add, extra space for some buffering
    uint32_t in1_t = block_size * 2;  // buffer for fused pre-add b tensor
    uint32_t out0_t = input_is_row_major ? Wt_next_block_up : block_size * 2;
    uint32_t im0_t = Wt_next_block_up;  // buffer for saving xmm
    uint32_t im3_t = Wt_next_block_up;  // buffer for xmm^2
    uint32_t in5_t = Wt_next_block_up;  // buffer for gamma
    uint32_t in6_t = Wt_next_block_up;  // buffer for beta
    uint32_t im6_t = block_size * 2;    // x=a+b reuse for x-E[x] computation plus a bit extra for buffering
    if (b) {
        im6_t = Wt_next_block_up;
        in0_t = 2 * block_size;
    }
    std::uint32_t im5_t = 2 * block_size;  // for buffering to/from *gamma/+beta
    std::uint32_t im4_t = 8;               // 8 just in case, 4 would prob suffice
    std::uint32_t im1_t = 2;
    std::uint32_t in2_t = 2;  // scaler for reduce coming from reader
    std::uint32_t in3_t = 2;  // epsilon coming from reader
    std::uint32_t im2_t = 2;  //

    // Double-buffered row-major staging for in-flight tilize and untilize.
    const std::uint32_t in_rm_tiles = input_is_row_major ? 2 * block_size : 0;
    const std::uint32_t in_rm_size = in_rm_tiles * in_single_tile_size;
    const std::uint32_t out_rm_tiles = input_is_row_major ? 2 * block_size : 0;
    const std::uint32_t out_rm_size = out_rm_tiles * out_single_tile_size;

    const std::uint64_t usable_cb_l1_bytes = ttnn::operations::core::program_cache_l1_capacity(device);

    // The reciprocal LUT is an externally bound L1 buffer, so the available capacity above
    // already excludes it from the free buffer span. Counting it here would charge its storage twice.
    const auto make_cb_footprint = [&](bool sfpu_statistics) {
        return LayerNormCbFootprint{
            .input = static_cast<std::uint64_t>(in0_t) * in_single_tile_size,
            .residual_input = b.has_value() ? static_cast<std::uint64_t>(in1_t) * inb_single_tile_size : 0,
            .output = static_cast<std::uint64_t>(out0_t) * out_single_tile_size,
            .centred_values = (!rms_norm || b.has_value()) ? static_cast<std::uint64_t>(im0_t) * single_tile_size : 0,
            .squared_values = sfpu_statistics ? 0 : static_cast<std::uint64_t>(im3_t) * single_tile_size,
            .gamma = gamma.has_value() ? static_cast<std::uint64_t>(in5_t) * gamma_single_tile_size : 0,
            .beta = beta.has_value() ? static_cast<std::uint64_t>(in6_t) * beta_single_tile_size : 0,
            .residual_values = b.has_value() && !rms_norm ? static_cast<std::uint64_t>(im6_t) * single_tile_size : 0,
            .affine_intermediate =
                gamma.has_value() || beta.has_value() ? static_cast<std::uint64_t>(im5_t) * single_tile_size : 0,
            .final_intermediate = static_cast<std::uint64_t>(im4_t) * single_tile_size,
            .mean = rms_norm ? 0 : static_cast<std::uint64_t>(im1_t) * single_tile_size,
            .scaler = sfpu_statistics ? 0 : static_cast<std::uint64_t>(in2_t) * scaler_tile_size,
            .epsilon = static_cast<std::uint64_t>(in3_t) * bfloat16_tile_size,
            .variance = static_cast<std::uint64_t>(im2_t) * single_tile_size,
            .row_major_staging = in_rm_size + out_rm_size,
        };
    };
    const bool tile_cb_fits_in_l1 = make_cb_footprint(false).fits(usable_cb_l1_bytes);
    const bool two_pass_cb_fits_in_l1 =
        tensor_args.recip_tensor.has_value() && make_cb_footprint(true).fits(usable_cb_l1_bytes);
    const auto statistics_backend = layernorm::select_interleaved_statistics_backend(
        requested_use_welford,
        device->arch(),
        rms_norm,
        input_is_row_major,
        fp32_dest_acc_en,
        {.input_format = in_data_format,
         .padded_width = Wp,
         .fuse_pre_add = b.has_value(),
         .has_gamma = gamma.has_value(),
         .has_beta = beta.has_value(),
         .compact_two_pass_fits_in_l1 = two_pass_cb_fits_in_l1});
    const bool use_welford = statistics_backend == layernorm::StatisticsBackend::SFPU_TWO_PASS;
    const bool compensated_finalizer_arch =
        device->arch() == tt::ARCH::BLACKHOLE || device->arch() == tt::ARCH::WORMHOLE_B0;
    const bool fp32_sfpu_finalizer = compensated_finalizer_arch && use_welford && !rms_norm && !input_is_row_major &&
                                     in_data_format == tt::DataFormat::Float32 &&
                                     out_data_format == tt::DataFormat::Float32 &&
                                     !operation_attributes.fused_activation.has_value();
    const bool selected_cb_fits_in_l1 = use_welford ? two_pass_cb_fits_in_l1 : tile_cb_fits_in_l1;
    if (use_welford) {
        TT_FATAL(tensor_args.recip_tensor.has_value(), "Reciprocal tensor not provided for Welford layernorm");
        recip_tensor = tensor_args.recip_tensor;
        reciprocal_buffer_size_bytes = recip_tensor->buffer()->aligned_size_per_bank();
    }

    bool large_tensor_needed = false;
    // The following constants were chosen empirically to
    // maximize the buffer size while still fitting the
    // largest cases (fused pre-add + gamma + beta) in L1.
    // There is room for optimization here based on different
    // conditions (like what buffers are actually used),
    // but having two constants for all cases is simpler.
    //
    // The base values (56 / 112) are calibrated for bfloat16 intermediate tiles.
    // When fp32_dest_acc_en is true, interm_data_format is Float32 so single_tile_size
    // doubles (4096 B vs 2048 B). All intermediate buffers (im0_t, im3_t, im5_t, …) use
    // single_tile_size, so the same number of tiles takes 2x the L1 space. Scaling
    // by bfloat16_tile_size / single_tile_size keeps the total intermediate buffer
    // footprint within the empirically validated L1 budget regardless of the
    // accumulation data format.
    const uint32_t with_weights_max_size = 56 * bfloat16_tile_size / single_tile_size;
    const uint32_t without_weights_max_size = 112 * bfloat16_tile_size / single_tile_size;
    // For input_is_row_major we also allow large_tensor_needed (same L1 logic applies).
    // use_row_major_kernel (row-major gamma/beta) still skips large_tensor check as before.
    if (!use_row_major_kernel || input_is_row_major) {
        if ((gamma.has_value() or beta.has_value() or in_data_format == tt::DataFormat::Float32) and
            !selected_cb_fits_in_l1) {
            // In the case that the required space is larger than what can be handled by the single pass
            large_tensor_needed = true;
            Wt_next_block_up = std::min(Wt_next_block_up, with_weights_max_size);
        } else if (!selected_cb_fits_in_l1) {
            large_tensor_needed = true;
            Wt_next_block_up = std::min(Wt_next_block_up, without_weights_max_size);
        }
    }
    // The compact Blackhole kernel can keep compensated centring in DEST and
    // multiply by the column-broadcast inverse standard deviation without an
    // intermediate spill. Residual and oversized cases retain the streaming
    // SFPU finaliser.
    const bool compact_fp32_finalizer =
        device->arch() == tt::ARCH::BLACKHOLE && fp32_sfpu_finalizer && !b.has_value() && !large_tensor_needed;
    if (fp32_sfpu_finalizer && !compact_fp32_finalizer) {
        large_tensor_needed = true;
    }
    const auto configure_large_tensor_buffers = [&]() {
        in0_t = Wt_next_block_up;
        im0_t = Wt_next_block_up;  // buffer for saving xmm
        im3_t = Wt_next_block_up;  // buffer for xmm^2
        in5_t = Wt_next_block_up;  // buffer for gamma
        in6_t = Wt_next_block_up;  // buffer for beta
        if (b) {
            im6_t = Wt_next_block_up;
            in0_t = 2 * block_size;
        }
        if (input_is_row_major) {
            // layernorm_large_tensor.cpp interleaves tilize / compute / untilize per block, so
            // dfb_in and dfb_out only ever hold one block at a time. Move the double-buffering to
            // dfb_in_rm / dfb_out_rm so the reader prefetches the next DRAM block while compute
            // processes the current one, and the writer drains concurrently.
            in0_t = block_size;
            out0_t = block_size;
        }
    };

    if (large_tensor_needed) {
        configure_large_tensor_buffers();
        while (Wt_next_block_up > block_size && !make_cb_footprint(use_welford).fits(usable_cb_l1_bytes)) {
            Wt_next_block_up -= block_size;
            configure_large_tensor_buffers();
        }
        const auto streaming_cb_footprint = make_cb_footprint(use_welford);
        TT_FATAL(
            streaming_cb_footprint.fits(usable_cb_l1_bytes),
            "LayerNorm streaming circular buffers require {} bytes, but only {} bytes of the allocator's L1 span "
            "are available",
            streaming_cb_footprint.total(),
            usable_cb_l1_bytes);
    }

    // When the input is ROW_MAJOR and float32, the in-flight tilize_block path requires
    // fp32_dest_acc_en=True. Without it, UNPACK's SRCA register file is 16-bit and
    // silently truncates every float32 value to bfloat16 before it reaches DST, producing
    // wrong tilized tiles and effectively garbage output.
    TT_FATAL(
        !(input_is_row_major && in_data_format == tt::DataFormat::Float32 && !fp32_dest_acc_en),
        "ROW_MAJOR float32 input requires fp32_dest_acc_en=True in the compute kernel config "
        "(SRCA is 16-bit when fp32_dest_acc_en=False, silently truncating float32 to bfloat16 during tilize)");

    TT_FATAL(in0_t % block_size == 0, "Buffer size in0_t ({}) must be divisible by block_size ({})", in0_t, block_size);
    TT_FATAL(in1_t % block_size == 0, "Buffer size in1_t ({}) must be divisible by block_size ({})", in1_t, block_size);
    TT_FATAL(
        out0_t % block_size == 0, "Buffer size out0_t ({}) must be divisible by block_size ({})", out0_t, block_size);
    TT_FATAL(im0_t % block_size == 0, "Buffer size im0_t ({}) must be divisible by block_size ({})", im0_t, block_size);
    TT_FATAL(im3_t % block_size == 0, "Buffer size im3_t ({}) must be divisible by block_size ({})", im3_t, block_size);
    TT_FATAL(in5_t % block_size == 0, "Buffer size in5_t ({}) must be divisible by block_size ({})", in5_t, block_size);
    TT_FATAL(in6_t % block_size == 0, "Buffer size in6_t ({}) must be divisible by block_size ({})", in6_t, block_size);
    TT_FATAL(im6_t % block_size == 0, "Buffer size im6_t ({}) must be divisible by block_size ({})", im6_t, block_size);

    ////////////////////////////////////////////////////////////////////////////
    //                      Application Setup
    ////////////////////////////////////////////////////////////////////////////
    const auto use_welford_and_not_rms_norm = use_welford && !rms_norm;
    const auto fuse_pre_add = b.has_value();
    const bool two_pass_small = use_welford_and_not_rms_norm && !large_tensor_needed;
    bool fused_pre_add_replay = false;

    // The large fused path normally rereads both inputs for normalisation after
    // materialising x = a + b for statistics. Retain the complete post-add row
    // through an aliased CB view when the actual free L1 span can hold it.
    if (device->arch() == tt::ARCH::BLACKHOLE && use_welford_and_not_rms_norm && large_tensor_needed && fuse_pre_add &&
        gamma.has_value() && beta.has_value() && !input_is_row_major && in_data_format == tt::DataFormat::Float32 &&
        !operation_attributes.fused_activation.has_value()) {
        const std::uint32_t full_row_tiles = tt::round_up(Wt, block_size);
        auto replay_footprint = make_cb_footprint(true);
        replay_footprint.residual_values = static_cast<std::uint64_t>(full_row_tiles) * single_tile_size;
        if (replay_footprint.fits(usable_cb_l1_bytes)) {
            im6_t = full_row_tiles;
            fused_pre_add_replay = true;
        }
    }

    // Multicast uses the active-core bounding box. The default core pool owns
    // inactive tail positions in that box; custom pools must be rectangular.
    const bool affine_mcast_core_set_safe =
        requested_cores == default_core_range(device) || all_cores.bounding_box().size() == num_cores;
    const bool affine_mcast =
        fused_pre_add_replay && num_cores >= 20 && num_tile_rows % num_cores == 0 && affine_mcast_core_set_safe;

    // The two-pass kernel retains the current row until its mean, centered M2,
    // and x-mean traversals are complete. When L1 permits, let the reader fill
    // the next two rows instead of stalling on that longer retention interval.
    // The non-fused c_29 FP32 alias shares cb_in's read-ahead storage. On the
    // fused path the current a/b row has already been consumed into cb_x, so two
    // rows in each input CB allow the reader to stay ahead of the longer compute
    // phase.
    if (two_pass_small) {
        const std::uint32_t read_ahead_in0_t = fuse_pre_add ? 2 * Wt_next_block_up : 3 * in0_t;
        const std::uint32_t read_ahead_in1_t = fuse_pre_add ? 2 * Wt_next_block_up : in1_t;
        auto read_ahead_footprint = make_cb_footprint(true);
        read_ahead_footprint.input = static_cast<std::uint64_t>(read_ahead_in0_t) * in_single_tile_size;
        read_ahead_footprint.residual_input =
            fuse_pre_add ? static_cast<std::uint64_t>(read_ahead_in1_t) * inb_single_tile_size : 0;
        if (read_ahead_footprint.fits(usable_cb_l1_bytes)) {
            in0_t = read_ahead_in0_t;
            in1_t = read_ahead_in1_t;
        }
    }

    // For Float32 input on the Welford path: expose the input tile data under two buffer indices
    // backed by the same SRAM (aliased buffers). dfb_x retains the default unpack mode so
    // post-welford FPU binary ops keep reading via SrcA; the welford-alias index gets
    // UnpackToDest so welford's transpose_tile reads full fp32 into DEST.
    //
    // We deliberately disable the alias for the fused-pre-add + large_tensor combination:
    // dfb_x = X there holds the post-add result, which already lost precision through the
    // FPU add (SrcA Tf32), so an fp32-preserving unpack on the welford side would not recover
    // any real information, but would require the SFPU replay buffer recovery
    // (welford_init<WelfordInitMode::PreserveStats>()) after every transpose_tile.
    //
    // The alias exists only to carry an UnpackToDest mode, which is legal and useful only when the
    // Dest register is 32 bits wide. With fp32_dest_acc_en off it would mark a buffer for a bypass
    // that preserves nothing, which the ProgramSpec validator rejects. The sharded factory gates its
    // equivalent the same way.
    const bool welford_fp32_alias = use_welford_and_not_rms_norm && in_data_format == tt::DataFormat::Float32 &&
                                    fp32_dest_acc_en && !(fuse_pre_add && large_tensor_needed);

    // Separate alias on EX and EX2 for the mean / M2 sliding-window accumulators in
    // layernorm_large_tensor_welford.cpp::welford_fuse_pre_add. That function spills LREG4/5 to
    // dfb_ex / dfb_ex2 between blocks and restores them via copy_tile at the top of the next
    // block. With dfb_ex / dfb_ex2 in the default unpack mode, copy_tile would take the SrcA path
    // and silently truncate FP32 to TF32 on every restore. Exposing the same memory under an
    // alias with UnpackToDest lets copy_tile take the FP32 path, while the original EX / EX2
    // indices stay in the default mode for the SrcA/SrcB consumers.
    const bool welford_state_fp32_alias =
        use_welford_and_not_rms_norm && interm_data_format == tt::DataFormat::Float32 &&
        ((large_tensor_needed && (fuse_pre_add || fp32_sfpu_finalizer)) || compact_fp32_finalizer);

    bool float32_reduction = fp32_dest_acc_en && !legacy_reduction;

    // Only layernorm.cpp and layernorm_large_tensor.cpp carry the TILIZE_IN / UNTILIZE_OUT
    // blocks, so on a row-major input those two fill IN themselves (from IN_RM) instead of the
    // reader filling it. The Welford compute kernels have no tilize block, which is why the
    // producer side of IN is chosen from the compute kernel rather than from the layout alone.
    const bool compute_tilizes = input_is_row_major && !use_welford_and_not_rms_norm;

    ////////////////////////////////////////////////////////////////////////////
    //                      Dataflow buffers
    ////////////////////////////////////////////////////////////////////////////
    m2::ProgramSpec spec{.name = "layernorm_multi_core"};
    if (affine_mcast) {
        spec.semaphores = {
            m2::SemaphoreSpec{.unique_id = AFFINE_READY, .target_nodes = all_cores},
            m2::SemaphoreSpec{.unique_id = AFFINE_DONE, .target_nodes = all_cores},
        };
    }

    auto add_dfb =
        [&spec](
            const m2::DFBSpecName& unique_id, uint32_t num_entries, uint32_t entry_size, tt::DataFormat data_format) {
            spec.dataflow_buffers.push_back(m2::DataflowBufferSpec{
                .unique_id = unique_id,
                .entry_size = entry_size,
                .num_entries = num_entries,
                .data_format_metadata = data_format,
            });
        };

    // Input buffer. On the non-fused Welford path this also serves as dfb_x for the welford
    // intake and the post-welford eltwise.
    add_dfb(IN, in0_t, in_single_tile_size, in_data_format);

    // Output buffer.
    add_dfb(OUT, out0_t, out_single_tile_size, out_data_format);

    // E[x]. Also holds the running mean spilled between blocks in
    // layernorm_large_tensor_welford.cpp's fused welford path.
    if (!rms_norm) {
        add_dfb(EX, im1_t, single_tile_size, interm_data_format);
    }

    // Reduce scaler, generated by the reader.
    if (!use_welford) {
        add_dfb(SCALER, in2_t, scaler_tile_size, scaler_data_format);
    }

    // Epsilon.
    add_dfb(EPS, in3_t, bfloat16_tile_size, tt::DataFormat::Float16_b);

    // Var[x]. Also holds the running M2 (sum of squared deviations) spilled between blocks in
    // layernorm_large_tensor_welford.cpp's fused welford path.
    add_dfb(EX2, im2_t, single_tile_size, interm_data_format);

    // x - E[x].
    if (!rms_norm || fuse_pre_add || large_tensor_needed) {
        add_dfb(XMM, im0_t, single_tile_size, interm_data_format);
    }

    // (x - E[x])^2.
    if (!use_welford) {
        add_dfb(XMM2, im3_t, single_tile_size, interm_data_format);
    }

    // Var[x] + eps.
    add_dfb(EX2PE, im4_t, single_tile_size, interm_data_format);

    // Large-tensor variance accumulator. The large-tensor non-Welford reduce kernel needs an
    // intermediate Float32 buffer that can be unpacked directly to dest (if doing a Float32
    // reduction).
    if (large_tensor_needed && !use_welford) {
        const auto accumulate_data_format = float32_reduction ? tt::DataFormat::Float32 : interm_data_format;
        const auto accumulate_tile_size = tt::tile_size(accumulate_data_format);
        add_dfb(ACCUMULATE, 1, accumulate_tile_size, accumulate_data_format);
    }

    // Row-major input staging buffer (only when input is ROW_MAJOR). Holds block_size tiles
    // worth of row-major data for in-flight tilization via tilize_block().
    if (input_is_row_major) {
        add_dfb(IN_RM, in_rm_tiles, in_single_tile_size, in_data_format);
    }

    // Row-major output staging buffer (only when input is ROW_MAJOR, so output is too). The
    // compute kernel untilizes completed tiles from OUT into this buffer block-by-block; the RM
    // writer kernel drains it and writes row-by-row to DRAM.
    if (input_is_row_major) {
        add_dfb(OUT_RM, out_rm_tiles, out_single_tile_size, out_data_format);
    }

    // gamma/beta streaming intermediate.
    if (gamma.has_value() || beta.has_value()) {
        add_dfb(FUSION, im5_t, single_tile_size, interm_data_format);
    }

    if (gamma.has_value()) {
        add_dfb(GAMMA, in5_t, gamma_single_tile_size, gamma_data_format);
    }

    if (beta.has_value()) {
        add_dfb(BETA, in6_t, beta_single_tile_size, beta_data_format);
    }

    if (b) {
        // Fused: x = a + b. Compute writes the post-add result here, then the welford intake
        // reads it via transpose_tile.
        if (!rms_norm) {
            add_dfb(X, im6_t, single_tile_size, interm_data_format);
        }
        add_dfb(INB, in1_t, inb_single_tile_size, inb_data_format);
    }

    // Reciprocal LUT, borrowed from the caller-supplied reciprocal tensor rather than allocated.
    if (use_welford) {
        spec.dataflow_buffers.push_back(m2::DataflowBufferSpec{
            .unique_id = RECIPROCALS,
            .entry_size = reciprocal_buffer_size_bytes,
            .num_entries = 1,
            .data_format_metadata = reciprocal_data_format,
            .borrowed_from = RECIP,
        });
    }

    // Welford fp32 aliases: a second index over the primary buffer's SRAM, same total size.
    if (welford_fp32_alias) {
        add_dfb(
            X_WELFORD,
            fuse_pre_add ? im6_t : in0_t,
            fuse_pre_add ? single_tile_size : in_single_tile_size,
            fuse_pre_add ? interm_data_format : in_data_format);
    }
    if (fp32_sfpu_finalizer && large_tensor_needed) {
        add_dfb(IN_FP32, in0_t, in_single_tile_size, in_data_format);
        if (fuse_pre_add) {
            add_dfb(INB_FP32, in1_t, inb_single_tile_size, inb_data_format);
            add_dfb(PRE_ADD_FP32, im6_t, single_tile_size, interm_data_format);
        }
    }
    if (compact_fp32_finalizer || (fp32_sfpu_finalizer && large_tensor_needed)) {
        add_dfb(EX2PE_FP32, im4_t, single_tile_size, interm_data_format);
    }
    if (welford_state_fp32_alias) {
        add_dfb(EX_WELFORD, im1_t, single_tile_size, interm_data_format);
        add_dfb(EX2_WELFORD, im2_t, single_tile_size, interm_data_format);
    }

    std::vector<m2::DFBSpecName> input_aliases{IN};
    if (welford_fp32_alias && !fuse_pre_add) {
        input_aliases.push_back(X_WELFORD);
    }
    if (fp32_sfpu_finalizer && large_tensor_needed) {
        input_aliases.push_back(IN_FP32);
    }
    if (input_aliases.size() > 1) {
        alias_group(spec, input_aliases);
    }
    if (fuse_pre_add) {
        std::vector<m2::DFBSpecName> residual_aliases{INB};
        if (fp32_sfpu_finalizer && large_tensor_needed) {
            residual_aliases.push_back(INB_FP32);
        }
        if (residual_aliases.size() > 1) {
            alias_group(spec, residual_aliases);
        }

        std::vector<m2::DFBSpecName> pre_add_aliases{X};
        if (welford_fp32_alias) {
            pre_add_aliases.push_back(X_WELFORD);
        }
        if (fp32_sfpu_finalizer && large_tensor_needed) {
            pre_add_aliases.push_back(PRE_ADD_FP32);
        }
        if (pre_add_aliases.size() > 1) {
            alias_group(spec, pre_add_aliases);
        }
    }
    if (welford_state_fp32_alias) {
        alias_pair(spec, EX, EX_WELFORD);
        alias_pair(spec, EX2, EX2_WELFORD);
    }
    if (compact_fp32_finalizer || (fp32_sfpu_finalizer && large_tensor_needed)) {
        alias_pair(spec, EX2PE, EX2PE_FP32);
    }

    ////////////////////////////////////////////////////////////////////////////
    //                      Tensor parameters
    ////////////////////////////////////////////////////////////////////////////
    spec.tensor_parameters.push_back(m2::TensorParameter{.unique_id = INPUT, .spec = a.tensor_spec()});
    spec.tensor_parameters.push_back(m2::TensorParameter{.unique_id = OUTPUT, .spec = output.tensor_spec()});
    if (b) {
        spec.tensor_parameters.push_back(m2::TensorParameter{.unique_id = RESIDUAL, .spec = b.value().tensor_spec()});
    }
    if (gamma.has_value()) {
        spec.tensor_parameters.push_back(
            m2::TensorParameter{.unique_id = GAMMA_T, .spec = gamma.value().tensor_spec()});
    }
    if (beta.has_value()) {
        spec.tensor_parameters.push_back(m2::TensorParameter{.unique_id = BETA_T, .spec = beta.value().tensor_spec()});
    }
    if (use_welford) {
        spec.tensor_parameters.push_back(
            m2::TensorParameter{.unique_id = RECIP, .spec = recip_tensor.value().tensor_spec()});
    }

    ////////////////////////////////////////////////////////////////////////////
    //                      Reader kernel
    ////////////////////////////////////////////////////////////////////////////
    const char* reader_kernel_path = nullptr;
    if (large_tensor_needed) {
        reader_kernel_path = use_welford_and_not_rms_norm
                                 ? "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/dataflow/"
                                   "reader_unary_interleaved_ln_large_tensor_welford.cpp"
                                 : "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/dataflow/"
                                   "reader_unary_interleaved_ln_large_tensor.cpp";
    } else {
        reader_kernel_path = use_row_major_kernel
                                 ? "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/dataflow/"
                                   "reader_unary_interleaved_ln_rm_gb.cpp"
                                 : "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/dataflow/"
                                   "reader_unary_interleaved_ln.cpp";
    }

    m2::KernelSpec reader{
        .unique_id = READER,
        .source = reader_kernel_path,
        .compile_time_args = {{"block_size", block_size}, {"W", W}},
        // reader_start is a tile-row index for the merged readers and a flat tile offset for the
        // two legacy tile readers, so the schema carries the host's own name for it rather than
        // either kernel's local reading of it.
        .runtime_arg_schema = {.runtime_arg_names = {"NCHt", "Wt", "reader_start", "eps"}},
        .hw_config = create_reader_datamovement_config(device->arch()),
    };
    if (input_is_row_major) {
        // Element size of the input tensor, for the row-major reader's address stride arithmetic.
        reader.compile_time_args.emplace("elem_size_bytes", static_cast<uint32_t>(a.element_size()));
        reader.runtime_arg_schema.runtime_arg_names.push_back("H_logical");
    }
    if (fuse_pre_add) {
        reader.compiler_options.defines.emplace("FUSE_PRE_ADD", "1");
    }
    if (gamma.has_value()) {
        reader.compiler_options.defines.emplace("FUSE_GAMMA", "1");
    }
    if (beta.has_value()) {
        reader.compiler_options.defines.emplace("FUSE_BETA", "1");
    }
    if (rms_norm) {
        reader.compiler_options.defines.emplace("RMSNORM", "1");
    }
    if (input_is_row_major) {
        reader.compiler_options.defines.emplace("TILIZE_IN", "1");
    }
    // SCALER exists only off the Welford path, so the gate that decides whether the reader
    // generates the reduce scaler has to reach the preprocessor: an `if constexpr` still looks
    // up dfb::scaler in its discarded branch.
    if (use_welford) {
        reader.compiler_options.defines.emplace("USE_WELFORD", "1");
    }
    // Same reason for the alias: X_WELFORD has no binding when the alias is inactive.
    if (welford_fp32_alias) {
        reader.compiler_options.defines.emplace("WELFORD_FP32_ALIAS", "1");
    }
    if (fp32_sfpu_finalizer && large_tensor_needed) {
        reader.compiler_options.defines.emplace("FP32_SFPU_FINALIZER", "1");
    }
    if (fused_pre_add_replay) {
        reader.compiler_options.defines.emplace("FUSED_PRE_ADD_REPLAY", "1");
    }

    if (!compute_tilizes) {
        bind_dfb(reader, IN, "in", m2::DFBEndpointType::PRODUCER);
    }
    bind_dfb(reader, EPS, "eps", m2::DFBEndpointType::PRODUCER);
    if (!use_welford) {
        bind_dfb(reader, SCALER, "scaler", m2::DFBEndpointType::PRODUCER);
    }
    if (fuse_pre_add) {
        bind_dfb(reader, INB, "inb", m2::DFBEndpointType::PRODUCER);
    }
    if (gamma.has_value()) {
        bind_dfb(reader, GAMMA, "gamma", m2::DFBEndpointType::PRODUCER);
    }
    if (beta.has_value()) {
        bind_dfb(reader, BETA, "beta", m2::DFBEndpointType::PRODUCER);
    }
    if (input_is_row_major) {
        bind_dfb(reader, IN_RM, "in_rm", m2::DFBEndpointType::PRODUCER);
    }
    if (welford_fp32_alias && !fuse_pre_add) {
        bind_dfb(reader, X_WELFORD, "x_welford", m2::DFBEndpointType::PRODUCER);
    }
    if (fp32_sfpu_finalizer && large_tensor_needed) {
        bind_dfb(reader, IN_FP32, "in_fp32", m2::DFBEndpointType::PRODUCER);
        if (fuse_pre_add) {
            bind_dfb(reader, INB_FP32, "inb_fp32", m2::DFBEndpointType::PRODUCER);
        }
    }

    bind_tensor(reader, INPUT, "src");
    if (b) {
        bind_tensor(reader, RESIDUAL, "src_b");
    }
    if (gamma.has_value()) {
        bind_tensor(reader, GAMMA_T, "gamma");
    }
    if (beta.has_value()) {
        bind_tensor(reader, BETA_T, "beta");
    }

    std::optional<m2::KernelSpec> reader_mcast_receiver;
    if (affine_mcast) {
        reader_mcast_receiver = reader;
        reader_mcast_receiver->unique_id = READER_MCAST_RECEIVER;
        reader_mcast_receiver->compiler_options.defines.emplace("AFFINE_MCAST", "1");
        reader_mcast_receiver->compiler_options.defines.emplace("AFFINE_MCAST_RECEIVER", "1");
        reader_mcast_receiver->runtime_arg_schema.runtime_arg_names.insert(
            reader_mcast_receiver->runtime_arg_schema.runtime_arg_names.end(), {"sender_noc_x", "sender_noc_y"});
        reader_mcast_receiver->tensor_bindings.erase(
            std::remove_if(
                reader_mcast_receiver->tensor_bindings.begin(),
                reader_mcast_receiver->tensor_bindings.end(),
                [](const m2::TensorBinding& binding) {
                    return binding.tensor_parameter_name == GAMMA_T || binding.tensor_parameter_name == BETA_T;
                }),
            reader_mcast_receiver->tensor_bindings.end());
        bind_semaphore(*reader_mcast_receiver, AFFINE_READY, "affine_ready");
        bind_semaphore(*reader_mcast_receiver, AFFINE_DONE, "affine_done");

        reader.compiler_options.defines.emplace("AFFINE_MCAST", "1");
        reader.compiler_options.defines.emplace("AFFINE_MCAST_SENDER", "1");
        reader.runtime_arg_schema.runtime_arg_names.insert(
            reader.runtime_arg_schema.runtime_arg_names.end(),
            {"mcast_start_x", "mcast_start_y", "mcast_end_x", "mcast_end_y", "num_mcast_dests", "num_receivers"});
        bind_semaphore(reader, AFFINE_READY, "affine_ready");
        bind_semaphore(reader, AFFINE_DONE, "affine_done");
    }

    ////////////////////////////////////////////////////////////////////////////
    //                      Writer kernel
    ////////////////////////////////////////////////////////////////////////////
    m2::KernelSpec writer{
        .unique_id = WRITER,
        .source = input_is_row_major ? "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/dataflow/"
                                       "writer_unary_interleaved_start_id_blocked_rm_output.cpp"
                                     : "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/dataflow/"
                                       "writer_unary_interleaved_start_id_blocked.cpp",
        .compile_time_args = {{"block_size", block_size}},
        // writer_start is a tile-row index for the row-major writer and a flat tile offset for
        // the tile writer, so the schema carries the host's own name for it.
        .runtime_arg_schema = {.runtime_arg_names = {"Wt", "num_tile_rows", "writer_start"}},
        .hw_config = create_writer_datamovement_config(device->arch()),
    };
    if (input_is_row_major) {
        // The RM writer needs elem_size to compute per-row NOC write sizes.
        writer.compile_time_args.emplace("elem_size_bytes", static_cast<uint32_t>(output.element_size()));
        writer.runtime_arg_schema.runtime_arg_names.push_back("H_logical");
        bind_dfb(writer, OUT_RM, "out_rm", m2::DFBEndpointType::CONSUMER);
    } else {
        bind_dfb(writer, OUT, "out", m2::DFBEndpointType::CONSUMER);
    }
    bind_tensor(writer, OUTPUT, "dst");

    ////////////////////////////////////////////////////////////////////////////
    //                      Compute kernel
    ////////////////////////////////////////////////////////////////////////////
    // Select compute kernel path.
    // For input_is_row_major: TILIZE_IN define handles in-flight tilization; large_tensor kernel allowed.
    // use_row_major_kernel (row-major gamma/beta only) still prevents large_tensor as before.
    const auto* compute_kernel_path =
        (large_tensor_needed && (!use_row_major_kernel || input_is_row_major))
            ? (use_welford_and_not_rms_norm ? "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/compute/"
                                              "layernorm_large_tensor_welford.cpp"
                                            : "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/compute/"
                                              "layernorm_large_tensor.cpp")
            : (use_welford_and_not_rms_norm
                   ? "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/compute/layernorm_welford.cpp"
                   : "ttnn/cpp/ttnn/operations/normalization/layernorm/device/kernels/compute/layernorm.cpp");

    auto compute_hw = to_compute_hardware_config(device->arch(), compute_kernel_config);

    m2::KernelSpec compute{
        .unique_id = COMPUTE,
        .source = compute_kernel_path,
        // Legacy defaults opt_level on the per-kernel-type config struct, where a compute kernel
        // gets O3; Metal 2.0's single type-agnostic CompilerOptions defaults to O2 for both
        // kinds, so the level has to be stated to keep the compile and the link where they were.
        .compiler_options = {.opt_level = KernelBuildOptLevel::O3},
        .compile_time_args =
            {{"Wt", Wt},
             {"block_size", block_size},
             {"do_gamma", static_cast<uint32_t>(gamma.has_value())},
             {"do_beta", static_cast<uint32_t>(beta.has_value())},
             {"fp32_dest_acc_en", static_cast<uint32_t>(fp32_dest_acc_en)},
             {"W", W}},
        .runtime_arg_schema = {.runtime_arg_names = {"NCHt"}},
        .hw_config = compute_hw,
    };
    if (use_welford_and_not_rms_norm) {
        compute.compile_time_args.emplace("tile_width", ttnn::types::TILE_SIZE);
        compute.compile_time_args.emplace("fuse_pre_add", static_cast<uint32_t>(fuse_pre_add));
        compute.compile_time_args.emplace("reciprocal_w", std::bit_cast<uint32_t>(1.0f / static_cast<float>(W)));
    } else {
        compute.compile_time_args.emplace("tile_width", tile_width);
        compute.compile_time_args.emplace("float32_reduction", static_cast<uint32_t>(float32_reduction));
        compute.compile_time_args.emplace("legacy_rsqrt", static_cast<uint32_t>(legacy_rsqrt));
    }

    // FUSE_PRE_ADD reaches every compute kernel, not only the non-Welford ones: the Welford
    // kernels name INB and X from contexts the preprocessor has to resolve, and those buffers
    // exist only when there is a residual to add.
    if (fuse_pre_add) {
        compute.compiler_options.defines.emplace("FUSE_PRE_ADD", "1");
    }
    // gamma / beta likewise gate GAMMA, BETA and FUSION, so their `if constexpr` gates are
    // promoted to the preprocessor.
    if (gamma.has_value()) {
        compute.compiler_options.defines.emplace("FUSE_GAMMA", "1");
    }
    if (beta.has_value()) {
        compute.compiler_options.defines.emplace("FUSE_BETA", "1");
    }
    if (rms_norm) {
        compute.compiler_options.defines.emplace("RMSNORM", "1");
    }
    if (input_is_row_major) {
        compute.compiler_options.defines.emplace("TILIZE_IN", "1");
        compute.compiler_options.defines.emplace("UNTILIZE_OUT", "1");
    }
    if (welford_fp32_alias) {
        compute.compiler_options.defines.emplace("WELFORD_FP32_ALIAS", "1");
    }
    if (welford_state_fp32_alias) {
        compute.compiler_options.defines.emplace("WELFORD_STATE_FP32_ALIAS", "1");
    }
    if (fp32_sfpu_finalizer && large_tensor_needed) {
        compute.compiler_options.defines.emplace("FP32_SFPU_FINALIZER", "1");
    }
    if (compact_fp32_finalizer) {
        compute.compiler_options.defines.emplace("COMPACT_FP32_FINALIZER", "1");
    }
    if (fused_pre_add_replay) {
        compute.compiler_options.defines.emplace("FUSED_PRE_ADD_REPLAY", "1");
    }
    if (operation_attributes.fused_activation.has_value()) {
        const auto& act = operation_attributes.fused_activation.value();
        auto act_defines =
            ttnn::operations::unary::utils::get_defines(act.op_type, act.params, "ACTIVATION", "i", output.dtype());
        for (auto& [key, val] : act_defines) {
            compute.compiler_options.defines.emplace(key, val);
        }
    }

    if (compute_tilizes) {
        bind_self_loop(compute, IN, "in");
    } else {
        bind_dfb(compute, IN, "in", m2::DFBEndpointType::CONSUMER);
    }
    if (input_is_row_major) {
        // The row-major output leaves through OUT_RM, so compute re-reads its own OUT tiles for
        // pack_untilize_block instead of handing them to the writer.
        bind_self_loop(compute, OUT, "out");
        bind_dfb(compute, IN_RM, "in_rm", m2::DFBEndpointType::CONSUMER);
        bind_dfb(compute, OUT_RM, "out_rm", m2::DFBEndpointType::PRODUCER);
    } else {
        bind_dfb(compute, OUT, "out", m2::DFBEndpointType::PRODUCER);
    }
    bind_dfb(compute, EPS, "eps", m2::DFBEndpointType::CONSUMER);
    bind_self_loop(compute, EX2, "ex2");
    bind_self_loop(compute, EX2PE, "ex2pe");
    if (fuse_pre_add) {
        bind_dfb(compute, INB, "inb", m2::DFBEndpointType::CONSUMER);
    }
    if (!use_welford) {
        bind_dfb(compute, SCALER, "scaler", m2::DFBEndpointType::CONSUMER);
        bind_self_loop(compute, XMM2, "xmm2");
    }
    if (gamma.has_value()) {
        bind_dfb(compute, GAMMA, "gamma", m2::DFBEndpointType::CONSUMER);
    }
    if (beta.has_value()) {
        bind_dfb(compute, BETA, "beta", m2::DFBEndpointType::CONSUMER);
    }
    if (!rms_norm) {
        bind_self_loop(compute, EX, "ex");
    }
    if (gamma.has_value() || beta.has_value()) {
        bind_self_loop(compute, FUSION, "fusion");
    }
    if (b && !rms_norm) {
        bind_self_loop(compute, X, "x");
    }
    if (!rms_norm || fuse_pre_add || large_tensor_needed) {
        bind_self_loop(compute, XMM, "xmm");
    }
    if (use_welford) {
        bind_self_loop(compute, RECIPROCALS, "reciprocals");
    }
    if (large_tensor_needed && !use_welford) {
        bind_self_loop(compute, ACCUMULATE, "accumulate");
    }
    if (welford_fp32_alias) {
        if (fuse_pre_add) {
            bind_self_loop(compute, X_WELFORD, "x_welford");
        } else {
            bind_dfb(compute, X_WELFORD, "x_welford", m2::DFBEndpointType::CONSUMER);
        }
    }
    if (welford_state_fp32_alias) {
        bind_self_loop(compute, EX_WELFORD, "ex_welford");
        bind_self_loop(compute, EX2_WELFORD, "ex2_welford");
    }
    if (fp32_sfpu_finalizer && large_tensor_needed) {
        bind_dfb(compute, IN_FP32, "in_fp32", m2::DFBEndpointType::CONSUMER);
        if (fuse_pre_add) {
            bind_dfb(compute, INB_FP32, "inb_fp32", m2::DFBEndpointType::CONSUMER);
            bind_self_loop(compute, PRE_ADD_FP32, "pre_add_fp32");
        }
    }
    if (compact_fp32_finalizer || (fp32_sfpu_finalizer && large_tensor_needed)) {
        bind_self_loop(compute, EX2PE_FP32, "ex2pe_fp32");
    }

    ////////////////////////////////////////////////////////////////////////////
    //                      Compute unpack modes
    ////////////////////////////////////////////////////////////////////////////
    // Legacy carried a vector indexed by buffer index, defaulted everywhere except the four
    // alias / accumulator sites. Those four become UnpackToDest; the remaining Float32 buffers
    // compute consumes get an explicit UnpackToSrc, which is required once the 32-bit Dest
    // register is enabled and which legacy supplied silently.
    //
    // The choice of which buffers get which mode assumes a Gen1 target (Wormhole, Blackhole),
    // where unpacking straight to Dest costs performance unless it is the only way to keep 32 bits
    // of precision. That is why UnpackToDest appears only at the fp32 alias sites and every other
    // Float32 buffer is pinned to UnpackToSrc. Gen2 reverses the tradeoff: unpacking to Dest is
    // free there and is the preferred mode for anything the SFPU consumes, so these assignments
    // stay legal but become slower than they need to be. They want revisiting before this op
    // targets Gen2.
    {
        auto& modes = m2::unpack_modes(std::get<m2::ComputeHardwareConfig>(compute.hw_config));
        std::vector<m2::DFBSpecName> unpack_to_dest;
        // Each entry is gated on the same condition as its binding: an entry naming a buffer the
        // kernel does not bind is rejected, and legacy set this one from float32_reduction alone,
        // writing into a vector slot for a buffer index that may not have been allocated.
        if (large_tensor_needed && !use_welford && float32_reduction) {
            unpack_to_dest.push_back(ACCUMULATE);
        }
        if (welford_fp32_alias) {
            unpack_to_dest.push_back(X_WELFORD);
        }
        if (fused_pre_add_replay) {
            // The primary X FIFO is retained for finalisation, so it can itself use
            // the full-FP32 destination path without a separate replay alias.
            unpack_to_dest.push_back(X);
        }
        if (welford_state_fp32_alias) {
            unpack_to_dest.push_back(EX_WELFORD);
            unpack_to_dest.push_back(EX2_WELFORD);
        }
        if (fp32_sfpu_finalizer && large_tensor_needed) {
            unpack_to_dest.push_back(IN_FP32);
            if (fuse_pre_add) {
                unpack_to_dest.push_back(INB_FP32);
                unpack_to_dest.push_back(PRE_ADD_FP32);
            }
        }
        if (compact_fp32_finalizer || (fp32_sfpu_finalizer && large_tensor_needed)) {
            unpack_to_dest.push_back(EX2PE_FP32);
        }
        for (const auto& dfb : unpack_to_dest) {
            modes.emplace(dfb, UnpackMode::UnpackToDest);
        }
        if (fp32_dest_acc_en) {
            for (const auto& binding : compute.dfb_bindings) {
                if (binding.endpoint_type != m2::DFBEndpointType::CONSUMER) {
                    continue;
                }
                if (dfb_data_format(spec, binding.dfb_spec_name) != tt::DataFormat::Float32) {
                    continue;
                }
                modes.emplace(binding.dfb_spec_name, UnpackMode::UnpackToSrc);
            }
        }
    }

    ////////////////////////////////////////////////////////////////////////////
    //                      Runtime arguments
    ////////////////////////////////////////////////////////////////////////////
    m2::KernelRunArgs reader_run_args{.kernel = READER};
    m2::KernelRunArgs reader_mcast_receiver_run_args{.kernel = READER_MCAST_RECEIVER};
    m2::KernelRunArgs writer_run_args{.kernel = WRITER};
    m2::KernelRunArgs compute_run_args{.kernel = COMPUTE};

    uint32_t curr_row = 0;
    auto all_core_coords = corerange_to_cores(all_cores, num_cores, true);
    const CoreCoord affine_mcast_sender_core = all_core_coords.front();
    const CoreRangeSet affine_mcast_sender_cores{CoreRange{affine_mcast_sender_core}};
    const CoreRangeSet affine_mcast_receiver_cores = all_cores.subtract(affine_mcast_sender_cores);
    const CoreRange affine_mcast_bbox = all_cores.bounding_box();
    const CoreCoord affine_mcast_start = device->worker_core_from_logical_core(affine_mcast_bbox.start_coord);
    const CoreCoord affine_mcast_end = device->worker_core_from_logical_core(affine_mcast_bbox.end_coord);
    const CoreCoord affine_mcast_sender_noc = device->worker_core_from_logical_core(affine_mcast_sender_core);
    for (std::uint32_t i = 0; i < num_cores; ++i) {
        CoreCoord core = all_core_coords[i];

        std::uint32_t num_tile_rows_per_core = 0;
        if (core_group_1.contains(core)) {
            num_tile_rows_per_core = num_tile_rows_per_core_group_1;
        } else if (core_group_2.contains(core)) {
            num_tile_rows_per_core = num_tile_rows_per_core_group_2;
        } else {
            TT_THROW("Core not in specified core ranges");
        }

        std::uint32_t tile_offset = curr_row * Wt;

        // Merged readers (rm_and_tile, large_tensor_rm_and_tile) use a unified start_tile_row = curr_row.
        // Legacy kernels (welford large-tensor, rm_gb) still expect tile_offset = curr_row * Wt.
        const bool reader_uses_tile_offset =
            (use_welford_and_not_rms_norm && large_tensor_needed) || (use_row_major_kernel && !input_is_row_major);
        const std::uint32_t reader_start = reader_uses_tile_offset ? tile_offset : curr_row;

        auto& active_reader_run_args =
            affine_mcast && core != affine_mcast_sender_core ? reader_mcast_receiver_run_args : reader_run_args;
        m2::AddRuntimeArgsForNode(
            active_reader_run_args.runtime_arg_values,
            core,
            {{"NCHt", num_tile_rows_per_core},
             {"Wt", Wt},
             {"reader_start", reader_start},
             {"eps", std::bit_cast<uint32_t>(eps)}});
        if (input_is_row_major) {
            m2::AddRuntimeArgsForNode(active_reader_run_args.runtime_arg_values, core, {{"H_logical", H_logical}});
        }
        if (affine_mcast) {
            if (core == affine_mcast_sender_core) {
                m2::AddRuntimeArgsForNode(
                    active_reader_run_args.runtime_arg_values,
                    core,
                    {{"mcast_start_x", affine_mcast_start.x},
                     {"mcast_start_y", affine_mcast_start.y},
                     {"mcast_end_x", affine_mcast_end.x},
                     {"mcast_end_y", affine_mcast_end.y},
                     {"num_mcast_dests", affine_mcast_bbox.size() - 1},
                     {"num_receivers", num_cores - 1}});
            } else {
                m2::AddRuntimeArgsForNode(
                    active_reader_run_args.runtime_arg_values,
                    core,
                    {{"sender_noc_x", affine_mcast_sender_noc.x}, {"sender_noc_y", affine_mcast_sender_noc.y}});
            }
        }

        // For the RM output writer start_tile_row is the starting tile-row index for this core,
        // not the flat tile offset, because the RM writer computes row addresses directly.
        const uint32_t writer_start = input_is_row_major ? curr_row : tile_offset;
        m2::AddRuntimeArgsForNode(
            writer_run_args.runtime_arg_values,
            core,
            {{"Wt", Wt}, {"num_tile_rows", num_tile_rows_per_core}, {"writer_start", writer_start}});
        if (input_is_row_major) {
            m2::AddRuntimeArgsForNode(writer_run_args.runtime_arg_values, core, {{"H_logical", H_logical}});
        }

        m2::AddRuntimeArgsForNode(compute_run_args.runtime_arg_values, core, {{"NCHt", num_tile_rows_per_core}});

        curr_row += num_tile_rows_per_core;
    }

    ////////////////////////////////////////////////////////////////////////////
    //                      Assemble
    ////////////////////////////////////////////////////////////////////////////
    if (affine_mcast) {
        spec.kernels = {
            std::move(reader), std::move(reader_mcast_receiver.value()), std::move(writer), std::move(compute)};
        spec.work_units = {
            m2::WorkUnitSpec{
                .name = "affine_sender",
                .kernels = {READER, WRITER, COMPUTE},
                .target_nodes = affine_mcast_sender_cores,
            },
            m2::WorkUnitSpec{
                .name = "affine_receivers",
                .kernels = {READER_MCAST_RECEIVER, WRITER, COMPUTE},
                .target_nodes = affine_mcast_receiver_cores,
            },
        };
    } else {
        spec.kernels = {std::move(reader), std::move(writer), std::move(compute)};
        spec.work_units = {m2::WorkUnitSpec{
            .name = "main",
            .kernels = {READER, WRITER, COMPUTE},
            .target_nodes = all_cores,
        }};
    }

    m2::ProgramRunArgs run_args;
    if (affine_mcast) {
        run_args.kernel_run_args = {
            std::move(reader_run_args),
            std::move(reader_mcast_receiver_run_args),
            std::move(writer_run_args),
            std::move(compute_run_args),
        };
    } else {
        run_args.kernel_run_args = {
            std::move(reader_run_args), std::move(writer_run_args), std::move(compute_run_args)};
    }
    run_args.tensor_args.emplace(INPUT, a.mesh_tensor());
    run_args.tensor_args.emplace(OUTPUT, output.mesh_tensor());
    if (b) {
        run_args.tensor_args.emplace(RESIDUAL, b.value().mesh_tensor());
    }
    if (gamma.has_value()) {
        run_args.tensor_args.emplace(GAMMA_T, gamma.value().mesh_tensor());
    }
    if (beta.has_value()) {
        run_args.tensor_args.emplace(BETA_T, beta.value().mesh_tensor());
    }
    if (use_welford) {
        run_args.tensor_args.emplace(RECIP, recip_tensor.value().mesh_tensor());
    }

    return ttnn::device_operation::ProgramArtifacts{
        .spec = std::move(spec),
        .run_params = std::move(run_args),
    };
}

CoreRangeSet LayerNormMultiCoreProgramFactory::default_core_range(IDevice* device) {
    auto grid_size = device->compute_with_storage_grid_size();
    return CoreRangeSet({CoreRange({0, 0}, {grid_size.x - 1, grid_size.y - 1})});
}


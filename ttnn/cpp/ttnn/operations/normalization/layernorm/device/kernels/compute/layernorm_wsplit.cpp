// Width-split copy of layernorm.cpp (LayerNormDefaultProgramConfig.width_split = nsplit > 1, RMSNorm only): this core
// owns Wt of the row's tiles. Its partial mean of squares (sum over its tiles / full W) goes to the reader through
// dfb::part; the reader exchanges it with the row's other nsplit - 1 cores and returns all nsplit partials in
// dfb::recv, whose sum + eps gives 1/rms. Everything else (streaming pre-add, h, x^2, normalize, gamma) is unchanged.
//

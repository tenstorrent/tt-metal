void add_kernel_and_work_unit_specs(
    m2::ProgramSpec& spec,
    const CoreRanges& core_ranges,
    const WorkerDistribution& workers,
    const GridParams& grid,
    const SpecConfig& config,
    uint32_t writer_num_varargs);


"""Host-only: copy conv2d_3x3's BLOCK / HEIGHT / layouts unit tests into unit_copy/, retargeted at this experiment's op
copy with WIDE_UNTILIZE set from WU_KNOB (default 2 = hybrid). No ttnn import.

    python3 make_unit_copies.py
    WU_KNOB=2 scripts/run_safe_pytest.sh --run-all --import-mode=prepend -p no:cacheprovider .../wide_untilize/unit_copy
"""

from pathlib import Path

HERE = Path(__file__).parent
SRC = HERE.parents[5] / "tests/ttnn/unit_tests/operations/conv2d_3x3"
DST = HERE / "unit_copy"
PKG = "wide_untilize_op_copy"

PREAMBLE = f"""# Generated by make_unit_copies.py from {{src}}: retargeted at the wide_untilize op copy.
import os as _wu_os
import sys as _wu_sys
import types as _wu_types
from pathlib import Path as _WuPath

if "{PKG}" not in _wu_sys.modules:
    _wu_pkg = _wu_types.ModuleType("{PKG}")
    _wu_pkg.__path__ = [str(_WuPath(__file__).resolve().parent.parent / "op_copy")]
    _wu_sys.modules["{PKG}"] = _wu_pkg
import importlib as _wu_importlib

_wu_pd = _wu_importlib.import_module("{PKG}.conv2d_3x3_program_descriptor")
_wu_pd.WIDE_UNTILIZE = int(_wu_os.environ.get("WU_KNOB", "2"))
"""


def main():
    DST.mkdir(exist_ok=True)
    for name in ("test_conv2d_3x3_block_sharded.py", "test_conv2d_3x3_height_sharded.py", "test_conv2d_3x3_layouts.py"):
        text = (SRC / name).read_text()
        text = text.replace("from ttnn.operations.conv2d_3x3 import", f"from {PKG}.conv2d_3x3 import").replace(
            '"ttnn.operations.conv2d_3x3.', f'"{PKG}.'
        )
        assert "ttnn.operations.conv2d_3x3" not in text, name
        (DST / name).write_text(PREAMBLE.format(src=name) + text)
        print("wrote", DST / name)


if __name__ == "__main__":
    main()

"""Host-only: copy conv2d_3x3's BLOCK / HEIGHT / layouts unit tests into unit_copy/, retargeted at this experiment's op
copy with the narrow_untilize knobs applied (NU_KNOBS, e.g. "NARROW_UNTILIZE=1,WIDE_UNTILIZE_BATCH=0"). No ttnn import.

    python3 make_unit_copies.py
    NU_KNOBS=NARROW_UNTILIZE=1 scripts/run_safe_pytest.sh --run-all --import-mode=prepend .../narrow_untilize/unit_copy
"""

from pathlib import Path

HERE = Path(__file__).parent
SRC = HERE.parents[5] / "tests/ttnn/unit_tests/operations/conv2d_3x3"
DST = HERE / "unit_copy"
PKG = "narrow_untilize_op_copy"

PREAMBLE = f"""# Generated by make_unit_copies.py from {{src}}: retargeted at the narrow_untilize op copy.
import os as _nu_os
import sys as _nu_sys
import types as _nu_types
from pathlib import Path as _NuPath

if "{PKG}" not in _nu_sys.modules:
    _nu_pkg = _nu_types.ModuleType("{PKG}")
    _nu_pkg.__path__ = [str(_NuPath(__file__).resolve().parent.parent / "op")]
    _nu_sys.modules["{PKG}"] = _nu_pkg
import importlib as _nu_importlib

_nu_pd = _nu_importlib.import_module("{PKG}.conv2d_3x3_program_descriptor")
for _nu_kv in [kv for kv in _nu_os.environ.get("NU_KNOBS", "").split(",") if kv]:
    _nu_k, _nu_v = _nu_kv.split("=")
    setattr(_nu_pd, _nu_k, int(_nu_v))
"""


def main():
    DST.mkdir(exist_ok=True)
    for name in ("test_conv2d_3x3_block_sharded.py", "test_conv2d_3x3_height_sharded.py", "test_conv2d_3x3_layouts.py"):
        text = (SRC / name).read_text()
        text = text.replace("from ttnn.operations.conv2d_3x3 import", f"from {PKG}.conv2d_3x3 import").replace(
            '"ttnn.operations.conv2d_3x3.', f'"{PKG}.'
        )
        assert "ttnn.operations.conv2d_3x3" not in text, name
        (DST / name).write_text(PREAMBLE.format(src=name) + text)
        print("wrote", DST / name)


if __name__ == "__main__":
    main()

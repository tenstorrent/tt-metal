"""Generate test_<unit file>_grad.py copies of tests/ttnn/unit_tests/operations/conv2d_3x3/<unit file> pointed at this
dir's grad/ copy (WSL_UT_PKG=op_base for the base), with every `import torch` moved into the functions that use it
(the repo's pre-commit hook rejects module-level torch imports anywhere under ttnn/).

    python3 mk_ut.py [test_conv2d_3x3_block_sharded.py ...]"""

import ast
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
UNIT = HERE.parents[5] / "tests/ttnn/unit_tests/operations/conv2d_3x3"
PKG = "ttnn.operations.conv2d_3x3"


def make(name):
    src = Path("/tmp/wsl/ut_new.py") if name == "test_conv2d_3x3_block_sharded.py" else UNIT / name
    text = src.read_text()
    tree = ast.parse(text)
    lines = text.splitlines(keepends=True)
    edits = []  # (first line idx, last line idx, replacement)
    for node in tree.body:
        if isinstance(node, ast.Import) and any(a.name == "torch" for a in node.names):
            edits.append((node.lineno - 1, node.end_lineno - 1, ""))
        elif isinstance(node, ast.ImportFrom) and node.module == PKG:
            rep = "".join(f"{a.asname or a.name} = _op_module.{a.name}\n" for a in node.names)
            edits.append((node.lineno - 1, node.end_lineno - 1, rep))
        elif isinstance(node, ast.Assign) and f'import_module("{PKG}.' in ast.get_source_segment(text, node):
            seg = ast.get_source_segment(text, node)
            tgt = node.targets[0].id
            if seg.endswith('_program_descriptor")'):
                edits.append((node.lineno - 1, node.end_lineno - 1, f"{tgt} = _pd\n"))
            else:
                edits.append((node.lineno - 1, node.end_lineno - 1, f"{tgt} = _op_module\n"))
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and "torch." in ast.unparse(node):
            first = node.body[0]
            edits.append((first.lineno - 1, first.lineno - 2, " " * first.col_offset + "import torch\n"))
    for lo, hi, rep in sorted(edits, key=lambda e: e[0], reverse=True):
        lines[lo : hi + 1] = [rep]
    loader = (
        "import os as _wsl_os\nimport sys as _wsl_sys\n\n"
        f"_wsl_sys.path.insert(0, {str(HERE)!r})\n"
        "from op_copies import copy_modules  # noqa: E402\n\n"
        '_op_module, _pd = copy_modules(_wsl_os.environ.get("WSL_UT_PKG", "grad"))\n'
    )
    out = "".join(lines)
    # the loader right after the module docstring
    first_stmt = ast.parse(out).body[1].lineno - 1
    out_lines = out.splitlines(keepends=True)
    out_lines.insert(first_stmt, loader)
    header = f"# Generated by mk_ut.py from tests/ttnn/unit_tests/operations/conv2d_3x3/{name} at ec6f75b0d28 (+ unit_tests.patch), pointed at grad/.\n"
    out = header + "".join(out_lines)
    tree2 = ast.parse(out)
    assert not [n for n in tree2.body if isinstance(n, (ast.Import, ast.ImportFrom)) and "torch" in ast.unparse(n)]
    dst = HERE / (name.replace(".py", "") + "_grad.py")
    dst.write_text(out)
    print("wrote", dst.name)


for name in sys.argv[1:] or ["test_conv2d_3x3_block_sharded.py"]:
    make(name)

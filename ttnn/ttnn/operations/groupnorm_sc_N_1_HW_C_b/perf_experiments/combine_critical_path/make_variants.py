"""Generate the per-variant kernel dirs (kernels_<name>/) of the combine_critical_path bake-off.

Each dir holds the baseline reader / writer (kernels_base, a byte copy of the op's kernels) and a compute kernel:
the baseline compute for `base`, else cand_src/compute.cpp with the variant's CCP_* switches prepended. Standalone
files (no relative include), so the JIT cache key always sees the full source.

Profiler zone ids are a 16-bit FNV-1a of "name,FILE,LINE,KERNEL_PROFILER"; a session that loads several variant dirs
can hit two different sites with the same id (TT_THROW "Source location hashes are colliding"). Each variant dir is
therefore padded with leading comment lines until none of its zone ids collides with the base dir, the earlier
variants, or the firmware / kernel_lib zone strings harvested from logs/*.log.

usage: make_variants.py
"""
from pathlib import Path
import re
import shutil

HERE = Path(__file__).parent
BASE = HERE / "kernels_base"
CAND = HERE / "cand_src" / "compute.cpp"
NAME = "groupnorm_sc_N_1_HW_C_b_{}.cpp"

# variant -> CCP switches (None = the baseline compute)
VARIANTS = {
    "vpub": dict(CCP_VPUB=1, CCP_FIN=0, CCP_MM1=0),
    "fin": dict(CCP_VPUB=0, CCP_FIN=1, CCP_MM1=0),
    "both": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=0),
    "all": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=1),
    "basez": dict(CCP_VPUB=0, CCP_FIN=0, CCP_MM1=0, CCP_SUBZONES=1),
    "bothz": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=0, CCP_SUBZONES=1),
    "allz": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=1, CCP_SUBZONES=1),
    # code-layout probes: 'both' with N nops after the root finalize (shifts only the root binary's pass 2)
    "both_n1": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=0, CCP_PADNOPS='"1"'),
    "both_n2": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=0, CCP_PADNOPS='"2"'),
    "both_n4": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=0, CCP_PADNOPS='"4"'),
    "both_n8": dict(CCP_VPUB=1, CCP_FIN=1, CCP_MM1=0, CCP_PADNOPS='"8"'),
}


ZONE_RE = re.compile(r'(?:ZoneScope\w*|DeviceZoneScopedN)\s*\((?:[^,"]*,\s*)?"([^"]+)"')
PAD = "// zone-id pad (make_variants.py)\n"


def hash16(s):
    h = 2166136261
    for c in s.encode():
        h = ((h ^ c) * 16777619) & 0xFFFFFFFF
    return ((h & 0xFFFF) ^ (h >> 16)) & 0xFFFF


def zone_strings(path, text):
    out = []
    for i, line in enumerate(text.splitlines(), 1):
        for m in ZONE_RE.finditer(line):
            out.append(f"{m.group(1)},{path},{i},KERNEL_PROFILER")
    return out


def harvested():
    out = set()
    for log in (HERE / "logs").glob("*.log"):
        for m in re.finditer(r"#pragma message: ([^'\n]*KERNEL_PROFILER)", log.read_text(errors="ignore")):
            if "combine_critical_path" not in m.group(1):
                out.add(m.group(1))
    return out


def main():
    src = CAND.read_text()
    taken = {}  # id -> string
    for s in sorted(harvested()):
        taken.setdefault(hash16(s), s)
    for role in ("reader", "writer", "compute"):
        f = BASE / NAME.format(role)
        for s in zone_strings(str(f.resolve()), f.read_text()):
            if taken.get(hash16(s), s) != s:
                print(f"WARNING: base zone id collision {s} vs {taken[hash16(s)]}")
            taken.setdefault(hash16(s), s)
    for name, sw in VARIANTS.items():
        d = HERE / f"kernels_{name}"
        d.mkdir(exist_ok=True)
        head = "".join(f"#define {k} {v}\n" for k, v in sw.items())
        bodies = {
            "reader": (BASE / NAME.format("reader")).read_text(),
            "writer": (BASE / NAME.format("writer")).read_text(),
            "compute": f"// generated by make_variants.py: variant {name}\n{head}{src}",
        }
        for pad in range(64):
            texts = {r: PAD * pad + b for r, b in bodies.items()}
            strs = [s for r, t in texts.items() for s in zone_strings(str((d / NAME.format(r)).resolve()), t)]
            ids = [hash16(s) for s in strs]
            if len(set(ids)) == len(ids) and not any(i in taken for i in ids):
                break
        else:
            raise SystemExit(f"no collision-free pad for {name}")
        for r, t in texts.items():
            (d / NAME.format(r)).write_text(t)
        for s, i in zip(strs, ids):
            taken[i] = s
        print(f"kernels_{name}: {sw} pad {pad} ({len(strs)} zone sites)")


if __name__ == "__main__":
    main()

"""dynamic_claim_v2: dispatcher-core work queue for clamp_square_practice.

Variants:
  baseline                     - the op's own descriptor (unchanged)
  disp[_p<P>][_h<H>][_f<F>][_k<K>][_r<R>][_b<B>]
                               - W = grid-1 workers + 1 dispatcher core (the last core, row-wise).
                                 First round (one guided chunk per worker) is host-assigned; the rest of
                                 the blocks are handed out by the dispatcher on request (guided
                                 self-scheduling). Recommended: disp_f4. P = grant prefetch depth (1|2),
                                 H = writer-pacing window
                                 (blocks), F/K = guided chunking: chunk = clamp(ceil(rem/(F*W)), 1, K)
                                 blocks, R = rate ramp (k-th grant <= R << k blocks; 0 = off),
                                 B = block tiles override. Defaults p2 h2 f2 k16 r0.
Env knobs (diagnostics only): DC_REQ_STRIDE, DC_UNROLL, DC_READY_MCAST, DC_GRANT_FLUSH.
"""
import os
from pathlib import Path

import ttnn

from ttnn.operations.clamp_square_practice import clamp_square_practice_program_descriptor as pd

HERE = Path(__file__).parent
KDIR = HERE / "kernels"
CB_IN, CB_OUT, CB_IDX, CB_REQ = 0, 1, 2, 3
IDX_PAGE = 16
IDX_DEPTH = 8
NUM_SEMS = 5  # GRANT0, GRANT1, PUB, WRITTEN, READY


def gen_compute():
    """Op compute kernel body (ClampSquareFused etc.) + the dynamic kernel_main."""
    src = (Path(pd.KERNEL_DIR) / "clamp_square_practice_compute.cpp").read_text()
    head = src[: src.index("void kernel_main()")]
    out = KDIR / "gen_compute.cpp"
    text = (
        "// GENERATED by descriptor.py from the op's compute kernel + compute_main.inc. Do not edit.\n"
        + head
        + (HERE / "compute_main.inc").read_text()
    )
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out


def parse(variant):
    cfg = {"alpha": 0, "P": 2, "H": 2, "B": None, "F": 2, "K": 16, "R": 0}
    for part in variant.split("_")[1:]:
        k, v = part[0], int(part[1:])
        cfg[{"a": "alpha", "p": "P", "h": "H", "b": "B", "f": "F", "k": "K", "r": "R"}[k]] = v
    return cfg


def dispatcher(x, out, min_val, max_val, alpha=0, P=2, H=2, B=None, F=2, K=16, R=0, stats=None):
    device = x.device()
    grid = device.compute_with_storage_grid_size()
    gx, gy = grid.x, grid.y
    assert gx >= 2 and gy >= 2
    T = x.buffer_num_pages()
    pb_in, pb_out = x.buffer_page_size(), out.buffer_page_size()
    all_cores = ttnn.CoreRangeSet([ttnn.CoreRange(ttnn.CoreCoord(0, 0), ttnn.CoreCoord(gx - 1, gy - 1))])
    disp = ttnn.CoreCoord(gx - 1, gy - 1)
    workers_set = ttnn.CoreRangeSet(
        [
            ttnn.CoreRange(ttnn.CoreCoord(0, 0), ttnn.CoreCoord(gx - 1, gy - 2)),
            ttnn.CoreRange(ttnn.CoreCoord(0, gy - 1), ttnn.CoreCoord(gx - 2, gy - 1)),
        ]
    )
    disp_set = ttnn.CoreRangeSet([ttnn.CoreRange(disp, disp)])
    workers = ttnn.corerange_to_cores(workers_set, row_wise=True)
    W = len(workers)

    per_core = -(-T // W)
    bt = max(1, min(B or pd.BLOCK_TILES_DEFAULT, pd.dest_limit(pd.FP32_DEST_ACC_EN, pd.DST_FULL_SYNC_EN), per_core))
    assert alpha == 0, "static share removed: measured to hurt (per-core write rates differ up to 7x)"
    pool_start = 0
    pool_blocks = -(-T // bt)
    assert pool_blocks < (1 << 20), "grant encoding: first_block needs 20 bits"
    # First round: one chunk per worker, the dispatcher's formula with grant index 0 (host-side, no message).
    first = []
    nxt = 0
    for _ in range(W):
        cnt = 0
        if nxt < pool_blocks:
            cnt = min(-(-(pool_blocks - nxt) // (F * W)), K)
            if R > 0:
                cnt = min(cnt, R)
        first.append((nxt, cnt))
        nxt += cnt
    first_round = nxt
    dynamic = 1 if first_round < pool_blocks else 0

    stride = int(os.environ.get("DC_REQ_STRIDE", "1"))  # REQ words per worker (1 = 4 B, 4 = 16 B)
    req_cb = 0  # set below
    # CB depth: the op's 32 blocks, capped at the fair share + window (a CB that covers everything a core
    # can hold in flight never blocks).
    cap = (-(-per_core // bt) + H + P + 1) * bt
    in_tiles = min(pd.INPUT_DEPTH_BLOCKS * bt, cap)
    out_tiles = min(pd.OUTPUT_DEPTH_BLOCKS * bt, cap)
    req_cb = ((W * stride * 4 + 15) // 16) * 16 + ((W * 4 + 15) // 16) * 16 + W * 16 + 64
    cbs = [
        ttnn.CBDescriptor(
            total_size=in_tiles * pb_in,
            core_ranges=workers_set,
            format_descriptors=[ttnn.CBFormatDescriptor(buffer_index=CB_IN, data_format=x.dtype, page_size=pb_in)],
        ),
        ttnn.CBDescriptor(
            total_size=out_tiles * pb_out,
            core_ranges=workers_set,
            format_descriptors=[ttnn.CBFormatDescriptor(buffer_index=CB_OUT, data_format=out.dtype, page_size=pb_out)],
        ),
        ttnn.CBDescriptor(
            total_size=IDX_DEPTH * IDX_PAGE,
            core_ranges=workers_set,
            format_descriptors=[
                ttnn.CBFormatDescriptor(buffer_index=CB_IDX, data_format=ttnn.uint32, page_size=IDX_PAGE)
            ],
        ),
        # REQ[W] (16 B each) + served[W] on the dispatcher. Declared on every core so its L1 address is the
        # same everywhere (workers compute the remote REQ address from their own get_write_ptr(cb_req)).
        ttnn.CBDescriptor(
            total_size=req_cb,
            core_ranges=all_cores,
            format_descriptors=[
                ttnn.CBFormatDescriptor(buffer_index=CB_REQ, data_format=ttnn.uint32, page_size=req_cb)
            ],
        ),
    ]

    dphys = device.worker_core_from_logical_core(disp)
    disp_xy = dphys.x | (dphys.y << 16)
    mn, mx = pd._fp32_bits(min_val), pd._fp32_bits(max_val)
    r_rt, w_rt, c_rt, d_rt = ttnn.RuntimeArgs(), ttnn.RuntimeArgs(), ttnn.RuntimeArgs(), ttnn.RuntimeArgs()
    wxy = []
    for i, c in enumerate(workers):
        b0, cnt = first[i]
        f_start, f_tiles = b0 * bt, max(0, min(cnt * bt, T - b0 * bt))
        r_rt[c.x][c.y] = [x.buffer_address(), f_start, f_tiles, pool_start, T, disp_xy, i, dynamic] + (
            [stats.buffer_address()] if stats is not None else []
        )
        w_rt[c.x][c.y] = [out.buffer_address(), f_start, f_tiles]
        c_rt[c.x][c.y] = [f_tiles, mn, mx]
        p = device.worker_core_from_logical_core(c)
        wxy.append(p.x | (p.y << 16))
    lo = device.worker_core_from_logical_core(ttnn.CoreCoord(0, 0))
    hi = device.worker_core_from_logical_core(ttnn.CoreCoord(gx - 1, gy - 1))
    d_rt[disp.x][disp.y] = (
        [pool_blocks, first_round]
        + wxy
        + ([stats.buffer_address()] if stats is not None else [])
        + [lo.x | (lo.y << 16), hi.x | (hi.y << 16)]
    )

    r_ct = [CB_IN, CB_IDX, CB_REQ, bt, pb_in, P, H] + list(ttnn.TensorAccessorArgs(x).get_compile_time_args())
    if stats is not None:
        r_ct += list(ttnn.TensorAccessorArgs(stats).get_compile_time_args())
        cbs.append(
            ttnn.CBDescriptor(
                total_size=64,
                core_ranges=workers_set,
                format_descriptors=[ttnn.CBFormatDescriptor(buffer_index=4, data_format=ttnn.uint32, page_size=64)],
            )
        )
    w_ct = [CB_OUT, CB_IDX, bt, pb_out] + list(ttnn.TensorAccessorArgs(out).get_compile_time_args())
    kernels = [
        ttnn.KernelDescriptor(
            kernel_source=str(KDIR / "reader.cpp"),
            core_ranges=workers_set,
            defines=[("REQ_STRIDE_WORDS", str(stride))] + ([("DC_STATS", "1")] if stats is not None else []),
            compile_time_args=r_ct,
            runtime_args=r_rt,
            config=ttnn.ReaderConfigDescriptor(),
        ),
        ttnn.KernelDescriptor(
            kernel_source=str(KDIR / "writer.cpp"),
            core_ranges=workers_set,
            compile_time_args=w_ct,
            runtime_args=w_rt,
            config=ttnn.WriterConfigDescriptor(),
        ),
        ttnn.KernelDescriptor(
            kernel_source=str(gen_compute()),
            core_ranges=workers_set,
            compile_time_args=[CB_IN, CB_OUT, bt],
            runtime_args=c_rt,
            config=ttnn.ComputeConfigDescriptor(
                fp32_dest_acc_en=pd.FP32_DEST_ACC_EN, dst_full_sync_en=pd.DST_FULL_SYNC_EN
            ),
        ),
        ttnn.KernelDescriptor(
            kernel_source=str(KDIR / "dispatcher.cpp"),
            core_ranges=disp_set,
            compile_time_args=[CB_REQ, P, W, F, K, R]
            + (list(ttnn.TensorAccessorArgs(stats).get_compile_time_args()) if stats is not None else []),
            defines=[
                ("GRANT_FLUSH", os.environ.get("DC_GRANT_FLUSH", "0")),
                ("REQ_STRIDE_WORDS", str(stride)),
                ("SWEEP_UNROLL", os.environ.get("DC_UNROLL", "8")),
                ("READY_MCAST", os.environ.get("DC_READY_MCAST", "1")),
            ]
            + ([("DC_STATS", "1")] if stats is not None else []),
            runtime_args=d_rt,
            config=ttnn.ReaderConfigDescriptor(),
        ),
    ]
    sems = [ttnn.SemaphoreDescriptor(id=i, core_ranges=all_cores, initial_value=0) for i in range(NUM_SEMS)]
    info = {"W": W, "bt": bt, "first_round": first_round, "pool_blocks": pool_blocks, "dynamic": dynamic}
    return ttnn.ProgramDescriptor(kernels=kernels, semaphores=sems, cbs=cbs), info


def build(variant, x, out, min_val, max_val, stats=None):
    if variant == "baseline":
        return pd.create_program_descriptor(x, out, min_val, max_val), {}
    if variant.startswith("disp"):
        return dispatcher(x, out, min_val, max_val, stats=stats, **parse(variant))
    raise ValueError(variant)

constexpr uint32_t LM_DM = 0, LM_DS = 2, LM_DR = 0, LM_DT = 2;  // must match gen.py
template <uint32_t scale_bf16>
inline void init() {
    // Instruction templates (backdoor install: VD = 12 + slot). Installed BEFORE the L12-14 constants.
    TTI_SFPMAD(p_sfpu::LREG12, 0, p_sfpu::LREG6, 12, 0);  // T0: VD = L12 * VD + L6 (VB := VD)
    TTI_SFPSWAP(0, p_sfpu::LCONST_0, 13, 9);              // T1: VD = max(VD, 0)  (min -> read-only LCONST_0)
    TTI_SFP_STOCH_RND(sfpi::SFPSTOCHRND_RND_EVEN, 0, 0, p_sfpu::LREG1, 14, sfpi::SFPSTOCHRND_MOD1_FP32_TO_FP16B);
    TTI_SFP_STOCH_RND(sfpi::SFPSTOCHRND_RND_EVEN, 0, 0, p_sfpu::LREG4, 15, sfpi::SFPSTOCHRND_MOD1_FP32_TO_FP16B);
    {  // seq 0 = LM_A: MAD T0 @LM_DM, SIMPLE T1 @LM_DS
        constexpr uint32_t simple_bits = 0x80 | (LM_DS << 3) | (4 + 1);
        constexpr uint32_t mad_bits = 0x80 | (LM_DM << 3) | (4 + 0);
        TTI_SFPLOADI(0, sfpi::SFPLOADI_MOD0_LOWER, (mad_bits << 8) | simple_bits);
        TTI_SFPLOADI(0, sfpi::SFPLOADI_MOD0_UPPER, 0);
        TTI_SFPCONFIG(0, 4 + 0, 0);
    }
    {  // seq 1 = LM_B (set X): ROUND T2 -> L16 @LM_DR, STORE L16 @LM_DT
        constexpr uint32_t round_bits = 0x80 | 0x40 | (LM_DR << 3) | (4 + 2);
        constexpr uint32_t store_bits = 0x40 | (LM_DT << 3) | 3;
        TTI_SFPLOADI(0, sfpi::SFPLOADI_MOD0_LOWER, 0);
        TTI_SFPLOADI(0, sfpi::SFPLOADI_MOD0_UPPER, (store_bits << 8) | round_bits);
        TTI_SFPCONFIG(0, 4 + 1, 0);
    }
    {  // seq 2 = LM_B (set Y): ROUND T3 -> L16 @LM_DR, STORE L16 @LM_DT
        constexpr uint32_t round_bits = 0x80 | 0x40 | (LM_DR << 3) | (4 + 3);
        constexpr uint32_t store_bits = 0x40 | (LM_DT << 3) | 3;
        TTI_SFPLOADI(0, sfpi::SFPLOADI_MOD0_LOWER, 0);
        TTI_SFPLOADI(0, sfpi::SFPLOADI_MOD0_UPPER, (store_bits << 8) | round_bits);
        TTI_SFPCONFIG(0, 4 + 2, 0);
    }
    TTI_SFPCONFIG(0xff0, 8, 1);  // Misc: UsesLoadMod0ForStore all, UnitDelayKind = WaitForElapsedInstructions
    load_consts<scale_bf16>();
}
// stall = true: the stock _llk_math_eltwise_sfpu_start_ (STALLWAIT(SFPU, MATH)); false: only point the SFPU at the
// DEST tile — on the PACK thread the MATH_PACK semaphore (posted with WAIT_SFPU | MATH) already ordered the tile.
template <bool stall = true>
inline void tile(uint32_t dst_index) {
    if constexpr (stall) {
        _llk_math_eltwise_sfpu_start_(dst_index);
    } else {
        math::set_dst_write_addr<DstTileShape::Tile32x32, UnpackDestination::SrcRegs>(dst_index);
    }
    load_tile_consts();
    LMEXP_PROLOGUE();
    TTI_REPLAY(0, LMEXP_BODY_LEN, 1, 1);
    LMEXP_BODY();
#pragma GCC unroll 0
    for (int k = 1; k < LMEXP_NBODIES; ++k) {
        TTI_REPLAY(0, LMEXP_BODY_LEN, 0, 0);
    }
    LMEXP_EPILOGUE();
    TTI_SFPNOP;  // drain margin for the last scheduled store
    TTI_SFPNOP;
    TTI_SFPNOP;
    _llk_math_eltwise_sfpu_done_();
}
// n consecutive DEST tiles starting at tile 0 of the current half, ONE SFPU start (stall) and ONE counter reset per
// group: each tile's stream advances the DEST RWC by exactly one tile (32 ADDR_MOD_6 (+2) LOADMACROs = 64 rows), so the
// next tile needs no SETC16 / SETRWC. stall_cond: the STALLWAIT(STALL_SFPU, cond) condition at group start (orders the
// previous group's SETRWC, a math-pipe instruction, before this group's SFPU stream).
template <uint32_t stall_cond>
inline void tiles(uint32_t n) {
    math::set_dst_write_addr<DstTileShape::Tile32x32, UnpackDestination::SrcRegs>(0);
    TTI_STALLWAIT(p_stall::STALL_SFPU, stall_cond);
#pragma GCC unroll 0
    for (uint32_t j = 0; j < n; ++j) {
        load_tile_consts();
        LMEXP_PROLOGUE();
        TTI_REPLAY(0, LMEXP_BODY_LEN, 1, 1);
        LMEXP_BODY();
#pragma GCC unroll 0
        for (int k = 1; k < LMEXP_NBODIES; ++k) {
            TTI_REPLAY(0, LMEXP_BODY_LEN, 0, 0);
        }
        LMEXP_EPILOGUE();
        TTI_SFPNOP;  // drain margin for the last scheduled store
        TTI_SFPNOP;
        TTI_SFPNOP;
    }
    _llk_math_eltwise_sfpu_done_();
}

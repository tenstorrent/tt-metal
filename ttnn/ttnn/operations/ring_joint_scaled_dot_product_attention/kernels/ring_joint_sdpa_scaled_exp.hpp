// ScaledExp<scale_bf16>: P = exp(scale * x) for the softmax chain (eltwise_chain UnaryOp: static init() + exec_impl()).
//
// RAW-LLK JUSTIFICATION: bypasses exp_tile<false, true>() (-> _sfpu_exp_21f_bf16_tti_, 17 issued SFPU instructions per
// 32-lane row, ~19.5 cycles/row, ~47% of the op) at bf16 DEST. Same exp_21f algorithm, same constants, bit-identical
// output on the softmax domain, with two mechanisms the helper cannot express:
//  (1) int/frac split by SFP_STOCH_RND(round-to-zero, fp32->uint16) + SFPCAST + one exact MAD (phi = t - floor t)
//      instead of EXEXP/EXMAN/SHFT/EXMAN9 + the [0,255] clamp; the poly coefficients are rescaled by exact powers of
//      two (c1*2^23, c2*2^46) so the Horner result is bit-identical, SFPSETEXP(mod 0) uses floor(t) as the exponent;
//      the scale is folded into the 1/ln2 MAD constant (K = fp32(s/ln2)) and t is clamped at 0 (SFPSWAP vs LCONST_0).
//  (2) SFPLOADMACRO software pipeline: per row LM_A = load + MAD(t) + SWAP(clamp), LM_B = bf16 RNE round + store,
//      6 explicit ops in between; rows 8 issue slots apart, 2 register sets, whole tile in one stream (replay body 16).
//      8 issue slots/row (~9.7 cycles/row measured) vs 17.
// Domain: bf16 DEST only (fp32 DEST -> stock exp_tile, a different algorithm); requires scale*x < 88.7 (t < 255;
// softmax inputs are <= 0 after the max subtraction, -inf -> exactly 0). NaN inputs are not preserved.
// State: init() clobbers LREG12/13/14, LOADMACRO templates 0-3, sequences 0-2 and the Misc config, ADDR_MOD_6/7
// (via exp_tile_init). exec clobbers LREG0-7, replay slots 0-15. Any SFPU op that runs later must run its own init
// (binary_max_min_init / recip_init do). init() must precede exec in the same chain (eltwise_chain guarantees it).

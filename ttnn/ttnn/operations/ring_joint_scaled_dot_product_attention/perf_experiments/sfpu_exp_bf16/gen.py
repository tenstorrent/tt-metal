# Generates the loadmacro-pipelined exp stream (32 rows / tile, 8 slots / row, 2 register sets).
import sys

O = dict(LMA=0, RN=5, CA=9, PHI=10, P1=12, P2=14, SE=15, LMB=19)
dM, dS, dR, dT = 0, 2, 0, 2
P = 8
R = 32
SETS = [dict(a=0, n=1, f=2), dict(a=3, n=4, f=5)]
last = P * (R - 1) + O["LMB"] + dT + 1
slot_ops = {}
for op, o in O.items():
    for r in range(R):
        t = P * r + o
        assert t not in slot_ops, (op, r, t, slot_ops.get(t))
        slot_ops[t] = (op, r)


def instr(t, D):
    if t not in slot_ops:
        return "TTI_SFPNOP;"
    op, r = slot_ops[t]
    s = SETS[r % 2]
    a, n, f = s["a"], s["n"], s["f"]
    if op == "LMA":
        return f"TTI_SFPLOADMACRO({(0<<2)|(a&3)}, 0, ADDR_MOD_6, {0|(a>>2)});"
    if op == "RN":
        return f"TTI_SFP_STOCH_RND(2, 0, 0, {a}, {n}, 6);"
    if op == "CA":
        return f"TTI_SFPCAST({n}, {f}, 0);"
    if op == "PHI":
        return f"TTI_SFPMAD({f}, p_sfpu::LCONST_1, {a}, {f}, 1);"
    if op == "P1":
        return f"TTI_SFPMAD({f}, p_sfpu::LREG13, p_sfpu::LREG14, {a}, 0);"
    if op == "P2":
        return f"TTI_SFPMAD({a}, {f}, p_sfpu::LREG7, {a}, 0);"
    if op == "SE":
        return f"TTI_SFPSETEXP(0, {a}, {n}, 0);"
    if op == "LMB":
        off = (2 * r - D) & 0x3FF
        assert off % 2 == 0
        return f"TTI_SFPLOADMACRO({((1 + r % 2)<<2)|(f&3)}, 0, ADDR_MOD_7, {off|(f>>2)});"


stream = []
D = 0
for t in range(last + 1):
    stream.append(instr(t, D))
    if t in slot_ops and slot_ops[t][0] == "LMA":
        D += 2
T0, BODY = 32, 16
steady_end = 256  # first slot after the last LM_A window
nb = (steady_end - T0) // BODY
body = stream[T0 : T0 + BODY]
for k in range(nb):
    assert stream[T0 + k * BODY : T0 + (k + 1) * BODY] == body, k
out = []
out.append("// ---- generated by gen.py: schedule " + str(O) + f" delays mad={dM} swap={dS} rnd={dR} store={dT}")
out.append("#define LMEXP_PROLOGUE() do { \\")
out += ["    " + x + " \\" for x in stream[:T0]]
out.append("} while (0)")
out.append(f"#define LMEXP_BODY_LEN {BODY}")
out.append(f"#define LMEXP_NBODIES {nb}")
out.append("#define LMEXP_BODY() do { \\")
out += ["    " + x + " \\" for x in body]
out.append("} while (0)")
out.append("#define LMEXP_EPILOGUE() do { \\")
out += ["    " + x + " \\" for x in stream[steady_end:]]
out.append("} while (0)")
out.append(f"// slots per tile: {len(stream)} ({len(stream)/R:.2f}/row)")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print(len(stream), nb)

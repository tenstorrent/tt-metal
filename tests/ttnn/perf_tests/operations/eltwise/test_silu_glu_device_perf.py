"""
Device kernel time of ttnn.silu_glu's one binary_ng program against the composite it replaces.

Generated by tt-polynomial-fitter from activations/products/silu_glu.json. The composite runs in this build one float32
step off the parameters the kernel is compiled for, where the program does not apply: the same programs, whose
cost does not depend on the parameters' values. Before anything is timed each call must launch the path it
names. Both run in one profiled process on the same BF16 operands; a call's time is the device kernel duration
summed over the programs it launches, the median of REPEATS calls, and the program must be faster by more than
MARGIN.
"""

import pandas as pd

import pytest
import torch
import ttnn
from loguru import logger

# The public parameters () silu_glu_tile is compiled for.
PARAMETERS = ()
# The boards the route runs silu_glu_tile on; Wormhole keeps the composite.
ROUTE_BOARDS = ("blackhole",)
OP_TYPE = "SILU_GLU"


def _board(device=None):
    return "blackhole" if ttnn.device.is_blackhole(device) else "wormhole_b0"


def _device_operations(call):
    """The result of ``call``, the device operations it launches and their arguments, as graph capture names them."""
    ttnn.graph.begin_graph_capture(ttnn.graph.RunMode.NORMAL)
    try:
        result = call()
    finally:
        graph = ttnn.graph.end_graph_capture()
    operations = [name for name in ttnn.graph.extract_calltrace(graph) if "DeviceOperation" in name]
    arguments = " ".join(str(argument) for node in graph for argument in node.get("arguments", []))
    return result, operations, arguments


def _off_parameters():
    """Each parameter one float32 step above the compiled one: the composite's own programs at the same cost."""
    return tuple(
        float(torch.nextafter(torch.tensor(p, dtype=torch.float32), torch.tensor(float("inf")))) for p in PARAMETERS
    )


SHAPES = [(512, 512), (1024, 1024)]
REPEATS = 5
MARGIN = 0.05
# Operands span each leaf's clamp or saturation point twice over.
REACH = (32.0, 32.0)
PATH = "tests/ttnn/perf_tests/operations/eltwise/test_silu_glu_device_perf.py"


def _inputs(height, width, device):
    generator = torch.Generator().manual_seed(0)
    tensors = []
    for reach in REACH:
        x = reach * (2 * torch.rand((1, 1, height, width), generator=generator) - 1)
        tensors.append(
            ttnn.from_torch(x.to(torch.bfloat16), dtype=ttnn.bfloat16, layout=ttnn.TILE_LAYOUT, device=device)
        )
    return tensors


def _calls(a, b):
    return {
        "composite": lambda: ttnn.multiply(ttnn.silu(a), b),
        "fused": lambda: ttnn.silu_glu(a, b, *PARAMETERS),
    }


def test_silu_glu_profiled_calls(device):
    """Each call's path, then the calls the device-perf test profiles, between signposts that name each one."""
    from tracy import signpost

    if _board(device) not in ROUTE_BOARDS:
        pytest.skip("this board keeps the composite")
    for height, width in SHAPES:
        a, b = _inputs(height, width, device)
        for path, call in _calls(a, b).items():
            # Graph capture runs the call once, which also compiles its programs.
            result, operations, arguments = _device_operations(call)
            ttnn.deallocate(result)
            assert (OP_TYPE in arguments) == (path == "fused"), f"the {path} call ran the other path"
            if path == "fused":
                assert len(set(operations)) == 1, f"the fused call launched {operations}"
            for repeat in range(REPEATS):
                signpost(f"{path}-{height}x{width}-{repeat}-start")
                ttnn.deallocate(call())
                signpost(f"{path}-{height}x{width}-{repeat}-end")
        ttnn.synchronize_device(device)


def _kernel_ns_per_region(csv_path):
    """Per pair of signposts, the device kernel duration summed over the programs between them, and their count."""
    regions, current = {}, None
    for _, row in pd.read_csv(csv_path).iterrows():
        if row["OP TYPE"] == "signpost":
            code = row["OP CODE"]
            current = code.removesuffix("-start") if code.endswith("-start") else None
            if current is not None:
                regions[current] = [0.0, 0]
        elif current is not None and str(row["DEVICE KERNEL DURATION [ns]"]) not in ("-", "nan"):
            regions[current][0] += float(row["DEVICE KERNEL DURATION [ns]"])
            regions[current][1] += 1
    return regions


@pytest.mark.models_device_performance_bare_metal
def test_silu_glu_device_perf():
    from tracy.common import clear_profiler_runtime_artifacts
    from tracy.process_model_log import get_latest_ops_log_filename, run_device_profiler

    board = _board()
    if board not in ROUTE_BOARDS:
        pytest.skip("this board keeps the composite")
    subdir = "silu_glu_device_perf"
    clear_profiler_runtime_artifacts()
    run_device_profiler(
        f"pytest {PATH}::test_silu_glu_profiled_calls", subdir, device_analysis_types=["device_kernel_duration"]
    )
    regions = _kernel_ns_per_region(get_latest_ops_log_filename(subdir))
    slow = []
    for height, width in SHAPES:
        per_call = {}
        for path in ("composite", "fused"):
            measured = [regions[f"{path}-{height}x{width}-{repeat}"] for repeat in range(REPEATS)]
            assert all(programs for _, programs in measured), f"a {path} call at {height}x{width} launched no program"
            per_call[path] = (sorted(ns for ns, _ in measured)[REPEATS // 2], measured[0][1])
        (composite, composite_programs), (fused, fused_programs) = per_call["composite"], per_call["fused"]
        logger.info(
            f"DEVICE_PERF silu_glu {board} {height}x{width} composite={composite:.0f}ns ({composite_programs} programs) "
            f"fused={fused:.0f}ns ({fused_programs} programs) speedup={composite / fused:.2f}x"
        )
        if fused > composite * (1 - MARGIN):
            slow.append(f"{height}x{width}: fused {fused:.0f} ns, composite {composite:.0f} ns")
    assert not slow, f"the program is not {MARGIN:.0%} faster than the composite: {slow}"

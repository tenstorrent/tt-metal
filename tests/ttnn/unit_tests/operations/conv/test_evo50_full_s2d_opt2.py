def _pack_weight_s2d(w, r=2):
    """[OC, C, kH, kW] -> [OC, C*r*r, ceil(kH/r), ceil(kW/r)], CHANNEL_MAJOR (c' = c*r*r + dy*r + dx)."""
    OC, C, kH, kW = w.shape
    kHp, kWp = -(-kH // r), -(-kW // r)
    wp = F.pad(w, (0, kWp * r - kW, 0, kHp * r - kH)).reshape(OC, C, kHp, r, kWp, r).permute(0, 1, 3, 5, 2, 4)
    return wp.reshape(OC, C * r * r, kHp, kWp)


def _hoist_50881318(w):
    """16x3x7x7 stride-2 stem weights -> 16x16x4x4 space-to-depth weights (12 packed channels + 4 zero channels)."""
    p = _pack_weight_s2d(w.float())
    return F.pad(p, (0, 0, 0, 0, 0, 16 - p.shape[1]))


def _hoist_2eefe5d4(b):
    """1x96x1x1 -> 1x1x1x96."""
    return b.reshape(1, 1, 1, -1)



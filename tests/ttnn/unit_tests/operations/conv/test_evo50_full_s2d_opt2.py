def _pcc(a, b):
    a = a.flatten().to(torch.float64)
    b = b.flatten().to(torch.float64)
    a, b = a - a.mean(), b - b.mean()
    d = a.norm() * b.norm()
    return 1.0 if d == 0 else (torch.dot(a, b) / d).item()


@pytest.mark.parametrize("device_params", [{"l1_small_size": 32768}], indirect=True)
def test_evo50_full_s2d_opt2(device):
    P = load_params()
    x = torch.from_numpy(np.load(f"{DATA_DIR}/evo50_inputs.npz")["input_luv"]).to(torch.bfloat16)
    zo = np.load(f"{DATA_DIR}/evo50_ort.npz")
    output_names = list(zo.files)
    ort = {n: torch.from_numpy(zo[n]).float() for n in output_names}
    T = prep_weights(device, P)

    def run():
        for k, _, lay in INPUTS:
            T[f"%arg{k}"] = ttnn.from_torch(
                x, dtype=ttnn.bfloat16, layout=ttnn.ROW_MAJOR_LAYOUT, device=device, memory_config=_mc(lay)
            )
        outs = []
        for o in forward(device, T):  # runtime output conversion: TILE -> ROW_MAJOR in DRAM
            if o.layout == ttnn.TILE_LAYOUT:
                o2 = ttnn.to_layout(o, ttnn.ROW_MAJOR_LAYOUT, memory_config=ttnn.DRAM_MEMORY_CONFIG)
                ttnn.deallocate(o)
                o = o2
            outs.append(o)
        return outs

    for o in run():  # warm-up: program cache + conv weight preparation
        ttnn.deallocate(o)
    ttnn.synchronize_device(device)

    signpost(header="evo50_inference-start")
    outs = run()
    ttnn.synchronize_device(device)
    signpost(header="evo50_inference-end")
    results = [ttnn.to_torch(o).float() for o in outs]

    worst = (1.0, None)
    for name, r in zip(output_names, results):
        assert list(r.shape) == list(ort[name].shape), (name, list(r.shape), list(ort[name].shape))
        gt = torch.from_numpy(
            np.fromfile(f"{GT_DIR}/{name.replace('/', '__').replace(':', '_')}.bin", dtype=np.float32).reshape(r.shape)
        )
        p_ort, p_gt = _pcc(ort[name], r), _pcc(gt, r)
        print(
            f"EVO50 {name.split('/')[-2]:<40} {str(list(r.shape)):<18} PCC vs onnxruntime {p_ort:.6f}  vs ground truth {p_gt:.6f}"
        )
        worst = min(worst, (p_gt, name))
    assert worst[0] > PCC_MIN, f"PCC {worst[0]:.6f} < {PCC_MIN} on {worst[1]}"

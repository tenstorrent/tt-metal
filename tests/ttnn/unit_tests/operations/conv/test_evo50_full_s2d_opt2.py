def _mc(name):
    """MemoryConfig of an IR layout (None for system memory)."""
    s = LAYOUTS[name]
    if " system_memory " in s:
        return None
    buf = ttnn.BufferType.DRAM if " dram " in s else ttnn.BufferType.L1
    ml = s.split()[2]
    if ml == "interleaved":
        return ttnn.MemoryConfig(ttnn.TensorMemoryLayout.INTERLEAVED, buf)
    dims = [int(v) for v in re.search(r"memref<(\d+)x(\d+)x", s).groups()]
    shard = (dims[0] * 32, dims[1] * 32) if s.startswith("TILE") else (dims[0], dims[1])
    ranges = [
        ttnn.CoreRange(ttnn.CoreCoord(int(a), int(b)), ttnn.CoreCoord(int(c), int(d)))
        for a, b, c, d in re.findall(r"<\((\d+),(\d+)\), \((\d+),(\d+)\)>", s)
    ]
    layout = {
        "height_sharded": ttnn.TensorMemoryLayout.HEIGHT_SHARDED,
        "width_sharded": ttnn.TensorMemoryLayout.WIDTH_SHARDED,
        "block_sharded": ttnn.TensorMemoryLayout.BLOCK_SHARDED,
    }[ml]
    return ttnn.MemoryConfig(
        layout, buf, ttnn.ShardSpec(ttnn.CoreRangeSet(set(ranges)), shard, ttnn.ShardOrientation.ROW_MAJOR)
    )


def _place(t, name):
    """A torch value in the IR layout `name`: a host tensor for system memory, else a device tensor."""
    s = LAYOUTS[name]
    layout = ttnn.TILE_LAYOUT if s.startswith("TILE") else ttnn.ROW_MAJOR_LAYOUT
    if " system_memory " in s:
        return ttnn.from_torch(t.to(torch.bfloat16), dtype=ttnn.bfloat16, layout=layout)
    return ttnn.from_torch(
        t.to(torch.bfloat16), dtype=ttnn.bfloat16, layout=layout, device=_place.device, memory_config=_mc(name)
    )



def _dev(t):
    return isinstance(t, ttnn.Tensor) and t.storage_type() == ttnn.StorageType.DEVICE and t.is_allocated()


def _free(T, name):
    """ttnn.deallocate where the IR deallocates, but never a persistent tensor, a host tensor, or a buffer a live view
    (reshape alias) still uses."""
    t = T.get(name)
    if t is None or name in PERSISTENT or not _dev(t):
        return
    del T[name]
    key = (t.memory_config().buffer_type, t.buffer_address())
    for o in T.values():
        if _dev(o) and (o.memory_config().buffer_type, o.buffer_address()) == key:
            return
    ttnn.deallocate(t)


def _conv(T, wkey, bkey, device, x, **kw):
    """conv2d; the prepared weights / bias the first call returns replace the raw host tensors in T."""
    out, wb = ttnn.conv2d(
        input_tensor=x,
        weight_tensor=T[wkey],
        bias_tensor=(T[bkey] if bkey else None),
        device=device,
        return_weights_and_bias=True,
        **kw,
    )
    T[wkey] = wb[0]
    if bkey and wb[1] is not None:
        T[bkey] = wb[1]
    return out



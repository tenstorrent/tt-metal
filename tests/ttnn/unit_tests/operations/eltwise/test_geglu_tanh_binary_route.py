"""
ttnn.geglu_tanh as one binary_ng program whose only arithmetic is geglu_tanh_tile.

Generated by tt-polynomial-fitter from activations/products/geglu_tanh.json. For BF16 gate and up,
at the parameters the kernel is compiled for, on a board that has it, the op runs one program; every other call
keeps the composite. Every finite BF16 encoding of one input runs against declared values of the other and is
scored in pure ULP against the exact product, which has no cancellation, so float64 holds it far below 1 ULP.
Special-value classes follow torch, except where the BF16 pipeline cannot store torch's result: a -0 or
subnormal input reaches the SFPU as +0, a subnormal result is stored as +0 and a NaN as +inf.
"""

import pytest
import torch
import ttnn
from loguru import logger

# The public parameters () geglu_tanh_tile is compiled for.
PARAMETERS = ()
# The boards the route runs geglu_tanh_tile on; Wormhole keeps the composite.
ROUTE_BOARDS = ("blackhole",)
OP_TYPE = "GEGLU_TANH"


def _board(device=None):
    return "blackhole" if ttnn.device.is_blackhole(device) else "wormhole_b0"


def _device_operations(call):
    """The result of ``call``, the device operations it launches and their arguments, as graph capture names them."""
    ttnn.graph.begin_graph_capture(ttnn.graph.RunMode.NORMAL)
    try:
        result = call()
    finally:
        graph = ttnn.graph.end_graph_capture()
    operations = [name for name in ttnn.graph.extract_calltrace(graph) if "DeviceOperation" in name]
    arguments = " ".join(str(argument) for node in graph for argument in node.get("arguments", []))
    return result, operations, arguments


def _off_parameters():
    """Each parameter one float32 step above the compiled one: the composite's own programs at the same cost."""
    return tuple(
        float(torch.nextafter(torch.tensor(p, dtype=torch.float32), torch.tensor(float("inf")))) for p in PARAMETERS
    )



#!/usr/bin/env python3
"""Generate the pipeline-stage Mesh Graph Descriptors swept by the bh-pipeline-sweep group.

This emits two families of ring-pipeline MGDs used to stress the topology mapper on the SC36
mock cluster (36 hosts x 32 ASICs = 1152 ASICs total):

  * 2x4 shape  -- device_topology [4, 2] RING,LINE (8 ASICs/stage, the repo's canonical "2x4
                  pipeline"). Single-host stages, no pinnings. Stage counts:
                  16, 32, 64, 80, 96, 112, 128, 144  (144 stages x 8 = 1152 ASICs = full SC36).

  * 4x4 shape  -- device_topology [4, 4] RING,RING (16 ASICs/stage). Single mesh type (M0): every
                  stage is a 4x4 torus split across a "1x2" split-host galaxy (host_topology [2, 1],
                  which is how the schema expresses the 1x2 split, matching blitz_decode_quad_galaxy_4x4).
                  All-to-all corner pinnings per stage (any listed corner chip may map to any listed
                  tray/asic position). Stage counts:
                  8, 16, 32, 40, 48, 56, 64, 72  (72 stages x 16 = 1152 ASICs = full SC36).

All rings close (last stage -> stage 0). Regenerate in place with:

    python3 tests/scripts/multihost/gen_pipeline_sweep_mgds.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

# Stage counts per shape (chosen so the largest ring exactly fills the 1152-ASIC SC36 mock).
STAGES_2X4 = [16, 32, 64, 80, 96, 112, 128, 144]
STAGES_4X4 = [8, 16, 32, 40, 48, 56, 64, 72]

# 4x4 all-to-all corner pinnings. Each stage emits a single many-to-many pinning group: any of the
# logical corner chips (PIN_CHIPS) may map to any of the galaxy-relative tray/asic positions in the set,
# and the solver enforces a bijection (distinct chips land on distinct ASICs). The position set
# alternates by mesh-id parity to match the 1x2 split-host galaxy wiring.
PIN_CHIPS = [0, 1, 3, 12, 15]  # logical chip ids pinned per stage
POS_EVEN = [(1, 3), (1, 7), (2, 3), (3, 3), (4, 3)]  # even mesh ids: (tray_id, asic_location)
POS_ODD = [(1, 2), (1, 6), (2, 2), (3, 2), (4, 2)]  # odd mesh ids:  (tray_id, asic_location)


def _instances(template_of_stage) -> str:
    lines = []
    for i, tmpl in enumerate(template_of_stage):
        lines.append(f'  instances {{ mesh {{ mesh_descriptor: "{tmpl}" mesh_id: {i} }} }}')
    return "\n".join(lines)


def _ring_connections(template_of_stage, *, channels: int, assign_z: bool) -> str:
    n = len(template_of_stage)
    blocks = []
    for i in range(n):
        j = (i + 1) % n  # last edge wraps back to 0 -> closed ring
        src, dst = template_of_stage[i], template_of_stage[j]
        block = [
            "  connections {",
            f'    nodes {{ mesh {{ mesh_descriptor: "{src}" mesh_id: {i} }} }}',
            f'    nodes {{ mesh {{ mesh_descriptor: "{dst}" mesh_id: {j} }} }}',
            f"    channels {{ count: {channels} policy: RELAXED }}",
        ]
        if assign_z:
            block.append("    assign_z_direction: true")
        block.append("  }")
        blocks.append("\n".join(block))
    return "\n".join(blocks)


def build_2x4(stages: int) -> str:
    template_of_stage = ["M0"] * stages
    return f"""# --- Meshes ---------------------------------------------------------------
# GENERATED by tests/scripts/multihost/gen_pipeline_sweep_mgds.py -- do not edit by hand.
# 2x4 pipeline ring, {stages} stages ({stages} x 8 = {stages * 8} ASICs). Each stage is a 4x2 RING,LINE
# single-host galaxy slice; the ring closes (stage {stages - 1} -> stage 0). No pinnings (single-host
# stages map freely on the SC36 mock).

mesh_descriptors {{
  name: "M0"
  arch: BLACKHOLE
  device_topology {{ dims: [ 4, 2 ] dim_types: [ RING, LINE ] }}
  host_topology   {{ dims: [ 1, 1 ] }}
  channels {{ count: 2 policy: RELAXED }}
}}

graph_descriptors {{
  name: "G0"
  type: "FABRIC"
{_instances(template_of_stage)}

{_ring_connections(template_of_stage, channels=8, assign_z=False)}
}}

# --- Instantiation ----------------------------------------------------------
top_level_instance {{ graph {{ graph_descriptor: "G0" graph_id: 0 }} }}
"""


def _pinnings_4x4(stages: int) -> str:
    out = []
    for i in range(stages):
        positions = POS_EVEN if i % 2 == 0 else POS_ODD
        out.append(f"# mesh_id {i}")
        out.append("pinnings {")
        for chip_id in PIN_CHIPS:
            out.append(f"  logical_fabric_node_id {{ mesh_id: {i} chip_id: {chip_id} }}")
        for tray_id, asic_location in positions:
            out.append(f"  physical_asic_position {{ tray_id: {tray_id} asic_location: {asic_location} }}")
        out.append("}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def build_4x4(stages: int) -> str:
    # Single mesh type: every stage is M0, a 4x4 torus split across a 1x2 (host_topology [2,1]) galaxy.
    # Each stage emits one all-to-all corner pinning group; the position set alternates by mesh-id parity.
    template_of_stage = ["M0"] * stages
    return f"""# --- Meshes ---------------------------------------------------------------
# GENERATED by tests/scripts/multihost/gen_pipeline_sweep_mgds.py -- do not edit by hand.
# 4x4 pipeline ring, {stages} stages ({stages} x 16 = {stages * 16} ASICs). Single mesh type (M0):
# every stage is a 4x4 RING,RING torus split across a 1x2 split-host galaxy (host_topology [2,1]).
# All-to-all corner pinnings; the position set alternates by mesh-id parity. The ring closes
# (stage {stages - 1} -> stage 0). Mirrors blitz_decode_quad_galaxy_4x4 scaled to {stages} stages.

mesh_descriptors {{
  name: "M0"
  arch: BLACKHOLE
  device_topology {{ dims: [ 4, 4 ] dim_types: [ RING, RING ] }}
  host_topology   {{ dims: [ 2, 1 ] }}
  channels {{ count: 2 policy: STRICT }}
}}

graph_descriptors {{
  name: "G0"
  type: "FABRIC"
{_instances(template_of_stage)}

{_ring_connections(template_of_stage, channels=8, assign_z=False)}
}}

# --- Instantiation ----------------------------------------------------------
top_level_instance {{ graph {{ graph_descriptor: "G0" graph_id: 0 }} }}

# --- Pinnings ---------------------------------------------------------------
# All-to-all corner pinning per mesh: the logical corner chips (0, 1, 3, 12, 15) may map to any of the
# tray/asic positions in the set. The solver enforces a bijection, so each chip lands on a distinct ASIC.
# The position set alternates by mesh-id parity to match the 1x2 split-host galaxy wiring.

{_pinnings_4x4(stages)}"""


def main() -> None:
    default_out = (
        Path(__file__).resolve().parents[3] / "tests/tt_metal/tt_fabric/custom_mesh_descriptors/pipeline_sweep"
    )
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument(
        "--out-dir",
        type=Path,
        default=default_out,
        help=f"Output directory for the generated MGDs (default: {default_out}).",
    )
    args = ap.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)

    written = []
    for stages in STAGES_2X4:
        path = args.out_dir / f"sweep_2x4_pipeline_{stages}stage_mesh_graph_descriptor.textproto"
        path.write_text(build_2x4(stages))
        written.append(path)
    for stages in STAGES_4X4:
        path = args.out_dir / f"sweep_4x4_pipeline_{stages}stage_mesh_graph_descriptor.textproto"
        path.write_text(build_4x4(stages))
        written.append(path)

    print(f"Wrote {len(written)} MGDs to {args.out_dir}:")
    for path in written:
        print(f"  {path.name}")


if __name__ == "__main__":
    main()

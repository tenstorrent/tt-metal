#!/usr/bin/env python3
"""Generate QUASAR_TEST_COVERAGE.md from the quasar test yamls.

The Quasar test lists grow steadily, and the release automation's relevance map
(.github/actions/scripts/ai_ip_tests.json) is keyed on (config, group, filter,
runner) tuples taken from them. Hand-maintained notes about "what runs where"
went stale within weeks, so this regenerates the picture from the yamls
themselves and cross-references the relevance map.

Usage:
    gen_test_coverage_doc.py            # rewrite QUASAR_TEST_COVERAGE.md
    gen_test_coverage_doc.py --check    # exit 1 if the file is out of date
"""
import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
MAP_PATH = REPO / ".github/actions/scripts/ai_ip_tests.json"
OUT_PATH = HERE / "QUASAR_TEST_COVERAGE.md"

# Where each yaml is consumed. This is the one thing not derivable from the repo
# -- the sim CI lives in GitLab (tensix/tt-umd-simulators). Verified 2026-08-11
# against that project's main branch; re-check when the emu branches merge.
YAML_SOURCES = [
    {
        "file": "quasar_sim_regresion_tests.yaml",
        "job": "metal_unit_test_vcs_qsr (VCS)",
        "configs_run": "1x3 only (hardcoded)",
        "feeds_release_jira": True,
        "note": (
            "The only list wired to the release gate. The job runs "
            "`select_quasar_tests.py <yaml> 1x3` and writes `test_results.tsv` "
            "(every outcome, passed and failed), "
            "which `report_rtl_sim_failures.py` turns into the \"RTL Sim CI "
            "test\" GitHub check output that this repo's `file_rtl_sim_jira.py` "
            "parses. Manifest rows are labelled `1x3` unconditionally."
        ),
    },
    {
        "file": "quasar_regression_tests.yaml",
        "job": "metal_unit_test_emu_quasar (Zebu/Aether emulator)",
        "configs_run": "all configs present in the yaml",
        "feeds_release_jira": False,
        "note": (
            "Nightly/triggered emulator run. **Not merged on GitLab main yet** -- "
            "it lives on branch `kstevens/emu-quasar-1x3-testing`. Results go to "
            "`gtest-summary/summary.json` and Slack `#tt-qsr-emu-ci`; this job "
            "does not write the `test_results.tsv` manifest, so none of these reach "
            "Jira today."
        ),
    },
    {
        "file": "quasar_local_tests.yaml",
        "job": "metal_unit_test_emu_quasar (Zebu/Aether emulator)",
        "configs_run": "all configs present in the yaml",
        "feeds_release_jira": False,
        "note": (
            "Tests the GitLab runner flow does not support yet; pytest-only "
            "today. Wired on branch `kstevens/pytest_ci`, also Slack-reported. "
            "Entries move to `quasar_regression_tests.yaml` as pipeline support "
            "lands."
        ),
    },
]


def load_rows(path):
    """Flatten a quasar tests yaml into one row per (group, filter, config)."""
    data = yaml.safe_load(path.read_text()) or {}
    rows = []
    for group, entries in data.items():
        for entry in entries or []:
            configs = [c.strip() for c in str(entry.get("config", "")).split(",") if c.strip()]
            for config in configs:
                rows.append(
                    {
                        "group": group,
                        "filter": str(entry.get("filter") or ""),
                        "config": config,
                        "runner": str(entry.get("runner") or "gtest"),
                        "env": entry.get("env") or {},
                        "back2back": bool(entry.get("back2back")),
                    }
                )
    return rows


def load_map():
    return json.loads(MAP_PATH.read_text()).get("relevant_tests", [])


def load_map_requirements():
    """The AIIPSW requirement inventory the release evidence report reports on."""
    return json.loads(MAP_PATH.read_text()).get("requirements", [])


def match(row, entries):
    """The relevance-map entry watching this row, or None (same rules as the filer)."""
    for e in entries:
        if (
            e.get("config", row["config"]) == row["config"]
            and e.get("group", row["group"]) == row["group"]
            and e.get("filter", row["filter"]) == row["filter"]
            and e.get("runner", row["runner"]) == row["runner"]
        ):
            return e
    return None


def md_escape(text):
    return text.replace("|", "\\|") or "_(all tests in file)_"


def render():
    entries = load_map()
    out = [
        "# Quasar test coverage",
        "",
        "<!-- GENERATED by tests/scripts/quasar/gen_test_coverage_doc.py -- do not edit by hand. -->",
        "",
        "What the Quasar test yamls contain, where each list actually runs, and "
        "which rows are watched by the release Jira automation "
        "(`.github/actions/scripts/ai_ip_tests.json`).",
        "",
        "Regenerate with `python3 tests/scripts/quasar/gen_test_coverage_doc.py`.",
        "",
        "## Summary",
        "",
        "| Test list | Rows | Distinct tests | Configs | Runners | Consumed by | Feeds release Jira |",
        "|---|---|---|---|---|---|---|",
    ]

    all_rows = {}
    for src in YAML_SOURCES:
        path = HERE / src["file"]
        if not path.is_file():
            continue
        rows = load_rows(path)
        all_rows[src["file"]] = rows
        configs = sorted({r["config"] for r in rows})
        runners = sorted({r["runner"] for r in rows})
        distinct = len({(r["group"], r["filter"]) for r in rows})
        out.append(
            f"| `{src['file']}` | {len(rows)} | {distinct} | {', '.join(configs)} | "
            f"{', '.join(runners)} | {src['job']} | "
            f"{'**yes**' if src['feeds_release_jira'] else 'no'} |"
        )

    watched = sum(1 for rows in all_rows.values() for r in rows if match(r, entries))
    total = sum(len(rows) for rows in all_rows.values())
    gated = sum(
        len(all_rows.get(s["file"], []))
        for s in YAML_SOURCES
        if s["feeds_release_jira"]
    )
    out += [
        "",
        f"**{total}** test rows across all lists; **{gated}** of them run in the job that "
        f"gates the release; **{watched}** are matched by the relevance map.",
        "",
    ]

    for src in YAML_SOURCES:
        rows = all_rows.get(src["file"])
        if not rows:
            continue
        out += [f"## `{src['file']}`", "", src["note"], ""]
        out += [
            f"Runs: {src['job']} — {src['configs_run']}.",
            "",
            "| Group | Filter | Config | Runner | Watched (requirement) |",
            "|---|---|---|---|---|",
        ]
        for r in sorted(rows, key=lambda r: (r["group"], r["filter"], r["config"])):
            e = match(r, entries)
            flag = f"✅ {e.get('requirement', 'yes')}" if e else "—"
            b2b = " _(back2back)_" if r["back2back"] else ""
            out.append(
                f"| `{r['group']}` | `{md_escape(r['filter'])}`{b2b} | {r['config']} | "
                f"{r['runner']} | {flag} |"
            )
        out.append("")

    # Requirement rollup: what each AIIPSW ticket is actually covered by.
    by_req = defaultdict(list)
    for fname, rows in all_rows.items():
        for r in rows:
            e = match(r, entries)
            if e and e.get("requirement"):
                by_req[e["requirement"]].append((fname, r))
    out += ["## Coverage by AIIPSW requirement", ""]
    inventory = load_map_requirements()
    if by_req or inventory:
        out += ["| Requirement | Watched rows | Lists | Reaches Jira today |", "|---|---|---|---|"]
        gating = {s["file"] for s in YAML_SOURCES if s["feeds_release_jira"]}
        # Every requirement in the inventory gets a row, covered or not, so the
        # release evidence report and this doc tell the same story.
        keys = [r["key"] for r in inventory] or sorted(by_req)
        for req in keys + [k for k in sorted(by_req) if k not in {r["key"] for r in inventory}]:
            hits = by_req.get(req, [])
            if not hits:
                why = next(
                    (r.get("_evidence") for r in inventory if r["key"] == req and r.get("_evidence")),
                    "no test wired into a Quasar yaml",
                )
                out.append(f"| {req} | 0 | — | **no** — {why} |")
                continue
            files = sorted({f for f, _ in hits})
            live = any(f in gating for f, _ in hits)
            out.append(
                f"| {req} | {len(hits)} | {', '.join(f'`{f}`' for f in files)} | "
                f"{'yes' if live else '**no** — emulator-only path'} |"
            )
    else:
        out.append("_No relevance-map entry currently matches any yaml row._")
    out.append("")

    # Entries that never win a match: no such row, or shadowed by an earlier
    # entry (match_entry returns the first hit, so order matters).
    unmatched = []
    for e in entries:
        hit = any(match(r, entries) is e for rows in all_rows.values() for r in rows)
        if not hit:
            unmatched.append(e)
    if unmatched:
        out += [
            "## Relevance-map entries that never win a match",
            "",
            "These file no ticket: either no yaml row matches them, or an earlier "
            "entry in the map already claims every row they would match. Stale "
            "entries should be dropped; the rest activate when their test lands.",
            "",
            "| Config | Group | Filter | Requirement |",
            "|---|---|---|---|",
        ]
        for e in unmatched:
            out.append(
                f"| {e.get('config', '*')} | `{e.get('group', '*')}` | "
                f"`{md_escape(e.get('filter', '*'))}` | {e.get('requirement', '—')} |"
            )
        out.append("")

    counts = Counter(
        (r["config"], r["runner"]) for rows in all_rows.values() for r in rows
    )
    out += ["## Rows by config and runner", "", "| Config | Runner | Rows |", "|---|---|---|"]
    for (config, runner), n in sorted(counts.items()):
        out.append(f"| {config} | {runner} | {n} |")
    out.append("")

    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the doc is out of date")
    args = ap.parse_args()

    content = render()
    if args.check:
        current = OUT_PATH.read_text() if OUT_PATH.is_file() else ""
        if current != content:
            print(f"ERROR: {OUT_PATH.name} is out of date; rerun {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{OUT_PATH.name} is up to date")
        return 0

    OUT_PATH.write_text(content)
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

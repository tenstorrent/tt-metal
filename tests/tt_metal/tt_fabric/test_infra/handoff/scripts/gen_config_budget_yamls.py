"""Writes the yamls that load each chip with as many sender configs as a 64x4 all_to_all (255) on a smaller mesh.

A 64x4 all_to_all gives every chip one sender entry of 255 configs, and the allocator puts a whole entry on one core.
These yamls give every chip `copies` x (chips - 1) configs (248 on an 8x4 Galaxy with 8 copies), in two shapes:

- packed_k<K>.yaml (method 1): `copies` all_to_all lines, so every chip has `copies` sender entries of chips - 1
  configs each. A static sender policy packs copies / K entries onto each core, so K sender cores per chip. This
  measures what spreading the configs over K cores does, without the split code.
- single_entry.yaml (method 2): one explicit sender per chip holding all `copies` x (chips - 1) configs, the shape a
  64x4 all_to_all has. Run it with TT_FABRIC_TEST_MAX_CONFIGS_PER_SENDER=N to have the host split each sender into
  ceil(configs / N) cores (configs dealt out round-robin); unset, every chip sends from one core.
- edge_rows.yaml / middle_rows.yaml: single_entry.yaml with only the edge rows (0, 1, rows - 2, rows - 1) or only the
  middle rows sending.
- parking_lot.yaml: the top half's rows of column 0 each send the same traffic to the last row of that column, so their
  streams merge at each router on the way down.
- floor.yaml: the same bytes from one all_to_all line (chips - 1 configs per chip, `copies` x `packets` packets each),
  a reference for what the fabric does when no core is near a per-core cap.

Every yaml moves the same packets (copies x (chips - 1) configs per chip, `packets` each), so device times compare.
"""

import argparse
from pathlib import Path


def describe_common_test_fields(packets: int, size: int) -> list[str]:
    return [
        "    enable_flow_control: true",
        "    fabric_setup:",
        "      topology: Mesh",
        "      num_links: 1",
        "    defaults:",
        "      ftype: unicast",
        "      ntype: unicast_write",
        f"      size: {size}",
        f"      num_packets: {packets}",
    ]


def write_packed_yaml(path: Path, copies: int, cores: int, receiver_configs_per_core: int, packets: int, size: int):
    entries_per_core = copies // cores
    lines = [
        f"# {copies} all_to_all entries per chip packed {entries_per_core} per sender core: {cores} sender core(s) per chip.",
        "# Generated by handoff/scripts/gen_config_budget_yamls.py.",
        "allocation_policies:",
        "  sender:",
        "    policy: ExhaustFirst",
        f"    max_configs_per_core: {entries_per_core}  # sender entries per core, not traffic configs",
        "  receiver:",
        f"    max_configs_per_core: {receiver_configs_per_core}",
        "",
        "Tests:",
        f'  - name: "ConfigBudget_packed_k{cores}"',
        *describe_common_test_fields(packets, size),
        "    patterns:",
        *["      - type: all_to_all" for _ in range(copies)],
    ]
    path.write_text("\n".join(lines) + "\n")


def write_single_entry_yaml(
    path: Path, chips: int, copies: int, receiver_configs_per_core: int, packets: int, size: int
):
    lines = [
        f"# One sender per chip with {copies} x {chips - 1} unicast configs, the shape of a large-mesh all_to_all.",
        "# Split it with TT_FABRIC_TEST_MAX_CONFIGS_PER_SENDER=N. Generated by handoff/scripts/gen_config_budget_yamls.py.",
        "allocation_policies:",
        "  receiver:",
        f"    max_configs_per_core: {receiver_configs_per_core}",
        "",
        "Tests:",
        '  - name: "ConfigBudget_single_entry"',
        *describe_common_test_fields(packets, size),
        "    senders:",
    ]
    for src in range(chips):
        lines.append(f"      - device: [0, {src}]")
        lines.append("        patterns:")
        # Destination order (each destination's copies together), the order the split cuts chunks in.
        for dst in range(chips):
            if dst == src:
                continue
            for _ in range(copies):
                lines.append(f"          - destination: {{device: [0, {dst}]}}")
    path.write_text("\n".join(lines) + "\n")


def write_floor_yaml(path: Path, copies: int, packets: int, size: int):
    lines = [
        f"# The same bytes as the other yamls from one all_to_all line ({copies} x {packets} packets per config): one",
        "# sender core per chip with chips - 1 configs, under every per-core cap. Generated by",
        "# handoff/scripts/gen_config_budget_yamls.py.",
        "Tests:",
        '  - name: "ConfigBudget_floor"',
        *describe_common_test_fields(copies * packets, size),
        "    patterns:",
        "      - type: all_to_all",
    ]
    path.write_text("\n".join(lines) + "\n")


def write_sender_rows_yaml(
    path: Path,
    name: str,
    sender_rows: list[int],
    rows: int,
    cols: int,
    copies: int,
    receiver_configs_per_core: int,
    packets: int,
    size: int,
):
    """Like single_entry.yaml, but only the chips in sender_rows send (to every other chip); the rest only receive.
    Chips are named by mesh coordinate [row, col], so the rows are the mesh's own."""
    lines = [
        f"# Only rows {sender_rows} of the {rows}x{cols} mesh send: one sender per chip with {copies} x {rows * cols - 1}"
        " configs, to every other chip.",
        "# Split it with TT_FABRIC_TEST_MAX_CONFIGS_PER_SENDER=N. Generated by handoff/scripts/gen_config_budget_yamls.py.",
        "allocation_policies:",
        "  receiver:",
        f"    max_configs_per_core: {receiver_configs_per_core}",
        "",
        "Tests:",
        f'  - name: "{name}"',
        *describe_common_test_fields(packets, size),
        "    senders:",
    ]
    for src_row in sender_rows:
        for src_col in range(cols):
            lines.append(f"      - device: [0, [{src_row}, {src_col}]]")
            lines.append("        patterns:")
            for dst_row in range(rows):
                for dst_col in range(cols):
                    if (dst_row, dst_col) == (src_row, src_col):
                        continue
                    for _ in range(copies):
                        lines.append(f"          - destination: {{device: [0, [{dst_row}, {dst_col}]]}}")
    path.write_text("\n".join(lines) + "\n")


def write_parking_lot_yaml(
    path: Path,
    source_rows: list[int],
    dest_row: int,
    col: int,
    copies: int,
    receiver_configs_per_core: int,
    packets: int,
    size: int,
):
    """Chips in source_rows of one column each send the same traffic to dest_row of that column, so their streams
    share the column's links and merge at each router on the way. With fair sharing they finish together; with
    turn-taking between upstream and local traffic at each router, the source nearest the destination finishes first."""
    lines = [
        f"# Parking lot: rows {source_rows} of column {col} each send {copies} x {packets} packets to row {dest_row},"
        " one sender core each.",
        "# Generated by handoff/scripts/gen_config_budget_yamls.py.",
        "allocation_policies:",
        "  receiver:",
        f"    max_configs_per_core: {receiver_configs_per_core}",
        "",
        "Tests:",
        '  - name: "ConfigBudget_parking_lot"',
        *describe_common_test_fields(packets, size),
        "    senders:",
    ]
    for src_row in source_rows:
        lines.append(f"      - device: [0, [{src_row}, {col}]]")
        lines.append("        patterns:")
        for _ in range(copies):
            lines.append(f"          - destination: {{device: [0, [{dest_row}, {col}]]}}")
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("out_dir", type=Path)
    parser.add_argument("--chips", type=int, default=32, help="chips in the mesh (8x4 Galaxy: 32)")
    parser.add_argument("--rows", type=int, default=8, help="mesh rows, for the row-subset and parking-lot yamls")
    parser.add_argument("--cols", type=int, default=4, help="mesh columns")
    parser.add_argument("--copies", type=int, default=8, help="configs per (source, destination) pair")
    parser.add_argument("--cores", type=int, nargs="+", default=[1, 2, 4, 8], help="sender cores per chip (method 1)")
    parser.add_argument("--receiver-configs-per-core", type=int, default=13)
    parser.add_argument("--packets", type=int, default=12500, help="packets per config (100k / copies)")
    parser.add_argument("--size", type=int, default=4096)
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    for cores in args.cores:
        if args.copies % cores != 0:
            parser.error(f"--copies {args.copies} doesn't divide evenly over {cores} cores")
        write_packed_yaml(
            args.out_dir / f"packed_k{cores}.yaml",
            args.copies,
            cores,
            args.receiver_configs_per_core,
            args.packets,
            args.size,
        )
    write_single_entry_yaml(
        args.out_dir / "single_entry.yaml",
        args.chips,
        args.copies,
        args.receiver_configs_per_core,
        args.packets,
        args.size,
    )
    write_floor_yaml(args.out_dir / "floor.yaml", args.copies, args.packets, args.size)
    edge_rows = [0, 1, args.rows - 2, args.rows - 1]
    middle_rows = [r for r in range(args.rows) if r not in edge_rows]
    common = (args.rows, args.cols, args.copies, args.receiver_configs_per_core, args.packets, args.size)
    write_sender_rows_yaml(args.out_dir / "edge_rows.yaml", "ConfigBudget_edge_rows", edge_rows, *common)
    write_sender_rows_yaml(args.out_dir / "middle_rows.yaml", "ConfigBudget_middle_rows", middle_rows, *common)
    write_parking_lot_yaml(
        args.out_dir / "parking_lot.yaml",
        source_rows=list(range(args.rows // 2)),
        dest_row=args.rows - 1,
        col=0,
        copies=args.copies,
        receiver_configs_per_core=args.receiver_configs_per_core,
        packets=4 * args.packets,
        size=args.size,
    )
    configs = args.copies * (args.chips - 1)
    print(f"Wrote {len(args.cores) + 5} yamls to {args.out_dir}: {configs} sender configs per chip (floor: {args.chips - 1})")


if __name__ == "__main__":
    main()

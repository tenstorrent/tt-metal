#include <cstdint>

#include "api/compute/experimental/sdpa.h"
#include "api/compute/tile_move_copy.h"
#include "api/dataflow/circular_buffer.h"

void kernel_main() {
    constexpr std::uint32_t count = get_compile_time_arg_val(0);
    constexpr std::uint32_t fidelity = get_compile_time_arg_val(1);
    constexpr std::uint32_t granularity = get_compile_time_arg_val(2);
    constexpr std::uint32_t output_tiles = 2;
    constexpr std::uint32_t recip_offset = 64;  // scratch tile 1, in DEST rows
    CircularBuffer input(tt::CBIndex::c_0);
    CircularBuffer output(tt::CBIndex::c_16);

    static_assert(sdpa_fidelity_from_sel<0>() == MathFidelity::LoFi);
    static_assert(sdpa_fidelity_from_sel<2>() == MathFidelity::HiFi2);
    static_assert(sdpa_fidelity_from_sel<3>() == MathFidelity::HiFi3);
    static_assert(sdpa_fidelity_from_sel<4>() == MathFidelity::HiFi4);

    compute_kernel_hw_startup(tt::CBIndex::c_0, tt::CBIndex::c_16);
    for (std::uint32_t tile = 0; tile < count; ++tile) {
        input.wait_front(1);
        output.reserve_back(1);
        tile_regs_acquire();
        copy_tile_to_dst_init_short(tt::CBIndex::c_0);
        copy_tile(tt::CBIndex::c_0, 0, 0);

        // Handoff after the input copy; MATH then waits for the reciprocal
        // generated by PACK. The final tile-register handoff occurs only once
        // normalization has finished on both threads.
        MATH((t6_semaphore_post<p_stall::MATH>(semaphore::FPU_SFPU)));
        PACK((t6_semaphore_wait_on_zero<p_stall::STALL_SFPU>(semaphore::FPU_SFPU)));
        PACK((t6_semaphore_get<p_stall::WAIT_SFPU>(semaphore::FPU_SFPU)));
        PACK((_llk_math_eltwise_unary_sfpu_init_<SfpuType::unused>()));
        PACK((sfpi::l_reg[sfpi::LRegs::LReg0] = sfpi::vFloat(2.0f)));
        PACK((sfpi::l_reg[sfpi::LRegs::LReg2] = sfpi::vFloat(2.0f)));

        compute_sdpa_recip<output_tiles, false, 0x3f800000, granularity, fidelity>(
            tt::CBIndex::c_1, 0, recip_offset, 0);
        PACK((t6_semaphore_wait_on_zero<p_stall::STALL_PACK>(semaphore::FPU_SFPU)));
        // Consume exactly the configured number of completion notifications.
        // Three input tiles catch a notification left over from a prior call.
        for (std::uint32_t signal = 0; signal < output_tiles / granularity; ++signal) {
            PACK((t6_semaphore_wait_on_zero<p_stall::STALL_PACK>(semaphore::FPU_SFPU)));
            PACK((t6_semaphore_get<p_stall::PACK>(semaphore::FPU_SFPU)));
        }
        tile_regs_commit();
        tile_regs_wait();
        pack_tile(0, tt::CBIndex::c_16);
        tile_regs_release();
        input.pop_front(1);
        output.push_back(1);
    }
}

// End-to-end (device) regression test for the sync_build_steps abandon-on-throw
// use-after-free. Companion to the deterministic unit test in
// tests/tt_metal/tt_metal/jit_build/test_sync_build_steps.cpp. Both guard the
// drain-before-rethrow behavior of sync_build_steps in tt_metal/jit_build/build.cpp
// (aa85a788b33).
//
// The bug: ProgramImpl::compile() launches one async build step per kernel and waits
// with sync_build_steps(). Each step's lambda captures compile()'s `IDevice* device`
// BY REFERENCE. A naive `for (e : events) e.get();` returns on the FIRST exception and
// abandons the still-in-flight sibling steps. When a kernel fails to compile, that
// exception unwinds compile()'s frame while sibling steps keep running and dereference
// the now-dangling `device` -> device->build_id() on a garbage vtable -> SIGSEGV on a
// worker thread, masking the real compile error.
//
// This test compiles ONE program that mixes several valid compute kernels (unique
// compile args, so each really compiles and stays in flight) with one data-movement
// kernel whose source deliberately fails to compile. The failing build step throws
// while the valid steps are still compiling:
//   draining (aa85a788b33) -> sync_build_steps drains every step, then rethrows ->
//                             CompileProgram throws cleanly and EXPECT_THROW passes.
//   naive wait             -> the in-flight sibling steps are abandoned -> use-after-free
//                             -> the process SIGSEGVs (crashes the binary rather than
//                             failing gracefully; the deterministic guard is the unit test).
//
// The device is opened with the single-MMIO-device CreateDevice() API rather than a mesh
// fixture: compilation only needs the device for build metadata (arch/build_id), and this
// keeps the test to one local device open/close.

#include <gtest/gtest.h>

#include <algorithm>
#include <cstdint>
#include <exception>
#include <filesystem>
#include <fstream>
#include <string>

#include <tt-metalium/circular_buffer_config.hpp>
#include <tt-metalium/host_api.hpp>
#include <tt-metalium/tt_metal.hpp>

#include "jit_build/build.hpp"
#include "tt_metal/jit_build/build_env_manager.hpp"

namespace tt::tt_metal {
namespace {

constexpr uint32_t kSingleTileSize = 2 * 1024;
const std::string kGoodComputeKernel = "tests/tt_metal/tt_metal/test_kernels/compute/eltwise_copy_3m.cpp";

std::filesystem::path regression_tmp_dir() {
    return std::filesystem::temp_directory_path() / "tt_sync_build_steps_regression";
}

// Write a kernel source that fails to compile (an undeclared function call -- a realistic
// kernel compile failure) and return its absolute path. Absolute kernel paths are accepted
// verbatim by CreateKernel/resolve_path, so this needs no file in the source tree.
std::filesystem::path write_uncompilable_kernel() {
    std::filesystem::create_directories(regression_tmp_dir());
    auto path = regression_tmp_dir() / "uncompilable_dm_kernel.cpp";
    std::ofstream out(path);
    out << "// Auto-generated by test_compile_failure_drain.cpp -- deliberately fails to compile.\n"
        << "void kernel_main() {\n"
        << "    tt_sync_build_steps_regression_undefined_symbol();\n"
        << "}\n";
    return path;
}

void add_tile_cbs(Program& program, const CoreRange& cores) {
    CircularBufferConfig cb_src =
        CircularBufferConfig(8 * kSingleTileSize, {{tt::CBIndex::c_0, tt::DataFormat::Float16_b}})
            .set_page_size(tt::CBIndex::c_0, kSingleTileSize);
    CreateCircularBuffer(program, cores, cb_src);
    CircularBufferConfig cb_out =
        CircularBufferConfig(kSingleTileSize, {{tt::CBIndex::c_16, tt::DataFormat::Float16_b}})
            .set_page_size(tt::CBIndex::c_16, kSingleTileSize);
    CreateCircularBuffer(program, cores, cb_out);
}

// Drop all cached kernel binaries for this device so the repro program's kernels compile
// from scratch. Without this the reproduction is cache-state-dependent: on a warm cache the
// "sibling" kernels are served instantly and are never in flight when the bad step throws,
// so the use-after-free never triggers. Same pattern as ClearKernelCache in
// test_compile_program.cpp.
void clear_kernel_cache(IDevice* dev) {
    const std::string kernel_root =
        BuildEnvManager::get_instance().get_device_build_env(dev->build_id()).build_env.get_out_kernel_root_path();
    std::error_code ec;
    std::filesystem::remove_all(kernel_root, ec);
    jit_build_cache_clear();
}

// Closes the device on scope exit even if an assertion or exception unwinds the test, so a
// failure here does not leak an open device into sibling tests in the same binary.
struct DeviceCloser {
    IDevice* dev;
    ~DeviceCloser() {
        if (dev != nullptr) {
            CloseDevice(dev);
        }
    }
};

}  // namespace

TEST(CompileFailureDrainTest, CompileProgramWithFailingKernelThrowsCleanly) {
    if (GetNumAvailableDevices() == 0) {
        GTEST_SKIP() << "requires a device";
    }

    IDevice* dev = CreateDevice(0);
    DeviceCloser closer{dev};

    // Sanity: prove the "good" compute kernel actually compiles on this device/arch, so the
    // throw below is attributable to the deliberately-broken kernel and not the valid ones.
    {
        Program good = CreateProgram();
        add_tile_cbs(good, CoreRange(CoreCoord(0, 0), CoreCoord(0, 0)));
        CreateKernel(good, kGoodComputeKernel, CoreCoord(0, 0), ComputeConfig{.compile_args = {1u, 0u}});
        EXPECT_NO_THROW(detail::CompileProgram(dev, good));
    }

    // Force every repro kernel to compile from scratch (see clear_kernel_cache) so the valid
    // kernels are genuinely in flight when the bad kernel's build step throws.
    clear_kernel_cache(dev);

    // Repro program: a grid of valid compute kernels (unique compile args -> each misses the
    // JIT cache and really compiles, staying in flight) plus one uncompilable data-movement
    // kernel whose build step throws mid-flight.
    Program program = CreateProgram();

    // A small grid keeps several compute kernels (3 TRISC build steps each) genuinely in
    // flight when the bad kernel's step throws, without inflating CI compile time.
    CoreCoord grid = dev->compute_with_storage_grid_size();
    const uint32_t gx = std::min<uint32_t>(grid.x, 2);
    const uint32_t gy = std::min<uint32_t>(grid.y, 2);
    CoreRange all_cores(CoreCoord(0, 0), CoreCoord(gx - 1, gy - 1));
    add_tile_cbs(program, all_cores);

    uint32_t tiles = 0;
    for (uint32_t y = 0; y < gy; ++y) {
        for (uint32_t x = 0; x < gx; ++x) {
            // arg0 (per_core_tile_cnt) varies per core -> unique hash -> real compile.
            CreateKernel(program, kGoodComputeKernel, CoreCoord(x, y), ComputeConfig{.compile_args = {++tiles, 0u}});
        }
    }

    // The one kernel that fails to compile, on a data-movement RISC of core (0,0) (which
    // already carries a valid compute kernel, so the two coexist).
    const auto bad_kernel = write_uncompilable_kernel();
    CreateKernel(
        program,
        bad_kernel.string(),
        CoreCoord(0, 0),
        DataMovementConfig{.processor = DataMovementProcessor::RISCV_0, .noc = NOC::RISCV_0_default});

    // sync_build_steps drains all in-flight steps, then rethrows the compile failure
    // -> a clean exception. Without the drain: abandons in-flight steps -> UAF -> SIGSEGV.
    EXPECT_THROW(detail::CompileProgram(dev, program), std::exception);

    std::error_code ec;
    std::filesystem::remove_all(regression_tmp_dir(), ec);
}

}  // namespace tt::tt_metal

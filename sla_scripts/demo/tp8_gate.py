"""Accuracy gate for a TP8/DP4 optimization step, plus the running step table.

usage: tp8_gate.py <tag>     gate runs/tp8dp4_gate_acc_<tag>.log + runs/tp8dp4_step_b128_<tag>.log, then rebuild table
       tp8_gate.py --table   only rebuild the table
Table: ~/teja/TP8_STEPS.md (and a copy in the agent store). Step names and "kept" come from runs/tp8_steps_meta.json.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

RUNS = Path.home() / "teja/runs"
STORE = Path(
    "/home/ubuntu/.local/state/cursor/agent-stores/cursor_agent_stores/68dbfeb4-f4d5-49df-99ca-f81c95318463/files"
)
# 500 scored tokens, so one token is 0.2 points; baseline top-1 is 96.8%
MIN_TOP1 = 96.4
MIN_TOP5 = 99.8
NUM_USERS = 128


def accuracy(path):
    m = re.findall(r"Top1 Accuracy: ([\d.]+)%, Top5 Accuracy: ([\d.]+)%", path.read_text())
    return (float(m[-1][0]), float(m[-1][1])) if m else (None, None)


def user_steps(path):
    seq = defaultdict(list)
    for line in path.read_text().splitlines():
        m = re.search(r"\[User (\d+)\] (.*)", line)
        if m:
            seq[int(m.group(1))].append(m.group(2).rstrip())
    return seq


def degenerate(text):
    text = text.removeprefix("...").strip()
    if len(text) < 20:
        return True
    return any(text.count(text[i : i + 12]) >= 3 for i in range(0, len(text) - 12))


def gate(tag):
    top1, top5 = accuracy(RUNS / f"tp8dp4_gate_acc_{tag}.log")
    step_log = RUNS / f"tp8dp4_step_b128_{tag}.log"
    outs = user_steps(step_log)
    base = user_steps(RUNS / "tp8dp4_step_b128_baseline.log")
    finals = {u: s[-1] for u, s in outs.items()}
    base_bad = {u for u, s in base.items() if degenerate(s[-1])}
    new_bad = sorted(u for u, t in finals.items() if degenerate(t) and u not in base_bad)
    same = sum(outs[u] == base[u] for u in base if u in outs)
    perf = re.findall(r"128th token decode time: ([\d.]+)ms \[([\d.]+) t/s/u, ([\d.]+) t/s\]", step_log.read_text())

    checks = {
        "top1": top1 is not None and top1 >= MIN_TOP1,
        "top5": top5 is not None and top5 >= MIN_TOP5,
        "all_users": len(finals) == NUM_USERS,
        "no_new_degenerate": not new_bad,
    }
    row = dict(
        tag=tag,
        gate="PASS" if all(checks.values()) else "FAIL",
        checks=checks,
        top1=top1,
        top5=top5,
        users=len(finals),
        new_degenerate_users=new_bad,
        greedy_identical=f"{same}/{len(base)}",
        ms=float(perf[-1][0]) if perf else None,
        tsu=float(perf[-1][1]) if perf else None,
        ts=float(perf[-1][2]) if perf else None,
    )
    with open(RUNS / "tp8_gates.jsonl", "a") as f:
        f.write(json.dumps(row) + "\n")
    print(json.dumps(row))


def fmt(v, f):
    return "—" if v is None else format(v, f)


def write_table():
    meta_file = RUNS / "tp8_steps_meta.json"
    meta = json.loads(meta_file.read_text()) if meta_file.exists() else {}
    rows = {}
    for line in (RUNS / "tp8_gates.jsonl").read_text().splitlines():
        r = json.loads(line)
        rows[r["tag"]] = r
    lines = [
        "# TP8/DP4 optimization steps, WH Galaxy, Llama-3.3-70B, 128 users",
        "",
        "Auto-generated by ~/teja/tp8_gate.py after every gate run. Gate: top-1 >= 96.4%, top-5 >= 99.8%,",
        "all 128 users produce output, no new degenerate output.",
        "",
        "| Step | Gate | Top-1 / Top-5 | Greedy identical | ms/token | Tokens/s/user | Total tokens/s | Kept? |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for tag in list(meta) + [t for t in rows if t not in meta]:
        if tag not in rows:
            continue
        r, m = rows[tag], meta.get(tag, {})
        lines.append(
            f"| {m.get('desc', tag)} | {r['gate']} | {fmt(r['top1'], '.1f')} / {fmt(r['top5'], '.1f')} "
            f"| {r['greedy_identical']} | {fmt(r['ms'], '.2f')} | {fmt(r['tsu'], '.2f')} | {fmt(r['ts'], ',.0f')} "
            f"| {m.get('kept', 'pending')} |"
        )
    table = "\n".join(lines) + "\n"
    (Path.home() / "teja/TP8_STEPS.md").write_text(table)
    if STORE.exists():
        (STORE / "TP8_STEPS.md").write_text(table)
    print(table)


if __name__ == "__main__":
    if sys.argv[1] != "--table":
        gate(sys.argv[1])
    write_table()

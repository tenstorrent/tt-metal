"""Generate a HOST-SPECIFIC Gemma 4 PP=4 x (8,1) rank binding from the live galaxy.

Why this exists: the [8,1] column -> physical device map is a per-galaxy property, and a wrong map
does NOT error. It silently builds a 4-stage pipeline whose stages are not galaxy columns, and the
perf numbers come out quietly wrong. Measured on two 32-chip Blackhole galaxies:

    rank  bh-glx-120-b03u02          bh-glx-110-a04u02
    0     0,1,2,3,11,10,9,8          0,1,2,3,27,26,25,24
    1     4,5,6,7,15,14,13,12        4,5,6,7,31,30,29,28
    2     28,29,30,31,23,22,21,20    12,13,14,15,23,22,21,20
    3     24,25,26,27,19,18,17,16    8,9,10,11,19,18,17,16

Every rank differs. So derive it instead of hardcoding: open the 8x4 mesh with the torus_xy
descriptor and ask create_submeshes(MeshShape(8,1)) for each column's device ids -- the identical
carving the single-process measurements use.

Usage (galaxy must be idle):
    python models/demos/gemma4/tests/perf/pp4/gen_gemma4_pp4_binding.py [--profile]

Writes <template stem>.<hostname>.yaml next to the template and prints the path.
"""

import argparse
import os
import re
import socket
import sys
from pathlib import Path

TOPO = Path("models/demos/common/prefill/runners/topology_configuration")
DEFAULT_TEMPLATE = TOPO / "gemma4_pipeline_prefill_4rank_8x1.yaml"
# --profile has its OWN template, and therefore its own output name. Sharing the plain template
# would write both variants to <stem>.<host>.yaml and the second run would silently overwrite the
# first -- leaving an "e2e" binding that carries TT_METAL_PROFILER_DIR, so every cell runs
# instrumented and reports inflated times with no indication why.
PROFILE_TEMPLATE = TOPO / "gemma4_pipeline_prefill_4rank_8x1_profile.yaml"


def probe_columns():
    import ttnn

    from models.demos.gemma4.tt.runners.adapters.gemma4 import Gemma4PrefillConfig
    from models.demos.common.prefill.runners.runner_utils import _create_fabric_router_config

    ttnn.set_fabric_config(
        ttnn.FabricConfig.FABRIC_2D_TORUS_XY,
        ttnn.FabricReliabilityMode.RELAXED_INIT,
        None,
        ttnn.FabricTensixConfig.DISABLED,
        ttnn.FabricUDMMode.DISABLED,
        ttnn.FabricManagerMode.DEFAULT,
        _create_fabric_router_config(max_payload_size=Gemma4PrefillConfig.FABRIC_PAYLOAD_SIZE),
    )
    md = ttnn.open_mesh_device(mesh_shape=ttnn.MeshShape(8, 4))
    try:
        full = list(md.get_device_ids())
        cols = [list(sm.get_device_ids()) for sm in md.create_submeshes(ttnn.MeshShape(8, 1))]
    finally:
        ttnn.close_mesh_device(md)
    if len(cols) != 4 or any(len(c) != 8 for c in cols):
        raise SystemExit(f"expected 4 columns of 8, got {[len(c) for c in cols]}")
    return full, cols


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--template", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--profile", action="store_true", help="use the profile template (per-rank TT_METAL_PROFILER_DIR)")
    args = ap.parse_args()

    host = socket.gethostname()
    tpl = Path(args.template) if args.template else (PROFILE_TEMPLATE if args.profile else DEFAULT_TEMPLATE)
    out = Path(args.out) if args.out else tpl.with_suffix("").with_name(f"{tpl.stem}.{host}.yaml")

    full, cols = probe_columns()
    print("full 8x4 device ids (row-major):", full)
    for i, c in enumerate(cols):
        print(f"  rank{i}: {','.join(map(str, c))}")

    text = tpl.read_text()
    changed = 0
    for r, col in enumerate(cols):
        ids = ",".join(map(str, col))
        pat = re.compile(r'(\{rank: %d, mesh_id: %d, mesh_host_rank: 0, env_overrides: \{.*?)TT_VISIBLE_DEVICES: "[^"]*"\}\}' % (r, r))
        text, n = pat.subn(lambda m: f'{m.group(1)}TT_VISIBLE_DEVICES: "{ids}"}}}}', text)
        if n != 1:
            raise SystemExit(f"template does not have exactly one rank {r} binding line (found {n}); is {tpl} right?")
        changed += n

    banner = (
        f"# GENERATED by gen_gemma4_pp4_binding.py on {host} -- do not hand-edit the TT_VISIBLE_DEVICES lists.\n"
        f"# The [8,1] column -> device map is per-galaxy; regenerate on every new machine.\n"
    )
    out.write_text(banner + text)
    print(f"\nwrote {out} ({changed} rank bindings)")
    print(str(out))


if __name__ == "__main__":
    sys.path.insert(0, os.environ.get("TT_METAL_HOME", "."))
    main()

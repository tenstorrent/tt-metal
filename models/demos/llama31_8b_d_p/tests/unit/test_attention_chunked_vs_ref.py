def _from_device(t):
    return ttnn.to_torch(ttnn.get_device_tensors(t)[0]).float()


def _to_device(t, mesh_device, dtype):
    return ttnn.from_torch(
        t,
        device=mesh_device,
        dtype=dtype,
        layout=ttnn.TILE_LAYOUT,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
        mesh_mapper=ttnn.ReplicateTensorToMesh(mesh_device),
    )


@torch.no_grad()
def _capture_layer_inputs(model, tokens):
    """**One** one-shot forward; returns each layer's *input* hidden state, host fp32.

    Layer 0's input is the embedding output; layer `i`'s is layer `i-1`'s output. Read through the
    `on_layer_output` seam `DEC-050` added for exactly this — a numerical probe that must not share
    a callback with P10's chunk-ack path.

    The copies are the bit-exact device values (the residual stream is bf16 and fp32 holds every
    bf16 value exactly), so re-uploading one as bf16 is lossless and the producers below see
    precisely what the assembled model produced.
    """
    x, rope_mats, _ = model.prepare_inputs_prefill(tokens)
    inputs = [_from_device(x)]
    captured = {}

    def _capture(layer_idx, hidden_states):
        captured[layer_idx] = _from_device(hidden_states)

    out = model.prefill_forward(x, rope_mats, skip_lm_head=True, on_layer_output=_capture)
    out.deallocate(True)
    for cos_or_sin in rope_mats:
        cos_or_sin.deallocate(True)
    inputs.extend(captured[i] for i in range(model.n_layers - 1))
    assert len(inputs) == model.n_layers
    return inputs


# ---------------------------------------------------------------------------------------------
# the two KV producers. Identical code either side of the RoPE call and the write offset.
# ---------------------------------------------------------------------------------------------
def _project_and_split(layer, normed, num_heads, num_kv_heads, compute_kernel_config):
    q, k, v = apply_qkv_projection(normed, layer.self_attn.weights, compute_kernel_config)
    tt_q, tt_k, tt_v = split_qkv_heads_prefill(q, k, v, num_heads, num_kv_heads)
    for t in (q, k, v, tt_q):
        t.deallocate(True)
    return tt_k, tt_v


def _write_heads(kv_cache, tt_k, tt_v, *, kv_actual, num_kv_heads, seq_len, head_dim):
    """`write_kv_chunk` once per KV head, head `h` -> layer slot `h`.

    The per-chip cache holds exactly one KV head, so the model's `[1, 8, S, 128]` tensor cannot be
    written in one call at TP=1 — the op refuses the head-count mismatch outright. Slicing head `h`
    out on device keeps the whole path on device; `head_dim` and the DRAM shard geometry are the
    same ones a chip sees at TP=8.
    """
    for head in range(num_kv_heads):
        k_head = ttnn.slice(tt_k, (0, head, 0, 0), (1, head + 1, seq_len, head_dim))
        v_head = ttnn.slice(tt_v, (0, head, 0, 0), (1, head + 1, seq_len, head_dim))
        write_kv_chunk(kv_cache, k_head, v_head, slot_idx=0, layer_idx=head, kv_actual=kv_actual, sp_axis=0)
        k_head.deallocate(True)
        v_head.deallocate(True)


@torch.no_grad()
def _produce_one_shot(mesh_device, layer, hidden, kv_cache, *, hf, head_dim, rope_contiguous, trans_mat):
    """The one-shot producer: the whole sequence in one call, **contiguous** RoPE, one write at 0."""
    seq_len = hidden.shape[-2]
    num_heads, num_kv_heads = hf["num_attention_heads"], hf["num_key_value_heads"]
    ckc = layer.self_attn.program_config.get_compute_kernel_config(mesh_device)

    # `RMSNorm.forward` does not consume its input, so the upload is freed here rather than left
    # to accumulate one `[1, 1, 512, 4096]` bf16 tensor per layer.
    x = _to_device(hidden, mesh_device, ACTIVATION_DTYPE)
    normed = layer.input_layernorm(x)
    x.deallocate(True)
    tt_k, tt_v = _project_and_split(layer, normed, num_heads, num_kv_heads, ckc)
    normed.deallocate(True)
    rotated = apply_rope(tt_k, rope_contiguous, trans_mat)
    tt_k.deallocate(True)
    _write_heads(kv_cache, rotated, tt_v, kv_actual=0, num_kv_heads=num_kv_heads, seq_len=seq_len, head_dim=head_dim)
    rotated.deallocate(True)
    tt_v.deallocate(True)


@torch.no_grad()
def _produce_chunked(
    mesh_device,
    layer,
    hidden,
    kv_cache,
    *,
    hf,
    head_dim,
    rope_indexed,
    trans_mat,
    chunk_size,
    freeze_rope_offset=False,
    freeze_write_offset=False,
):
    """The chunked producer: one call per chunk, **indexed** RoPE, write offset advancing per chunk.

    `freeze_rope_offset` is the delta-1 negative control (rope every chunk at
    `kv_actual_global = 0`); `freeze_write_offset` is the delta-2 one (write every chunk at
    `kv_actual = 0`). Neither is a code path the model can take — both exist so the gate can show
    that the two offsets are what it is actually measuring.
    """
    seq_len = hidden.shape[-2]
    num_heads, num_kv_heads = hf["num_attention_heads"], hf["num_key_value_heads"]
    ckc = layer.self_attn.program_config.get_compute_kernel_config(mesh_device)

    for start in range(0, seq_len, chunk_size):
        chunk = hidden[:, :, start : start + chunk_size, :]
        x = _to_device(chunk, mesh_device, ACTIVATION_DTYPE)
        normed = layer.input_layernorm(x)
        x.deallocate(True)
        tt_k, tt_v = _project_and_split(layer, normed, num_heads, num_kv_heads, ckc)
        normed.deallocate(True)
        rotated = apply_rope(
            tt_k,
            rope_indexed,
            trans_mat,
            kv_actual_global=0 if freeze_rope_offset else start,
            cluster_axis=0,
        )
        tt_k.deallocate(True)
        _write_heads(
            kv_cache,
            rotated,
            tt_v,
            kv_actual=0 if freeze_write_offset else start,
            num_kv_heads=num_kv_heads,
            seq_len=chunk_size,
            head_dim=head_dim,
        )
        rotated.deallocate(True)
        tt_v.deallocate(True)


def _readback(kv_cache, num_kv_heads, seq_len):
    """The cache's 8 head slots -> `[1, num_kv_heads, S, head_dim]`, fp32, in device (Meta) order."""
    k = _readback_one(kv_cache.k, num_kv_heads, seq_len)
    v = _readback_one(kv_cache.v, num_kv_heads, seq_len)
    return k, v


def _readback_one(cache, num_kv_heads, seq_len):
    host = ttnn.to_torch(ttnn.get_device_tensors(cache)[0]).float()  # [slots, 1, seq_local, head_dim]
    # `sp = 1`, so local row == global position and no inverse block-cyclic reorder is needed —
    # which is also exactly why this gate cannot test that reorder (`R-001`).
    return torch.stack([host[head, 0, :seq_len, :] for head in range(num_kv_heads)], dim=0).unsqueeze(0)


def _fresh_cache(mesh_device, num_kv_heads, seq_len, head_dim):
    """One cache with a **layer slot per KV head** — 8 slots, one KV head each."""
    return allocate_kv_cache(
        mesh_device,
        num_layers=num_kv_heads,
        max_seq_len=seq_len,
        num_users=1,
        head_dim=head_dim,
        cache_dtype=CACHE_DTYPE,
    )


# ---------------------------------------------------------------------------------------------
# the layer-0 floors (§2.2 as corrected by `R-021`)
# ---------------------------------------------------------------------------------------------
@torch.no_grad()
def _layer0_floors(hf, state_dict, tokens, seq_len):
    """`(k_floor_meta, v_floor)` — the **complete** layer-0 floor, and it is a tensor, not a PCC.

    Every value the device holds is rounded to the dtype it holds it in; everything else is fp32:

    * the producer's **input** — the device's embedding output is bf16;
    * the **norm gain** — bf16 on device (`tt/rms_norm.py`);
    * the **projection weight** — `bfloat8_b`, and quantised in the *transposed, Meta-swizzled*
      orientation the device stores it in, then mapped back (`_device_valued`, shared with `G-MODEL`);
    * the **RoPE tables** — bf16, because `tt/rope.py::build_prefill_rope` delegates to a helper
      that builds bf16 and takes no dtype argument. Omitting this is `R-021` exactly: at 32 layers
      the same omission was worth 45% of the floor error;
    * the **stored output** — `bfloat8_b`, quantised **after** the HF->Meta permutation, because
      bf8_b's shared exponent is per 16-element block of the last dim.

    No internal intermediate is quantised (§2.2's conservative reading), so this is a floor rather
    than a flattered one.
    """
    head_dim = derive_head_dim(hf)
    nkv, eps = hf["num_key_value_heads"], hf["rms_norm_eps"]

    embed = state_dict["model.embed_tokens.weight"]
    hidden = quantize_like_device(
        torch.nn.functional.embedding(tokens, embed.float()).reshape(1, 1, seq_len, -1), ACTIVATION_DTYPE
    )
    gain = quantize_like_device(
        state_dict["model.layers.0.input_layernorm.weight"].float().reshape(1, 1, -1, ttnn.TILE_SIZE),
        ACTIVATION_DTYPE,
    ).reshape(-1)
    normed = gain * (hidden * torch.rsqrt(hidden.pow(2).mean(-1, keepdim=True) + eps))
    normed = normed.reshape(seq_len, -1)

    def _proj(name):
        weight = _device_valued(
            f"model.layers.0.self_attn.{name}.weight", state_dict[f"model.layers.0.self_attn.{name}.weight"], head_dim
        )
        return (normed @ weight.transpose(-1, -2)).view(1, seq_len, nkv, head_dim).transpose(1, 2)

    cos, sin = _hf_cos_sin(hf, seq_len)
    cos_q = quantize_like_device(cos.reshape(1, 1, seq_len, head_dim), ACTIVATION_DTYPE).reshape(cos.shape)
    sin_q = quantize_like_device(sin.reshape(1, 1, seq_len, head_dim), ACTIVATION_DTYPE).reshape(sin.shape)

    k_meta = _to_meta(_rope_hf(_proj("k_proj"), cos_q, sin_q), head_dim)
    return quantize_like_device(k_meta, CACHE_DTYPE), quantize_like_device(_proj("v_proj"), CACHE_DTYPE)


# =============================================================================================
# Delta 1, in isolation and on **bit-equality** rather than PCC.
# =============================================================================================
@torch.no_grad()
@pytest.mark.parametrize("mesh_device", [(1, 1)], indirect=True)
@pytest.mark.parametrize("seq_len", [512], ids=lambda s: f"s{s}")
def test_indexed_rope_is_bit_identical_to_contiguous(mesh_device, seq_len, reset_seeds):
    """Delta 1 alone: the **indexed** RoPE must equal the **contiguous** one, `torch.equal`.

    This is the one claim in `G-CHUNK` that is a *layout and addressing* claim rather than a
    numerical one — the indexed op derives each chunk's start row on device from a single
    `kv_actual_global`, and getting that offset wrong is a mapping bug. Recipe §2.5: "Gate every
    layout, mapping or address claim on **bit-equality** (`torch.equal`, `rtol=atol=0`), not on
    PCC", because a rotated mapping still scored PCC 0.99890.

    It needs neither the checkpoint nor the golden trace, so it also runs on a weightless box —
    which makes it the cheapest possible first check for anyone debugging a chunked-prefill number.
    """
    hf = llama_config_dims()
    head_dim, nkv = derive_head_dim(hf), hf["num_key_value_heads"]
    trans_mat = build_transformation_mat(mesh_device)
    x = torch.randn(1, nkv, seq_len, head_dim)

    contiguous = build_prefill_rope(mesh_device, hf, seq_len)
    tt_x = _to_device(x, mesh_device, ACTIVATION_DTYPE)
    rotated = apply_rope(tt_x, contiguous, trans_mat)
    one_shot = _from_device(rotated)
    tt_x.deallocate(True)
    rotated.deallocate(True)

    indexed = build_indexed_rope(mesh_device, hf, max_seq_len=seq_len, chunk_size=CHUNK_SIZE, sp_axis=0)
    assert tuple(indexed[0].shape) == (
        1,
        1,
        seq_len,
        head_dim,
    ), f"the indexed tables must cover the whole cache, got {tuple(indexed[0].shape)}"
    pieces = []
    for start in range(0, seq_len, CHUNK_SIZE):
        tt_chunk = _to_device(x[:, :, start : start + CHUNK_SIZE], mesh_device, ACTIVATION_DTYPE)
        rotated = apply_rope(tt_chunk, indexed, trans_mat, kv_actual_global=start, cluster_axis=0)
        pieces.append(_from_device(rotated))
        tt_chunk.deallocate(True)
        rotated.deallocate(True)
    ttnn.synchronize_device(mesh_device)
    chunked = torch.cat(pieces, dim=2)

    delta = float((one_shot - chunked).abs().max())
    per_chunk = [
        float((one_shot[:, :, c * CHUNK_SIZE : (c + 1) * CHUNK_SIZE] - pieces[c]).abs().max())
        for c in range(seq_len // CHUNK_SIZE)
    ]
    logger.info(
        f"[G-CHUNK] delta 1 in isolation, {seq_len // CHUNK_SIZE} chunks of {CHUNK_SIZE}: "
        f"indexed vs contiguous max|delta| = {delta} (per chunk {per_chunk}), "
        f"torch.equal = {torch.equal(one_shot, chunked)}"
    )
    assert torch.equal(one_shot, chunked), (
        f"the indexed RoPE is not bit-identical to the contiguous one: max|delta| = {delta}, "
        f"per chunk {per_chunk}. An address claim gated on PCC is not gated (recipe section 2.5)."
    )



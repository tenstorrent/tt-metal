"""Gates `G-CHUNK` and `G-GOLDEN` — chunked vs one-shot KV production, and both vs the fp32 golden.

**What this file can and cannot prove, stated up front** (`DEC-056`, `R-028`). A chunked prefill
differs from a one-shot prefill in exactly three places:

| # | delta | tested here |
|---|---|---|
| 1 | the RoPE table and op (`build_indexed_rope` + `rotary_embedding_indexed` at `kv_actual_global = chunk offset`, vs `build_prefill_rope` + `rotary_embedding_llama` over the whole sequence) | **yes** |
| 2 | the cache write offset (`write_kv_chunk(kv_actual=offset)` N times vs once at 0) | **yes** |
| 3 | the attention core (chunk *k*'s queries must attend the prefix read back out of the cache) | **no — refused on a single device** |

Delta 3 is `tt/attention/prefill.py:218`'s deliberate `NotImplementedError`: a plain `is_causal`
SDPA assumes Q row 0 aligns with K row 0, so with a non-empty cache it is off by `cached_len` and
*silently wrong*. It needs the SP ring-joint SDPA over the block-cyclic cache (`tt/attention/
dense_sp.py`, P8) or a paged chunked SDPA. So this file feeds **the same hidden states** to both
paths — taken from one one-shot forward of the real 32-layer model — which isolates deltas 1 and 2
exactly, and leaves delta 3 to P8. Nothing here is weakened to make a number: the un-runnable half
is recorded `BLOCKED` in `bringup_log/06_GATES.md`, not quietly dropped.

Second constraint, and the reason the KV cache is driven through its public functions rather than
through `Model.prefill_forward` (`R-027`, measured): the packed cache holds **one KV head per
chip** (`tt/attention/kv_cache.py:130` allocates `[num_users*num_layers, 1, seq_local, head_dim]`),
so a model-level cache write needs `TP == num_key_value_heads == 8`. At `(1,1)` the model's
attention produces 8 local KV heads and `update_padded_kv_cache` dies with
`TT_FATAL ... cache and input num-heads dim must match`
(`ttnn/cpp/ttnn/operations/experimental/deepseek_prefill/update_padded_kv_cache/device/update_padded_kv_cache_device_operation.cpp:230`). This file therefore writes head `h` into cache
slot `h` — same op, same DRAM geometry, same `head_dim=128`, one head per write, which is exactly
what a chip does at TP=8.

Everything else is real: the real checkpoint, the real (Meta-swizzled) device weights, the real
`input_layernorm` -> `q/k/v_proj` -> `nlp_create_qkv_heads` -> RoPE op sequence
`tt/attention/prefill.py:139-176` runs, the real DRAM `NdShard` cache, all 32 layers, and an fp32
golden that shares none of the device's rounding.

**Input distribution:** none — the input is the real tokenized prompt from the golden trace, and the
weights are the real checkpoint. There is no random tensor to choose a distribution for, which is
the strongest version of Appendix E.1's rule.
**Reference dtype policy:** the golden is `transformers`' own math in fp32 on the checkpoint's bf16
weights upcast exactly, stored fp32 (`scripts/generate_golden_kv_cache.py` header). The device
holds bf8_b weights, bf16 activations and a bf8_b cache, so the reference does **not** share the
device's rounding.
**Noise floor** (Appendix E.2): the golden K/V pushed through ttnn's own bf8_b quantiser — the cache
dtype is the whole storage budget — with `err_ratio` reported per layer.

Set the golden trace with `$PREFILL_TRACE_DIR` (`DEC-057`), generated by::

    python3 models/demos/llama31_8b_d_p/scripts/generate_golden_kv_cache.py \\
        --prompt-file prompt.txt --max-tokens 512 --pad-to 512 --out DIR

Run::

    export PREFILL_TRACE_DIR=DIR
    pytest models/demos/llama31_8b_d_p/tests/unit/test_attention_chunked_vs_ref.py -x -q
"""


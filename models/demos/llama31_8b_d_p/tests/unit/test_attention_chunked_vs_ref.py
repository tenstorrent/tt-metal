def _golden_layer(layer_idx: int):
    """`(k_hf, v)` for one layer, fp32, `[1, num_kv_heads, S, head_dim]` in **HF** layout."""
    path = os.path.join(_TRACE_DIR, "kv_cache", f"layer_{layer_idx}.safetensors")
    with safe_open(path, framework="pt", device="cpu") as h:
        return (
            h.get_tensor(f"key_cache_layer_{layer_idx}").float(),
            h.get_tensor(f"value_cache_layer_{layer_idx}").float(),
        )


def _to_meta(k_hf: torch.Tensor, head_dim: int) -> torch.Tensor:
    """HF half-split rotary order -> Meta interleaved order over `head_dim`.

    The device's Q/K projection weights are `reverse_permute`d at load
    (`models/tt_transformers/tt/load_checkpoints.py:891`), so the device's K rows are Meta-ordered
    and the golden's are not. `_meta_head_index` is the same map `G-LAYER`'s SDPA substitution uses.
    """
    return k_hf[..., _meta_head_index(head_dim)]



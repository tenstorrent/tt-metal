# The blocked half, asserted as a refusal so it cannot silently start passing wrong
# =====================================================================================
@pytest.mark.parametrize("mesh_device", [TestFactory.SINGLE_CARD_MESH_SHAPE], indirect=True)
@torch.no_grad()
def test_model_level_chunked_prefill_is_refused_on_one_card(mesh_device, reset_seeds, expect_error):
    """The two blockers behind `G-CHUNK`'s `BLOCKED` half, both asserted as *loud* refusals.

    1. `cached_len > 0` on a single device: `tt/attention/prefill.py:218` raises rather than run an
       `is_causal` SDPA that is off by `cached_len`.
    2. `TP != num_key_value_heads`: the packed cache is one head per chip, so a model-level write at
       TP=1 dies inside `update_padded_kv_cache`. `TtPrefillRuntime._resolve_kv` converts that
       `TT_FATAL` into a message naming the mesh (`R-027`).

    If either ever stops raising, this test fails — which is the point. A silent success here would
    mean chunked prefill had started returning plausible, wrong KV.
    """
    from models.demos.llama31_8b_d_p.tt.attention import Attention, ProgramConfig, attention_config_from_hf
    from models.demos.llama31_8b_d_p.tt.tt_prefill_runtime import TtPrefillRuntime, TtPrefillRuntimeConfig

    hf_config = llama_hf_config(llama_config_dims())
    objs = TestFactory.setup_test(mesh_device)

    # Blocker 1, reached through the real forward with real tensors (random projection weights —
    # this asserts a refusal, not a number). `kv_cache=None` matters: `write_kv_chunk` runs BEFORE
    # the refusal (`tt/attention/prefill.py:182` then `:218`), so with a cache attached at TP=1 the
    # cache's own head-count TT_FATAL fires first and blocker 1 is never reached — which is itself
    # why blocker 2 has to be checked separately below.
    cfg = attention_config_from_hf(hf_config, max_seq_len=2 * CHUNK)
    gen = torch.Generator().manual_seed(0)
    state = {
        "q_proj.weight": torch.randn(cfg.num_heads * cfg.head_dim, cfg.hidden_size, generator=gen) * 0.02,
        "k_proj.weight": torch.randn(cfg.num_kv_heads * cfg.head_dim, cfg.hidden_size, generator=gen) * 0.02,
        "v_proj.weight": torch.randn(cfg.num_kv_heads * cfg.head_dim, cfg.hidden_size, generator=gen) * 0.02,
        "o_proj.weight": torch.randn(cfg.hidden_size, cfg.num_heads * cfg.head_dim, generator=gen) * 0.02,
    }
    attn = Attention(
        mesh_device,
        cfg,
        state,
        mesh_config=objs["mesh_config"],
        ccl_manager=None,  # TP=1 / SP=1: no collective is entered
        program_config=ProgramConfig(),
        layer_idx=0,
        transformation_mats={"prefill": build_transformation_mat(mesh_device)},
    )
    rope_indexed = build_indexed_rope(mesh_device, hf_config, max_seq_len=2 * CHUNK, chunk_size=CHUNK)
    x = _to_device(mesh_device, torch.randn(1, 1, CHUNK, cfg.hidden_size, generator=gen))
    with expect_error(NotImplementedError, "single-device chunked cache-read attention"):
        attn(x, rope_mats=rope_indexed, kv_cache=None, cached_len=CHUNK, indexed_rope=True)

    # `_resolve_kv` is reachable without an 8 B model: build the config, not the runtime.
    config = TtPrefillRuntimeConfig(
        num_layers=1,
        max_seq_len=SEQ_LEN,
        mesh_shape=tuple(mesh_device.shape),
        default_chunk_size=CHUNK,
        num_users=1,
    )
    assert config.chunk_size == CHUNK == config.default_chunk_size, "config.chunk_size must alias default_chunk_size"
    stub = TtPrefillRuntime.__new__(TtPrefillRuntime)
    stub.config = config
    stub.hf_config = hf_config
    stub.kv_cache = allocate_kv_cache(
        mesh_device, num_layers=1, max_seq_len=SEQ_LEN, num_users=1, head_dim=hf_config.head_dim
    )
    with expect_error(AssertionError, "ONE KV head per chip"):
        stub._resolve_kv(None)
    logger.info(
        "[G-CHUNK] both single-device blockers refuse loudly: cached_len>0 attention "
        "(tt/attention/prefill.py) and TP != num_key_value_heads (TtPrefillRuntime._resolve_kv)"
    )

    cache_bug = _fresh_cache()  # negative control: every chunk roped at offset 0

    dump_dir = tmp_path / "device_dump"
    dump_dir.mkdir(parents=True, exist_ok=True)
    from safetensors.torch import save_file

    rows = []
    worst = {"mutual_k": 1.0, "mutual_v": 1.0, "golden_k": 1.0, "golden_v": 1.0, "ratio_k": 0.0}
    bug_worst = 1.0
    for layer_idx in range(num_layers):
        layer = tt_model.layers[layer_idx]

        # --- path A: one shot over the whole sequence ---
        tt_k, tt_v = _produce_kv(
            mesh_device,
            layer,
            h_in[layer_idx],
            n_heads=n_heads,
            n_kv_heads=n_kv_heads,
            rope_mats=rope_one_shot,
            kv_actual=None,
            indexed=False,
        )
        _write_heads(cache_one_shot, tt_k, tt_v, n_kv_heads=n_kv_heads, span=seq_len, head_dim=head_dim, kv_actual=0)
        tt_k.deallocate(True)
        tt_v.deallocate(True)

        # --- path B: N chunks, indexed rope at each chunk's own global offset ---
        for chunk_idx in range(n_chunks):
            lo = chunk_idx * chunk
            tt_k, tt_v = _produce_kv(
                mesh_device,
                layer,
                h_in[layer_idx][:, :, lo : lo + chunk, :],
                n_heads=n_heads,
                n_kv_heads=n_kv_heads,
                rope_mats=rope_indexed,
                kv_actual=lo,
                indexed=True,
            )
            _write_heads(cache_chunked, tt_k, tt_v, n_kv_heads=n_kv_heads, span=chunk, head_dim=head_dim, kv_actual=lo)
            tt_k.deallocate(True)
            tt_v.deallocate(True)

            # --- negative control: the same chunks with kv_actual_global pinned at 0 ---
            tt_k, tt_v = _produce_kv(
                mesh_device,
                layer,
                h_in[layer_idx][:, :, lo : lo + chunk, :],
                n_heads=n_heads,
                n_kv_heads=n_kv_heads,
                rope_mats=rope_indexed,
                kv_actual=0,
                indexed=True,
            )
            _write_heads(cache_bug, tt_k, tt_v, n_kv_heads=n_kv_heads, span=chunk, head_dim=head_dim, kv_actual=lo)
            tt_k.deallocate(True)
            tt_v.deallocate(True)
        ttnn.synchronize_device(mesh_device)

        read = dict(n_kv_heads=n_kv_heads, n_tokens=seq_len, max_seq_len=seq_len)
        k_one, v_one = _read_cache(mesh_device, cache_one_shot, chunk_size=seq_len, **read)
        k_chunk, v_chunk = _read_cache(mesh_device, cache_chunked, chunk_size=chunk, **read)
        k_bug, _v_bug = _read_cache(mesh_device, cache_bug, chunk_size=chunk, **read)
        g_k, g_v = _golden_layer(trace_dir, layer_idx, n_tokens=seq_len, perm=perm)

        _, mutual_k = comp_pcc(k_one, k_chunk, 0.0)
        _, mutual_v = comp_pcc(v_one, v_chunk, 0.0)
        _, golden_k = comp_pcc(g_k, k_chunk, 0.0)
        _, golden_v = comp_pcc(g_v, v_chunk, 0.0)
        _, golden_k_one = comp_pcc(g_k, k_one, 0.0)
        _, bug_k = comp_pcc(g_k, k_bug, 0.0)
        # Appendix E.2 floor: the cache stores K and nothing else, so its dtype is the whole
        # STORAGE budget. The measured value also carries bf8_b weights and bf16 activations, so a
        # ratio above 1 is expected here and is *named*, not attributed to the cache (E.5).
        _, floor_k = comp_pcc(g_k, quantize_like_device(g_k, ttnn.bfloat8_b), 0.0)
        ratio_k = err_ratio(golden_k, floor_k)

        rows.append((layer_idx, float(mutual_k), float(mutual_v), float(golden_k), float(golden_v), ratio_k))
        worst["mutual_k"] = min(worst["mutual_k"], float(mutual_k))
        worst["mutual_v"] = min(worst["mutual_v"], float(mutual_v))
        worst["golden_k"] = min(worst["golden_k"], float(golden_k))
        worst["golden_v"] = min(worst["golden_v"], float(golden_v))
        worst["ratio_k"] = max(worst["ratio_k"], ratio_k)
        bug_worst = min(bug_worst, float(bug_k))
        logger.info(
            f"[G-CHUNK] L{layer_idx:>2}: chunked-vs-one-shot K={mutual_k:.5f} V={mutual_v:.5f} | "
            f"vs golden (chunked) K={golden_k:.5f} V={golden_v:.5f} | (one-shot) K={golden_k_one:.5f} | "
            f"bf8_b K floor={floor_k:.5f} err_ratio={ratio_k:.2f}x | offset-0 control K={bug_k:.5f}"
        )

        save_file(
            {
                f"key_cache_layer_{layer_idx}": k_chunk.contiguous(),
                f"value_cache_layer_{layer_idx}": v_chunk.contiguous(),
            },
            str(dump_dir / f"layer_{layer_idx}.safetensors"),
        )

    with open(dump_dir / "metadata.json", "w") as handle:
        json.dump(
            {
                "convention": "meta",
                "n_tokens": seq_len,
                "layers": list(range(num_layers)),
                "head_dim": head_dim,
                "rotary_dim": head_dim,
                "num_kv_heads": n_kv_heads,
                "mesh_shape": list(tuple(mesh_device.shape)),
                "chunk_size": chunk,
                "cache_dtype": str(ttnn.bfloat8_b),
            },
            handle,
            indent=2,
        )

    logger.info(
        f"[G-CHUNK] {num_layers} layers, seq={seq_len}, {n_chunks} x {chunk}: "
        f"min chunked-vs-one-shot K={worst['mutual_k']:.5f} V={worst['mutual_v']:.5f} "
        f"(threshold {MUTUAL_PCC}) | min vs golden K={worst['golden_k']:.5f} (>= {GOLDEN_PCC_K}) "
        f"V={worst['golden_v']:.5f} (>= {GOLDEN_PCC_V}) | worst K err_ratio={worst['ratio_k']:.2f}x "
        f"of the bf8_b storage floor | negative control (offset-0 rope) worst K={bug_worst:.5f} "
        f"(must be <= {NEGATIVE_CONTROL_MAX_PCC})"
    )

    # --- R-025: the per-layer error-STEP curve, re-measured at this chunk size ---
    # DEC-047 set MAX_LAYER_ERROR_STEP = 4.0 from the hidden-state curve at seq 128 and R-025 asks
    # for it to be re-derived at a realistic chunk size. This is the same statistic on the KV
    # product (which is what P7 owns): consecutive (1 - pcc) ratios. A *step* is a single-layer
    # bug; smooth growth is accumulation. Recorded for both parametrised cases so the threshold has
    # two chunk sizes behind it instead of one.
    steps_k = [(rows[i][0], (1 - rows[i][3]) / max(1 - rows[i - 1][3], 1e-12)) for i in range(1, len(rows))]
    steps_v = [(rows[i][0], (1 - rows[i][4]) / max(1 - rows[i - 1][4], 1e-12)) for i in range(1, len(rows))]
    checked_k = [(i, st) for i, st in steps_k if i >= STEP_CHECK_FROM_LAYER]
    checked_v = [(i, st) for i, st in steps_v if i >= STEP_CHECK_FROM_LAYER]
    max_step_k, at_k = max(checked_k, key=lambda t: t[1])[::-1]
    max_step_v, at_v = max(checked_v, key=lambda t: t[1])[::-1]
    logger.info(
        f"[G-CHUNK] R-025 KV error-step curve at seq={seq_len} chunk={chunk}: max K step = "
        f"{max_step_k:.2f}x at L{at_k}, max V step = {max_step_v:.2f}x at L{at_v} "
        f"(ceiling {MAX_KV_ERROR_STEP}x, checked from L{STEP_CHECK_FROM_LAYER} per DEC-047). "
        f"Excluded early steps (near-exact baseline, K): "
        f"{[(i, round(st, 2)) for i, st in steps_k if i < STEP_CHECK_FROM_LAYER]}; "
        f"K error span {1 - max(r[3] for r in rows):.2e} .. {1 - min(r[3] for r in rows):.2e}"
    )
    layer0_ratio = rows[0][5]
    logger.info(
        f"[G-CHUNK] E.2/E.5 floor accounting at seq={seq_len}: layer 0 err_ratio = "
        f"{layer0_ratio:.2f}x of the bf8_b storage floor (ceiling {MAX_LAYER0_ERR_RATIO}x) — layer 0's "
        f"input is the EXACT embedding, so the storage floor is its whole budget. Worst layer "
        f"err_ratio = {worst['ratio_k']:.2f}x, which is NOT a finding against that floor: from layer "
        f"1 on the input hidden state already carries the accumulated bf8_b-weight error of every "
        f"layer below (G-MODEL: 32-layer hidden state 0.9997646), so a storage-only floor models the "
        f"wrong thing. The step curve above is the instrument for those layers."
    )

    # --- G-GOLDEN's per-layer table, produced by the shipped script ---
    lines = []
    dump_ok, _dump_rows, summary = compare_device_dump(
        trace_dir, dump_dir, pcc_k=GOLDEN_PCC_K, pcc_v=GOLDEN_PCC_V, out=lines.append
    )
    for line in lines:
        logger.info(f"[G-GOLDEN] {line}")

    assert worst["mutual_k"] >= MUTUAL_PCC, (
        f"[G-CHUNK] chunked KV differs from one-shot: min K PCC {worst['mutual_k']} < {MUTUAL_PCC}. "
        f"Both paths store the same values from the same hidden states, so this is the indexed RoPE "
        f"offset or the cache write offset, not precision."
    )
    assert worst["mutual_v"] >= MUTUAL_PCC, f"[G-CHUNK] chunked V differs from one-shot: {worst['mutual_v']}"
    assert worst["golden_k"] >= GOLDEN_PCC_K, f"[G-CHUNK] chunked K vs golden: {worst['golden_k']} < {GOLDEN_PCC_K}"
    assert worst["golden_v"] >= GOLDEN_PCC_V, f"[G-CHUNK] chunked V vs golden: {worst['golden_v']} < {GOLDEN_PCC_V}"
    assert max(max_step_k, max_step_v) <= MAX_KV_ERROR_STEP, (
        f"[G-CHUNK] a single layer multiplies the KV error by more than {MAX_KV_ERROR_STEP}x "
        f"(K {max_step_k:.2f}x at L{at_k}, V {max_step_v:.2f}x at L{at_v}, seq={seq_len}): that is a "
        f"per-layer bug, not accumulation — chase the layer, not the depth (R-025 / DEC-047)"
    )
    assert layer0_ratio <= MAX_LAYER0_ERR_RATIO, (
        f"[G-CHUNK] layer 0's K sits {layer0_ratio:.2f}x off the bf8_b storage floor (ceiling "
        f"{MAX_LAYER0_ERR_RATIO}x). Layer 0's input is exact, so nothing upstream can explain this: "
        f"it is the projection, the RoPE or the cache write."
    )
    assert bug_worst <= NEGATIVE_CONTROL_MAX_PCC, (
        f"[G-CHUNK] NEGATIVE CONTROL FAILED: roping every chunk at kv_actual_global=0 still scores "
        f"K PCC {bug_worst} > {NEGATIVE_CONTROL_MAX_PCC} against the golden. The test cannot "
        f"distinguish a correct chunk offset from a wrong one, so its PASS means nothing."
    )
    assert dump_ok, (
        f"[G-GOLDEN] compare_device_dump rejected the dump: min K {summary.get('min_k')} "
        f"min V {summary.get('min_v')}"
    )



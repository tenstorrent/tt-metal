def _one_shot_hidden_states(mesh_device, tt_model, token_ids, hf_config, seq_len):
    """One one-shot forward; return every layer's **input** hidden state, on the host.

    Layer `i`'s input is layer `i-1`'s output, and layer 0's input is the embedding. The
    `on_layer_complete(layer_idx, hidden_states)` seam (`DEC-045`) hands over the live tensor, so it
    is copied to host immediately — the next layer deallocates it (`tt/layer.py:224`).
    """
    tokens_embd, rope_mats, _ = tt_model.prepare_inputs_prefill(
        torch.tensor(token_ids, dtype=torch.int32), start_pos=0, build_rope=True
    )
    inputs = [ttnn.to_torch(ttnn.get_device_tensors(tokens_embd)[0]).float()]
    outputs = []

    def on_layer_complete(layer_idx, hidden_states):
        # Live tensor: copy, never deallocate (`tt/model.py:318-324`).
        outputs.append(ttnn.to_torch(ttnn.get_device_tensors(hidden_states)[0]).float())

    out = tt_model.prefill_forward(
        tokens_embd,
        rot_mats_global=rope_mats,
        kv_cache=None,
        skip_lm_head=True,
        on_layer_complete=on_layer_complete,
    )
    out.deallocate(True)
    assert len(outputs) == tt_model.num_layers, f"seam fired {len(outputs)} times, expected {tt_model.num_layers}"
    inputs.extend(outputs[:-1])
    assert all(tuple(h.shape) == (1, 1, seq_len, hf_config.hidden_size) for h in inputs)
    return inputs


def _to_device(mesh_device, host_tensor):
    return ttnn.from_torch(
        host_tensor,
        device=mesh_device,
        dtype=ttnn.bfloat16,
        layout=ttnn.TILE_LAYOUT,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
        mesh_mapper=ttnn.ReplicateTensorToMesh(mesh_device),
    )


def _produce_kv(mesh_device, layer, h_in_host, *, n_heads, n_kv_heads, rope_mats, kv_actual, indexed):
    """Run the real K/V producer for one span: norm -> q/k/v -> head split -> RoPE.

    This is `tt/attention/prefill.py:139-176` verbatim in op order and arguments; only the SDPA and
    `o_proj` tail is omitted, because the cache is written before them (`:184`). Returns
    `(tt_k_post_rope, tt_v_raw)`, each `[1, n_kv_heads, span, head_dim]`, still live.
    """
    x = _to_device(mesh_device, h_in_host)
    normed = layer.input_layernorm(x)
    attn = layer.self_attn
    tt_q_flat, tt_kv_flat = apply_qkv_projection(normed, attn.weights, attn.compute_kernel_config)
    normed.deallocate(True)
    _, tt_k, tt_v = split_qkv_heads_prefill(tt_q_flat, tt_kv_flat, n_heads, n_kv_heads)
    tt_q_flat.deallocate(True)
    tt_kv_flat.deallocate(True)
    pre_rope = tt_k
    tt_k = apply_rope(
        tt_k,
        rope_mats,
        attn.transformation_mats["prefill"],
        is_decode_mode=False,
        kv_actual_global=kv_actual if indexed else None,
        cluster_axis=0 if indexed else None,
    )
    pre_rope.deallocate(True)
    return tt_k, tt_v


def _write_heads(kv_cache, tt_k, tt_v, *, n_kv_heads, span, head_dim, kv_actual):
    """Write each KV head into its own cache slot (`slot = head`), one head per call.

    `write_kv_chunk` writes a single `(slot, layer)` and the per-chip cache is one head wide, so a
    `[1, 8, S, 128]` tensor cannot go in as one call — it would silently write only the first head
    (`tt/attention/kv_cache.py:181`). Slicing per head is the same write a chip performs at TP=8.
    """
    for head in range(n_kv_heads):
        k_head = ttnn.slice(tt_k, (0, head, 0, 0), (1, head + 1, span, head_dim))
        v_head = ttnn.slice(tt_v, (0, head, 0, 0), (1, head + 1, span, head_dim))
        write_kv_chunk(kv_cache, k_head, v_head, slot_idx=head, layer_idx=0, kv_actual=kv_actual, sp_axis=0)
        k_head.deallocate(True)
        v_head.deallocate(True)


def _read_cache(mesh_device, kv_cache, *, n_kv_heads, n_tokens, chunk_size, max_seq_len):
    """Read the 8 head-slots back in natural token order -> `(k, v)` `[1, n_kv_heads, n_tokens, hd]`."""
    positions = blockcyclic_positions(mesh_device.shape[0], chunk_size, max_seq_len)

    def _one(cache_tensor, slot):
        device_rows = ttnn.to_torch(ttnn.get_device_tensors(cache_tensor)[0])[slot, 0].float()
        natural = torch.empty_like(device_rows)
        natural[positions] = device_rows
        return natural[:n_tokens]

    k = torch.stack([_one(kv_cache.k, h) for h in range(n_kv_heads)], dim=0).unsqueeze(0)
    v = torch.stack([_one(kv_cache.v, h) for h in range(n_kv_heads)], dim=0).unsqueeze(0)
    return k, v


def _golden_layer(trace_dir, layer_idx, *, n_tokens, perm):
    from safetensors import safe_open

    with safe_open(str(trace_dir / "kv_cache" / f"layer_{layer_idx}.safetensors"), framework="pt") as handle:
        k = handle.get_tensor(f"key_cache_layer_{layer_idx}").float()[:, :, :n_tokens, :][..., perm]
        v = handle.get_tensor(f"value_cache_layer_{layer_idx}").float()[:, :, :n_tokens, :]
    return k, v



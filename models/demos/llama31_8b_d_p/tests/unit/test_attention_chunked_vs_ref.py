@requires_hf_reference
def test_golden_trace_structure_is_valid():
    """`verify_golden_kv.verify_structure` accepts the trace: every layer, shape, finite, non-constant.

    This is `G-GOLDEN`'s host gate (Appendix A lists its device as **host**). The non-constant check
    is the one that matters: an all-zero cache passes "no NaNs" and then scores a *nan* PCC, so a
    dead producer would present as a broken comparison rather than a broken producer.
    """
    trace_dir = _trace_dir()
    lines = []
    ok, metadata = verify_structure(trace_dir, out=lines.append)
    for line in lines:
        logger.info(f"[G-GOLDEN]{line}")
    assert ok, f"golden trace {trace_dir} failed structural verification:\n" + "\n".join(lines)
    dims = llama_config_dims()
    assert metadata["num_kv_heads"] == dims["num_key_value_heads"] == 8
    assert metadata["head_dim"] == dims["head_dim"] == 128
    assert metadata["reference_dtype_policy"].startswith("checkpoint bfloat16 upcast exactly to fp32")
    assert metadata["explicit_causal_mask"] is True, (
        "the golden was generated without an explicit causal mask; eager attention applies only the "
        "mask it is handed, so layers 1+ would be non-causal and silently wrong (Appendix F.2)"
    )
    logger.info(
        f"[G-GOLDEN] trace OK: {metadata['num_layers']} layers x {metadata['n_tokens']} tokens "
        f"({metadata['n_real_tokens']} real), K/V {metadata['key_cache_shape']}, "
        f"dtype {metadata['dtype']}, reference: {metadata['reference']}"
    )


def test_hf_to_meta_lane_permutation_carries_frequencies_to_adjacent_lanes():
    """The one RoPE-convention permutation in this package, checked semantically, without a device.

    HF puts frequency `i` at lanes `(i, i + 64)`; Meta at `(2i, 2i + 1)`. Getting the direction
    wrong does not fail loudly — it produces a plausible 0.5-0.9 K PCC, the Appendix B signature —
    and the map is **not** an involution (`perm[perm][:4] == [0, 32, 64, 96]`), so "apply it to
    whichever side" is also wrong. The check is therefore the defining property rather than an
    algebraic shortcut: label each HF lane with the frequency index it carries, permute, and require
    that Meta lanes `2i` and `2i+1` both come out labelled `i`.
    """
    head_dim = 128
    perm = hf_to_meta_lane_permutation(head_dim, head_dim)
    assert torch.equal(torch.sort(perm).values, torch.arange(head_dim)), "not a permutation"
    assert not torch.equal(perm, torch.arange(head_dim)), "expected a non-identity permutation"

    hf_frequency_of_lane = torch.arange(head_dim) % (head_dim // 2)
    meta = hf_frequency_of_lane[perm]
    expected = torch.arange(head_dim) // 2
    assert torch.equal(
        meta, expected
    ), f"HF->Meta permutation does not put frequency i on Meta lanes (2i, 2i+1): got {meta[:8].tolist()}"
    # Spot-check the exact mapping the gpt-oss reader uses (`models/demos/gpt_oss_d_p/tt/tt_prefill_runtime.py:552-556`):
    # Meta lane 0 <- HF lane 0, Meta lane 1 <- HF lane 64, Meta lane 2 <- HF lane 1.
    assert perm.tolist()[:4] == [0, 64, 1, 65]
    logger.info(
        "[G-GOLDEN] HF->Meta lane permutation puts frequency i on Meta lanes (2i, 2i+1); "
        "perm[:4] = [0, 64, 1, 65]; it is NOT an involution"
    )


@requires_hf_reference
@torch.no_grad()
def test_golden_driver_agrees_with_hfs_own_model_loop():
    """The golden's per-layer driver == `LlamaModel`'s own loop, bit-for-bit, on the same weights.

    `generate_golden_kv_cache.py` builds one `LlamaDecoderLayer` at a time and supplies the RoPE
    tables, the causal mask and the position ids itself. Every one of those is a place a driver can
    be subtly wrong while every layer still runs and every shape still checks out — and a wrong
    golden makes every downstream PCC meaningless in the *safe-looking* direction. So this compares
    against `LlamaModel.forward`, which constructs all three internally: two independent drivers,
    the same HF layer code, the same real weights.

    Two layers only: the driver is depth-independent (the loop body is identical for every `i`),
    and `LlamaModel` at full depth would mean 32 GiB of fp32 weight for no extra information.
    """
    from transformers import LlamaConfig
    from transformers.cache_utils import DynamicCache
    from transformers.models.llama import modeling_llama as ml

    from models.demos.llama31_8b_d_p.scripts.generate_golden_kv_cache import _ShardReader, generate
    from models.demos.llama31_8b_d_p.tests.test_factory import hf_model_path

    ckpt = Path(hf_model_path())
    n_layers, seq_len = 2, 64
    token_ids = list(range(1000, 1000 + seq_len))

    cfg = LlamaConfig.from_pretrained(str(ckpt))
    cfg._attn_implementation = "eager"
    cfg.num_hidden_layers = n_layers
    hf_model = ml.LlamaModel(cfg).float().eval()
    reader = _ShardReader(ckpt)
    hf_state = {
        "embed_tokens.weight": reader.get("model.embed_tokens.weight"),
        "norm.weight": reader.get("model.norm.weight"),
    }
    for layer_idx in range(n_layers):
        hf_state.update(
            {f"layers.{layer_idx}.{k}": v for k, v in reader.substate(f"model.layers.{layer_idx}.").items()}
        )
    hf_model.load_state_dict(hf_state, strict=True)

    reference_cache = DynamicCache(config=cfg)
    hf_model(
        input_ids=torch.tensor(token_ids, dtype=torch.long).unsqueeze(0),
        past_key_values=reference_cache,
        use_cache=True,
    )

    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        generate(
            ckpt_dir=ckpt,
            token_ids=token_ids,
            out_dir=Path(tmp),
            num_layers=n_layers,
            progress=lambda _msg: None,
        )
        identity = torch.arange(cfg.head_dim)
        for layer_idx in range(n_layers):
            golden_k, golden_v = _golden_layer(Path(tmp), layer_idx, n_tokens=seq_len, perm=identity)
            torch.testing.assert_close(golden_k, reference_cache.layers[layer_idx].keys.float(), rtol=0.0, atol=0.0)
            torch.testing.assert_close(golden_v, reference_cache.layers[layer_idx].values.float(), rtol=0.0, atol=0.0)
    logger.info(
        f"[G-GOLDEN] the per-layer streaming driver reproduces LlamaModel's own loop BIT-EXACTLY "
        f"(rtol=atol=0) for {n_layers} layers x {seq_len} tokens on real weights"
    )


def test_device_dump_metadata_contract_matches_the_verifier():
    """`dump_slot_kv`'s metadata keys are exactly the ones `compare_device_dump` reads.

    The two live in different files (`tt/tt_prefill_runtime.py` and `scripts/verify_golden_kv.py`)
    and are only ever exercised together on a TP=8 mesh (`R-027`), so nothing else stops them
    drifting on the single card this phase runs on. Asserted from the source text because the
    writer cannot be *called* here.
    """
    runtime_src = (Path(__file__).resolve().parents[2] / "tt" / "tt_prefill_runtime.py").read_text()
    verifier_src = (Path(__file__).resolve().parents[2] / "scripts" / "verify_golden_kv.py").read_text()
    for key in ("convention", "n_tokens", "layers", "head_dim", "rotary_dim"):
        assert f'"{key}"' in runtime_src, f"dump_slot_kv no longer writes {key!r}"
        assert f'"{key}"' in verifier_src, f"compare_device_dump no longer reads {key!r}"
    assert '"convention": "meta"' in runtime_src, "the device dump must declare the Meta K convention"
    logger.info("[G-GOLDEN] dump_slot_kv <-> compare_device_dump metadata contract intact")



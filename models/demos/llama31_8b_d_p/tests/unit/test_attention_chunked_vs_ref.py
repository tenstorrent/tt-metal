@requires_hf_reference
@requires_golden_trace
@torch.no_grad()
@pytest.mark.parametrize("mesh_device", [(1, 1)], indirect=True)
def test_chunked_kv_equals_one_shot_and_golden(mesh_device, reset_seeds):
    """The gate: chunked == one-shot per layer, both vs the fp32 golden, L0 ratio, per-layer step."""
    hf = llama_config_dims()
    metadata = _golden_metadata()
    n_layers = int(metadata["num_layers"])
    seq_len = int(metadata["n_tokens"])
    head_dim, nkv = derive_head_dim(hf), hf["num_key_value_heads"]

    assert (
        n_layers == hf["num_hidden_layers"]
    ), f"the trace has {n_layers} layers, the model has {hf['num_hidden_layers']}"
    assert metadata["dtype"] == "float32", f"the golden must be fp32, this trace is {metadata['dtype']!r} (DEC-059)"
    assert seq_len % CHUNK_SIZE == 0, f"seq_len {seq_len} is not a multiple of CHUNK_SIZE {CHUNK_SIZE}"
    tokens = torch.tensor(metadata["token_ids"], dtype=torch.long).reshape(1, seq_len)
    n_chunks = seq_len // CHUNK_SIZE

    state_dict = _load_checkpoint(n_layers)
    model = _build_model(mesh_device, hf, state_dict, n_layers, seq_len)
    layer_inputs = _capture_layer_inputs(model, tokens)

    rope_contiguous = build_prefill_rope(mesh_device, hf, seq_len)
    rope_indexed = build_indexed_rope(mesh_device, hf, max_seq_len=seq_len, chunk_size=CHUNK_SIZE, sp_axis=0)
    trans_mat = model.transformation_mats["prefill"]

    k_floor_l0, v_floor_l0 = _layer0_floors(hf, state_dict, tokens, seq_len)

    curve = {"mutual_k": {}, "mutual_v": {}, "one_shot_k": {}, "one_shot_v": {}, "chunked_k": {}, "chunked_v": {}}
    l0 = {}

    for layer_idx in range(n_layers):
        layer = model.layers[layer_idx]
        hidden = layer_inputs[layer_idx]

        cache_one_shot = _fresh_cache(mesh_device, nkv, seq_len, head_dim)
        _produce_one_shot(
            mesh_device,
            layer,
            hidden,
            cache_one_shot,
            hf=hf,
            head_dim=head_dim,
            rope_contiguous=rope_contiguous,
            trans_mat=trans_mat,
        )
        cache_chunked = _fresh_cache(mesh_device, nkv, seq_len, head_dim)
        _produce_chunked(
            mesh_device,
            layer,
            hidden,
            cache_chunked,
            hf=hf,
            head_dim=head_dim,
            rope_indexed=rope_indexed,
            trans_mat=trans_mat,
            chunk_size=CHUNK_SIZE,
        )
        ttnn.synchronize_device(mesh_device)

        one_shot_k, one_shot_v = _readback(cache_one_shot, nkv, seq_len)
        chunked_k, chunked_v = _readback(cache_chunked, nkv, seq_len)
        golden_k_hf, golden_v = _golden_layer(layer_idx)
        golden_k = _to_meta(golden_k_hf, head_dim)

        _, mutual_k = comp_pcc(one_shot_k, chunked_k, 0.0)
        _, mutual_v = comp_pcc(one_shot_v, chunked_v, 0.0)
        curve["mutual_k"][layer_idx], curve["mutual_v"][layer_idx] = float(mutual_k), float(mutual_v)
        for name, ref, got in (
            ("one_shot_k", golden_k, one_shot_k),
            ("one_shot_v", golden_v, one_shot_v),
            ("chunked_k", golden_k, chunked_k),
            ("chunked_v", golden_v, chunked_v),
        ):
            _, pcc = comp_pcc(ref, got, 0.0)
            curve[name][layer_idx] = float(pcc)

        if layer_idx == 0:
            # Both floors, and the difference between them is `R-021`'s point.
            _, storage_k = comp_pcc(golden_k, quantize_like_device(golden_k, CACHE_DTYPE), 0.0)
            _, storage_v = comp_pcc(golden_v, quantize_like_device(golden_v, CACHE_DTYPE), 0.0)
            _, complete_k = comp_pcc(golden_k, k_floor_l0, 0.0)
            _, complete_v = comp_pcc(golden_v, v_floor_l0, 0.0)
            l0 = {
                "storage_floor_k": float(storage_k),
                "storage_floor_v": float(storage_v),
                "complete_floor_k": float(complete_k),
                "complete_floor_v": float(complete_v),
            }

        logger.info(
            f"[G-CHUNK] L{layer_idx:>2}: mutual K={float(mutual_k):.7f} V={float(mutual_v):.7f} | "
            f"vs golden one-shot K={curve['one_shot_k'][layer_idx]:.7f} V={curve['one_shot_v'][layer_idx]:.7f} "
            f"chunked K={curve['chunked_k'][layer_idx]:.7f} V={curve['chunked_v'][layer_idx]:.7f}"
        )
        for cache in (cache_one_shot, cache_chunked):
            cache.k.deallocate(True)
            cache.v.deallocate(True)

    # --- deltas 1+2: chunked must equal one-shot, per layer -----------------------------------
    worst_mutual_k = min(curve["mutual_k"].values())
    worst_mutual_v = min(curve["mutual_v"].values())
    exact_layers = sum(
        1
        for layer_idx in range(n_layers)
        if curve["mutual_k"][layer_idx] >= 1.0 and curve["mutual_v"][layer_idx] >= 1.0
    )
    logger.info(
        f"[G-CHUNK] chunked vs one-shot over {n_layers} layers, {n_chunks} chunks of {CHUNK_SIZE}: "
        f"worst K={worst_mutual_k:.7f} V={worst_mutual_v:.7f}; layers scoring exactly 1.0 on both: "
        f"{exact_layers}/{n_layers} (threshold {MUTUAL_PCC_THRESHOLD}; given identical hidden states "
        f"these two producers should be exact)"
    )

    # --- L0: the ratio to the floor, against both floor definitions ---------------------------
    ratios = {}
    for name, floor_key in (
        ("one_shot_k", "k"),
        ("chunked_k", "k"),
        ("one_shot_v", "v"),
        ("chunked_v", "v"),
    ):
        measured = curve[name][0]
        ratios[name] = {
            "measured": measured,
            "storage": err_ratio(measured, l0[f"storage_floor_{floor_key}"]),
            "complete": err_ratio(measured, l0[f"complete_floor_{floor_key}"]),
        }
        logger.info(
            f"[G-CHUNK] L0 {name}: PCC={measured:.7f}  storage floor={l0[f'storage_floor_{floor_key}']:.7f} "
            f"-> {ratios[name]['storage']:.2f}x  |  complete floor={l0[f'complete_floor_{floor_key}']:.7f} "
            f"-> {ratios[name]['complete']:.2f}x  (budget {MAX_L0_ERR_RATIO}x)"
        )

    # --- the per-layer error step -------------------------------------------------------------
    steps = {}
    for name in ("chunked_k", "chunked_v"):
        steps[name] = {}
        for layer_idx in range(1, n_layers):
            prev_err = 1.0 - curve[name][layer_idx - 1]
            steps[name][layer_idx] = float("inf") if prev_err <= 0 else (1.0 - curve[name][layer_idx]) / prev_err
    gated = {
        name: {k: v for k, v in steps[name].items() if k >= FIRST_GATED_STEP_LAYER}
        for name in ("chunked_k", "chunked_v")
    }
    for name in ("chunked_k", "chunked_v"):
        worst = max(gated[name], key=gated[name].get)
        logger.info(
            f"[G-CHUNK] {name}: worst gated per-layer step L{worst} = {gated[name][worst]:.2f}x "
            f"(budget {MAX_LAYER_STEP}x); min PCC over all layers = {min(curve[name].values()):.7f}"
        )

    os.makedirs(_RAW_DIR, exist_ok=True)
    curve_path = os.path.join(_RAW_DIR, "G-CHUNK_per_layer_pcc.json")
    with open(curve_path, "w") as f:
        json.dump(
            {
                "trace_dir": _TRACE_DIR,
                "seq_len": seq_len,
                "chunk_size": CHUNK_SIZE,
                "n_chunks": n_chunks,
                "n_layers": n_layers,
                "cache_dtype": "bfloat8_b",
                "weight_dtype": "bfloat8_b",
                "activation_dtype": "bfloat16",
                "golden": "fp32 HF LlamaDecoderLayer, streamed; bit-identical to LlamaModel's own loop (G-GOLDEN)",
                "layer0_floors": l0,
                "layer0_ratios": ratios,
                "per_layer": {name: {str(k): v for k, v in sorted(vals.items())} for name, vals in curve.items()},
                "per_layer_step": {name: {str(k): v for k, v in sorted(vals.items())} for name, vals in steps.items()},
            },
            f,
            indent=2,
        )
    logger.info(f"[G-CHUNK] per-layer curve written to {curve_path}")

    # --- assertions ---------------------------------------------------------------------------
    for layer_idx in range(n_layers):
        assert curve["mutual_k"][layer_idx] >= MUTUAL_PCC_THRESHOLD, (
            f"L{layer_idx}: chunked K vs one-shot K is {curve['mutual_k'][layer_idx]:.7f}, below "
            f"{MUTUAL_PCC_THRESHOLD}. Fed identical hidden states these differ only in the indexed "
            f"RoPE offset (delta 1) and the cache write offset (delta 2)."
        )
        assert curve["mutual_v"][layer_idx] >= MUTUAL_PCC_THRESHOLD, (
            f"L{layer_idx}: chunked V vs one-shot V is {curve['mutual_v'][layer_idx]:.7f}, below "
            f"{MUTUAL_PCC_THRESHOLD}. V is never rotated, so only the write offset can move it."
        )
    for name in ("one_shot_k", "chunked_k"):
        worst = min(curve[name].values())
        assert worst >= GOLDEN_K_THRESHOLD, f"{name} vs golden: worst layer PCC {worst:.7f} < {GOLDEN_K_THRESHOLD}"
    for name in ("one_shot_v", "chunked_v"):
        worst = min(curve[name].values())
        assert worst >= GOLDEN_V_THRESHOLD, f"{name} vs golden: worst layer PCC {worst:.7f} < {GOLDEN_V_THRESHOLD}"
    for name, ratio in ratios.items():
        assert ratio["complete"] <= MAX_L0_ERR_RATIO, (
            f"L0 {name} is {ratio['complete']:.2f}x its COMPLETE floor (budget {MAX_L0_ERR_RATIO}x). "
            f"The floor already carries the bf16 input, the bf16 norm gain, the bf8_b projection "
            f"weight, the bf16 RoPE tables and the bf8_b store, so the remainder is this package's."
        )
    for name in ("chunked_k", "chunked_v"):
        for layer_idx, step in gated[name].items():
            assert step <= MAX_LAYER_STEP, (
                f"{name}: the per-layer error step at L{layer_idx} is {step:.2f}x (budget "
                f"{MAX_LAYER_STEP}x) — a step is one layer's logic error, not depth accumulation"
            )


# =============================================================================================
# The negative controls, one per delta.
# =============================================================================================
@requires_hf_reference
@requires_golden_trace
@torch.no_grad()
@pytest.mark.parametrize("mesh_device", [(1, 1)], indirect=True)
@pytest.mark.parametrize(
    "control", ["freeze_rope_offset", "freeze_write_offset"], ids=["delta1_rope_at_0", "delta2_write_at_0"]
)
def test_chunked_kv_offset_negative_controls(mesh_device, control, reset_seeds):
    """Break one offset at a time; the mutual PCC must collapse.

    * `freeze_rope_offset` — delta 1: every chunk is roped as if it started at position 0. **K only**
      can move, because V is never rotated; the recipe's quoted control pair (0.706 / 0.655,
      `BRINGUP_RECIPE.md:1674-1675`) is not reproducible in a decomposition that feeds both
      producers the same hidden states, and the gate block says so.
    * `freeze_write_offset` — delta 2: every chunk is written at `kv_actual = 0`, so chunk 3
      overwrites chunk 0's rows. **Both** K and V must collapse.

    Two layers only: the control is about the offsets, not about depth, and it must be able to fail
    for a reason the gate above would not already have caught.
    """
    hf = llama_config_dims()
    metadata = _golden_metadata()
    seq_len = int(metadata["n_tokens"])
    head_dim, nkv = derive_head_dim(hf), hf["num_key_value_heads"]
    tokens = torch.tensor(metadata["token_ids"], dtype=torch.long).reshape(1, seq_len)
    n_layers = 2

    state_dict = _load_checkpoint(n_layers)
    model = _build_model(mesh_device, hf, state_dict, n_layers, seq_len)
    layer_inputs = _capture_layer_inputs(model, tokens)

    rope_contiguous = build_prefill_rope(mesh_device, hf, seq_len)
    rope_indexed = build_indexed_rope(mesh_device, hf, max_seq_len=seq_len, chunk_size=CHUNK_SIZE, sp_axis=0)
    trans_mat = model.transformation_mats["prefill"]

    layer, hidden = model.layers[0], layer_inputs[0]
    cache_one_shot = _fresh_cache(mesh_device, nkv, seq_len, head_dim)
    _produce_one_shot(
        mesh_device,
        layer,
        hidden,
        cache_one_shot,
        hf=hf,
        head_dim=head_dim,
        rope_contiguous=rope_contiguous,
        trans_mat=trans_mat,
    )
    cache_broken = _fresh_cache(mesh_device, nkv, seq_len, head_dim)
    _produce_chunked(
        mesh_device,
        layer,
        hidden,
        cache_broken,
        hf=hf,
        head_dim=head_dim,
        rope_indexed=rope_indexed,
        trans_mat=trans_mat,
        chunk_size=CHUNK_SIZE,
        **{control: True},
    )
    ttnn.synchronize_device(mesh_device)

    one_shot_k, one_shot_v = _readback(cache_one_shot, nkv, seq_len)
    broken_k, broken_v = _readback(cache_broken, nkv, seq_len)
    _, pcc_k = comp_pcc(one_shot_k, broken_k, 0.0)
    _, pcc_v = comp_pcc(one_shot_v, broken_v, 0.0)
    logger.info(
        f"[G-CHUNK] control {control}: mutual K={float(pcc_k):.5f} V={float(pcc_v):.5f} "
        f"(the correct run scores 1.0 on both; threshold {MUTUAL_PCC_THRESHOLD})"
    )

    assert float(pcc_k) < MUTUAL_PCC_THRESHOLD, (
        f"breaking {control} left the mutual K PCC at {float(pcc_k):.7f} — the gate is not measuring " f"that offset"
    )
    if control == "freeze_write_offset":
        assert float(pcc_v) < MUTUAL_PCC_THRESHOLD, (
            f"breaking the write offset left the mutual V PCC at {float(pcc_v):.7f}; every chunk "
            f"wrote at kv_actual=0, so chunk 3 must have overwritten chunk 0"
        )
    else:
        # Recorded, not asserted away: V is never rotated, so this control cannot move it. That is
        # an invariant, and it is why delta 2 needs its own control.
        assert (
            float(pcc_v) >= MUTUAL_PCC_THRESHOLD
        ), f"freezing the RoPE offset changed V (PCC {float(pcc_v):.7f}) — V must never be rotated"

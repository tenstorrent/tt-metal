def _is_plain_input(value):
    """True for values a module forward takes as data rather than as live state.

    Used to tell captured tensors/flags apart from objects like a KV cache WITHOUT naming any of
    them. A name list only ever covers the models whoever wrote it had in mind; asking the value
    what it is keeps working when a model ships a cache class nobody here has heard of.
    """
    import torch as _torch

    if value is None or isinstance(value, (bool, int, float, str, _torch.Tensor)):
        return True
    if isinstance(value, (list, tuple)):
        return all(_is_plain_input(_v) for _v in value)
    return False


def _captured_sample_dirs(component_name):
    """Every captured input set for a component: the primary first, then any extra samples.

    The primary stays exactly where it always was, so everything that reads `args.pt` next to
    `manifest.json` is untouched; extra samples live under `samples/<n>/`.
    """
    comp_dir = _component_dir(component_name)
    if not comp_dir.is_dir():
        return []
    dirs = [comp_dir]
    extra_root = comp_dir / _SAMPLES_SUBDIR
    if extra_root.is_dir():
        dirs.extend(sorted((d for d in extra_root.iterdir() if d.is_dir()), key=lambda d: d.name))
    return dirs


def _load_sample(sample_dir):
    """`(args, kwargs, output)` from one captured sample directory, or None if it is incomplete.

    The one reader of a captured set: the primary and every extra come through here, so a set that
    loads for one cannot fail to load for the other.
    """
    import torch as _torch

    paths = [sample_dir / n for n in _ARTIFACT_FILES]
    if not all(p.is_file() for p in paths):
        return None
    try:
        return tuple(_torch.load(p, map_location="cpu", weights_only=False) for p in paths)
    except Exception as _e:
        print(f"[bringup] captured sample load failed for {sample_dir}: {_e}", flush=True)
        return None


def _captured_kwargs_and_primary(torch_module, cap_args, cap_kwargs):
    """Turn one captured `(args, kwargs)` pair into `(kwargs, primary)` for a module call.

    Shared by the first sample and every extra one. When this lived inline in the short-circuit,
    extra samples would have needed their own copy of the dtype cast, the positional-to-name
    mapping and the primary pick -- three chances for the samples to be prepared differently from
    the one the test actually gates on.
    """
    import torch as _torch

    cap_kwargs = dict(cap_kwargs or {})
    # Cast captured floats to the live module's parameter dtype. Capture usually runs in float32
    # while the test's model often loads in bfloat16; without this the attention forward raises on
    # mismatched dtypes and the test skips despite the inputs being fine.
    target_dtype = None
    try:
        for p in torch_module.parameters():
            if p.is_floating_point():
                target_dtype = p.dtype
                break
    except Exception:
        target_dtype = None

    def _cast(x):
        if target_dtype is None or x is None:
            return x
        if isinstance(x, _torch.Tensor) and x.is_floating_point() and x.dtype != target_dtype:
            return x.to(target_dtype)
        if isinstance(x, (list, tuple)):
            seq = [_cast(v) for v in x]
            return tuple(seq) if isinstance(x, tuple) else type(x)(seq)
        # Cache-like objects hold their tensors in attributes, so casting only the top level left
        # those at the capture dtype -- the mismatch that made dropping the cache look necessary.
        held = getattr(x, "__dict__", None)
        if isinstance(held, dict) and held:
            for attr, val in list(held.items()):
                new = _cast(val)
                if new is not val:
                    try:
                        setattr(x, attr, new)
                    except Exception:
                        pass
        return x

    cap_args = tuple(_cast(v) for v in cap_args) if cap_args else cap_args
    kwargs = {k: _cast(v) for k, v in cap_kwargs.items()}
    if cap_args:
        import inspect as _inspect

        names = [
            p.name
            for p in _inspect.signature(torch_module.forward).parameters.values()
            if p.name != "self" and p.kind not in (p.VAR_POSITIONAL, p.VAR_KEYWORD)
        ]
        for i, v in enumerate(cap_args):
            if i >= len(names):
                break
            if names[i] not in kwargs:
                kwargs[names[i]] = v
    primary = None
    for name, val in kwargs.items():
        if isinstance(val, _torch.Tensor):
            primary = (name, val)
            break
    if primary is None:
        primary = ("(captured)", _torch.zeros(1))
    return kwargs, primary


def _captured_extra_samples(component_name, torch_module):
    """Prepared `(name, kwargs, primary, golden)` for every captured input set after the first.

    Correctness used to be argued from a single input, which cannot distinguish a port that is
    right from one that happens to line up for one shape. Prepared through the SAME helper the
    gating sample uses, so an extra sample cannot be built differently from the one it backs up.
    """
    out = []
    for sample_dir in _captured_sample_dirs(component_name)[1:]:
        loaded = _load_sample(sample_dir)
        if loaded is None:
            continue
        cap_args, cap_kwargs, cap_out = loaded
        kwargs, primary = _captured_kwargs_and_primary(torch_module, cap_args, cap_kwargs)
        out.append((sample_dir.name, kwargs, primary, cap_out))
    return out


def _stateful_keys(kwargs):
    """Which captured kwargs are live state rather than data, asked of the values themselves."""
    return tuple(k for k, v in (kwargs or {}).items() if not _is_plain_input(v))


def _reference_forward(torch_module, sample_kwargs):
    """Run the reference forward, preferring the captured state and falling back without it.

    Returns `(output, kwargs_actually_used)`. Raises the last exception if nothing worked, so each
    caller phrases its own skip. Passing the captured state is what makes the reference reproduce
    the forward the model really ran; a module that rebuilds its state internally rejects it, and
    those components stay testable instead of skipping.

    Shared because the sharded test runs the SAME reference: if only one of them knew how to retry,
    a component needing the fallback would pass in one and skip in the other for no visible reason.
    """
    import torch as _torch

    candidates = [sample_kwargs]
    # Asked of the kwargs in hand rather than read off shared state, so every sample -- the one the
    # test gates on and each extra one -- is judged by what it actually holds.
    stateful = _stateful_keys(sample_kwargs)
    if stateful:
        candidates.append({_k: _v for _k, _v in sample_kwargs.items() if _k not in stateful})
    last_exc = None
    for cand in candidates:
        try:
            with _torch.no_grad():
                out = torch_module(**cand)
            if cand is not sample_kwargs:
                print(
                    f"[bringup] reference forward rejected captured state {list(stateful)}; " f"retried without it",
                    flush=True,
                )
            return out, cand
        except Exception as exc:
            last_exc = exc
    raise last_exc


def _check_captured_fidelity(torch_out):
    """Fail if the reference forward did not reproduce the output that capture recorded.

    `output.pt` was loaded and then dropped on the floor. It is the one thing that can say whether
    the inputs this test rebuilt drive the module the way the real forward did. If the reference
    cannot reproduce it, then whatever PCC the test prints afterwards describes a computation the
    model never performed, and a green result means nothing.

    Held to the SAME bar the component itself must meet: a reconstruction we would not accept from
    the TT port is not good enough to be the yardstick that judges it.
    """
    golden = _CAPTURED_STATE.get("golden_out")
    if golden is None or torch_out is None:
        return
    _g = globals()
    _normalize, _pcc_fn, _target = _g.get("_normalize_out"), _g.get("comp_pcc"), _g.get("PCC_TARGET")
    if _normalize is None or _pcc_fn is None or _target is None:
        return
    import torch as _torch

    try:
        golden = _normalize(golden)
    except Exception:
        return
    if not (isinstance(golden, _torch.Tensor) and isinstance(torch_out, _torch.Tensor)):
        return
    if tuple(golden.shape) != tuple(torch_out.shape):
        print(
            f"[bringup] captured golden shape {tuple(golden.shape)} != reference "
            f"{tuple(torch_out.shape)}; fidelity not checked",
            flush=True,
        )
        return
    _ok, _pcc = _pcc_fn(golden.to(_torch.float32), torch_out.to(_torch.float32), _target)
    print(f"[bringup] captured-golden fidelity pcc={_pcc}", flush=True)
    if not _ok:
        import pytest as _pytest

        _pytest.fail(
            f"the reference forward does not reproduce the captured output for "
            f"{_g.get('COMPONENT_NAME', '?')}: fidelity pcc={_pcc} below {_target}. The inputs "
            f"this test rebuilt do not drive the module the way the captured forward did, so any "
            f"PCC measured against this reference would not describe the real computation."
        )


def _build_torch_reference():
    # AutoModelForCausalLM-first fallback: HF causal-LM models
    # (Llama / Qwen / Mistral / DeepSeek / Phi / Gemma / ...) follow
    # the `XxxForCausalLM(model: XxxModel)` structure. `AutoModel.from_pretrained`
    # returns the INNER `XxxModel` (no LM head); captured submodule paths
    # typically reference the OUTER `XxxForCausalLM` (e.g. `model.layers.0`).
    # The path mismatch causes `_resolve` to land on a bare `nn.Module`
    # whose `_forward_unimplemented` raises TypeError on every kwarg.
    # Mirror the multi-class fallback pattern already established in
    # `agentic/probe.py:159`, `output_validation.py:830-965`, and
    # `activation_diff.py:1163-1171` so the PCC test harness resolves
    # the same class the capture step used.
    model = None
    _last_err = None
    for _cls_name in ("AutoModelForCausalLM", "AutoModel"):
        try:
            _cls = getattr(transformers, _cls_name)
        except AttributeError:
            continue
        try:
            model = _cls.from_pretrained(
                HF_MODEL_ID, trust_remote_code=True, torch_dtype="bfloat16", low_cpu_mem_usage=True
            )
            break
        except Exception as _e:
            _last_err = _e
            continue
    if model is None:
        try:
            import importlib.util as _ilu
            import os as _os

            _rl = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "_reference_loader.py")
            if _os.path.isfile(_rl):
                _spec = _ilu.spec_from_file_location("_reference_loader", _rl)
                _rlmod = _ilu.module_from_spec(_spec)
                _spec.loader.exec_module(_rlmod)
                model = _rlmod.load_reference_model(HF_MODEL_ID)
        except Exception as _rle:
            _last_err = _rle
    if model is None:
        raise RuntimeError(
            f"Could not load {HF_MODEL_ID} via AutoModelForCausalLM or "
            f"AutoModel; last error: {type(_last_err).__name__}: {_last_err}"
        )
    model.eval()
    torch_module = None
    resolved_path = None
    # BUG-2 FIX: if capture-inputs recorded a submodule_path in the manifest,
    # try THAT path FIRST. Capture and test must resolve to the same submodule
    # or captured args won't fit the test-resolved torch_module's signature.
    _captured_path = _captured_submodule_path(COMPONENT_NAME)
    if _captured_path:
        try:
            torch_module = _resolve(model, _captured_path)
            resolved_path = _captured_path
            print(f"[bringup] resolved torch submodule via captured manifest path `{_captured_path}`")
        except (AttributeError, IndexError, KeyError, TypeError):
            torch_module = None
            resolved_path = None
    if torch_module is None:
        for path in _CANDIDATE_SUBMODULE_PATHS:
            try:
                torch_module = _resolve(model, path)
                resolved_path = path
                break
            except (AttributeError, IndexError, KeyError, TypeError):
                continue
    if torch_module is None:
        pytest.skip(
            "none of the canonical submodule paths resolved for "
            f"`nemotron_h_m_l_p` of {HF_MODEL_ID}; edit `_CANDIDATE_SUBMODULE_PATHS`."
        )
    if not (_captured_path and resolved_path == _captured_path):
        print(f"[bringup] resolved torch submodule via `{resolved_path}`")

    sig = inspect.signature(torch_module.forward)
    kwargs = {}
    primary = None
    for name, param in sig.parameters.items():
        if name == "self":
            continue
        if param.kind in (param.VAR_POSITIONAL, param.VAR_KEYWORD):
            continue
        is_required = param.default is inspect.Parameter.empty
        is_well_known = name in _WELL_KNOWN_INPUTS
        if not is_required and not is_well_known:
            continue
        value = _make_arg_for(name, model=model, torch_module=torch_module)
        if isinstance(value, _Omit):
            continue
        kwargs[name] = value
        if primary is None and isinstance(value, torch.Tensor):
            primary = (name, value)
    if primary is None:
        primary = ("(synthetic)", torch.randn(1, 64, 64))
    return torch_module, kwargs, primary


def _build_ttnn_port(device, torch_module):
    mod = importlib.import_module(STUB_IMPORT_PATH)
    if hasattr(mod, "build"):
        return mod.build(device, torch_module)
    return getattr(mod, COMPONENT_SAFE)


def _normalize_out(out):
    if isinstance(out, tuple) and out:
        out = out[0]
    if hasattr(out, "last_hidden_state"):
        out = out.last_hidden_state
    if isinstance(out, (list, tuple)) and out:
        out = out[0]
    return out


def _ttnn_module_call(ttnn_module, primary_tensor, kwargs, primary_name, device):
    """Run the TT module on one prepared input set; float32 torch tensor back, or None.

    Chains the same primitives the gating comparison uses, so an extra sample cannot be fed to the
    port differently from the one it is meant to back up. The gating path drives those primitives
    under separate stage timeouts instead of calling this, so that a hang can still be pinned to
    the exact step that stalled.
    """
    ttnn_input = _ttnn_from_torch_mesh_safe(primary_tensor, device)
    extra = {k: v for k, v in kwargs.items() if k != primary_name}
    out = ttnn_module(ttnn_input, **extra)
    if isinstance(out, tuple) and out:
        out = out[0]
    if out is None:
        return None
    return _ttnn_to_torch_mesh_safe(out, device).to(torch.float32)


class _StageTimeout(Exception):
    pass


def _stage_timeout_handler(signum, frame):
    raise _StageTimeout(
        "stage exceeded TT_PLANNER_TEST_STAGE_S budget; the previous step "
        "(see last [bringup] stage=... print) did not return in time"
    )


def _set_stage_timeout(seconds: int):
    if seconds <= 0:
        return
    try:
        import signal as _signal

        _signal.signal(_signal.SIGALRM, _stage_timeout_handler)
        _signal.alarm(seconds)
    except (ValueError, AttributeError, ImportError):
        pass


def _clear_stage_timeout():
    try:
        import signal as _signal

        _signal.alarm(0)
    except (ValueError, AttributeError, ImportError):
        pass


def _is_mesh_device(device):
    """Mesh-agnostic helper: True iff `device` is a multi-device mesh."""
    try:
        if isinstance(device, ttnn.MeshDevice):
            return True
    except AttributeError:
        pass
    return hasattr(device, "get_device_ids") or hasattr(device, "get_devices")


def _ttnn_from_torch_mesh_safe(tensor, device, *, dtype=ttnn.bfloat16, layout=ttnn.TILE_LAYOUT):
    """`ttnn.from_torch` that works on both single-device and mesh devices.

    On a mesh, the tensor is replicated to every device so per-device compute
    produces identical shards (readable from device 0)."""
    t = tensor.to(torch.bfloat16) if dtype == ttnn.bfloat16 else tensor
    if _is_mesh_device(device):
        try:
            return ttnn.from_torch(
                t,
                dtype=dtype,
                layout=layout,
                device=device,
                mesh_mapper=ttnn.ReplicateTensorToMesh(device),
            )
        except (AttributeError, TypeError):
            pass
    return ttnn.from_torch(t, dtype=dtype, layout=layout, device=device)


def _ttnn_to_torch_mesh_safe(ttnn_tensor, device):
    """`ttnn.to_torch` that works on both single-device and mesh devices.

    Uses the same `mesh_composer=ConcatMeshToTensor(...)` pattern that the
    existing tt-metal demos use, which is the only known-stable way to read
    back from a MeshDevice (bare `to_torch` and `get_device_tensors[0]` can
    busy-loop in the C extension with the GIL held).

    A device synchronize is issued first so any pending kernels finish
    before the readback (otherwise the readback can deadlock on a kernel
    that never completes)."""
    # CPU-fallback `__call__` paths legitimately return `torch.Tensor`
    # (e.g. when a stub was rolled back to `.bak` after the auto-iterate
    # cap-out, or when a `_apply_*` helper invoked the torch reference
    # because the ttnn path raised). Without this guard,
    # `ttnn.to_torch(...)` would try `tensor.to_torch(mesh_composer=...)`
    # on a torch.Tensor and raise:
    #   AttributeError: 'Tensor' object has no attribute 'to_torch'
    # — turning a clean numerical comparison into an opaque crash.
    # Observed in the 2026-05-22 sam2-hiera-small final pytest after
    # decoder_head was restored from `.bak`.
    if isinstance(ttnn_tensor, torch.Tensor):
        return ttnn_tensor
    try:
        if hasattr(ttnn, "synchronize_device"):
            ttnn.synchronize_device(device)
        elif hasattr(device, "synchronize"):
            device.synchronize()
    except Exception:
        pass

    if _is_mesh_device(device):
        for mk_composer in (
            lambda: ttnn.concat_mesh_to_tensor_composer(device, 0),
            lambda: ttnn.ConcatMeshToTensor(device, dim=0),
        ):
            try:
                composer = mk_composer()
            except (AttributeError, TypeError):
                continue
            try:
                t = ttnn.to_torch(ttnn_tensor, mesh_composer=composer)
                if t is None:
                    continue
                if t.ndim >= 1 and t.shape[0] > 1:
                    n_devices = 1
                    try:
                        ids = device.get_device_ids() if hasattr(device, "get_device_ids") else []
                        n_devices = len(ids) or 1
                    except Exception:
                        pass
                    if n_devices > 1 and t.shape[0] % n_devices == 0:
                        t = t[: t.shape[0] // n_devices]
                return t
            except Exception:
                continue
    return ttnn.to_torch(ttnn_tensor)


# `l1_small_size` is the per-chip allocation reserved for L1_SMALL buffers,
# which `ttnn.conv2d` (specifically the sliding-window/halo helper) and
# `ttnn.max_pool2d` use for scratch. With the historical default of `{}`
# (i.e. l1_small_size=0), the FIRST conv2d in any vision/CNN model raises
# `TT_FATAL: bank size is 0 B` and falls back to a slow torch-on-host
# implementation. That fallback is correct but turns a 30s on-device PCC
# test into a 5-15min one, blows past the auto-iterate wall-clock budget,
# and pollutes the compute split with runtime CPU fallbacks that the LLM
# would otherwise correctly mark MIXED. 24576 (24 KiB) matches the
# established convention used by every existing vision demo in this repo
# (see e.g. `models/demos/vision/segmentation/sam2_hiera_small/demo/
# demo_for_image_classification.py:98`). It is harmless on models that
# don't use conv2d/max_pool2d — those L1_SMALL banks just stay empty.
@pytest.mark.parametrize("device_params", [{"l1_small_size": 24576}], indirect=True)
def test_nemotron_h_m_l_p(device_params, device):
    stage_budget_s = int(os.environ.get("TT_PLANNER_TEST_STAGE_S", "120"))

    try:
        _seed = int(os.environ.get("TT_PLANNER_TEST_SEED", "0"))
    except ValueError:
        _seed = 0
    torch.manual_seed(_seed)

    _module_level = os.environ.get("TT_PLANNER_GOLDEN_CACHE", "1") not in ("", "0", "false", "False")
    _golden_cache_file = None
    _golden_hit = None
    if _module_level:
        try:
            from models.common.golden_cache import golden_cache_path, load_golden_cache

            _golden_cache_file = golden_cache_path(__file__, COMPONENT_NAME, _seed)
            _golden_hit = load_golden_cache(_golden_cache_file)
        except Exception:
            _golden_hit = None
    if _golden_hit is not None:
        torch_module, sample_kwargs, primary, torch_out = _golden_hit
        print("[bringup] stage=golden_cache_hit (skipped full-model load)", flush=True)
    else:
        print("[bringup] stage=build_torch_reference", flush=True)
        _set_stage_timeout(stage_budget_s)
        try:
            torch_module, sample_kwargs, primary = _build_torch_reference()
        finally:
            _clear_stage_timeout()

        try:
            torch_module = torch_module.float()
        except Exception:
            pass
        for _k in list(sample_kwargs.keys()):
            _v = sample_kwargs[_k]
            if isinstance(_v, torch.Tensor) and _v.is_floating_point():
                sample_kwargs[_k] = _v.to(torch.float32)
        _pn, _pt = primary
        if isinstance(_pt, torch.Tensor) and _pt.is_floating_point():
            primary = (_pn, _pt.to(torch.float32))

        print("[bringup] stage=torch_forward", flush=True)
        _set_stage_timeout(stage_budget_s)
        try:
            try:
                torch_out, sample_kwargs = _reference_forward(torch_module, sample_kwargs)
            except Exception as exc:
                pytest.skip(
                    f"HF reference forward({list(sample_kwargs.keys())}) raised "
                    f"{type(exc).__name__} for {COMPONENT_NAME}: {exc} -- "
                    f"the synthetic inputs from _make_arg_for() are incompatible "
                    f"with this submodule's expected shapes. Either edit the test "
                    f"to provide model-specific kwargs, or skip this Phase-2 PCC "
                    f"and validate via the top-level demo instead."
                )
        finally:
            _clear_stage_timeout()
        torch_out = _normalize_out(torch_out)
        _check_captured_fidelity(torch_out)
        if _module_level and _golden_cache_file:
            try:
                from models.common.golden_cache import save_golden_cache

                save_golden_cache(_golden_cache_file, torch_module, sample_kwargs, primary, torch_out)
            except Exception:
                pass

    print("[bringup] stage=ttnn_build", flush=True)
    _set_stage_timeout(stage_budget_s)
    try:
        ttnn_module = _build_ttnn_port(device, torch_module)
    finally:
        _clear_stage_timeout()

    primary_name, primary_tensor = primary

    print(f"[bringup] stage=ttnn_input (mesh={_is_mesh_device(device)})", flush=True)
    _set_stage_timeout(stage_budget_s)
    try:
        ttnn_input = _ttnn_from_torch_mesh_safe(primary_tensor, device)
    finally:
        _clear_stage_timeout()

    print("[bringup] stage=ttnn_forward", flush=True)
    _set_stage_timeout(stage_budget_s)
    try:
        ttnn_extra_kwargs = {k: v for k, v in sample_kwargs.items() if k != primary_name}
        import pathlib as _pathlib

        from models.common.native_probe import run_native_probe as _run_native_probe

        _stub_for_probe = _pathlib.Path(__file__).resolve().parents[2] / "_stubs" / (COMPONENT_NAME + ".py")
        ttnn_out, _np = _run_native_probe(_stub_for_probe, lambda: ttnn_module(ttnn_input, **ttnn_extra_kwargs))
        print(
            f"[bringup] native_probe ttnn_dispatch={_np['ttnn_dispatch']} torch_ops={_np['torch_ops']}",
            flush=True,
        )
    finally:
        _clear_stage_timeout()
    if isinstance(ttnn_out, tuple) and ttnn_out:
        ttnn_out = ttnn_out[0]

    print("[bringup] stage=ttnn_to_torch", flush=True)
    _set_stage_timeout(stage_budget_s)
    try:
        ttnn_out_torch = _ttnn_to_torch_mesh_safe(ttnn_out, device).to(torch.float32)
    finally:
        _clear_stage_timeout()

    if isinstance(torch_out, torch.Tensor):
        torch_out = torch_out.to(torch.float32)

    ok, pcc = comp_pcc(torch_out, ttnn_out_torch, PCC_TARGET)
    print(f"[bringup] achieved PCC={pcc} target={PCC_TARGET} component={COMPONENT_NAME}", flush=True)
    assert ok, (
        f"PCC {pcc} below target {PCC_TARGET} for {COMPONENT_NAME} of " f"{HF_MODEL_ID} (primary arg `{primary_name}`)"
    )

    # One input proves the port lines up for ONE input. A component can be right for the shape it
    # was captured at and wrong for the next; every additional captured set is held to the same
    # target so passing means the port generalises, not that it matched once.
    _failures = []
    for _name, _kw, _prim, _golden in _captured_extra_samples(COMPONENT_NAME, torch_module):
        _set_stage_timeout(stage_budget_s)
        try:
            _ref, _kw = _reference_forward(torch_module, _kw)
        except Exception as exc:
            print(f"[bringup] sample {_name}: reference forward raised {exc}; not counted", flush=True)
            continue
        finally:
            _clear_stage_timeout()
        _ref = _normalize_out(_ref)
        _pname, _ptensor = _prim
        _tt = _ttnn_module_call(ttnn_module, _ptensor, _kw, _pname, device)
        if _tt is None:
            print(f"[bringup] sample {_name}: TT call did not return a tensor; not counted", flush=True)
            continue
        _sok, _spcc = comp_pcc(_ref.to(torch.float32), _tt, PCC_TARGET)
        print(f"[bringup] sample {_name} PCC={_spcc} target={PCC_TARGET}", flush=True)
        if not _sok:
            _failures.append(f"{_name}={_spcc}")
    assert not _failures, (
        f"{COMPONENT_NAME} met PCC {pcc} on the captured sample it was gated on but failed "
        f"other captured inputs ({', '.join(_failures)}), so the port matches one input rather "
        f"than the component -- target {PCC_TARGET}"
    )

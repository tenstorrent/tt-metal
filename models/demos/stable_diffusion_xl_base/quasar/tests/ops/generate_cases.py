"""Generate the per-op unit tests (``test_<op>.py``) and ``docs/OPS.md`` from a model trace.

The trace is produced by running ``TtUNet2DConditionModel.forward`` (1024x1024, Wormhole
``ModelOptimisations1024x1024``) and ``TtEulerDiscreteScheduler`` under a shape-propagating
fake ``ttnn`` (``trace_sdxl.py``, kept in ``docs/``), which records every device op call with
its tensor specs and configs. ``generate_cases.py`` dedups the calls into unique cases per op.

    python models/demos/stable_diffusion_xl_base/quasar/tests/ops/generate_cases.py \
        models/demos/stable_diffusion_xl_base/quasar/docs/trace_1024.json.gz
"""

import collections
import gzip
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(HERE, "..", "..", "docs")

HOST_ONLY = {"allocate_tensor_on_device", "copy_host_to_device_tensor"}
TEST_PREP_ONLY = {"permute"}  # only the WH tests used it (NCHW -> NHWC), the Quasar tests do it in torch

# ops already bound under ttnn.experimental.quasar (python-side check at generation time, see main())
HEADER = '''# SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.

# SPDX-License-Identifier: Apache-2.0

"""Per-op unit test for ``{op}`` as the 1024x1024 SDXL base UNet (Quasar port) calls it.

GENERATED by generate_cases.py from a trace of TtUNet2DConditionModel / TtEulerDiscreteScheduler;
do not edit by hand. {ncases} unique case(s) covering {ncalls} call(s) in one UNet forward.

Each case lists the input tensors (shape, dtype, layout, memory config incl. shard spec), the
op kwargs / program configs, the expected output spec, how many times the model issues exactly
this call and which modules do. See op_case.py for how a case is executed and compared.

Run on craq-sim (see quasar/README.md for the environment):
  pytest {relpath} -k <case id>
"""

import pytest

from models.demos.stable_diffusion_xl_base.quasar.tests.ops.op_case import run_case

CASES = {cases}


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_{op}(device, case):
    run_case(device, case)
'''


def canon_params(op, p):
    """Drop trace-only keys and normalise what the test needs."""
    p = {k: v for k, v in p.items() if k not in ("note",)}
    if op == "slice":
        # "(slice(None, None, None), slice(160, None, None))" -> explicit start / end
        idx = p.pop("index")
        parts = idx.strip("()").split("), ")
        p["slice_index_repr"] = idx
    return p


def slice_bounds(rec):
    import re

    shape = rec["inputs"]["input"]["shape"]
    idx = rec["params"]["index"]
    sl = re.findall(r"slice\(([^,]+), ([^,]+), ([^)]+)\)", idx)
    start, end = [], []
    for d, (a, b, _) in enumerate(sl):
        start.append(0 if a == "None" else int(a))
        end.append(shape[d] if b == "None" else int(b))
    for d in range(len(sl), len(shape)):
        start.append(0)
        end.append(shape[d])
    return start, end


def short_mem(m):
    if m is None:
        return "host"
    if m["shard"] is None:
        return f'{m["buffer"]} interleaved'
    g = m["shard"]["grid"]
    gs = ",".join(f"({a},{b})-({c},{d})" for a, b, c, d in g)
    return f'{m["buffer"]} {m["layout"].lower().replace("_", " ")} grid {gs} shard {m["shard"]["shape"]}'


def short_spec(t):
    return f'{t["shape"]} {t["dtype"].lower()} {t["layout"].lower()} {short_mem(t["mem"])}'


def signature(rec):
    p = canon_params(rec["op"], rec["params"])
    return json.dumps(
        {"op": rec["op"], "inputs": rec["inputs"], "params": p, "outputs": rec["outputs"]}, sort_keys=True
    )


def module_name(m):
    return m.split("<")[0]


def _lit(v):
    return json.dumps(v).replace("true", "True").replace("false", "False").replace("null", "None")


def pyliteral(cases):
    """Compact literal: one case per block, one key per line, values on one line (black is told to leave it)."""
    out = ["[  # fmt: off"]
    for c in cases:
        out.append("    {")
        for k, v in c.items():
            if k == "inputs":
                out.append('        "inputs": {')
                for name, spec in v.items():
                    out.append(f"            {_lit(name)}: {_lit(spec)},")
                out.append("        },")
            else:
                out.append(f"        {_lit(k)}: {_lit(v)},")
        out.append("    },")
    out.append("]  # fmt: on")
    return "\n".join(out)


def summarize_params(op, p):
    keep = {}
    for k, v in p.items():
        if k in ("memory_config", "compute_kernel_config", "compute_config", "slice_config", "note", "dtype"):
            continue
        if k == "program_config" and isinstance(v, dict):
            t = v["type"].replace("MatmulMultiCoreReuseMultiCast", "MM-").replace("ProgramConfig", "")
            fields = {
                kk: vv
                for kk, vv in v.items()
                if kk
                in (
                    "compute_with_storage_grid_size",
                    "in0_block_w",
                    "per_core_M",
                    "per_core_N",
                    "out_subblock_h",
                    "out_subblock_w",
                    "fused_activation",
                    "mcast_in0",
                    "fuse_batch",
                    "q_chunk_size",
                    "k_chunk_size",
                    "block_h",
                    "block_w",
                    "subblock_w",
                    "inplace",
                )
            }
            fields = {
                kk: (
                    vv.get("CoreCoord") or vv.get("xy") or vv.get("CoreGrid")
                    if isinstance(vv, dict) and ("CoreCoord" in vv or "xy" in vv or "CoreGrid" in vv)
                    else vv
                )
                for kk, vv in fields.items()
            }
            keep["program_config"] = f"{t}{json.dumps(fields)}"
            continue
        if k == "conv_config" and isinstance(v, dict):
            cg = v.get("core_grid")
            keep["conv_config"] = (
                f'{v["shard_layout"]} abh={v["act_block_h_override"]} act_db={v["enable_act_double_buffer"]} '
                f'w_db={v["enable_weights_double_buffer"]} wdtype={v["weights_dtype"]} '
                f'out_grid={cg["CoreRangeSet"] if (v.get("override_output_sharding_config") and cg) else "auto"}'
            )
            continue
        if k == "core_grid" and isinstance(v, dict):
            keep[k] = v.get("CoreGrid")
            continue
        if v is None or v == [] or v == {}:
            continue
        keep[k] = v
    cc = p.get("compute_kernel_config") or p.get("compute_config")
    if cc:
        keep[
            "compute"
        ] = f'{cc["math_fidelity"]}{" fp32acc" if cc["fp32_dest_acc_en"] else ""}{" l1acc" if cc["packer_l1_acc"] else ""}{" approx" if cc["math_approx_mode"] else ""}'
    mc = p.get("memory_config")
    if mc:
        keep["out_mem"] = short_mem(mc)
    return ", ".join(f"{k}={v}" for k, v in keep.items())


def main():
    trace_path = sys.argv[1]
    opener = gzip.open if trace_path.endswith(".gz") else open
    with opener(trace_path, "rt") as f:
        d = json.load(f)
    R = d["records"]
    try:
        import ttnn

        Q = ttnn.experimental.quasar

        def exists(op):
            if op == "scaled_dot_product_attention":
                return hasattr(Q.transformer, "scaled_dot_product_attention")
            if op == "mul_":
                return hasattr(Q, "multiply_")
            return hasattr(Q, op)

    except Exception:  # pragma: no cover

        def exists(op):
            return None

    per_op = collections.OrderedDict()
    for r in R:
        op = r["op"]
        if op in HOST_ONLY or op in TEST_PREP_ONLY or r["module"] == "test_inputs":
            continue
        per_op.setdefault(op, collections.OrderedDict())
        sig = signature(r)
        per_op[op].setdefault(sig, []).append(r)

    op_order = sorted(per_op, key=lambda o: (-len(per_op[o]), o))
    md = []
    md.append("# SDXL base UNet 1024x1024 on Quasar: op inventory\n")
    md.append(
        "Generated by `tests/ops/generate_cases.py` from a trace of `TtUNet2DConditionModel.forward` "
        "(1024x1024 latents 1x4x128x128, encoder states 1x77x2048, Wormhole `ModelOptimisations1024x1024` "
        "configs) plus `TtEulerDiscreteScheduler.scale_model_input/step`. Every row is one *distinct* call "
        "signature (shapes, dtypes, layouts, memory configs, program configs); `calls` is how many times one "
        "UNet forward issues it. Memory configs are the ones the model requests; conv2d output shard specs "
        "and matmul block-sharded output specs are derived from the configs (the op picks the real one).\n"
    )
    md.append("Grids are Wormhole 8x8; Quasar has 8x4. The per-op tests remap them by default (`SDXL_QSR_GRID=fit`).\n")
    md.append(
        "`bfloat8_b` (all matmul / conv weights, group-norm masks) is **not a Quasar data format** "
        "(`is_supported_quasar` in `tt_metal/common/tt_backend_api_types.cpp`: Float16/Float16_b/Float32/Fp8/Int/MxFp*/MxInt*). "
        "The per-op tests build those tensors as `bfloat16` (`SDXL_QSR_KEEP_BFP8=1` keeps them) and "
        "`ModelOptimisations1024x1024Quasar` defaults every weight dtype to `bfloat16`; MX formats are the eventual target.\n"
    )
    md.append("\n## Summary\n")
    md.append("| op | calls / forward | unique cases | in `ttnn.experimental.quasar` today | unit test |")
    md.append("|---|---:|---:|---|---|")
    total_cases = 0
    for op in op_order:
        cases = per_op[op]
        ncalls = sum(len(v) for v in cases.values())
        total_cases += len(cases)
        ex = exists(op)
        status = "yes (configs untested)" if ex else ("**missing**" if ex is False else "?")
        md.append(f"| `{op}` | {ncalls} | {len(cases)} | {status} | `tests/ops/test_{op}.py` |")
    md.append(
        f"\nTotal: {len(op_order)} ops, {total_cases} unique cases, {sum(sum(len(v) for v in c.values()) for c in per_op.values())} op calls per UNet forward (+ scheduler).\n"
    )
    md.append(
        "\nNot in the table: `ttnn.from_torch` / `ttnn.to_torch` / `ttnn.deallocate` (host), "
        "`ttnn.allocate_tensor_on_device` and `ttnn.copy_host_to_device_tensor` (scheduler host<->device "
        "transfers of 0-d bf16 tensors), the group-norm mask/weight host helpers, and `permute` "
        "(only the Wormhole tests used it on device for the NCHW->NHWC input prep; the Quasar tests do that in torch).\n"
    )

    for op in op_order:
        cases = per_op[op]
        md.append(f"\n## `{op}`\n")
        md.append("| id | calls | inputs | params | output | modules |")
        md.append("|---|---:|---|---|---|---|")
        case_list = []
        for i, (sig, recs) in enumerate(cases.items()):
            r0 = recs[0]
            mods = sorted({module_name(r["module"]) for r in recs})
            p = canon_params(op, r0["params"])
            if op == "slice":
                p["slice_start"], p["slice_end"] = slice_bounds(r0)
            main_in = (
                r0["inputs"].get("input")
                or r0["inputs"].get("input_a")
                or r0["inputs"].get("query")
                or next(iter(r0["inputs"].values()))
            )
            shp = "x".join(str(x) for x in main_in["shape"]) if main_in["shape"] else "scalar"
            mem = main_in["mem"]
            memtag = (
                "host"
                if mem is None
                else (mem["buffer"].lower() + ("_" + mem["layout"].split("_")[0].lower() if mem["shard"] else "_il"))
            )
            cid = f"{i:02d}_{shp}_{memtag}"
            case = {
                "id": cid,
                "op": op,
                "count": len(recs),
                "modules": mods[:6] + (["..."] if len(mods) > 6 else []),
                "site": r0["site"],
                "inputs": r0["inputs"],
                "params": p,
                "outputs": [o for o in r0["outputs"] if isinstance(o, dict)],
            }
            case_list.append(case)
            ins = "<br>".join(f"`{k}`: {short_spec(v)}" for k, v in r0["inputs"].items())
            outs = "<br>".join(short_spec(o) for o in case["outputs"])
            md.append(
                f"| `{cid}` | {len(recs)} | {ins} | {summarize_params(op, p)} | {outs} | {', '.join(mods[:4])}{' ...' if len(mods) > 4 else ''} |"
            )

        relpath = f"models/demos/stable_diffusion_xl_base/quasar/tests/ops/test_{op}.py"
        src = HEADER.format(
            op=op,
            ncases=len(case_list),
            ncalls=sum(len(v) for v in cases.values()),
            relpath=relpath,
            cases=pyliteral(case_list),
        )
        with open(os.path.join(HERE, f"test_{op}.py"), "w") as f:
            f.write(src)

    os.makedirs(DOCS, exist_ok=True)
    with open(os.path.join(DOCS, "OPS.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print(f"wrote {len(op_order)} test files and OPS.md ({total_cases} cases)")


if __name__ == "__main__":
    main()

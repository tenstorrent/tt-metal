"""Runtime for the per-op SDXL UNet unit tests in this directory.

Each ``test_<op>.py`` holds a ``CASES`` list of pure data: one entry per distinct way the
1024x1024 ``TtUNet2DConditionModel`` (Wormhole ``ModelOptimisations1024x1024`` configs) calls
that op: tensor shapes, dtypes, layouts, memory configs (incl. shard specs), program / conv /
compute configs and the op's kwargs. The lists were generated by tracing the model
(``generate_cases.py`` next to this file) and must not be hand-edited: fix the generator.

``run_case(device, case)`` rebuilds the inputs with random data, calls
``ttnn.experimental.quasar.<op>`` (via ``qsr``) and checks the result against a torch golden.

Grid handling (``SDXL_QSR_GRID`` env var):
* ``fit`` (default): the captured configs target the Wormhole 8x8 worker grid; Quasar has 8x4.
  Sharded memory configs are remapped onto the device grid (same strategy, shard shapes
  recomputed), matmul / layer-norm / SDPA program configs and the conv output-grid override are
  dropped (op auto-config), and group-norm ``core_grid`` follows the remapped input shard grid.
  This mode answers "does the op work functionally on Quasar for this shape".
* ``captured``: everything exactly as traced. Needs a device grid of at least 8x8.

Data types: Quasar has no block-float formats, so the traced ``BFLOAT8_B`` tensors (matmul /
conv weights, group-norm masks) are built as ``BFLOAT16`` unless ``SDXL_QSR_KEEP_BFP8=1``.
"""


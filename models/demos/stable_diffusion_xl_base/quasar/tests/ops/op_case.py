def call_op(op, tensors, params, specs, device):
    """Call ttnn.experimental.quasar.<op> with the case's kwargs. Returns a tuple of outputs."""
    p = params
    out_spec = specs["outputs"][0] if specs["outputs"] else None
    mem = (
        build_mem(p.get("memory_config"), out_spec["shape"], out_spec["layout"], device)
        if (p.get("memory_config") and out_spec)
        else None
    )

    if op == "conv2d":
        # SDXL_QSR_CONV_SPATIAL_DIV=n shrinks the image by n in H and W (channels, kernel, configs unchanged)
        # so a 30+ GFLOP conv becomes simulator-sized while exercising the same per-channel blocking.
        sd = spatial_div()
        if sd > 1:
            p = dict(p, input_height=p["input_height"] // sd, input_width=p["input_width"] // sd)
        out = qsr.conv2d(
            input_tensor=tensors["input"],
            weight_tensor=tensors["weight"],
            bias_tensor=tensors.get("bias"),
            in_channels=p["in_channels"],
            out_channels=p["out_channels"],
            device=device,
            kernel_size=tuple(p["kernel_size"]),
            stride=tuple(p["stride"]),
            padding=tuple(p["padding"]),
            dilation=tuple(p["dilation"]),
            batch_size=p["batch_size"],
            input_height=p["input_height"],
            input_width=p["input_width"],
            groups=p["groups"],
            conv_config=build_conv_config(p["conv_config"]),
            compute_config=build_compute_config(p["compute_config"]),
            slice_config=ttnn.Conv2dL1FullSliceConfig,
            memory_config=None,
            return_output_dim=False,
            return_weights_and_bias=False,
            dtype=DTYPE[p["dtype"]] if p.get("dtype") else None,
        )
        return (out,)
    if op in ("linear", "matmul"):
        pc = build_matmul_program_config(p.get("program_config"), specs, p, device)
        # with the program config dropped (fit mode, 1D configs) a block-sharded output needs the program-config
        # grid, so fall back to an interleaved output in the same buffer type
        if pc is None and mem is not None and mem.is_sharded():
            mem = ttnn.MemoryConfig(ttnn.TensorMemoryLayout.INTERLEAVED, mem.buffer_type)
        kw = dict(
            program_config=pc,
            memory_config=mem,
            compute_kernel_config=build_compute_config(p.get("compute_kernel_config")),
        )
        if p.get("dtype"):
            kw["dtype"] = DTYPE[p["dtype"]]
        activation = p.get("activation")
        # The captured program config may carry a fused activation (GEGLU: GELU); when the config is dropped
        # (fit mode) pass it as the op's activation so the result still matches the golden.
        if pc is None and isinstance(p.get("program_config"), dict) and p["program_config"].get("fused_activation"):
            activation = p["program_config"]["fused_activation"]["UnaryWithParam"].lower()
        if activation:
            kw["activation"] = activation
        if op == "linear":
            kw["bias"] = tensors.get("bias")
            return (qsr.linear(tensors["input"], tensors["weight"], **kw),)
        return (qsr.matmul(tensors["input"], tensors["weight"], **kw),)
    if op in ("add", "add_", "multiply", "mul_", "div"):
        b = tensors["input_b"] if "input_b" in tensors else p["scalar_b"]
        kw = {}
        if p.get("activations"):
            kw["activations"] = build_activations(p["activations"])
        if "fast_and_approximate_mode" in p:
            kw["fast_and_approximate_mode"] = p["fast_and_approximate_mode"]
        return (getattr(qsr, op)(tensors["input_a"], b, **kw),)
    if op in ("silu", "sin", "cos", "reciprocal"):
        return (getattr(qsr, op)(tensors["input"]),)
    if op == "group_norm":
        cg = p["core_grid"]["CoreGrid"]
        core_grid = (
            ttnn.CoreGrid(x=tensors["_gn_cores_x"], y=tensors["_gn_cores_y"])
            if grid_mode() == "fit"
            else ttnn.CoreGrid(x=cg[0], y=cg[1])
        )
        return (
            qsr.group_norm(
                tensors["input"],
                num_groups=p["num_groups"],
                input_mask=tensors["input_mask"],
                negative_mask=tensors.get("negative_mask"),
                weight=tensors["weight"],
                bias=tensors["bias"],
                epsilon=p["epsilon"],
                memory_config=tensors["input"].memory_config(),
                core_grid=core_grid,
                inplace=p["inplace"],
                num_out_blocks=p.get("num_out_blocks"),
            ),
        )
    if op == "layer_norm":
        pc = build_layernorm_program_config(p.get("program_config"), tensors["input"].memory_config())
        out_mem = mem if (mem is not None and not mem.is_sharded()) else tensors["input"].memory_config()
        return (
            qsr.layer_norm(
                tensors["input"],
                weight=tensors["weight"],
                bias=tensors["bias"],
                epsilon=p["epsilon"],
                memory_config=out_mem,
                program_config=pc,
                compute_kernel_config=build_compute_config(p.get("compute_kernel_config")),
            ),
        )
    if op == "nlp_create_qkv_heads":
        kw = dict(num_heads=p["num_heads"], transpose_k_heads=p["transpose_k_heads"], memory_config=mem)
        if p.get("num_kv_heads") is not None:
            kw["num_kv_heads"] = p["num_kv_heads"]
        outs = qsr.nlp_create_qkv_heads(tensors["input"], **kw)
        return tuple(o for o in outs if o is not None)[: 1 if p.get("num_kv_heads") == 0 else 3]
    if op == "nlp_concat_heads":
        return (qsr.nlp_concat_heads(tensors["input"], memory_config=mem),)
    if op == "scaled_dot_product_attention":
        return (
            qsr.scaled_dot_product_attention(
                tensors["query"],
                tensors["key"],
                tensors["value"],
                is_causal=p["is_causal"],
                attn_mask=None,
                program_config=build_sdpa_program_config(p.get("program_config"), device),
                compute_kernel_config=build_compute_config(p.get("compute_kernel_config")),
                memory_config=mem,
            ),
        )
    if op == "upsample":
        return (qsr.upsample(tensors["input"], tuple(p["scale_factor"])),)
    if op == "concat":
        ins = [tensors[k] for k in sorted(tensors, key=lambda n: int(n.split("_")[-1]))]
        return (qsr.concat(ins, p["dim"]),)
    if op == "reshape":
        return (qsr.reshape(tensors["input"], tuple(p["shape"])),)
    if op == "unsqueeze":
        return (qsr.unsqueeze(tensors["input"], p["dim"]),)
    if op == "slice":
        return (qsr.slice(tensors["input"], p["slice_start"], p["slice_end"]),)
    if op == "to_layout":
        return (qsr.to_layout(tensors["input"], LAYOUT[p["layout"]]),)
    if op == "to_memory_config":
        return (qsr.to_memory_config(tensors["input"], mem),)
    if op == "sharded_to_interleaved":
        return (qsr.sharded_to_interleaved(tensors["input"], mem),)
    if op == "move":
        return (qsr.move(tensors["input"]),)
    if op == "to_device":
        host = tensors["input"]
        return (
            qsr.to_device(
                host,
                device,
                memory_config=build_mem(
                    specs["outputs"][0]["mem"], specs["outputs"][0]["shape"], specs["outputs"][0]["layout"], device
                ),
            ),
        )
    raise NotImplementedError(op)



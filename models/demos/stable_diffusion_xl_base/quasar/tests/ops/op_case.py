def shrink_conv_case(case):
    """Apply SDXL_QSR_CONV_SPATIAL_DIV to a conv2d case: input rows N*H*W -> N*(H/n)*(W/n), params updated."""
    sd = spatial_div()
    if case["op"] != "conv2d" or sd == 1:
        return case
    p = case["params"]
    H, W = p["input_height"] // sd, p["input_width"] // sd
    case = dict(case, params=dict(p, input_height=H, input_width=W), inputs=dict(case["inputs"]))
    spec = dict(case["inputs"]["input"])
    shape = list(spec["shape"])
    if len(shape) == 4 and shape[0] == 1 and shape[1] == 1:
        shape[2] = p["batch_size"] * H * W
    else:  # [B, H, W, C] (upsampler convs)
        shape[1], shape[2] = H, W
    spec["shape"] = shape
    case["inputs"]["input"] = spec
    return case


def run_case(device, case):
    case = shrink_conv_case(case)
    op = case["op"]
    params = case["params"]
    gen = torch.Generator().manual_seed(case.get("seed", 0))
    inputs_t = {}
    tensors = {}

    for name, spec in case["inputs"].items():
        if op == "group_norm" and name in ("input_mask", "negative_mask", "weight", "bias"):
            continue  # derived below from the raw gamma/beta
        if op == "to_device":
            spec = dict(spec, on_device=False)
        scale = 1.0
        if op in ("conv2d", "linear", "matmul") and name == "weight":
            scale = 1.0 / math.sqrt(spec["shape"][-2] if op != "conv2d" else spec["shape"][1] * 9)
        if op in ("reciprocal", "div") and name in ("input", "input_b"):
            data = torch.rand(spec["shape"] if spec["shape"] != [] else (), generator=gen) + 0.5
        else:
            data = random_data(spec, gen, scale)
        if op == "conv2d" and name == "weight":
            data = data  # [Cout, Cin, kh, kw], uploaded as the model does (host, ROW_MAJOR, fp32/bf16)
        inputs_t[name] = data
        tensors[name] = build_tensor(spec, data, device)

    if op == "group_norm":
        C = case["inputs"]["input"]["shape"][-1]
        G = params["num_groups"]
        gamma = torch.randn(C, generator=gen) * 0.1 + 1.0
        beta = torch.randn(C, generator=gen) * 0.1
        inputs_t["gn_weight"], inputs_t["gn_bias"] = gamma, beta
        in_mem = tensors["input"].memory_config()
        if grid_mode() == "fit":
            nx, ny = mem_grid_dims(in_mem)
        else:
            nx, ny = params["core_grid"]["CoreGrid"]
        tensors["_gn_cores_x"], tensors["_gn_cores_y"] = nx, ny
        gamma_rm = ttnn.create_group_norm_weight_bias_rm(gamma, C, nx)
        beta_rm = ttnn.create_group_norm_weight_bias_rm(beta, C, nx)
        tensors["weight"] = qsr.from_torch(gamma_rm, ttnn.bfloat16, layout=ttnn.ROW_MAJOR_LAYOUT, device=device)
        tensors["bias"] = qsr.from_torch(beta_rm, ttnn.bfloat16, layout=ttnn.ROW_MAJOR_LAYOUT, device=device)
        mask = ttnn.create_group_norm_input_mask(C, G, nx, dtype_for("BFLOAT8_B"))
        tensors["input_mask"] = qsr.to_device(mask, device)
        if "negative_mask" in case["inputs"]:
            nmask = ttnn.create_group_norm_input_negative_mask(C, G, nx, dtype_for("BFLOAT8_B"))
            tensors["negative_mask"] = qsr.to_device(nmask, device)

    outputs = call_op(op, tensors, params, case, device)
    golden = GOLDEN[op](inputs_t, params)
    if not isinstance(golden, tuple):
        golden = (golden,)

    pcc = PCC.get(op, DEFAULT_PCC)
    for i, (got, exp) in enumerate(zip(outputs, golden)):
        got_t = to_torch(got)
        exp_t = exp.float()
        assert list(got_t.shape) == list(exp_t.shape), f"output {i}: shape {list(got_t.shape)} != {list(exp_t.shape)}"
        if op in (
            "to_layout",
            "to_memory_config",
            "sharded_to_interleaved",
            "move",
            "to_device",
            "reshape",
            "unsqueeze",
            "slice",
            "concat",
        ):
            assert torch.equal(
                got_t.to(torch.bfloat16), exp_t.to(torch.bfloat16)
            ), f"output {i}: data movement op changed values"
        else:
            assert_with_pcc(exp_t, got_t, pcc)

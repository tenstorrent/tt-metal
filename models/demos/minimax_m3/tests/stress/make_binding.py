"""Write the tt-run rank binding, mesh graph descriptor, producer env and run.json for one stress run.

One [2,4] stage per 8 chips of a Blackhole galaxy, Z-chained 0 -> 1 -> 2 -> 3 (the device groups below follow
single_bh_galaxy_4x4x2_z_chain_graph_descriptor.textproto). Prints the number of stages on stdout.
"""

import argparse
import json
import os
import shlex
import sys

M3_NUM_LAYERS = 60
STAGE_DEVICES = ["0,1,2,3,4,5,6,7", "24,25,26,27,28,29,30,31", "16,17,18,19,20,21,22,23", "8,9,10,11,12,13,14,15"]
MGD_4_STAGES = "tt_metal/fabric/mesh_graph_descriptors/single_bh_galaxy_4x4x2_z_chain_graph_descriptor.textproto"
MANIFEST = "models/demos/minimax_m3/tt/runners/manifests/minimax_m3.json"
WATCHER_ENV = {
    "TT_METAL_WATCHER": "30",
    "TT_METAL_WATCHER_DISABLE_ETH": "1",
    "TT_METAL_WATCHER_DISABLE_SANITIZE_NOC": "1",
    "TT_METAL_WATCHER_DISABLE_RING_BUFFER": "1",
    "TT_METAL_WATCHER_DISABLE_STACK_USAGE": "1",
    "TT_METAL_WATCHER_DISABLE_PAUSE": "1",
    "TT_METAL_WATCHER_DISABLE_CB_SANITIZE": "1",
}
SP, TP = 2, 4


def parse_layers(a):
    if a.layers:
        stages = [[int(x) for x in s.split(",") if x] for s in a.layers.split()]
    else:
        n, f = a.layers_per_stage, a.first_layer
        stages = [list(range(f + i * n, f + (i + 1) * n)) for i in range(a.stages)]
    if not 1 <= len(stages) <= len(STAGE_DEVICES):
        sys.exit(f"1-{len(STAGE_DEVICES)} stages supported, got {len(stages)}: {stages}")
    bad = [x for s in stages for x in s if not 0 <= x < M3_NUM_LAYERS]
    if bad or not all(stages):
        sys.exit(f"layers must be non-empty per stage and in [0, {M3_NUM_LAYERS}): {stages}")
    return stages


def chain_mgd(n):
    lines = [
        f"# {n} Z-chained [2,4] Blackhole meshes (generated by make_binding.py)",
        'mesh_descriptors {\n  name: "M0"\n  arch: BLACKHOLE\n  device_topology { dims: [ 2, 4 ] dim_types: [ LINE, LINE ] }'
        "\n  host_topology   { dims: [ 1, 1 ] }\n  channels { count: 2 policy: STRICT }\n}",
        'graph_descriptors {\n  name: "G0"\n  type: "FABRIC"',
    ]
    lines += [f'  instances {{ mesh {{ mesh_descriptor: "M0" mesh_id: {i} }} }}' for i in range(n)]
    for i in range(n - 1):
        lines.append(
            "  connections {\n"
            f'    nodes {{ mesh {{ mesh_descriptor: "M0" mesh_id: {i} }} }}\n'
            f'    nodes {{ mesh {{ mesh_descriptor: "M0" mesh_id: {i + 1} }} }}\n'
            "    channels { count: 4 policy: RELAXED }\n    assign_z_direction: true\n  }"
        )
    lines += ["}", 'top_level_instance { graph { graph_descriptor: "G0" graph_id: 0 } }', ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--tt-metal-home", default=os.environ.get("TT_METAL_HOME", os.getcwd()))
    ap.add_argument("--layers", default="", help='per-stage absolute layers, e.g. "37,38 39,40 41,42 43,44"')
    ap.add_argument("--first-layer", type=int, default=37)
    ap.add_argument("--layers-per-stage", type=int, default=2)
    ap.add_argument("--stages", type=int, default=4)
    ap.add_argument("--users", type=int, default=90)
    ap.add_argument("--max-seq-len", type=int, default=1048576)
    ap.add_argument("--chunk-size", type=int, default=2048)
    ap.add_argument("--fabric", default="2d")
    ap.add_argument("--profile", default="paced")
    ap.add_argument("--seed", type=int, default=59542)
    ap.add_argument("--service-id", default="m3_stress")
    ap.add_argument("--run-id", default="m3_stress")
    ap.add_argument("--cache-path", default="/mnt/weka/model-cache/scratch/minimax/MiniMax-M3-cache/prefill")
    ap.add_argument(
        "--trace-dir", default="/mnt/weka/model-cache/scratch/minimax/MiniMax-M3-cache/prefill/golden/longbook_56320"
    )
    ap.add_argument("--kernel-cache", required=True)
    ap.add_argument("--watcher", action="store_true")
    ap.add_argument("--env", action="append", default=[], help="K=V for runner and producer (repeatable)")
    a = ap.parse_args()

    stages = parse_layers(a)
    n = len(stages)
    home = os.path.abspath(a.tt_metal_home)
    run = os.path.abspath(a.run_dir)
    os.makedirs(run, exist_ok=True)
    extra = dict(kv.split("=", 1) for kv in a.env)

    if n == len(STAGE_DEVICES):
        mgd = os.path.join(home, MGD_4_STAGES)
    else:
        mgd = os.path.join(run, "mesh_graph.textproto")
        with open(mgd, "w") as f:
            f.write(chain_mgd(n))

    model = {
        "PREFILL_MODEL": "minimax_m3",
        "PREFILL_SP": str(SP),
        "PREFILL_TP": str(TP),
        "PREFILL_NUM_LAYERS": str(sum(len(s) for s in stages)),
        "PREFILL_CHUNK_SIZE": str(a.chunk_size),
        "PREFILL_MAX_SEQ_LEN": str(a.max_seq_len),
        "PREFILL_NUM_USERS": str(a.users),
        "PREFILL_H2D_SERVICE_ID": a.service_id,
        "M3_INDEX_CACHE_BF16": "0",
    }
    runner = {
        "PREFILL_MANIFEST": os.path.join(home, MANIFEST),
        **model,
        "PREFILL_FABRIC_MODE": a.fabric,
        "PREFILL_PP_LAYER_COUNTS": ",".join(str(len(s)) for s in stages),
        "PREFILL_MIGRATION_TABLE_PATH": os.path.join(run, "kv_chunk_table.pb"),
        "PREFILL_MIGRATION_DEVICE_MAP_PATH": os.path.join(run, "kv_device_map.json"),
        "M3_INDEX_K_TP_SHARD": "1",
        "M3_WEIGHTS_FROM_CACHE": "1",
        "TT_CACHE_PATH": a.cache_path,
        "TT_METAL_CACHE": a.kernel_cache,
        "TT_METAL_INSPECTOR": "1",
        "TT_METAL_INSPECTOR_RPC": "1",
        "LOGURU_LEVEL": "INFO",
        "STRESS_RUN_ID": a.run_id,
        **(WATCHER_ENV if a.watcher else {}),
        **extra,
    }
    q = json.dumps
    lines = ["# generated by models/demos/minimax_m3/tests/stress/make_binding.py", "rank_bindings:"]
    for r, layers in enumerate(stages):
        env = {
            "TT_VISIBLE_DEVICES": STAGE_DEVICES[r],
            "STRESS_LAYERS": ",".join(map(str, layers)),
            "TT_METAL_LOGS_PATH": os.path.join(run, f"logs_r{r}"),
        }
        os.makedirs(env["TT_METAL_LOGS_PATH"], exist_ok=True)
        lines.append(f"  - rank: {r}\n    mesh_id: {r}\n    mesh_host_rank: 0\n    env_overrides:")
        lines += [f"      {k}: {q(v)}" for k, v in env.items()]
    lines.append(f"mesh_graph_desc_path: {q(mgd)}")
    lines.append("global_env:")
    lines += [f"  {k}: {q(v)}" for k, v in runner.items()]
    with open(os.path.join(run, "binding.yaml"), "w") as f:
        f.write("\n".join(lines) + "\n")

    producer = {
        **model,
        "PREFILL_TRACE_DIR": a.trace_dir,
        "PREFILL_SEND_SHUTDOWN": "1",
        "PREFILL_PRODUCER_MULTI_TURN_PROB": "1",
        "PREFILL_PRODUCER_MAX_REQUESTS": "100000000",
        "PREFILL_PRODUCER_SEED": str(a.seed),
        "STRESS_PROFILE": a.profile,
        "LOGURU_LEVEL": "INFO",
        **extra,
    }
    with open(os.path.join(run, "producer.env"), "w") as f:
        f.writelines(f"export {k}={shlex.quote(v)}\n" for k, v in producer.items())

    info = dict(stages=n, layers=stages, devices=STAGE_DEVICES[:n], service_id=a.service_id, profile=a.profile)
    with open(os.path.join(run, "run.json"), "w") as f:
        json.dump(info, f, indent=1)
    print(n)


if __name__ == "__main__":
    main()

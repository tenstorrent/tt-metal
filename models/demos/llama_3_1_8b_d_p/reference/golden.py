"""Per-module golden runner: run the torch reference and dump each block's inputs/outputs.

Torch only — same purity contract as `model.py`.

## What this is, and what it is not

These are the **per-module goldens** of D1/M1: one dict per block holding the block's inputs, its
weights and its outputs, all fp16. They are what the device PCC tests in D2/D3/M2/M3 measure
against. They are cheap to regenerate (a single block at a few thousand tokens), so the recipe is
explicit that they are *deliberately not cached* the way the whole-model reference is.

They are **not** the golden trace. That is a different artifact, generated by
`scripts/generate_golden_kv_cache.py`, needs the real checkpoint, lives beside the weights, and is
what P1/P2 grade against.

## Cache keying

`ModuleGoldenKey` is frozen, and every field in it changes the output. That is the load-bearing
property borrowed from `deepseek_v3_d_p/utils/transformer_helpers.py:ReferenceCacheKey`: a changed
field yields a different filename, so a stale golden is never reused silently. Add a knob to a
golden and it goes in the key, or the next run reads someone else's numbers.

The whole-model reference (M1) is the expensive one and reuses DeepSeek's `ReferenceCacheKey` +
`save_reference_cache` / `load_reference_cache` directly — see `tests/torch_ref/test_golden_cache.py`.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, replace
from pathlib import Path

import torch

from .config import LlamaConfigConstants
from .model import (
    REF_DTYPE,
    RefAttention,
    RefDecoderLayer,
    RefMLP,
    RefRMSNorm,
    RefRotaryEmbedding,
    causal_mask,
)

GOLDEN_DIR_ENV = "LLAMA31_8B_MODULE_GOLDEN_DIR"
DEFAULT_GOLDEN_DIR = "/tmp/llama_3_1_8b_module_goldens"


@dataclass(frozen=True)
class ModuleGoldenKey:
    """Every field that changes a per-module golden's contents.

    Frozen on purpose: a test that wants a variant must `replace()` it, which changes the filename.
    """

    block: str  # "rms_norm" | "mlp" | "attention" | "decoder_layer" | "rope"
    seq_len: int
    hidden_size: int
    intermediate_size: int
    num_attention_heads: int
    num_key_value_heads: int
    head_dim: int
    rope_theta: float
    rope_type: str
    rope_factor: float
    rms_norm_eps: float
    batch_size: int
    seed: int
    dtype: str  # str(torch dtype) of the reference compute

    def __str__(self) -> str:
        return (
            f"{self.block}_s{self.seq_len}_h{self.hidden_size}_i{self.intermediate_size}"
            f"_q{self.num_attention_heads}_kv{self.num_key_value_heads}_hd{self.head_dim}"
            f"_theta{self.rope_theta:g}_{self.rope_type}{self.rope_factor:g}"
            f"_eps{self.rms_norm_eps:g}_b{self.batch_size}_seed{self.seed}_{self.dtype}"
        )


def golden_dir() -> Path:
    return Path(os.environ.get(GOLDEN_DIR_ENV, DEFAULT_GOLDEN_DIR))


def make_key(block: str, config: LlamaConfigConstants, seq_len: int, batch_size: int = 1, seed: int = 0):
    return ModuleGoldenKey(
        block=block,
        seq_len=seq_len,
        hidden_size=config.hidden_size,
        intermediate_size=config.intermediate_size,
        num_attention_heads=config.num_attention_heads,
        num_key_value_heads=config.num_key_value_heads,
        head_dim=config.head_dim,
        rope_theta=config.rope_theta,
        rope_type=config.rope_scaling["rope_type"],
        rope_factor=config.rope_scaling["factor"],
        rms_norm_eps=config.rms_norm_eps,
        batch_size=batch_size,
        seed=seed,
        dtype=str(REF_DTYPE),
    )


def save_module_golden(key: ModuleGoldenKey, payload: dict) -> Path:
    d = golden_dir()
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{key}.pt"
    torch.save(payload, path)
    return path


def load_module_golden(key: ModuleGoldenKey) -> dict:
    path = golden_dir() / f"{key}.pt"
    if not path.exists():
        raise FileNotFoundError(f"module golden not found: {path}")
    return torch.load(path, weights_only=True)


# ---------------------------------------------------------------------------
# Block builders. Each returns (module, inputs, outputs) with everything fp16.
# ---------------------------------------------------------------------------


def _rand(*shape, seed=None, scale=1.0):
    if seed is not None:
        torch.manual_seed(seed)
    return (torch.randn(*shape, dtype=torch.float32) * scale).to(REF_DTYPE)


def golden_rms_norm(config: LlamaConfigConstants, seq_len: int, batch_size: int = 1, seed: int = 0) -> dict:
    """Plain RMSNorm at real width. Gain drawn around 1.0, which is where trained gains sit."""
    torch.manual_seed(seed)
    x = _rand(batch_size, seq_len, config.hidden_size)
    norm = RefRMSNorm(config.hidden_size, config.rms_norm_eps)
    with torch.no_grad():
        norm.weight.copy_((1.0 + 0.1 * torch.randn(config.hidden_size)).to(REF_DTYPE))
        out = norm(x)
    return {"x": x, "weight": norm.weight.detach().clone(), "eps": config.rms_norm_eps, "out": out}


def golden_mlp(config: LlamaConfigConstants, seq_len: int, batch_size: int = 1, seed: int = 0) -> dict:
    """Dense SwiGLU MLP at real dims (4096 -> 14336 -> 4096)."""
    torch.manual_seed(seed)
    x = _rand(batch_size, seq_len, config.hidden_size)
    mlp = RefMLP(config)
    with torch.no_grad():
        out = mlp(x)
    return {
        "x": x,
        "gate_proj": mlp.gate_proj.weight.detach().clone(),
        "up_proj": mlp.up_proj.weight.detach().clone(),
        "down_proj": mlp.down_proj.weight.detach().clone(),
        "out": out,
    }


def golden_rope(config: LlamaConfigConstants, seq_len: int, batch_size: int = 1, seed: int = 0) -> dict:
    """cos/sin tables plus a rotated Q/K pair.

    Dumping the tables themselves (not just the rotated output) is what lets the attention test feed
    the device the SAME cos/sin — so that test measures attention and not the rope constants.
    """
    torch.manual_seed(seed)
    rope = RefRotaryEmbedding(config)
    position_ids = torch.arange(seq_len)[None, :].expand(batch_size, -1)
    cos, sin = rope(position_ids)
    n_q, n_kv, hd = config.num_attention_heads, config.num_key_value_heads, config.head_dim
    q = _rand(batch_size, n_q, seq_len, hd)
    k = _rand(batch_size, n_kv, seq_len, hd)
    from .model import apply_rotary_pos_emb

    with torch.no_grad():
        q_rot, k_rot = apply_rotary_pos_emb(q, k, cos, sin)
    return {
        "inv_freq": rope.inv_freq.detach().clone(),
        "cos": cos,
        "sin": sin,
        "q": q,
        "k": k,
        "q_rot": q_rot,
        "k_rot": k_rot,
    }


def golden_attention(config: LlamaConfigConstants, seq_len: int, batch_size: int = 1, seed: int = 0) -> dict:
    """Whole attention block, plus the post-RoPE K and raw V the KV cache stores."""
    torch.manual_seed(seed)
    x = _rand(batch_size, seq_len, config.hidden_size)
    attn = RefAttention(config)
    rope = RefRotaryEmbedding(config)
    position_ids = torch.arange(seq_len)[None, :].expand(batch_size, -1)
    cos, sin = rope(position_ids)
    with torch.no_grad():
        out, k_rope, v = attn(x, (cos, sin), causal_mask(seq_len), return_kv=True)
    return {
        "x": x,
        "cos": cos,
        "sin": sin,
        "q_proj": attn.q_proj.weight.detach().clone(),
        "k_proj": attn.k_proj.weight.detach().clone(),
        "v_proj": attn.v_proj.weight.detach().clone(),
        "o_proj": attn.o_proj.weight.detach().clone(),
        "out": out,
        "k_rope": k_rope,
        "v": v,
    }


def golden_decoder_layer(config: LlamaConfigConstants, seq_len: int, batch_size: int = 1, seed: int = 0) -> dict:
    """One complete decoder layer, residuals included — the D2/D3 composition check."""
    torch.manual_seed(seed)
    x = _rand(batch_size, seq_len, config.hidden_size)
    layer = RefDecoderLayer(config)
    rope = RefRotaryEmbedding(config)
    position_ids = torch.arange(seq_len)[None, :].expand(batch_size, -1)
    cos, sin = rope(position_ids)
    with torch.no_grad():
        out, k_rope, v = layer(x, (cos, sin), causal_mask(seq_len), return_kv=True)
    sd = {k: v_.detach().clone() for k, v_ in layer.state_dict().items()}
    return {"x": x, "cos": cos, "sin": sin, "state_dict": sd, "out": out, "k_rope": k_rope, "v": v}


BUILDERS = {
    "rms_norm": golden_rms_norm,
    "mlp": golden_mlp,
    "rope": golden_rope,
    "attention": golden_attention,
    "decoder_layer": golden_decoder_layer,
}


def get_module_golden(
    block: str,
    config: LlamaConfigConstants,
    seq_len: int,
    batch_size: int = 1,
    seed: int = 0,
    regenerate: bool = False,
) -> dict:
    """Load this block's golden from disk, computing and saving it on a miss.

    Per-module goldens are cheap, so a miss recomputes rather than failing — the opposite of the
    whole-model reference cache, where a miss must fail loudly in CI instead of burning an hour
    (`deepseek_v3_d_p/tests/test_mla.py:293` is that pattern).
    """
    key = make_key(block, config, seq_len, batch_size, seed)
    if not regenerate:
        try:
            return load_module_golden(key)
        except FileNotFoundError:
            pass
    payload = BUILDERS[block](config, seq_len, batch_size=batch_size, seed=seed)
    save_module_golden(key, payload)
    return payload



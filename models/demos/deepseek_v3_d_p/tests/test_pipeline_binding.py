"""Host-only checks of assemble_pipeline_binding.py: no devices, no ttnn.

The predictor's tray-half model is pinned against the cabling descriptors (tt-cluster-descriptors
submodule; those cases skip without it) and against a real probe: gen_pipeline_binding.py --layout 4x4
on bh-glx-120-c06u14 gave the top half 0,4,28,24,1,5,29,25,2,6,30,26,3,7,31,27.
"""
from pathlib import Path

import pytest

from models.demos.deepseek_v3_d_p.utils import assemble_pipeline_binding as apb

REPO = Path(__file__).resolve().parents[4]
DESCRIPTORS = REPO / "tt_metal/third_party/tt-cluster-descriptors/superclusters/blackhole"
C06U14 = (
    DESCRIPTORS / "SC36_32x4_revAB_subtorus_aisleC/SC36_32x4_revAB_subtorus_aisleC_cluster_desc/"
    "SC36_32x4_revAB_subtorus_aisleC_cluster_desc_bh-glx-120-c06u14_rank_10.yaml"
)
TOPO = REPO / "models/demos/common/prefill/runners/topology_configuration"

needs_descriptors = pytest.mark.skipif(
    not (REPO / apb.SC4_MAPPING).exists(), reason="tt-cluster-descriptors submodule not checked out"
)


@pytest.fixture(autouse=True)
def _repo_root(monkeypatch):
    # Descriptor and template paths are repo-relative, as on the command line.
    monkeypatch.chdir(REPO)


def sc4(hosts=None):
    galaxies = [apb.Galaxy(d) for d in apb.load_mapping(apb.SC4_MAPPING)[:hosts]]
    return galaxies, apb.predict(galaxies)


@needs_descriptors
def test_sc4_halves_seams_and_pins():
    galaxies, rows = sc4()
    assert [g.name for g in galaxies] == [f"bh-glx-110-{h}" for h in ("c07u08", "c07u02", "c08u02", "c08u08")]
    for g, (top, bottom) in zip(galaxies, rows):
        assert sorted(apb.to_logical(g, top)) == list(range(16))
        assert sorted(apb.to_logical(g, bottom)) == list(range(16, 32))
        # Mirrored: the bottom's first listed row is physical row 7, cabled to the top's row 0.
        assert all(g.linked(t, b) for t, b in zip(top[0], bottom[0]))
        assert apb.pin_positions(g, top) == ((1, 1), (1, 5))
        assert apb.pin_positions(g, bottom) == ((3, 1), (3, 5))
    # In-host seam 28 links (3<->4: 12, 2<->5: 8, 0<->7: 8), inter-galaxy 16, as the MGD declares.
    assert [n for _, n in apb.seam_report(galaxies, rows)] == [28, 16, 28, 16, 28, 16, 28]


@needs_descriptors
def test_two_hosts_chain_forward_not_around_the_ring():
    # With two hosts the previous host is also the next; the halves must still come out chained.
    galaxies, rows = sc4(hosts=2)
    assert [n for _, n in apb.seam_report(galaxies, rows)] == [28, 16, 28]
    assert sorted(apb.to_logical(galaxies[0], rows[0][0])) == list(range(16))


@pytest.mark.skipif(not C06U14.exists(), reason="tt-cluster-descriptors submodule not checked out")
def test_half_model_reproduces_a_measured_probe():
    g = apb.Galaxy(C06U14)
    halves = [apb.to_logical(g, apb.half_rows(a, b)) for a, b in g.halves()]
    assert [0, 4, 28, 24, 1, 5, 29, 25, 2, 6, 30, 26, 3, 7, 31, 27] in halves


def write_probe(path, host, top, bottom):
    lines = [f"# GENERATED by gen_pipeline_binding.py on {host} -- do not hand-edit.\n", "rank_bindings:\n"]
    for r, ids in enumerate((top, bottom)):
        lines.append(
            f'  - {{rank: {r}, mesh_id: {r}, mesh_host_rank: 0, env_overrides: {{TT_VISIBLE_DEVICES: "{",".join(map(str, ids))}"}}}}\n'
        )
    path.write_text("".join(lines))
    return path


def test_assemble_puts_host_k_on_ranks_2k_and_2k_plus_1(tmp_path):
    probes = [
        write_probe(tmp_path / f"h{k}.yaml", f"host{k}", range(16 * k, 16 * k + 16), range(100 + k, 116 + k))
        for k in range(4)
    ]
    out = tmp_path / "binding.yaml"
    assert apb.main(["assemble", *[a for p in probes for a in ("--probe", str(p))], "--out", str(out)]) == 0
    cfg = apb.yaml.safe_load(out.read_text())
    ids = {b["rank"]: b["env_overrides"]["TT_VISIBLE_DEVICES"] for b in cfg["rank_bindings"]}
    assert sorted(ids) == list(range(8))
    assert ids[4] == ",".join(map(str, range(32, 48)))
    assert ids[5] == ",".join(map(str, range(102, 118)))
    assert "--host host0:2,host1:2,host2:2,host3:2 --map-by slot" in out.read_text()
    assert cfg["global_env"]["PREFILL_SP_AXIS"] == "1"
    assert cfg["global_env"]["PREFILL_TP_SHARD_KV"] == "0"


def test_assemble_rejects_a_descriptor_with_another_mesh_count(tmp_path, expect_error):
    probes = [write_probe(tmp_path / f"h{k}.yaml", f"host{k}", range(16), range(16, 32)) for k in range(2)]
    args = ["assemble", *[a for p in probes for a in ("--probe", str(p))], "--out", str(tmp_path / "b.yaml")]
    with expect_error(SystemExit, "declares 8 meshes for 4 ranks"):
        apb.main(args)


@pytest.mark.parametrize(
    "top, bottom, error",
    [(range(15), range(16, 32), "needs 16 distinct"), (range(16), range(8, 24), "share devices")],
)
def test_read_probe_rejects_bad_halves(tmp_path, expect_error, top, bottom, error):
    with expect_error(SystemExit, error):
        apb.read_probe(write_probe(tmp_path / "p.yaml", "h", top, bottom))


def test_compare_errors_on_chips_and_notes_on_order():
    predicted = [[list(range(16)), list(range(16, 32))]]
    errors, notes = apb.compare(["h"], predicted, [[list(reversed(range(16))), list(range(16, 32))]])
    assert not errors and len(notes) == 1 and "rank 0" in notes[0]
    errors, _ = apb.compare(["h"], predicted, [[list(range(16)), list(range(17, 33))]])
    assert len(errors) == 1 and "rank 1" in errors[0]



#!/bin/bash
# run_galaxy_overlap.sh [OUT_DIR] -- the flat expert + combine overlap on a Galaxy, one command, ~1-2 h.
#
# A Galaxy chip's 12 x 10 grid lets the flat expert keep its 64 gate/up cores (np 1) on rows 1-9 while combine's
# senders take row 0 (on a LoudBox p150's 11 x 10, GLM 5.3 / Kimi K2.7 drop to 32 there). This measures whether
# GLM 5.3 and Kimi K2.7 then overlap as well as Kimi K3 does on the LoudBox (-23 / -26 %).
#
# Steps (logs and summary.md in OUT_DIR, default generated/flat_cmb_galaxy/<timestamp>):
#   1. plan_check   the flat plans on one chip (galaxy_plan_check.py): rows 1-9 should keep np 1 for glm-53 / kimi-k27
#   2. rows         overlap perf, flat on rows 1-9 (the test's default); FLAT_CMB_LOG prints combine's cells
#   3. xdown cells  the row-0 cells combine leaves free (from step 2), re-checked by galaxy_plan_check.py
#   4. serial       FLAT_CMB_NO_OVERLAP=1: flat on its own whole-grid plan, then combine (the baseline)
#   5. xdown        overlap perf, rows 1-9 + those row-0 cells as extra down cores (MIMO_FL_XDOWN)
#   6. acc_rows / acc_xdown   accuracy of both overlap layouts (bit-identical to flat then combine, PCC vs torch)
#   7. summary.md   summarize_overlap.py
#
# Env: FLAT_CMB_MESH (galaxy-8x1: the whole 8 x 4 torus up, ops on one column = the LoudBox ring's work, default;
# galaxy-8x4: all 32 chips), FLAT_CMB_MODELS (default kimi-k27,glm-53,kimi-k3), FLAT_CMB_ITERS (default 20),
# ACC=0 skips step 6, STEPS="2 4 5" runs a subset (step 3 is needed for 5: XDOWN=<cells> sets them by hand).
# Prerequisite: this branch built (ninja -C build_Release install); ./python_env (or the active env) with ttnn's deps.
# Do not edit this file while it runs (bash reads it as it goes).
set -u
REPO=$(cd "$(dirname "$0")" && git rev-parse --show-toplevel)
cd "$REPO" || exit 3
OUT=${1:-generated/flat_cmb_galaxy/$(date +%Y%m%d_%H%M%S)}
mkdir -p "$OUT"
[ -f python_env/bin/activate ] && source python_env/bin/activate  # (else the active env)
export TT_METAL_HOME=$REPO PYTHONPATH=$REPO/ttnn:$REPO:$REPO/tools TT_METAL_PINNED_MEMORY_CACHE_LIMIT_BYTES=0
export FLAT_CMB_MESH=${FLAT_CMB_MESH:-galaxy-8x1} FLAT_CMB_MODELS=${FLAT_CMB_MODELS:-kimi-k27,glm-53,kimi-k3}
export FLAT_CMB_ITERS=${FLAT_CMB_ITERS:-20}
# the Galaxy's own fabric (auto-discovered torus), fast dispatch, no left-over layout knobs
unset TT_MESH_GRAPH_DESC_PATH TT_METAL_SLOW_DISPATCH_MODE MIMO_FL_ROWS MIMO_FL_XDOWN FLAT_CMB_NO_OVERLAP FLAT_CMB_EAGER
TOOLS=models/demos/deepseek_v3_d_p/tests/op_unit_tests/flat_combine_tools
# (FLAT_CMB_MESH=ring-8x1: the same steps on a LoudBox's 8 p150 ring, for a like-for-like reference)
[ "$FLAT_CMB_MESH" = ring-8x1 ] && export TT_MESH_GRAPH_DESC_PATH=$REPO/$TOOLS/p150_x8_ring_8x1.textproto
T=models/demos/deepseek_v3_d_p/tests/op_unit_tests/test_flat_combine_overlap.py
STEPS=${STEPS:-"1 2 3 4 5 6"}
has() { [[ " $STEPS " == *" $1 "* ]]; }
log() { echo "[$(date +%H:%M:%S)] $*" | tee -a "$OUT/run.log"; }

# run <tag> <pytest -k expr> [ENV=val ...]: one pytest run under the safe runner (hang detection, reset, triage)
run() {
    local tag=$1 sel=$2
    shift 2
    log "$tag: -k '$sel' $*"
    env "$@" timeout 7200 scripts/run_safe_pytest.sh --run-all "$T" -k "$sel" -s -rA >"$OUT/$tag.log" 2>&1
    log "$tag: $(grep -oE 'SAFE_PYTEST_RESULT: \w+' "$OUT/$tag.log" | tail -1) $(grep -oE '[0-9]+ (passed|failed|errors?|skipped)' "$OUT/$tag.log" | tr '\n' ' ')"
    grep -E "^SKIPPED" "$OUT/$tag.log" | head -2 | cut -c1-200 | sed 's/^/    /' | tee -a "$OUT/run.log"
    grep -oE "flat\+combine .*traced: .*" "$OUT/$tag.log" | sed 's/^/    /' | tee -a "$OUT/run.log"
}

log "mesh $FLAT_CMB_MESH, models $FLAT_CMB_MODELS, $FLAT_CMB_ITERS iterations, out $OUT, git $(git rev-parse --short HEAD)"
if has 1; then
    log "plan_check"
    # one chip, no fabric; under the safe runner's device lock
    timeout 900 flock /tmp/tt-device.lock python "$TOOLS/galaxy_plan_check.py" >"$OUT/plan_check.log" 2>&1 ||
        log "plan_check FAILED (see $OUT/plan_check.log)"
    grep PLAN_CHECK "$OUT/plan_check.log" | tee -a "$OUT/run.log"
fi
has 2 && run rows perf FLAT_CMB_LOG=1
if has 3 && [ -z "${XDOWN:-}" ]; then
    # combine's cells (union over the chips), then every row-0 cell of the grid it leaves
    cells=$(grep -oE "combine cells over all chips:.*" "$OUT/rows.log" | head -1)
    width=$(grep -oE "PLAN_CHECK grid [0-9]+" "$OUT/plan_check.log" 2>/dev/null | grep -oE "[0-9]+$")
    XDOWN=""
    if [ -n "$cells" ] && [ -n "$width" ]; then
        XDOWN=$(python3 -c 'import re, sys
used = {(int(x), int(y)) for x, y in re.findall(r"\((\d+),(\d+)\)", sys.argv[1])}
print(";".join(f"{x},0" for x in range(int(sys.argv[2])) if (x, 0) not in used))' "$cells" "$width")
    fi
    log "combine cells: ${cells#*:} -> free row-0 cells (MIMO_FL_XDOWN): ${XDOWN:-none found}"
fi
if has 3 && [ -n "${XDOWN:-}" ]; then
    timeout 900 flock /tmp/tt-device.lock python "$TOOLS/galaxy_plan_check.py" "$XDOWN" >"$OUT/plan_check_xdown.log" 2>&1
    grep -E "PLAN_CHECK .*xdown|PLAN_CHECK (OK|problems)" "$OUT/plan_check_xdown.log" | tee -a "$OUT/run.log"
fi
has 4 && run serial perf FLAT_CMB_NO_OVERLAP=1
if has 5; then
    if [ -n "${XDOWN:-}" ]; then run xdown perf "MIMO_FL_XDOWN=$XDOWN"; else log "xdown: skipped (no free row-0 cells)"; fi
fi
if has 6 && [ "${ACC:-1}" != 0 ]; then
    run acc_rows "not perf"
    [ -n "${XDOWN:-}" ] && run acc_xdown "not perf" "MIMO_FL_XDOWN=$XDOWN"
fi
args=()
for t in serial rows xdown acc_rows acc_xdown; do [ -f "$OUT/$t.log" ] && args+=("$t=$OUT/$t.log"); done
python3 "$TOOLS/summarize_overlap.py" "${args[@]}" | tee "$OUT/summary.md"
log "done: $OUT/summary.md"

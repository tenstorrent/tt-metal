def dtype(name: str):
    return ttnn.bfloat8_b if "BFLOAT8" in name else ttnn.bfloat16


def program_config_from_desc(d: dict, fused_activation=None):
    """Program config for one swept candidate; None for the TTNN default."""
    if d["kind"] == "default":
        return None
    g = ttnn.CoreCoord(*d["grid"])
    common = dict(
        compute_with_storage_grid_size=g,
        in0_block_w=d["ib"],
        out_subblock_h=d["sh"],
        out_subblock_w=d["sw"],
        per_core_M=d["pcm"],
        per_core_N=d["pcn"],
    )
    if d["kind"] == "mc2d":
        return ttnn.MatmulMultiCoreReuseMultiCastProgramConfig(
            **common, transpose_mcast=False, fuse_batch=False, fused_activation=fused_activation
        )
    if d["kind"] == "reuse":
        return ttnn.MatmulMultiCoreReuseProgramConfig(**common)
    return ttnn.MatmulMultiCoreReuseMultiCast1DProgramConfig(
        **common, fuse_batch=True, fused_activation=fused_activation, mcast_in0=d["kind"] == "mc1d_in0"
    )



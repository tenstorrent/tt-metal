"""Load-balanced placement of the DeepSeek-V4.1 routed experts over the mesh chips (bead 8y7.9.8).

The in-tree MoE stores expert slot ``s`` on linear chip ``s // experts_per_chip`` (``ExpertMapping``: linear chip
``group * dispatch_group_size + chip``, a dispatch group is a mesh column). In the checkpoint's expert order, real
text loads the chips very unevenly: a few experts take most of a prompt's routed pairs (top-6 of 384 carry
40-65 % at layers 2 / 20 / 21 / 24) and only some experts get any token, so every MoE op waits for the most loaded
chip (G2 reconciliation: MoE skew ~6.9 ms per layer).

Expert ids are internal to the MoE: relabelling them (gate rows, correction biases and experts permuted together)
leaves routing and output unchanged up to top-k ties. ``expert_order`` gives the relabelling: ``order[slot]`` is the
checkpoint expert stored at device slot ``slot``, chosen to balance the per-chip MoE cost on the documented load
profile ``expert_load_profile.json`` (routed pairs per expert of the reference gate on 12 training prompts; its
``source`` and ``validation`` fields, generated by ``tests/v41/expert_load_profile.py``).

Per-chip cost model (``chip_costs``), fitted on the per-chip kernel times of the traced MoE (bfp8 routed experts,
LoudBox 2x4, one 5120-token chunk, checkpoint order, 12 layer / prompt cases; routed-expert op rms error 90 us):
the routed-expert op costs ``ACTIVE_EXPERT_US`` per expert with at least one token (its weights are read once) plus
``PAIR_US`` per routed pair; dispatch and combine cost ``SENT_PAIR_US`` per pair a chip sends within its dispatch
group (its tokens' pairs to the group's experts, ~ the group's pairs / group size). Counts are scaled from the
profile's prompt length to ``CHUNK_TOKENS``.

Placement (deterministic): greedy, experts in descending order of their largest cost contribution, each to the
non-full chip minimizing (max over prompts, sum over prompts) of the most expensive chip after the assignment
(lowest chip on ties); then the best single swap between a chip that is the most expensive for some prompt and any
other chip, minimizing the mean over prompts of the most expensive chip, until no swap strictly improves it. Chips
list their experts in ascending id order.

Layers without a profile and expert counts the chips do not divide keep the checkpoint order (``None``).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np

PROFILE_PATH = Path(__file__).with_name("expert_load_profile.json")
ACTIVE_EXPERT_US = 113.5
PAIR_US = 0.222
SENT_PAIR_US = 0.57  # dispatch 0.30 + combine 0.27
CHUNK_TOKENS = 5120  # production prefill chunk
REFINE_ITERATIONS = 1000  # upper bound; the refinement stops at the first swap that does not improve


@lru_cache(maxsize=None)
def load_profile() -> dict:
    return json.loads(PROFILE_PATH.read_text())


def _contributions(counts: np.ndarray, dispatch_group_size: int) -> tuple[np.ndarray, np.ndarray]:
    """Per prompt and expert: the cost an expert adds to its own chip, and to every chip of its dispatch group."""
    local = ACTIVE_EXPERT_US * (counts > 0) + PAIR_US * counts
    return local, SENT_PAIR_US * counts / dispatch_group_size


def chip_costs(counts: np.ndarray, chip: np.ndarray, dispatch_group_size: int, num_chips: int) -> np.ndarray:
    """Modelled MoE cost (us) of every chip [prompts, chips] for routed pairs ``counts`` [prompts, experts] (at the
    chunk's token count) with expert ``e`` on linear chip ``chip[e]``."""
    local, group = _contributions(np.atleast_2d(counts), dispatch_group_size)
    per_chip = np.stack([np.bincount(chip, weights=row, minlength=num_chips) for row in local])
    per_group = np.stack([np.bincount(chip // dispatch_group_size, weights=row) for row in group])
    return per_chip + np.repeat(per_group, dispatch_group_size, axis=1)[:, :num_chips]


def place(counts: np.ndarray, dispatch_group_size: int, num_dispatch_groups: int) -> list[int]:
    """Balanced placement of ``counts`` [prompts, experts] (routed pairs per expert per prompt, at the chunk's token
    count) over ``dispatch_group_size * num_dispatch_groups`` chips of equal expert count: the chip of every expert."""
    num_prompts, num_experts = counts.shape
    num_chips, gs = dispatch_group_size * num_dispatch_groups, dispatch_group_size
    cap = num_experts // num_chips
    assert cap * num_chips == num_experts, (num_experts, num_chips)
    local, group = _contributions(counts, gs)
    chip = np.full(num_experts, -1)
    loads, groups, sizes = (
        np.zeros((num_prompts, num_chips)),
        np.zeros((num_prompts, num_dispatch_groups)),
        np.zeros(num_chips, dtype=int),
    )

    def total(loads, groups):
        return loads + np.repeat(groups, gs, axis=-1)

    for e in np.argsort(-(local + group).max(0), kind="stable"):
        best = None
        for c in range(num_chips):
            if sizes[c] == cap:
                continue
            l2, g2 = loads.copy(), groups.copy()
            l2[:, c] += local[:, e]
            g2[:, c // gs] += group[:, e]
            worst = total(l2, g2).max(1)
            key = (worst.max(), worst.sum())
            if best is None or key < best[0]:
                best = (key, c)
        c = best[1]
        chip[e], sizes[c] = c, sizes[c] + 1
        loads[:, c] += local[:, e]
        groups[:, c // gs] += group[:, e]
    for _ in range(REFINE_ITERATIONS):
        now = total(loads, groups)
        best, swap = now.max(1).mean() - 1e-9, None
        for a in np.unique(now.argmax(1)):
            ia = np.flatnonzero(chip == a)
            for b in range(num_chips):
                if b == a:
                    continue
                ib = np.flatnonzero(chip == b)
                dl = local[:, ia, None] - local[:, None, ib]  # moving ia -> b and ib -> a
                dg = group[:, ia, None] - group[:, None, ib]
                l2 = np.repeat(loads[:, :, None, None], len(ia), 2).repeat(len(ib), 3)
                g2 = np.repeat(groups[:, :, None, None], len(ia), 2).repeat(len(ib), 3)
                l2[:, a] -= dl
                l2[:, b] += dl
                g2[:, a // gs] -= dg
                g2[:, b // gs] += dg
                j = (l2 + np.repeat(g2, gs, axis=1)).max(1).mean(0)
                i, k = np.unravel_index(np.argmin(j), j.shape)
                if j[i, k] < best:
                    best, swap = j[i, k], (ia[i], ib[k], a, b)
        if swap is None:
            break
        x, y, a, b = swap
        chip[x], chip[y] = b, a
        loads[:, a] += local[:, y] - local[:, x]
        loads[:, b] += local[:, x] - local[:, y]
        groups[:, a // gs] += group[:, y] - group[:, x]
        groups[:, b // gs] += group[:, x] - group[:, y]
    return chip.tolist()


def profile_counts(layer: int) -> np.ndarray | None:
    """The layer's training-prompt routed pairs [prompts, experts] scaled to ``CHUNK_TOKENS`` (None: no profile)."""
    profile = load_profile()
    counts = profile["counts"].get(str(layer))
    if counts is None:
        return None
    return np.asarray(counts, dtype=np.float64) * (CHUNK_TOKENS / profile["source"]["seq_len"])


@lru_cache(maxsize=None)
def expert_order(
    layer: int, num_experts: int, dispatch_group_size: int, num_dispatch_groups: int
) -> tuple[int, ...] | None:
    """``order[slot]`` = the checkpoint expert of device slot ``slot`` for V4.1 ``layer`` (slot // experts per chip =
    linear chip), or None to keep the checkpoint order."""
    counts = profile_counts(layer)
    num_chips = dispatch_group_size * num_dispatch_groups
    if counts is None or num_experts % num_chips or counts.shape[1] != num_experts:
        return None
    chip = place(counts, dispatch_group_size, num_dispatch_groups)
    return tuple(e for c in range(num_chips) for e in range(num_experts) if chip[e] == c)

"""Load-balanced placement of the DeepSeek-V4.1 routed experts over the mesh chips (beads 8y7.9.8, 8y7.9.12).

The in-tree MoE stores expert slot ``s`` on linear chip ``s // experts_per_chip`` (``ExpertMapping``: linear chip
``group * dispatch_group_size + chip``, a dispatch group is a mesh column). In the checkpoint's expert order, real
text loads the chips very unevenly: a few experts take most of a prompt's routed pairs (single experts carry up to
15 % of them at layers 2 / 20 / 21 / 24) and only some experts get any token, so every MoE op waits for the most
loaded chip.

Expert ids are internal to the MoE: relabelling them (gate rows, correction biases and experts permuted together)
leaves routing and output unchanged up to top-k ties. ``expert_order`` gives the relabelling: ``order[slot]`` is the
checkpoint expert stored at device slot ``slot``, chosen to balance the per-chip MoE cost on the documented load
profile ``expert_load_profile.json`` (routed pairs per expert of the reference gate on 12 training prompts, each at
its first 2048 and first 5120 tokens; its ``source``, ``rows`` and ``validation`` fields, generated by
``tests/v41/expert_load_profile.py``). The 2048-token rows stand for short prompts and partial last chunks.

Per-chip cost model (``chip_costs``), fitted on the per-chip kernel times of the traced MoE (bfp8 routed experts,
LoudBox 2x4, one 5120-token chunk of real text, checkpoint order and the 8y7.9.8 placement, 12 layer / placement
cases, bead 8y7.9.12): the routed-expert op costs ``ACTIVE_EXPERT_US`` per expert with at least one token (its
weights are read once) plus 0.228 us per routed pair (rms 85 us); dispatch takes 0.31 us per pair received by the
most loaded chip of the dispatch group (corr 0.95), so a pair costs ``PAIR_US`` = 0.228 + 0.31 us on the chip that
receives it; combine is the wait for the dispatch group's slowest chip (no cost of its own), and the MoE span is
the most expensive chip plus a constant. Counts are scaled from each profile row's token count to ``CHUNK_TOKENS``.

Placement (deterministic): greedy, experts in descending order of their largest cost, each to the non-full chip
minimizing (max over prompts, sum over prompts) of the most expensive chip after the assignment (lowest chip on
ties); then the best single swap between a chip that is the most expensive for some prompt and any other chip,
minimizing the mean over prompts of the most expensive chip, until no swap strictly improves it. Chips list their
experts in ascending id order.

Layers without a profile and expert counts the chips do not divide keep the checkpoint order (``None``).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np

PROFILE_PATH = Path(__file__).with_name("expert_load_profile.json")
ACTIVE_EXPERT_US = 114.5
PAIR_US = 0.228 + 0.31  # routed-expert op + dispatch, per pair the chip receives
CHUNK_TOKENS = 5120  # production prefill chunk
REFINE_ITERATIONS = 1000  # upper bound; the refinement stops at the first swap that does not improve


@lru_cache(maxsize=None)
def load_profile() -> dict:
    return json.loads(PROFILE_PATH.read_text())


def _expert_costs(counts: np.ndarray) -> np.ndarray:
    """Per prompt and expert: the cost (us) an expert adds to its chip."""
    return ACTIVE_EXPERT_US * (counts > 0) + PAIR_US * counts


def chip_costs(counts: np.ndarray, chip: np.ndarray, num_chips: int) -> np.ndarray:
    """Modelled MoE cost (us) of every chip [prompts, chips] for routed pairs ``counts`` [prompts, experts] (at the
    chunk's token count) with expert ``e`` on chip ``chip[e]``."""
    cost = _expert_costs(np.atleast_2d(counts))
    return np.stack([np.bincount(chip, weights=row, minlength=num_chips) for row in cost])


def place(counts: np.ndarray, num_chips: int) -> list[int]:
    """Balanced placement of ``counts`` [prompts, experts] (routed pairs per expert per prompt, at the chunk's token
    count) over ``num_chips`` chips of equal expert count: the chip of every expert."""
    num_prompts, num_experts = counts.shape
    cap = num_experts // num_chips
    assert cap * num_chips == num_experts, (num_experts, num_chips)
    cost = _expert_costs(counts)
    chip = np.full(num_experts, -1)
    loads, sizes = np.zeros((num_prompts, num_chips)), np.zeros(num_chips, dtype=int)
    for e in np.argsort(-cost.max(0), kind="stable"):
        best = None
        for c in np.flatnonzero(sizes < cap):
            worst = np.maximum(np.delete(loads, c, 1).max(1, initial=0.0), loads[:, c] + cost[:, e])
            key = (worst.max(), worst.sum())
            if best is None or key < best[0]:
                best = (key, c)
        c = best[1]
        chip[e], sizes[c], loads[:, c] = c, sizes[c] + 1, loads[:, c] + cost[:, e]
    for _ in range(REFINE_ITERATIONS):
        best, swap = loads.max(1).mean() - 1e-9, None
        for a in np.unique(loads.argmax(1)):
            ia = np.flatnonzero(chip == a)
            for b in range(num_chips):
                if b == a:
                    continue
                ib = np.flatnonzero(chip == b)
                d = cost[:, ia, None] - cost[:, None, ib]  # moving ia -> b and ib -> a
                rest = np.delete(loads, [a, b], 1).max(1, initial=0.0)[:, None, None]
                j = np.maximum(rest, np.maximum(loads[:, a, None, None] - d, loads[:, b, None, None] + d)).mean(0)
                i, k = np.unravel_index(np.argmin(j), j.shape)
                if j[i, k] < best:
                    best, swap = j[i, k], (ia[i], ib[k], a, b)
        if swap is None:
            break
        x, y, a, b = swap
        chip[x], chip[y] = b, a
        loads[:, a] += cost[:, y] - cost[:, x]
        loads[:, b] += cost[:, x] - cost[:, y]
    return chip.tolist()


def profile_counts(layer: int) -> np.ndarray | None:
    """The layer's profile routed pairs [rows, experts], each row scaled to ``CHUNK_TOKENS`` (None: no profile)."""
    profile = load_profile()
    counts = profile["counts"].get(str(layer))
    if counts is None:
        return None
    tokens = np.asarray([row["tokens"] for row in profile["rows"]], dtype=np.float64)
    return np.asarray(counts, dtype=np.float64) * (CHUNK_TOKENS / tokens)[:, None]


@lru_cache(maxsize=None)
def expert_order(
    layer: int, num_experts: int, dispatch_group_size: int, num_dispatch_groups: int
) -> tuple[int, ...] | None:
    """``order[slot]`` = the checkpoint expert of device slot ``slot`` for V4.1 ``layer`` (slot // experts per chip =
    linear chip), or None to keep the checkpoint order."""
    counts = profile_counts(layer)
    num_chips = dispatch_group_size * num_dispatch_groups
    if counts is None or num_experts % num_chips or counts.shape[1] != num_experts:
        return None
    chip = place(counts, num_chips)
    return tuple(e for c in range(num_chips) for e in range(num_experts) if chip[e] == c)

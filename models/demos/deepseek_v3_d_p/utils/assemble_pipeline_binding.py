"""Build the multi-host 4x4 pipeline rank binding: two ranks per galaxy, top half then bottom half.

CI binds the SC4 4x4 leg by tt-run discovery (run_multirank_pcc.sh); this is the explicit-binding
path, for a manual run and to check what discovery does. gen_pipeline_binding.py --layout 4x4 probes
ONE galaxy and writes its 2-rank file. The tray-half chip map differs by host, so a multi-host run
needs every host's probe stitched into one file, in host-ring order. No devices or ttnn needed; runs
anywhere.

    assemble  per-host probe files -> one binding. Host k's rank 0 (top) becomes rank 2k and its
              rank 1 (bottom, rows already mirrored by the probe) becomes rank 2k+1.
    predict   the same binding from the cabling descriptors (tt-cluster-descriptors submodule), plus
              a per-boundary link count. For a mock dry run before the hosts are free, and to check
              real probes against (--check-probe): a differing chip set is an error, a differing
              order only a note, since the topology mapper picks the order inside a half.

Both print the mpirun placement the binding needs (it has no host field):
`--host h0:2,h1:2,... --map-by slot`.

The descriptor model is the Rev C one, read off the aisle C cabling: a host has 4 trays of 8 ASICs
(tray = PCIe bus high nibble, ASIC = low nibble, as control_plane.cpp's get_ubb_id). A tray is
4 rows x 2 cols, ASIC a on row (a-1) % 4, col (a-1) // 4. Two trays cabled ASIC to ASIC on all 8
make a 4x4 half, row r = [A(r+1), A(r+5), B(r+5), B(r+1)], the 4-wide X ring closing
B(r+1) -> A(r+1). The half whose rows 0 and 1 cable to the previous host is the top; the bottom's
physical rows 4..7 are ASICs 4..1, so the same formula lists it mirrored (TP row t on row 7-t).
Anything that does not fit this model raises instead of guessing.
"""
import argparse
import collections
import os
import re
import sys
from pathlib import Path

import yaml

# Run as a script from the repo root (the descriptor paths are relative to it too).
sys.path.insert(0, os.environ.get("TT_METAL_HOME", "."))
from models.demos.deepseek_v3_d_p.utils.gen_pipeline_binding import TOPO, fill_rank_bindings  # noqa: E402

TEMPLATE = TOPO / "pipeline_prefill_request_sc4_8rank_4x4_sp1.yaml"
SC4_MAPPING = Path(
    "tt_metal/third_party/tt-cluster-descriptors/superclusters/blackhole/SC20_32x4_revC_subtorus_aisleC/"
    "SC4_32x4_revC_subtorus_aisleC_mapping.yaml"
)
RANKS_PER_HOST = 2
HALF_CHIPS = 16
_GENERATED_ON = re.compile(r"^# GENERATED by gen_pipeline_binding\.py on (\S+)", re.M)


# --- assemble -------------------------------------------------------------------------------------


def read_probe(path):
    """(host, [top ids, bottom ids]) from one gen_pipeline_binding.py --layout 4x4 output."""
    text = Path(path).read_text()
    bindings = sorted(yaml.safe_load(text)["rank_bindings"], key=lambda b: b["rank"])
    if [b["rank"] for b in bindings] != list(range(RANKS_PER_HOST)):
        raise SystemExit(f"{path}: expected ranks 0..{RANKS_PER_HOST - 1}, got {[b['rank'] for b in bindings]}")
    halves = []
    for b in bindings:
        raw = (b.get("env_overrides") or {}).get("TT_VISIBLE_DEVICES", "")
        ids = [int(x) for x in raw.split(",") if x.strip()]
        if len(ids) != HALF_CHIPS or len(set(ids)) != HALF_CHIPS:
            raise SystemExit(f"{path}: rank {b['rank']} needs {HALF_CHIPS} distinct device ids, got {raw!r}")
        halves.append(ids)
    if set(halves[0]) & set(halves[1]):
        raise SystemExit(f"{path}: top and bottom halves share devices {sorted(set(halves[0]) & set(halves[1]))}")
    m = _GENERATED_ON.search(text)
    return (m.group(1) if m else None), halves


def flatten(per_host):
    """[[top, bottom] per host] -> one device list per rank, rank 2k = host k's top half."""
    return [half for halves in per_host for half in halves]


def host_slots(hosts):
    return ",".join(f"{h}:{RANKS_PER_HOST}" for h in hosts)


def mgd_mesh_count(path):
    return len(re.findall(r"^\s*instances\s*\{\s*mesh\s*\{", Path(path).read_text(), re.M))


def render(template, per_host, hosts, source, mgd=None):
    """Fill the template for len(per_host) hosts; a template with more ranks is cut to fit.

    `mgd` replaces the template's mesh_graph_desc_path. Either way the descriptor must declare one
    mesh per rank: the 8-rank template's descriptor is wrong for fewer hosts."""
    text = Path(template).read_text()
    subs = flatten(per_host)
    if mgd:
        text, n = re.subn(r"^mesh_graph_desc_path: .*$", f"mesh_graph_desc_path: {mgd}", text, flags=re.M)
        if n != 1:
            raise SystemExit(f"{template} has {n} mesh_graph_desc_path lines, expected 1")
    mgd_path = re.search(r"^mesh_graph_desc_path: (\S+)", text, re.M).group(1)
    if mgd_mesh_count(mgd_path) != len(subs):
        raise SystemExit(f"{mgd_path} declares {mgd_mesh_count(mgd_path)} meshes for {len(subs)} ranks; pass --mgd")
    lines = text.splitlines(keepends=True)
    rank_line = re.compile(r"^\s*- \{rank: (\d+),")
    kept = [l for l in lines if not (m := rank_line.match(l)) or int(m.group(1)) < len(subs)]
    if sum(1 for l in kept if rank_line.match(l)) != len(subs):
        raise SystemExit(f"{template} has fewer than {len(subs)} rank bindings")
    text = fill_rank_bindings("".join(kept), subs, template)
    banner = (
        f"# GENERATED by assemble_pipeline_binding.py ({source}) -- do not hand-edit the TT_VISIBLE_DEVICES lists.\n"
        f"# Host order (rank 2k, 2k+1 on host k): {', '.join(hosts)}\n"
        f'# Launch with: --mpi-args "--host {host_slots(hosts)} --map-by slot ..."\n'
    )
    return banner + text


# --- predict --------------------------------------------------------------------------------------


class Galaxy:
    """One host's cluster descriptor, reduced to what the half model needs."""

    def __init__(self, path):
        d = yaml.safe_load(Path(path).read_text())
        self.name = d["cluster_id"]
        bus = {int(c): int(b, 16) for c, b in d["chip_to_bus_id"].items()}
        # UMD's TT_VISIBLE_DEVICES takes logical ids, which are BDF-sorted indices.
        self.logical = {c: i for i, c in enumerate(sorted(bus, key=lambda c: bus[c]))}
        self.unique = {int(c): int(u) for c, u in d["chip_unique_ids"].items()}
        trays = collections.defaultdict(dict)
        for c, b in bus.items():
            trays[b & 0xF0][b & 0x0F] = c
        if len(trays) != 4 or any(sorted(t) != list(range(1, 9)) for t in trays.values()):
            raise SystemExit(f"{self.name}: not 4 trays of ASICs 1..8 by bus id; the Rev C model does not apply")
        self.trays = [trays[k] for k in sorted(trays)]
        self.bus = bus
        self.links = collections.Counter()
        for a, b in d["ethernet_connections"]:
            self.links[frozenset((a["chip"], b["chip"]))] += 1
        self.remote = collections.Counter()  # (local chip, remote unique id) -> links
        for a, b in d.get("ethernet_connections_to_remote_devices") or []:
            self.remote[(a["chip"], int(b["remote_chip_id"]))] += 1

    def linked(self, a, b):
        return self.links[frozenset((a, b))]

    def halves(self):
        """The two (A, B) tray pairs that form a half, A holding the lower logical id.

        X-ring partners are cabled ASIC to ASIC on all 8. The trays of the other half share only
        some (the row 0<->7 wrap, the 2<->5 chord and 3<->4 each join equal ASICs too)."""
        pairs = []
        free = list(range(4))
        while free:
            i = free.pop(0)
            j = [j for j in free if all(self.linked(self.trays[i][k], self.trays[j][k]) for k in range(1, 9))]
            if len(j) != 1:
                raise SystemExit(f"{self.name}: tray {i} has {len(j)} X-ring partners, expected 1")
            free.remove(j[0])
            pairs.append((self.trays[i], self.trays[j[0]]))
        lowest = lambda t: min(self.logical[c] for c in t.values())
        return [(t0, t1) if lowest(t0) < lowest(t1) else (t1, t0) for t0, t1 in pairs]


def half_rows(a, b):
    return [[a[r + 1], a[r + 5], b[r + 5], b[r + 1]] for r in range(4)]


def _check_ring_rows(g, rows):
    for r, row in enumerate(rows):
        for c in range(4):
            if not g.linked(row[c], row[(c + 1) % 4]):
                raise SystemExit(f"{g.name}: row {r} chips {row[c]} and {row[(c + 1) % 4]} are not cabled")


def predict(galaxies):
    """Per host, [top rows, bottom rows (mirrored)] as chip ids, from the cabling alone."""
    if len(galaxies) < 2:
        raise SystemExit("predict needs at least two hosts: top and bottom are told apart by the inter-host cables")
    owner = {u: (gi, c) for gi, g in enumerate(galaxies) for c, u in g.unique.items()}

    def cabled_to(g, chips, other):
        return sum(n for (c, u), n in g.remote.items() if c in chips and owner.get(u, (None,))[0] == other)

    out = []
    for i, g in enumerate(galaxies):
        h0, h1 = g.halves()
        sets = [set(h0[0].values()) | set(h0[1].values()), set(h1[0].values()) | set(h1[1].values())]
        # The bottom half cables to the next host; the last host has none in the chain, so its top
        # half is the one cabled to the previous host. Not the ring wrap: with 2 hosts it is the
        # same host from both sides.
        other = i + 1 if i + 1 < len(galaxies) else i - 1
        cables = [cabled_to(g, s, other) for s in sets]
        if min(cables) != 0 or max(cables) == 0:
            raise SystemExit(
                f"{g.name}: cables to {galaxies[other].name} per half are {cables}, expected one half only"
            )
        cabled, uncabled = (h0, h1) if cables[0] else (h1, h0)
        top, bottom = (uncabled, cabled) if other > i else (cabled, uncabled)
        a, b = top
        top_rows = half_rows(a, b)
        # Bottom A' is the tray under top's A: their ASIC 4s (rows 3 and 4) are cabled.
        a2, b2 = bottom if g.linked(a[4], bottom[0][4]) else (bottom[1], bottom[0])
        bottom_rows = half_rows(a2, b2)
        for rows in (top_rows, bottom_rows):
            _check_ring_rows(g, rows)
        for c in range(4):
            if not g.linked(top_rows[3][c], bottom_rows[3][c]):
                raise SystemExit(f"{g.name}: col {c} has no row 3 <-> row 4 link")
        out.append([top_rows, bottom_rows])
    return out


def seam_report(galaxies, rows):
    """(label, links) for each stage boundary, in pipeline order. 0 links means the chain is broken."""
    report = []
    flat = lambda rr: {c for row in rr for c in row}
    for i, g in enumerate(galaxies):
        top, bottom = flat(rows[i][0]), flat(rows[i][1])
        n = sum(cnt for pair, cnt in g.links.items() if len(pair & top) == 1 and len(pair & bottom) == 1)
        report.append((f"{g.name} top -> bottom", n))
        if i + 1 < len(galaxies):
            nxt = galaxies[i + 1]
            next_top = {nxt.unique[c] for c in flat(rows[i + 1][0])}
            n = sum(cnt for (c, u), cnt in g.remote.items() if c in bottom and u in next_top)
            report.append((f"{g.name} bottom -> {nxt.name} top", n))
    return report


# control_plane.cpp ubb_bus_ids for Blackhole: tray id = index of the bus high nibble, plus 1.
_BH_UBB_TRAY_BUS = (0x00, 0x40, 0xC0, 0x80)


def pin_positions(g, rows):
    """(tray_id, asic_location) of mesh chips 0 and 1, the two pins that fix a half's orientation.

    tray_id is the UBB tray the MGD's pinnings name (get_ubb_id), not the bus nibble."""
    return tuple((_BH_UBB_TRAY_BUS.index(g.bus[c] & 0xF0) + 1, g.bus[c] & 0x0F) for c in rows[0][:2])


def to_logical(g, rows):
    return [g.logical[c] for row in rows for c in row]


def load_mapping(path):
    m = yaml.safe_load(Path(path).read_text())["rank_to_cluster_mock_cluster_desc"]
    return [m[k] for k in sorted(m)]


def write_mock_mapping(descs, out):
    """An 8-rank mock mapping: both ranks of host k point at host k's descriptor."""
    lines = ["# GENERATED by assemble_pipeline_binding.py: two ranks per galaxy host, in host-ring order.\n"]
    lines.append("rank_to_cluster_mock_cluster_desc:\n")
    for k, d in enumerate(descs):
        for r in range(RANKS_PER_HOST):
            lines.append(f'  {RANKS_PER_HOST * k + r}: "{d}"\n')
    Path(out).write_text("".join(lines))


def compare(hosts, predicted, probed):
    """Errors for differing chip sets, notes for differing order. Returns (errors, notes)."""
    errors, notes = [], []
    for k, (p, q) in enumerate(zip(predicted, probed)):
        for half, name in ((0, "top"), (1, "bottom")):
            rank = RANKS_PER_HOST * k + half
            if set(p[half]) != set(q[half]):
                errors.append(
                    f"rank {rank} ({hosts[k]} {name}): probe {sorted(q[half])} vs descriptors {sorted(p[half])}"
                )
            elif p[half] != q[half]:
                notes.append(f"rank {rank} ({hosts[k]} {name}): same chips, mapper order {q[half]}")
    return errors, notes


# --- CLI ------------------------------------------------------------------------------------------


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("assemble", help="stitch per-host probe files, in host-ring order")
    a.add_argument("--probe", action="append", required=True, help="one per host, in ring order")
    a.add_argument("--host", action="append", help="host names, same order (default: each probe's banner)")
    p = sub.add_parser("predict", help="derive the binding from cabling descriptors")
    p.add_argument("--mapping", default=str(SC4_MAPPING), help="mock mapping yaml listing one descriptor per host")
    p.add_argument("--hosts", type=int, help="use only the first N hosts of the mapping")
    p.add_argument("--check-probe", action="append", help="probe files to compare against, in host order")
    p.add_argument("--mock-mapping-out", help="also write a 2-ranks-per-host mock mapping here")
    for s in (a, p):
        s.add_argument("--template", default=str(TEMPLATE))
        s.add_argument("--mgd", help="mesh graph descriptor to name instead of the template's")
        s.add_argument("--out", help="binding to write (predict: optional)")
    args = ap.parse_args(argv)

    if args.cmd == "assemble":
        probes = [read_probe(f) for f in args.probe]
        hosts = args.host or [h for h, _ in probes]
        if len(hosts) != len(probes) or not all(hosts):
            raise SystemExit("name every host with --host (a probe file has no GENERATED banner)")
        if len(set(hosts)) != len(hosts):
            raise SystemExit(f"duplicate host in {hosts}")
        if not args.out:
            raise SystemExit("assemble needs --out")
        Path(args.out).write_text(
            render(args.template, [h for _, h in probes], hosts, "assembled from probes", mgd=args.mgd)
        )
        print(f"wrote {args.out} ({RANKS_PER_HOST * len(hosts)} ranks)")
        print(f"placement: --host {host_slots(hosts)} --map-by slot")
        return 0

    descs = load_mapping(args.mapping)[: args.hosts]
    galaxies = [Galaxy(d) for d in descs]
    hosts = [g.name for g in galaxies]
    rows = predict(galaxies)
    predicted = [[to_logical(g, r[0]), to_logical(g, r[1])] for g, r in zip(galaxies, rows)]
    for k, h in enumerate(hosts):
        for half, name in ((0, "top"), (1, "bottom (mirrored)")):
            print(f"rank {RANKS_PER_HOST * k + half}  {h}  {name:18} {','.join(map(str, predicted[k][half]))}")
    print("\nboundary links:")
    seams = seam_report(galaxies, rows)
    for label, n in seams:
        print(f"  {label:50} {n}")
    if any(n == 0 for _, n in seams):
        raise SystemExit("a stage boundary has no links: wrong host order for this cabling?")
    pins = {tuple(pin_positions(g, r[half]) for half in (0, 1)) for g, r in zip(galaxies, rows)}
    print("\npins (tray_id, asic_location) for mesh chips 0 and 1:")
    for top, bottom in sorted(pins):
        print(f"  top {top}  bottom {bottom}")
    if len(pins) != 1:
        print("  hosts disagree: one MGD pinning set cannot serve them all", file=sys.stderr)
    print(f"\nplacement: --host {host_slots(hosts)} --map-by slot")
    if args.out:
        Path(args.out).write_text(
            render(args.template, predicted, hosts, f"predicted from {args.mapping}", mgd=args.mgd)
        )
        print(f"wrote {args.out}")
    if args.mock_mapping_out:
        write_mock_mapping(descs, args.mock_mapping_out)
        print(f"wrote {args.mock_mapping_out}")
    if args.check_probe:
        probed = [read_probe(f)[1] for f in args.check_probe]
        errors, notes = compare(hosts, predicted, probed)
        for n in notes:
            print(f"note: {n}")
        for e in errors:
            print(f"MISMATCH: {e}", file=sys.stderr)
        return 1 if errors else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())

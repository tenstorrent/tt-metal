"""Artifact-availability policy shared by the PaddleOCR-VL PCC / accuracy tests.

The PCC and accuracy suites need ``demo/golden/`` (CPU-HuggingFace-reference
tensors and decoded text, generated by ``generate_goldens.py``). It is gitignored
-- 94 MB, entirely reproducible from the committed corpus and script -- so on a
dev box its absence should skip; on a runner that is supposed to have it staged, a
skip would hide the very breakage the suite exists to catch, so an unattended run
sets ``PADDLEOCR_VL_REQUIRE_ARTIFACTS=1`` and the same condition becomes a hard
failure.

Kept out of ``conftest.py`` so tests can import it directly without depending on
how pytest happens to have imported the conftest module.
"""
from __future__ import annotations

import os

import pytest


def require_artifacts() -> bool:
    """True when missing artifacts must fail instead of skip (set for unattended runs)."""
    return os.environ.get("PADDLEOCR_VL_REQUIRE_ARTIFACTS", "").strip().lower() in ("1", "true", "yes")


def missing_artifact(msg: str) -> None:
    """Skip on a dev box; fail under ``PADDLEOCR_VL_REQUIRE_ARTIFACTS=1``.

    Regenerate with ``python models/demos/blackhole/paddleocr_vl/tests/generate_goldens.py``.
    """
    if require_artifacts():
        pytest.fail(f"{msg} [PADDLEOCR_VL_REQUIRE_ARTIFACTS=1]")
    pytest.skip(msg)

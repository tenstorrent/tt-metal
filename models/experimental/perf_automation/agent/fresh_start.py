"""Everything a run remembers, so `--fresh` can start one that remembers nothing.

WHY THIS EXISTS. A run carries state forward on purpose -- a baseline is expensive, a coverage window
costs device probes, and the write-once anchor exists so the report and the stop gate cannot score
one run against two different ceilings. All of that is right while the tool is unchanged. It is wrong
the moment the tool IS changed, because a pinned value records what it is and never which rule
produced it, so a number from a superseded formula outlives the fix indefinitely.

Measured on Voxtral-Mini-3B, 2026-08-14. The ceiling anchor held:

    {"kind": "active_bytes", "value_ms": 3611.4831, "mode": "bytes_mb",
     "source": "checkpoint bytes + HF config"}

3611.48 MB is total_params x 1.0 -- the placeholder width, from before the ceiling learned to divide
by the width the loader actually chose. compute_target takes `bytes_per_unit` ahead of every other
source, so the corrected rule (params x 2.0 measured = 7.223 GB) never ran, and the report published
141.8 tok/s/u against a true ~71. Clearing the coverage and knob caches did not touch it: it lives in
the persistent measurement ledger, and the run that "started fresh" inherited a ceiling pinned days
earlier. The model then reads as twice as close to the hardware wall as it is, which is the input to
can_stop.

WHAT IS DELIBERATELY KEPT. Hardware facts are not run state: the board topology and the device
recovery record describe the machine, not this attempt, and re-deriving them costs device time for no
gain. Everything else here is a memory OF a run and is safe to lose -- expensive to rebuild, never
wrong to rebuild.

NOTHING TRACKED BY GIT IS TOUCHED. Model source is reverted by the run's own reset step, which git can
undo; this removes only generated state, so a mistake here costs a slow run and never a lost edit.
"""

from __future__ import annotations

import shutil
from pathlib import Path

# Run memory: keyed by model+task, rebuilt by the next run at the cost of device time.
_STATE_GLOBS = (
    "perf_measurements_*.jsonl",  # THE ANCHOR LIVES HERE -- ceiling bytes, BEFORE/AFTER e2e
    "perf_measurements_*.jsonl.lock",
    "perf_mcp_baseline_*.json",
    "perf_mcp_full_pipeline_baseline_1cq_*.json",
    "perf_mcp_throughput_*.json",
    "perf_mcp_stage_ms_*.json",
    "perf_mcp_gate_verdicts_*.json",
    "perf_mcp_fullpipe_consumed_*.json",
    "perf_mcp_knob_cache.json",
    "perf_integrity_resolve_cache.json",
    "perf_mcp_thermal_profile.json",  # a LEARNED threshold: 68.6C, from samples its own clean reading contradicts
    "perf_mcp_fullpipe_gate.log",
    "cc_kernlog_*.json",
    "cc_kernlog_*.json.cumulative",
    "cc_kernlog_*.json.target",
    "cc_kernlog_*.agent.log",
    "perftest_*.agent.log",
)
_STATE_DIRS = ("perf_mcp_profile_cache", "perf_mcp_last_profile")

# The machine, not the run. Re-deriving these costs device time and answers the same thing.
KEEP = ("perf_mcp_board_topology.json", "tt_device_recovery_model_main.json")

# Caches the tool writes beside its own source.
_TOOL_GLOBS = ("cc_optimize/.coverage_cache.json", "cc_optimize/.mcp_config_*.json")

# Generated by a previous run into the model directory; untracked, so git will not restore them.
_MODEL_GLOBS = (
    "perf_target_inputs.json",
    "tests/e2e/*_perf.py.trace_caps.json",
)


def plan(state_dir, tool_root=None, model_dir=None) -> list:
    """Every path `--fresh` would remove, in the order it would remove them. Nothing is deleted."""
    out: list = []
    sd = Path(state_dir) if state_dir else None
    if sd and sd.is_dir():
        for pat in _STATE_GLOBS:
            out += [p for p in sorted(sd.glob(pat)) if p.name not in KEEP]
        for name in _STATE_DIRS:
            p = sd / name
            if p.exists():
                out.append(p)
    if tool_root:
        for pat in _TOOL_GLOBS:
            out += sorted(Path(tool_root).glob(pat))
    if model_dir:
        for pat in _MODEL_GLOBS:
            out += sorted(Path(model_dir).glob(pat))
    return out


def wipe(state_dir, tool_root=None, model_dir=None, dry_run: bool = False) -> list:
    """Remove the run's memory. Returns what was removed (or would be, when dry_run)."""
    removed = []
    for p in plan(state_dir, tool_root, model_dir):
        if dry_run:
            removed.append(p)
            continue
        try:
            if p.is_dir():
                shutil.rmtree(p)
            else:
                p.unlink()
            removed.append(p)
        except OSError:
            continue
    return removed


def describe(removed) -> str:
    if not removed:
        return "nothing to clear -- this model has no run memory"
    return "cleared %d item(s) of run memory:\n%s" % (
        len(removed),
        "\n".join("      - %s" % p for p in removed),
    )

"""Issue 2: depth-knob discovery asked an agent a question the tool already knew the answer to,
over a prompt that had been truncated past the answer.

Two compounding defects, both observed on llama3_1_8b_p150 (2026-07-30):

1. The perf test is GENERATED BY THIS TOOL, and the template hardcodes
   ``os.environ.get("TT_PERF_LAYERS")`` (agent/perf_test_gen.py). So the tool sent an agent the
   model's source and asked "which env var caps the layer count?" -- about a variable it injects
   itself. The answer is knowable by reading the tree, with no agent call at all.

2. The prompt concatenated ``tt/*.py`` in ALPHABETICAL order and broke out once the total passed
   60,000 chars -- appending first, then checking. On this model ``attention.py`` (56 KB) and
   ``ccl.py`` (18 KB) blew the cap before ``pipeline.py`` was reached, and pipeline.py:70 is the
   ONE line that reads TT_PERF_LAYERS. The agent was shown a body of source that genuinely does
   not answer the question, correctly replied ``{}`` four times, and the tool then fabricated a
   knob on attempt five.

A prompt built from the env-READ lines cannot be truncated past the answer, because the answer is
one of those lines.
"""

import importlib.util
import sys
from pathlib import Path

import pytest

_PA = Path(__file__).resolve().parent.parent
_CC = _PA / "cc_optimize"


def _mod():
    sys.path.insert(0, str(_PA))
    spec = importlib.util.spec_from_file_location("cc_run_knob", str(_CC / "run.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def _model(tmp_path, files):
    tt = tmp_path / "tt"
    tt.mkdir(parents=True, exist_ok=True)
    for name, body in files.items():
        (tt / name).write_text(body)
    return tmp_path


_READS_LAYERS = "import os\n_perf_layers = os.environ.get('TT_PERF_LAYERS')\n"


@pytest.fixture
def no_agent(monkeypatch):
    """Any agent call during these tests is itself the failure."""
    m = _mod()
    calls = []

    def _boom(prompt):
        calls.append(prompt)
        return "{}"

    monkeypatch.setattr(m, "_claude_text", _boom)
    monkeypatch.setattr(m, "_knob_cache_get", lambda *_a, **_k: None)
    monkeypatch.setattr(m, "_knob_cache_put", lambda *_a, **_k: None)
    return m, calls


def test_tool_generated_convention_needs_no_agent(tmp_path, no_agent):
    m, calls = no_agent
    root = _model(tmp_path, {"pipeline.py": _READS_LAYERS})
    got = m._llm_depth_env(root, 4)
    assert got == {"TT_PERF_LAYERS": "4"}, f"expected the tool's own convention, got {got}"
    assert not calls, (
        "the tool asked an agent which env var caps layers -- but the model already reads "
        "TT_PERF_LAYERS, which is the variable THIS TOOL injects. No agent call is warranted."
    )


def test_the_llama_truncation_regression(tmp_path, no_agent):
    """attention.py (56 KB) + ccl.py (18 KB) sort before pipeline.py and blow a 60 KB budget.
    The answer lives in pipeline.py, so a size-truncated alphabetical dump loses it."""
    m, calls = no_agent
    root = _model(
        tmp_path,
        {
            "attention.py": "# pad\n" + ("x = 1\n" * 9000),  # ~56 KB
            "ccl.py": "# pad\n" + ("y = 2\n" * 3000),  # ~18 KB
            "pipeline.py": _READS_LAYERS,
        },
    )
    got = m._llm_depth_env(root, 8)
    assert got == {
        "TT_PERF_LAYERS": "8"
    }, f"pipeline.py's TT_PERF_LAYERS was not found behind 74 KB of other sources; got {got}"
    assert not calls


def test_depth_var_in_any_file_is_found(tmp_path, no_agent):
    m, calls = no_agent
    root = _model(tmp_path, {"zzz_last_alphabetically.py": _READS_LAYERS})
    assert m._llm_depth_env(root, 2) == {"TT_PERF_LAYERS": "2"}
    assert not calls


def test_getenv_spelling_is_recognised(tmp_path, no_agent):
    m, calls = no_agent
    root = _model(tmp_path, {"p.py": 'import os\nn = os.getenv("TT_PERF_LAYERS")\n'})
    assert m._llm_depth_env(root, 16) == {"TT_PERF_LAYERS": "16"}
    assert not calls


def test_model_without_the_convention_still_asks(tmp_path, monkeypatch):
    """A model that genuinely exposes no tool-convention knob must still fall through to the agent
    -- this fix removes a needless question, it does not remove the capability."""
    m = _mod()
    seen = {}

    def _fake(prompt):
        seen["prompt"] = prompt
        return '{"MY_MODEL_LAYERS": "3"}'

    monkeypatch.setattr(m, "_claude_text", _fake)
    monkeypatch.setattr(m, "_knob_cache_get", lambda *_a, **_k: None)
    monkeypatch.setattr(m, "_knob_cache_put", lambda *_a, **_k: None)
    root = _model(tmp_path, {"p.py": 'import os\nn = os.environ.get("MY_MODEL_LAYERS")\n'})
    got = m._llm_depth_env(root, 3)
    assert got == {"MY_MODEL_LAYERS": "3"}
    assert "prompt" in seen, "the agent path must still be reachable"


def test_prompt_carries_the_env_lines_even_from_a_huge_tree(tmp_path, monkeypatch):
    """When the agent IS asked, the prompt must contain the env-read line no matter how large the
    tree is. This is the truncation defect stated as a property."""
    m = _mod()
    seen = {}

    def _fake(prompt):
        seen["prompt"] = prompt
        return "{}"

    monkeypatch.setattr(m, "_claude_text", _fake)
    monkeypatch.setattr(m, "_knob_cache_get", lambda *_a, **_k: None)
    monkeypatch.setattr(m, "_knob_cache_put", lambda *_a, **_k: None)
    monkeypatch.setenv("PERF_MCP_KNOB_RETRIES", "1")
    root = _model(
        tmp_path,
        {
            "aaa_huge.py": "# pad\n" + ("x = 1\n" * 40000),  # ~250 KB, sorts first
            "zzz_answer.py": 'import os\nn = os.environ.get("WEIRD_DEPTH_CAP")\n',
        },
    )
    m._llm_depth_env(root, 2)
    assert "WEIRD_DEPTH_CAP" in seen["prompt"], (
        "the env-read line was truncated out of the prompt by a large unrelated file -- exactly "
        "the llama3_1_8b_p150 failure"
    )

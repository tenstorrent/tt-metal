"""TTNN decoder layer for Qwen3-Coder-30B-A3B-Instruct.

Built bottom-up and validated piece by piece against the layer-only HuggingFace
reference in ``tests/reference.py``. Attention lands first; the MoE block and
the composed layer follow.

Shape of this model's attention
-------------------------------
    hidden 2048 | 32 Q heads | 4 KV heads (8:1 GQA) | head_dim 128

``32 * 128 = 4096 != hidden``, so ``o_proj`` is ``[2048, 4096]`` -- head_dim is
an independent config field here, not ``hidden / n_heads``. There is no
attention bias and no sliding window, so every layer is plain causal attention.

Two Qwen3-specific things the more common Llama-shaped ports do not have:

  * **QK-norm.** An RMSNorm over ``head_dim`` is applied per head to Q and to K,
    after the head split and *before* RoPE. Note it is Q and K only -- gemma4,
    which this file follows closely, additionally norms V because Gemma has a
    ``v_norm``. Qwen3 does not; adding it there would silently corrupt V.

  * **RoPE theta lives in ``rope_scaling``.** ``config.rope_theta`` does not
    exist on this checkpoint; the value (1e7, the long-context setting) is
    nested at ``config.rope_scaling["rope_theta"]``. Rather than reach in and
    risk a stale default, the cos/sin cache is produced by
    ``Qwen3MoeRotaryEmbedding`` itself, which is correct by construction.

RoPE convention is HF-style throughout -- see the note in ``weight_mapping.py``.
Weights therefore keep their checkpoint channel order.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import torch

import ttnn


@dataclass(frozen=True)
class AttentionConfig:
    hidden_size: int
    num_attention_heads: int
    num_key_value_heads: int
    head_dim: int
    rms_norm_eps: float

    @classmethod
    def from_hf(cls, config) -> "AttentionConfig":
        assert not getattr(config, "attention_bias", False), "attention bias is not wired up"
        assert not getattr(config, "use_sliding_window", False), "sliding-window attention is not wired up"
        return cls(
            hidden_size=config.hidden_size,
            num_attention_heads=config.num_attention_heads,
            num_key_value_heads=config.num_key_value_heads,
            head_dim=config.head_dim,
            rms_norm_eps=config.rms_norm_eps,
        )


@dataclass
class AttentionWeights:
    """Device-resident attention weights, as produced by ``weight_mapping``."""

    wqkv: ttnn.Tensor  # [1, 1, hidden, (n_heads + 2*n_kv_heads) * head_dim]
    wo: ttnn.Tensor  # [1, 1, n_heads * head_dim, hidden]
    q_norm: ttnn.Tensor  # [1, 1, 1, head_dim]
    k_norm: ttnn.Tensor  # [1, 1, 1, head_dim]


def build_rope_cache(hf_config, max_seq_len: int, device) -> tuple[ttnn.Tensor, ttnn.Tensor]:
    """Upload a ``[1, 1, max_seq_len, head_dim]`` cos/sin pair for HF-style RoPE.

    Generated by the reference rotary module so ``rope_theta`` (and any future
    scaling) can never drift from the checkpoint.
    """
    from ..tests.reference import rotary_embeddings

    cos, sin = rotary_embeddings(hf_config, max_seq_len)  # [1, S, head_dim]
    out = []
    for t in (cos, sin):
        out.append(
            ttnn.from_torch(
                t.unsqueeze(0).float(),
                dtype=ttnn.bfloat16,
                layout=ttnn.TILE_LAYOUT,
                device=device,
                memory_config=ttnn.DRAM_MEMORY_CONFIG,
            )
        )
    return out[0], out[1]


def _per_head_rms_norm(tensor: ttnn.Tensor, weight: ttnn.Tensor, eps: float) -> ttnn.Tensor:
    """RMSNorm over the last dim, applied independently per head.

    ``ttnn.rms_norm`` normalises the last dimension of a 2D-ish tile grid, so
    the heads are folded into the row dimension and unfolded afterwards.
    Input/output ``[1, n_heads, seq, head_dim]``.
    """
    shape = tensor.shape
    flat = ttnn.reshape(tensor, (1, 1, shape[1] * shape[2], shape[3]))
    normed = ttnn.rms_norm(flat, weight=weight, epsilon=eps)
    return ttnn.reshape(normed, shape)


def _apply_rope(tensor: ttnn.Tensor, cos_cache, sin_cache, token_index=None) -> ttnn.Tensor:
    """HF-style rotary embedding, restoring the logical dim-2 length afterwards.

    The op pads dim 2 up to a tile multiple, and dim 2 means different things in
    the two modes -- which makes this a hazard twice over:

    * **decode**: dim 2 is the head count. Q already has 32 heads so nothing
      happens, but K has only ``num_kv_heads`` = 4 and comes back 32-deep. The
      reshape declares logical-vs-padded before slicing, following the
      tt_transformers ``_hf_rope_decode`` pattern.

    * **prefill**: dim 2 is the sequence. At a non-tile-aligned length (say 33)
      Q and K return padded to 64 while **V never passes through RoPE** and
      stays 33, so SDPA rejects them with "K and V sequence length must match".
      Slicing back is what keeps odd prompt lengths working.
    """
    orig = tensor.shape
    out = ttnn.experimental.rotary_embedding(tensor, cos_cache, sin_cache, token_index)
    if out.shape[2] != orig[2]:
        if token_index is not None:
            out = ttnn.reshape(out, (orig[0], orig[1], orig[2], orig[3]), (orig[0], orig[1], 32, orig[3]))
            out = out[:, :, : orig[2]]
        else:
            out = ttnn.slice(out, [0, 0, 0, 0], [orig[0], orig[1], orig[2], orig[3]])
    return out


def rope_transformation_matrix() -> "torch.Tensor":
    """The 32x32 matrix ``rotary_embedding_llama`` rotates a tile row with.

    ``+1`` at ``(2i, 2i+1)`` and ``-1`` at ``(2i+1, 2i)`` -- i.e. the Meta
    channel pairing, expressed as a matmul so the kernel needs no gather. This
    is what makes the llama op cheaper than the HF one at the same core count:
    the HF op reads a cos/sin row out of a DRAM cache per call, this one
    multiplies by a resident 32x32 tile.
    """
    import torch

    d = 32
    m = torch.zeros(1, 1, d, d)
    m[..., torch.arange(0, d, 2), torch.arange(1, d, 2)] = 1
    m[..., torch.arange(1, d, 2), torch.arange(0, d, 2)] = -1
    return m


def apply_rope_llama(tensor: ttnn.Tensor, cos_shard, sin_shard, trans_mat) -> ttnn.Tensor:
    """Meta-style rotary embedding, decode mode.

    ``tensor``, ``cos_shard`` and ``sin_shard`` must all be the height-sharded
    ``[1, batch, 32, head_dim]`` L1 config ``nlp_create_qkv_heads_decode``
    produces, and ``tensor`` must be in **Meta** channel order -- which is a
    property of the *weights*, established once at upload by
    ``weight_mapping.permute_wqkv_to_meta``, not of anything done here.

    Measured against ``_apply_rope`` at the shipped per-die decode shape:
    3.84 -> 1.26 us, ``max|diff|`` exactly 0.0 and PCC 1.0000000
    (``doc/optimized_multichip_decoder/probes/rope_probe.py``).

    Unlike ``_apply_rope`` this needs **no** reshape-and-slice afterwards: the
    op is shape-preserving in decode mode, so the dim-2 padding hazard that
    ``_apply_rope`` documents does not arise.
    """
    return ttnn.experimental.rotary_embedding_llama(tensor, cos_shard, sin_shard, trans_mat, is_decode_mode=True)


def _concat_heads_decode(attn: ttnn.Tensor, config: AttentionConfig) -> ttnn.Tensor:
    """Merge heads in decode mode. ``attn`` ``[1, batch, num_heads, head_dim]``.

    ``nlp_concat_heads_decode`` is the multi-core decode variant and requires a
    height-sharded input with one core per user, whereas SDPA-decode hands back
    a DRAM interleaved tensor -- hence the reshard. The op also pads batch up to
    a full tile, so the result is sliced back to the logical batch.
    """
    batch = attn.shape[1]

    grid_x = min(batch, 8)
    while batch % grid_x:
        grid_x -= 1
    grid_y = batch // grid_x
    core_grid = ttnn.CoreRangeSet({ttnn.CoreRange(ttnn.CoreCoord(0, 0), ttnn.CoreCoord(grid_x - 1, grid_y - 1))})
    shard_cfg = ttnn.create_sharded_memory_config(
        shape=(ttnn.TILE_SIZE, config.head_dim),
        core_grid=core_grid,
        strategy=ttnn.ShardStrategy.HEIGHT,
        orientation=ttnn.ShardOrientation.ROW_MAJOR,
        use_height_and_width_as_shard_shape=True,
    )

    sharded = ttnn.to_memory_config(attn, shard_cfg)
    out = ttnn.experimental.nlp_concat_heads_decode(sharded, num_heads=config.num_attention_heads)
    ttnn.deallocate(sharded)
    out = ttnn.sharded_to_interleaved(out, ttnn.DRAM_MEMORY_CONFIG)
    if out.shape[2] != batch:
        out = out[:, :, :batch, :]
    return out


@dataclass
class KVCache:
    """K/V cache, either contiguous per user or paged through a block table.

    Paged mode is what a serving stack actually uses: logical positions are
    mapped to physical blocks by ``page_table``, so users can share a block pool
    instead of each reserving ``max_seq_len``. Both modes are kept because they
    exercise different kernels -- ``paged_*`` ops versus their contiguous
    counterparts -- and the contiguous path is the simpler thing to bisect
    against when a paged result looks wrong.
    """

    k: ttnn.Tensor
    v: ttnn.Tensor
    page_table: ttnn.Tensor | None = None
    block_size: int = 0

    @property
    def is_paged(self) -> bool:
        return self.page_table is not None


def create_kv_cache(
    device,
    config: AttentionConfig,
    max_batch: int,
    max_seq_len: int,
    block_size: int | None = None,
) -> KVCache:
    """Allocate a KV cache.

    ``block_size=None`` gives a contiguous cache of
    ``[max_batch, n_kv_heads, max_seq_len, head_dim]``. Passing a block size
    switches to a paged cache of ``[num_blocks, n_kv_heads, block_size,
    head_dim]`` with an identity page table -- block ``b`` of user ``u`` lives
    at physical block ``u * blocks_per_seq + b``. A real scheduler would hand
    out blocks from a free pool; the identity mapping keeps the plumbing honest
    (every op still goes through the table) without pulling a block allocator
    into the decoder.
    """
    n_kv, head_dim = config.num_key_value_heads, config.head_dim

    if block_size is None:
        shape = (max_batch, n_kv, max_seq_len, head_dim)
        page_table = None
    else:
        blocks_per_seq = math.ceil(max_seq_len / block_size)
        shape = (max_batch * blocks_per_seq, n_kv, block_size, head_dim)
        page_table = ttnn.from_torch(
            torch.arange(max_batch * blocks_per_seq, dtype=torch.int32).reshape(max_batch, blocks_per_seq),
            dtype=ttnn.int32,
            layout=ttnn.ROW_MAJOR_LAYOUT,
            device=device,
        )

    k, v = (
        ttnn.from_torch(
            torch.zeros(shape),
            dtype=ttnn.bfloat16,
            layout=ttnn.TILE_LAYOUT,
            device=device,
            memory_config=ttnn.DRAM_MEMORY_CONFIG,
        )
        for _ in range(2)
    )
    return KVCache(k=k, v=v, page_table=page_table, block_size=block_size or 0)


def match_cache_dtype(cache: ttnn.Tensor, x: ttnn.Tensor) -> ttnn.Tensor:
    """Return ``x`` in the cache tensor's dtype, casting only if they differ.

    **For the fill (prefill) writers only.** The two cache writers have
    *opposite* dtype contracts, and neither says so out loud, which is how
    stage 07's ``R19_kv_bfp8`` came to score at chance.
    ``doc/datatype_sweep/probes/kv_bfp8_diagnosis.py`` measures both at the op
    level, with no model:

    ==================  ============  ============  =============================
    op                  cache         input         round-trip PCC
    ==================  ============  ============  =============================
    paged_fill_cache    bfloat16      bfloat16      1.0 (control)
    paged_fill_cache    bfloat8_b     bfloat16      **NaN**
    paged_fill_cache    bfloat8_b     bfloat8_b     1.0
    paged_update_cache  bfloat16      bfloat16      1.0 (control)
    paged_update_cache  bfloat8_b     bfloat16      0.999969
    paged_update_cache  bfloat8_b     bfloat8_b     **rejected by the op**
    ==================  ============  ============  =============================

    So ``paged_fill_cache`` needs the input cast **to** the cache dtype -- it
    validates the input against a permissive ``OR`` that a mismatch satisfies,
    and then writes NaN -- while ``paged_update_cache`` needs the input left
    **alone**: it converts into the cache itself and hard-rejects a block-float
    input (``paged_update_cache_device_operation.cpp:296``, *"Data type of input
    tensor for update cache must be FLOAT32 or BFLOAT16"*). Casting at the
    decode writer would turn silent corruption into a hard crash, which is why
    this helper is applied at the fill sites and deliberately not at the update
    sites.

    Taking the dtype off the **cache tensor itself** rather than off
    ``precision.kv_cache_dtype`` keeps the guarantee true by construction: the
    thing the write must agree with is the allocated cache, and this cannot
    drift from it even if a caller allocates a cache some other way.

    The cast is a no-op in the shipped configuration (``kv_cache_dtype ==
    activation_dtype == bfloat16``), so it costs nothing unless the cache dtype
    is actually moved.
    """
    if x.dtype == cache.dtype:
        return x
    return ttnn.typecast(x, cache.dtype, memory_config=x.memory_config())


def _fill_cache(kv_cache: KVCache, k: ttnn.Tensor, v: ttnn.Tensor, user_id: int) -> None:
    """Write a whole prompt's K/V into the cache.

    The paged kernel writes block-at-a-time, so a prompt that does not fill its
    last block is zero-padded up to a block boundary first. Those trailing
    positions are never read: decode passes ``cur_pos``, and SDPA only attends
    up to it.

    K/V are cast to the cache's own dtype before the write -- see
    :func:`match_cache_dtype` for why the ops will not do it for us. The cast
    goes *after* the pad, because ``ttnn.pad`` is a bfloat16/float32 op.
    """
    if not kv_cache.is_paged:
        ttnn.fill_cache(kv_cache.k, match_cache_dtype(kv_cache.k, k), user_id)
        ttnn.fill_cache(kv_cache.v, match_cache_dtype(kv_cache.v, v), user_id)
        return

    seq_len = k.shape[2]
    padded = math.ceil(seq_len / kv_cache.block_size) * kv_cache.block_size
    if padded != seq_len:
        pad = [(0, 0), (0, 0), (0, padded - seq_len), (0, 0)]
        k = ttnn.pad(k, pad, value=0.0)
        v = ttnn.pad(v, pad, value=0.0)

    ttnn.experimental.paged_fill_cache(
        kv_cache.k, match_cache_dtype(kv_cache.k, k), kv_cache.page_table, batch_idx=user_id
    )
    ttnn.experimental.paged_fill_cache(
        kv_cache.v, match_cache_dtype(kv_cache.v, v), kv_cache.page_table, batch_idx=user_id
    )


def attention_decode(
    x: ttnn.Tensor,
    weights: AttentionWeights,
    config: AttentionConfig,
    cos_cache: ttnn.Tensor,
    sin_cache: ttnn.Tensor,
    kv_cache: KVCache,
    current_pos: ttnn.Tensor,
    token_index: int,
    compute_kernel_config=None,
) -> ttnn.Tensor:
    """Single-token attention against the KV cache.

    ``x`` is ``[1, 1, batch, hidden]`` and the return matches. ``current_pos``
    is an int32 tensor of shape ``[batch]`` holding each user's write position;
    ``token_index`` is the same value as a Python int, needed because the
    rotary op takes a scalar rather than a tensor.
    """
    k_cache, v_cache, page_table = kv_cache.k, kv_cache.v, kv_cache.page_table

    xqkv = ttnn.linear(
        x,
        weights.wqkv,
        dtype=ttnn.bfloat16,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
        compute_kernel_config=compute_kernel_config,
    )

    # Blackhole: nlp_create_qkv_heads_decode's interleaved reader zeroes
    # odd-indexed Q rows when the fused input sits in DRAM, due to a NoC
    # DRAM-read alignment violation (tt-metal #16667). Staging through L1 takes
    # a different code path and is unaffected. No-op on Wormhole.
    if xqkv.memory_config().buffer_type == ttnn.BufferType.DRAM:
        xqkv = ttnn.to_memory_config(xqkv, ttnn.L1_MEMORY_CONFIG)

    q, k, v = ttnn.experimental.nlp_create_qkv_heads_decode(
        xqkv,
        num_heads=config.num_attention_heads,
        num_kv_heads=config.num_key_value_heads,
        memory_config=ttnn.L1_HEIGHT_SHARDED_MEMORY_CONFIG,
    )
    ttnn.deallocate(xqkv)

    # The decode ops disagree about layout: rms_norm wants interleaved DRAM,
    # while paged_update_cache requires a *sharded* update tensor
    # (paged_update_cache_device_operation.cpp:255). So remember the sharded
    # config the split produced and restore it once the norm and RoPE are done.
    kv_sharded_mem = k.memory_config()

    q = _per_head_rms_norm(ttnn.to_memory_config(q, ttnn.DRAM_MEMORY_CONFIG), weights.q_norm, config.rms_norm_eps)
    k = _per_head_rms_norm(ttnn.to_memory_config(k, ttnn.DRAM_MEMORY_CONFIG), weights.k_norm, config.rms_norm_eps)

    q = _apply_rope(q, cos_cache, sin_cache, token_index=token_index)
    k = _apply_rope(k, cos_cache, sin_cache, token_index=token_index)

    k = ttnn.to_memory_config(k, kv_sharded_mem)  # v never left the sharded layout
    # page_table=None is the contiguous path; the same op serves both.
    # NOT cast to the cache dtype -- unlike the fill writers above.
    # ``paged_update_cache`` requires a FLOAT32/BFLOAT16 update and converts into
    # the cache itself; handing it a block-float input is rejected outright
    # (``paged_update_cache_device_operation.cpp:296``). Measured both ways in
    # ``doc/datatype_sweep/probes/kv_bfp8_diagnosis.json``. See
    # :func:`match_cache_dtype`.
    ttnn.experimental.paged_update_cache(k_cache, k, update_idxs_tensor=current_pos, page_table=page_table)
    ttnn.experimental.paged_update_cache(v_cache, v, update_idxs_tensor=current_pos, page_table=page_table)
    ttnn.deallocate(k)
    ttnn.deallocate(v)

    if kv_cache.is_paged:
        attn = ttnn.transformer.paged_scaled_dot_product_attention_decode(
            q,
            k_cache,
            v_cache,
            page_table_tensor=page_table,
            cur_pos_tensor=current_pos,
            scale=config.head_dim**-0.5,
            memory_config=ttnn.DRAM_MEMORY_CONFIG,
        )
    else:
        attn = ttnn.transformer.scaled_dot_product_attention_decode(
            q,
            k_cache,
            v_cache,
            cur_pos_tensor=current_pos,
            scale=config.head_dim**-0.5,
            memory_config=ttnn.DRAM_MEMORY_CONFIG,
        )
    ttnn.deallocate(q)

    attn = _concat_heads_decode(attn, config)
    out = ttnn.linear(
        attn,
        weights.wo,
        dtype=ttnn.bfloat16,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
        compute_kernel_config=compute_kernel_config,
    )
    ttnn.deallocate(attn)
    return out


def attention_prefill(
    x: ttnn.Tensor,
    weights: AttentionWeights,
    config: AttentionConfig,
    cos_cache: ttnn.Tensor,
    sin_cache: ttnn.Tensor,
    kv_cache: KVCache | None = None,
    user_id: int = 0,
    compute_kernel_config=None,
    sdpa_program_config=None,
    activation_dtype=ttnn.bfloat16,
) -> ttnn.Tensor:
    """Causal self-attention over a full sequence. ``x``/return ``[1, 1, S, hidden]``.

    When ``kv_cache`` is given, the post-RoPE K and V for the whole sequence are
    written into it so a decode pass can continue from position S.

    ``sdpa_program_config`` is passed straight through to the prefill SDPA op and
    defaults to ``None`` -- the op default, which is what **every** caller
    currently uses, including the multichip path, and what every number in this
    file was measured at. It is a seam, exactly like
    ``attention_decode_optimized``'s: stage 06 used it to build and measure a
    length-dependent chunking worth 6.3-6.8x on this op at S >= 4096, and then
    **did not adopt it** because it costs a top-1 point on ``run_teacher_forcing``
    and buys nothing at the 158-token prompt that gate uses. See
    ``multichip_decoder._sdpa_prefill_program_config`` for the numbers and for
    what it would take to adopt.

    ``activation_dtype`` is the dtype the two projections emit. It defaults to
    ``ttnn.bfloat16``, which is the literal that used to be written here, so
    every existing caller is unchanged; the multichip prefill layer passes
    ``precision.activation_dtype`` so that field reaches prefill attention and
    not only decode.
    """
    xqkv = ttnn.linear(
        x,
        weights.wqkv,
        dtype=activation_dtype,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
        compute_kernel_config=compute_kernel_config,
    )

    q, k, v = ttnn.experimental.nlp_create_qkv_heads(
        xqkv,
        num_heads=config.num_attention_heads,
        num_kv_heads=config.num_key_value_heads,
        transpose_k_heads=False,  # SDPA wants [.., S, head_dim], not a pre-transposed K
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
    )
    ttnn.deallocate(xqkv)

    # QK-norm, then RoPE -- this order is what Qwen3MoeAttention.forward does.
    q = _per_head_rms_norm(q, weights.q_norm, config.rms_norm_eps)
    k = _per_head_rms_norm(k, weights.k_norm, config.rms_norm_eps)

    q = _apply_rope(q, cos_cache, sin_cache)
    k = _apply_rope(k, cos_cache, sin_cache)

    # Seed the cache with the prompt's post-RoPE K/V so decode can continue.
    if kv_cache is not None:
        _fill_cache(kv_cache, k, v, user_id=user_id)

    # GQA is handled inside SDPA: it broadcasts the 4 KV heads across 32 Q heads.
    # Default scale is head_dim ** -0.5, which is what Qwen3 uses.
    attn = ttnn.transformer.scaled_dot_product_attention(q, k, v, is_causal=True, program_config=sdpa_program_config)
    for t in (q, k, v):
        ttnn.deallocate(t)

    attn = ttnn.experimental.nlp_concat_heads(attn, memory_config=ttnn.DRAM_MEMORY_CONFIG)
    out = ttnn.linear(
        attn,
        weights.wo,
        dtype=activation_dtype,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
        compute_kernel_config=compute_kernel_config,
    )
    ttnn.deallocate(attn)
    return out


@dataclass(frozen=True)
class MoEConfig:
    hidden_size: int
    num_experts: int
    num_experts_per_tok: int
    moe_intermediate_size: int
    norm_topk_prob: bool

    @classmethod
    def from_hf(cls, config) -> "MoEConfig":
        assert config.hidden_act == "silu", f"expected silu, got {config.hidden_act}"
        assert config.decoder_sparse_step == 1 and not config.mlp_only_layers, "every layer is expected to be MoE"
        return cls(
            hidden_size=config.hidden_size,
            num_experts=config.num_experts,
            num_experts_per_tok=config.num_experts_per_tok,
            moe_intermediate_size=config.moe_intermediate_size,
            norm_topk_prob=config.norm_topk_prob,
        )


def router_forward(x: ttnn.Tensor, w_router: ttnn.Tensor, config: MoEConfig) -> ttnn.Tensor:
    """Dense routing weights ``[1, 1, S, num_experts]``: top-k weights, zeros elsewhere.

    Returning a *dense* tensor rather than (values, indices) keeps everything on
    device and trace-compatible -- the experts consume it as a sparsity pattern
    and as the post-hoc scaling factor.

    Selection happens on the **raw logits**, not on softmax probabilities, and
    the softmax is taken over the 8 survivors only. That is algebraically the
    same answer HF computes, and numerically a far better one.

    Why it is the same answer. Softmax is monotonic, so the top-k of the
    probabilities is the top-k of the logits -- the 128-wide softmax cannot
    change *who* wins. And with ``norm_topk_prob`` the shared denominator
    cancels out of the renormalisation::

        w_i = [exp(x_i)/Z] / sum_{j in top8}[exp(x_j)/Z]
            =  exp(x_i)     / sum_{j in top8} exp(x_j)

    so ``Z``, the sum over all 128 experts, is never needed. (This cancellation
    is what makes the rewrite legal; it does **not** hold if
    ``norm_topk_prob`` is False, hence the assert.)

    Why it is a better answer. Measured on this checkpoint with a 128-token
    activation sample:

        ttnn.topk on fp32 logits ............ 0/128 tokens misrouted (exact)
        ttnn.topk on fp32 softmax probs ..... 0/128 (topk itself is fine)
        ttnn.softmax fp32 vs torch fp32 ..... max abs error 3.3e-4

    The last line is the problem. Softmax over 128 experts leaves the 8th-place
    probability near 0.008 with only ~1.4e-5 separating it from the 9th, so a
    3.3e-4 error decides the cut by luck -- and ``ttnn.softmax`` carries that
    error even when handed an fp32 tensor, so no dtype change rescues it.
    Routing through the full softmax cost 34/128 misrouted tokens (83/128 with
    a bf16 softmax, dense PCC 0.88). Comparing logits sidesteps it: the gaps
    there are ordinary-sized.

    The projection stays bf16 -- it is accurate to PCC 0.9999973 and costs only
    3/128 on its own -- but it accumulates into fp32 so the comparison is clean.
    Weights are cast to bf16 for the scatter, which has no fp32 tiled support;
    that is harmless, since representing a weight to 0.4% is not the same
    problem as deciding which weights exist.
    """
    assert config.norm_topk_prob, (
        "router selects on raw logits, which relies on the softmax denominator "
        "cancelling during top-k renormalisation; that only holds when "
        "norm_topk_prob is True"
    )

    logits = ttnn.linear(x, w_router, dtype=ttnn.float32, memory_config=ttnn.DRAM_MEMORY_CONFIG)

    top_logits, top_indices = ttnn.topk(logits, k=config.num_experts_per_tok, dim=-1)

    # softmax over the 8 survivors, written out rather than calling
    # ttnn.softmax so the reduction is the ttnn.sum already exercised by
    # test_router_weights_sum_to_one. Subtracting the max is for exp() range
    # only; any shared shift cancels in the division.
    top_max = ttnn.max(top_logits, dim=-1, keepdim=True)
    exp_logits = ttnn.exp(ttnn.sub(top_logits, top_max))
    total = ttnn.sum(exp_logits, dim=-1, keepdim=True)
    top_values = ttnn.div(exp_logits, total)

    zeros = ttnn.typecast(ttnn.zeros_like(logits), ttnn.bfloat16)
    dense = ttnn.scatter(
        zeros,
        dim=-1,
        index=top_indices,
        src=ttnn.typecast(top_values, ttnn.bfloat16),
    )
    for t in (logits, top_logits, top_indices, top_max, exp_logits, total, top_values):
        ttnn.deallocate(t)
    return dense


def upload_router_weight(router: torch.Tensor, device) -> ttnn.Tensor:
    """``[num_experts, hidden]`` checkpoint tensor -> ``[1, 1, hidden, num_experts]``."""
    return ttnn.from_torch(
        router.T.contiguous().reshape(1, 1, router.shape[1], router.shape[0]).float(),
        dtype=ttnn.bfloat16,
        layout=ttnn.TILE_LAYOUT,
        device=device,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
    )


@dataclass
class ExpertWeights:
    gate_proj: ttnn.Tensor  # [1, num_experts, hidden, intermediate]
    up_proj: ttnn.Tensor  # [1, num_experts, hidden, intermediate]
    down_proj: ttnn.Tensor  # [1, num_experts, intermediate, hidden]


def upload_expert_weights(torch_weights: dict[str, torch.Tensor], device, config: MoEConfig) -> ExpertWeights:
    """Unfuse and transpose the batched expert tensors into sparse_matmul layout.

    ``weight_mapping`` keeps the checkpoint's fused ``[E, 2I, H]`` form because
    that is what the HF module holds and what the reference test validates
    against. ``sparse_matmul`` wants them separate and transposed, so the split
    happens here rather than at conversion time -- the fusion order stays
    guarded by ``test_moe_matches_unfused_reimplementation``.
    """
    fused = torch_weights["experts_gate_up"]  # [E, 2I, H], gate first
    inter = config.moe_intermediate_size

    # bf16 while correctness is being established, so a PCC miss means a bug
    # rather than quantisation. bfloat8_b is the intended production dtype
    # (gemma4 and gpt_oss both ship it) and is a later, measurable step -- one
    # layer's experts are ~604M params, 1.2GB at bf16, which fits comfortably.
    def up(t: torch.Tensor) -> ttnn.Tensor:
        return ttnn.from_torch(
            t.contiguous().float(),
            dtype=ttnn.bfloat16,
            layout=ttnn.TILE_LAYOUT,
            device=device,
            memory_config=ttnn.DRAM_MEMORY_CONFIG,
        )

    return ExpertWeights(
        gate_proj=up(fused[:, :inter, :].transpose(-2, -1).unsqueeze(0)),
        up_proj=up(fused[:, inter:, :].transpose(-2, -1).unsqueeze(0)),
        # checkpoint down_proj is [E, H, I]; sparse_matmul wants [1, E, I, H]
        down_proj=up(torch_weights["experts_down"].transpose(-2, -1).unsqueeze(0)),
    )


def build_expert_sparsity(device, num_experts: int) -> ttnn.Tensor:
    """All-ones sparsity mask ``[1, 1, 1, E]``, ROW_MAJOR.

    Every expert is computed for every token group; the routing weights zero
    out the inactive ones after the down projection. That is the established
    gpt_oss/gemma4 pattern -- it trades compute for a static, trace-friendly
    shape rather than gathering per-token expert assignments.
    """
    return ttnn.from_torch(
        torch.ones(1, 1, 1, num_experts, dtype=torch.bfloat16),
        layout=ttnn.ROW_MAJOR_LAYOUT,
        dtype=ttnn.bfloat16,
        device=device,
    )


def _expert_compute_kernel_config(device):
    """HiFi4, and ``fp32_dest_acc_en`` deliberately OFF.

    The functional path holds expert weights in **bf16** (see
    ``upload_expert_weights``), so the accumulation over hidden/intermediate has
    16 bits of mantissa to preserve and LoFi -- the matmul default, which keeps
    the top 5 -- is not enough. Enabling fp32 dest accumulation looks like the
    natural next lever but must not be used here: it halves the matmul dest from
    8 tiles to 4, which corrupts expert output on Blackhole (tt-metal #49068,
    hit on BH-QB-2). HiFi4 alone provides the accuracy.

    The optimized decoder quantises the experts to bfloat4_b, where there is no
    longer any low-order mantissa for HiFi4 to resolve, and measured LoFi as
    both faster and marginally more accurate -- so it overrides this with its
    own config rather than reusing it. See
    ``optimized_decoder.EXPERT_MATH_FIDELITY``.
    """
    return ttnn.init_device_compute_kernel_config(
        device.arch(),
        math_fidelity=ttnn.MathFidelity.HiFi4,
        math_approx_mode=False,
        fp32_dest_acc_en=False,
        packer_l1_acc=False,
    )


def _sparse_matmul_config(m: int, n: int, in0_block_w: int = 1):
    """Spread the N dimension over the largest usable slice of an 8x8 grid."""
    n_tiles = math.ceil(n / 32)
    best_cores, best_cx, best_cy = 1, 1, 1
    for num_cores in range(1, min(65, n_tiles + 1)):
        if n_tiles % num_cores:
            continue
        for cy in range(1, 9):
            if num_cores % cy == 0:
                cx = num_cores // cy
                if cx <= 8 and num_cores > best_cores:
                    best_cores, best_cx, best_cy = num_cores, cx, cy
                    break
    per_core_n = n_tiles // best_cores
    return ttnn.MatmulMultiCoreReuseMultiCast1DProgramConfig(
        compute_with_storage_grid_size=ttnn.CoreCoord(best_cx, best_cy),
        in0_block_w=in0_block_w,
        out_subblock_h=1,
        out_subblock_w=1,
        out_block_h=1,
        out_block_w=per_core_n,
        per_core_M=max(32, m) // 32,
        per_core_N=per_core_n,
        fuse_batch=False,
        fused_activation=None,
        mcast_in0=True,
    )


# sparse_matmul folds the group dimension (chunk_len / 32) into M, which grows
# num_blocks_y and can overflow the core grid. Chunking at exactly one tile
# keeps group_size == 1 so all blocking comes from N.
EXPERT_CHUNK_SIZE = 32


def _experts_chunk(
    hidden: ttnn.Tensor,
    routing: ttnn.Tensor,
    weights: ExpertWeights,
    config: MoEConfig,
    sparsity_base: ttnn.Tensor,
) -> ttnn.Tensor:
    """One 32-token chunk through all experts. ``hidden`` ``[1, 1, 32, H]``."""
    chunk_len = hidden.shape[2]
    n_experts = config.num_experts
    hidden_size = config.hidden_size
    group_size = chunk_len // EXPERT_CHUNK_SIZE

    device = hidden.device()
    compute_config = _expert_compute_kernel_config(device)
    output_tile = ttnn.Tile([32, 32])
    gate_up_config = _sparse_matmul_config(EXPERT_CHUNK_SIZE, config.moe_intermediate_size)
    down_config = _sparse_matmul_config(EXPERT_CHUNK_SIZE, hidden_size)

    hidden_grouped = ttnn.reshape(hidden, (1, group_size, EXPERT_CHUNK_SIZE, hidden_size))
    sparsity = ttnn.repeat(sparsity_base, (1, 1, group_size, 1))
    nnz = n_experts * group_size

    def project(weight):
        out = ttnn.sparse_matmul(
            hidden_grouped,
            weight,
            sparsity=sparsity,
            nnz=nnz,
            memory_config=ttnn.DRAM_MEMORY_CONFIG,
            output_tile=output_tile,
            program_config=gate_up_config,
            compute_kernel_config=compute_config,
            dtype=ttnn.bfloat16,
        )
        inter = out.shape[-1]
        return ttnn.reshape(ttnn.transpose(out, 1, 3), (1, n_experts, chunk_len, inter)), inter

    gate, inter = project(weights.gate_proj)
    up, _ = project(weights.up_proj)
    ttnn.deallocate(hidden_grouped)

    # SwiGLU -- Qwen3 is hidden_act="silu". gemma4, which this follows, uses
    # GeGLU; swapping the activation runs fine and returns wrong numbers.
    down_input = ttnn.reshape(ttnn.mul(ttnn.silu(gate), up), (1, n_experts, chunk_len, inter))
    ttnn.deallocate(gate)
    ttnn.deallocate(up)

    down = ttnn.sparse_matmul(
        down_input,
        weights.down_proj,
        sparsity=sparsity_base,
        nnz=n_experts,
        memory_config=ttnn.DRAM_MEMORY_CONFIG,
        output_tile=output_tile,
        program_config=down_config,
        is_input_a_sparse=True,
        compute_kernel_config=compute_config,
        dtype=ttnn.bfloat16,
    )
    ttnn.deallocate(down_input)

    # Scale each expert's contribution by its routing weight (zero for the 120
    # experts this token did not select), then sum over the expert dimension.
    states = ttnn.reshape(down, (1, n_experts, chunk_len, hidden_size))
    states = ttnn.mul(states, ttnn.permute(routing, (0, 3, 2, 1)))  # [1, E, S, 1]
    states = ttnn.unsqueeze_to_4D(ttnn.experimental.fast_reduce_nc(states, dims=[1]))
    return ttnn.reshape(states, (1, 1, chunk_len, hidden_size))


def moe_prefill(
    x: ttnn.Tensor,
    routing: ttnn.Tensor,
    weights: ExpertWeights,
    config: MoEConfig,
    sparsity_base: ttnn.Tensor,
) -> ttnn.Tensor:
    """Full MoE expert pass over a sequence. ``x`` ``[1, 1, S, H]``, any S.

    ``sparse_matmul`` works a tile at a time, so a sequence that is not a
    multiple of 32 is zero-padded up to one and the extra rows are dropped from
    the result. Padded rows carry an all-zero routing vector, so every expert's
    contribution to them is scaled by zero -- they cost a little compute and
    cannot perturb the real tokens.
    """
    seq_len = x.shape[2]
    padded_len = math.ceil(seq_len / EXPERT_CHUNK_SIZE) * EXPERT_CHUNK_SIZE

    if padded_len != seq_len:
        pad = [(0, 0), (0, 0), (0, padded_len - seq_len), (0, 0)]
        x = ttnn.pad(x, pad, value=0.0)
        routing = ttnn.pad(routing, pad, value=0.0)

    outputs = []
    for start in range(0, padded_len, EXPERT_CHUNK_SIZE):
        end = start + EXPERT_CHUNK_SIZE
        outputs.append(
            _experts_chunk(
                ttnn.slice(x, [0, 0, start, 0], [1, 1, end, config.hidden_size]),
                ttnn.slice(routing, [0, 0, start, 0], [1, 1, end, config.num_experts]),
                weights,
                config,
                sparsity_base,
            )
        )
    out = outputs[0] if len(outputs) == 1 else ttnn.concat(outputs, dim=2)
    if padded_len != seq_len:
        out = ttnn.slice(out, [0, 0, 0, 0], [1, 1, seq_len, config.hidden_size])
    return out


def moe_decode(
    x: ttnn.Tensor,
    routing: ttnn.Tensor,
    weights: ExpertWeights,
    config: MoEConfig,
) -> ttnn.Tensor:
    """MoE for a single token per user. ``x`` ``[1, 1, batch, H]``.

    Unlike the prefill path this uses **real** sparsity: the dense routing
    tensor is handed to ``sparse_matmul`` directly, so only the selected experts
    are computed rather than all 128. Prefill cannot do that -- across 32 tokens
    the union of selected experts approaches the full set, so an all-ones mask
    with a post-hoc mask-out is both simpler and no more expensive. In decode
    the working set really is ``batch * top_k``, and skipping the other 120
    experts per token is the entire reason decode is affordable.
    """
    batch = x.shape[2]
    n_experts = config.num_experts
    hidden_size = config.hidden_size
    # True non-zero count of the sparsity tensor. gemma4 passes top_k because
    # its decode is single-user; with several users each contributing top_k
    # entries the kernel needs the full count or it under-sizes the work.
    nnz = config.num_experts_per_tok * batch

    sparsity = ttnn.to_layout(routing, ttnn.ROW_MAJOR_LAYOUT)
    output_tile = ttnn.Tile([32, 32])
    compute_config = _expert_compute_kernel_config(x.device())
    gate_up_config = _sparse_matmul_config(batch, config.moe_intermediate_size)
    down_config = _sparse_matmul_config(batch, hidden_size)

    def project(weight):
        out = ttnn.sparse_matmul(
            x,
            weight,
            sparsity=sparsity,
            nnz=nnz,
            memory_config=ttnn.L1_MEMORY_CONFIG,
            output_tile=output_tile,
            program_config=gate_up_config,
            compute_kernel_config=compute_config,
            dtype=ttnn.bfloat16,
        )
        inter = out.shape[-1]
        out = ttnn.transpose(ttnn.reshape(out, (batch, n_experts, 1, inter)), 1, 2)
        return ttnn.reshape(out, (batch, n_experts, inter)), inter

    gate, inter = project(weights.gate_proj)
    up, _ = project(weights.up_proj)

    down_input = ttnn.mul(ttnn.silu(gate), up)  # SwiGLU, not GeGLU
    ttnn.deallocate(gate)
    ttnn.deallocate(up)
    down_input = ttnn.reshape(ttnn.transpose(down_input, 1, 0), (1, n_experts, batch, inter))

    down = ttnn.sparse_matmul(
        down_input,
        weights.down_proj,
        sparsity=sparsity,
        nnz=nnz,
        memory_config=ttnn.L1_MEMORY_CONFIG,
        output_tile=output_tile,
        program_config=down_config,
        is_input_a_sparse=True,
        compute_kernel_config=compute_config,
        dtype=ttnn.bfloat16,
    )
    ttnn.deallocate(down_input)

    states = ttnn.reshape(ttnn.permute(down, (0, 2, 1, 3)), (batch, n_experts, hidden_size))
    states = ttnn.mul(states, ttnn.reshape(routing, (batch, n_experts, 1)))
    states = ttnn.unsqueeze_to_4D(ttnn.sum(states, dim=1))
    return ttnn.reshape(states, (1, 1, batch, hidden_size), (1, 1, max(32, batch), hidden_size))


@dataclass(frozen=True)
class DecoderLayerConfig:
    attention: AttentionConfig
    moe: MoEConfig
    rms_norm_eps: float

    @classmethod
    def from_hf(cls, config) -> "DecoderLayerConfig":
        return cls(
            attention=AttentionConfig.from_hf(config),
            moe=MoEConfig.from_hf(config),
            rms_norm_eps=config.rms_norm_eps,
        )


@dataclass
class DecoderLayerWeights:
    input_layernorm: ttnn.Tensor
    post_attention_layernorm: ttnn.Tensor
    attention: AttentionWeights
    router: ttnn.Tensor
    experts: ExpertWeights


def decoder_layer_prefill(
    x: ttnn.Tensor,
    weights: DecoderLayerWeights,
    config: DecoderLayerConfig,
    cos_cache: ttnn.Tensor,
    sin_cache: ttnn.Tensor,
    sparsity: ttnn.Tensor,
    kv_cache: KVCache | None = None,
    user_id: int = 0,
) -> ttnn.Tensor:
    """One full decoder layer. ``x`` / return ``[1, 1, S, hidden]``.

    Passing ``kv_cache`` seeds it with the prompt's K/V so decode can continue
    from position S.

    Pre-norm, matching ``Qwen3MoeDecoderLayer.forward``::

        h = x + attn(norm1(x))
        out = h + moe(norm2(h))

    Note the MoE consumes a single normed tensor for *both* the router and the
    experts. Some ports (gemma4) thread separate router/expert inputs because
    their router applies its own normalisation; Qwen3's does not, and feeding
    the router the un-normed residual instead would change every routing
    decision.
    """
    eps = config.rms_norm_eps

    normed = ttnn.rms_norm(x, weight=weights.input_layernorm, epsilon=eps)
    attn_out = attention_prefill(normed, weights.attention, config.attention, cos_cache, sin_cache, kv_cache, user_id)
    ttnn.deallocate(normed)
    hidden = ttnn.add(x, attn_out)
    ttnn.deallocate(attn_out)

    normed = ttnn.rms_norm(hidden, weight=weights.post_attention_layernorm, epsilon=eps)
    routing = router_forward(normed, weights.router, config.moe)
    moe_out = moe_prefill(normed, routing, weights.experts, config.moe, sparsity)
    ttnn.deallocate(normed)
    ttnn.deallocate(routing)

    out = ttnn.add(hidden, moe_out)
    ttnn.deallocate(hidden)
    ttnn.deallocate(moe_out)
    return out


def decoder_layer_decode(
    x: ttnn.Tensor,
    weights: DecoderLayerWeights,
    config: DecoderLayerConfig,
    cos_cache: ttnn.Tensor,
    sin_cache: ttnn.Tensor,
    kv_cache: KVCache,
    current_pos: ttnn.Tensor,
    token_index: int,
) -> ttnn.Tensor:
    """One decoder layer, single token per user. ``x`` / return ``[1, 1, batch, hidden]``.

    Same graph as ``decoder_layer_prefill`` -- only the attention and expert
    kernels differ, because decode attends against the KV cache and can exploit
    real routing sparsity.
    """
    eps = config.rms_norm_eps

    normed = ttnn.rms_norm(x, weight=weights.input_layernorm, epsilon=eps)
    attn_out = attention_decode(
        normed, weights.attention, config.attention, cos_cache, sin_cache, kv_cache, current_pos, token_index
    )
    ttnn.deallocate(normed)
    hidden = ttnn.add(x, attn_out)
    ttnn.deallocate(attn_out)

    normed = ttnn.rms_norm(hidden, weight=weights.post_attention_layernorm, epsilon=eps)
    routing = router_forward(normed, weights.router, config.moe)
    moe_out = moe_decode(normed, routing, weights.experts, config.moe)
    ttnn.deallocate(normed)
    ttnn.deallocate(routing)

    out = ttnn.add(hidden, moe_out)
    ttnn.deallocate(hidden)
    ttnn.deallocate(moe_out)
    return out


def upload_layer_weights(torch_weights: dict[str, torch.Tensor], device, config: DecoderLayerConfig):
    """Everything one decoder layer needs, from ``convert_layer_weights`` output."""

    def norm(t: torch.Tensor) -> ttnn.Tensor:
        return ttnn.from_torch(
            t.reshape(1, 1, 1, -1).float(),
            dtype=ttnn.bfloat16,
            layout=ttnn.TILE_LAYOUT,
            device=device,
            memory_config=ttnn.DRAM_MEMORY_CONFIG,
        )

    return DecoderLayerWeights(
        input_layernorm=norm(torch_weights["input_layernorm"]),
        post_attention_layernorm=norm(torch_weights["post_attention_layernorm"]),
        attention=upload_attention_weights(torch_weights, device),
        router=upload_router_weight(torch_weights["router"], device),
        experts=upload_expert_weights(torch_weights, device, config.moe),
    )


def upload_attention_weights(torch_weights: dict[str, torch.Tensor], device) -> AttentionWeights:
    """Move the host-side tensors from ``weight_mapping`` onto the device."""

    def up(t: torch.Tensor, pad_to_4d: bool = False) -> ttnn.Tensor:
        if pad_to_4d:
            t = t.reshape(1, 1, 1, -1)
        while t.dim() < 4:
            t = t.unsqueeze(0)
        return ttnn.from_torch(
            t.float(),
            dtype=ttnn.bfloat16,
            layout=ttnn.TILE_LAYOUT,
            device=device,
            memory_config=ttnn.DRAM_MEMORY_CONFIG,
        )

    return AttentionWeights(
        wqkv=up(torch_weights["wqkv"]),
        wo=up(torch_weights["wo"]),
        q_norm=up(torch_weights["q_norm"], pad_to_4d=True),
        k_norm=up(torch_weights["k_norm"], pad_to_4d=True),
    )

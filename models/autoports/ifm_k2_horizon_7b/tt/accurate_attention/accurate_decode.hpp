#include "api/compute/eltwise_binary_sfpu.h"

// Accurate flash-decode helpers. The binding stores scores, outputs, sums,
// correction factors and tree-exchange buffers in FP32. Every recurrence CB is
// UnpackToDestFp32, and all of its compute reads use these A2D copies and column
// broadcasts, so FP32 state never passes through the 19-bit source registers.
// Multiply/add run on SFPU in FP32 destination registers, as in accurate_stats.hpp.

inline void k2d_copy(uint32_t cb, uint32_t tile, uint32_t dst) {
    reconfig_data_format_srca(cb);
    copy_init(cb);
    copy_tile(cb, tile, dst);
}

inline void k2d_bcast(uint32_t cb, uint32_t tile, uint32_t dst) {
    // FP32/UnpackToDestFp32 broadcasts unpack A2D; 16-bit column broadcasts use srcB.
    reconfig_data_format(cb, cb);
    unary_bcast_init<BroadcastType::COL>(cb);
    unary_bcast<BroadcastType::COL>(cb, tile, dst);
    unary_bcast_uninit<BroadcastType::COL>(cb);
}

// Row sums of the FP32 probabilities: stock reduce_tile<SUM> mis-reduces FP32 score
// tiles, so accumulate P @ col_identity (1.0 in column 0, generated by the stock writer
// in c_11) in FP32 destination registers, as prefill's matmul_reduce. The result has
// the stock column-0 layout. P enters srcB exactly as it does for the PV matmul, so
// numerator and denominator see identical probabilities.
template <uint32_t rows>
void k2d_row_sum(uint32_t scores_cb, uint32_t col_identity_cb, uint32_t sum_cb, uint32_t cols) {
    CircularBuffer scores(scores_cb), identity(col_identity_cb), sums(sum_cb);
    scores.wait_front(rows * cols);
    identity.wait_front(1);
    sums.reserve_back(rows);
    reconfig_data_format(col_identity_cb, scores_cb);  // matmul: in1 -> srcA, in0 -> srcB
    matmul_init(scores_cb, col_identity_cb);
    pack_reconfig_data_format(sum_cb);
    for (uint32_t row = 0; row < rows; ++row) {
        tile_regs_acquire();
        for (uint32_t col = 0; col < cols; ++col) {
            matmul_tiles(scores_cb, col_identity_cb, row * cols + col, 0, 0);
        }
        tile_regs_commit();
        tile_regs_wait();
        pack_tile(0, sum_cb);
        tile_regs_release();
    }
    sums.push_back(rows);
}

// Stock move_block assumes the caller configured unpack/pack for the same format.
// Formats now differ between CBs, so configure both sides for every move.
template <bool pop_in_cb>
void k2d_move(uint32_t in_cb, uint32_t out_cb, uint32_t num_tiles) {
    reconfig_data_format_srca(in_cb);
    pack_reconfig_data_format(out_cb);
    move_block<pop_in_cb>(in_cb, out_cb, num_tiles);
}

// cur_sum = cur_sum + prev_sum * alpha; consumes prev_sum, keeps alpha.
void k2d_sum_update(uint32_t cur_sum, uint32_t prev_sum, uint32_t alpha, uint32_t rows) {
    CircularBuffer cur(cur_sum), prev(prev_sum), factors(alpha);
    cur.wait_front(rows);
    prev.wait_front(rows);
    factors.wait_front(rows);
    pack_reconfig_data_format(cur_sum);
    for (uint32_t row = 0; row < rows; ++row) {
        tile_regs_acquire();
        k2d_copy(prev_sum, row, 0);
        k2d_copy(alpha, row, 1);
        mul_binary_tile_init();
        mul_binary_tile(0, 1, 0);
        k2d_copy(cur_sum, 0, 1);
        add_binary_tile_init();
        add_binary_tile(0, 1, 0);
        tile_regs_commit();
        cur.pop_front(1);
        cur.reserve_back(1);
        tile_regs_wait();
        pack_tile(0, cur_sum);
        tile_regs_release();
        cur.push_back(1);
    }
    prev.pop_front(rows);
}

// out = out * bcast(alpha) + current; consumes current and alpha.
template <uint32_t rows, uint32_t cols>
void k2d_out_update(uint32_t out_cb, uint32_t current_cb, uint32_t alpha) {
    constexpr uint32_t count = rows * cols;
    CircularBuffer out(out_cb), cur(current_cb), factors(alpha);
    out.wait_front(count);
    cur.wait_front(count);
    factors.wait_front(rows);
    pack_reconfig_data_format(out_cb);
    for (uint32_t tile = 0; tile < count; ++tile) {
        tile_regs_acquire();
        k2d_copy(out_cb, 0, 0);
        k2d_bcast(alpha, tile / cols, 1);
        mul_binary_tile_init();
        mul_binary_tile(0, 1, 0);
        k2d_copy(current_cb, tile, 1);
        add_binary_tile_init();
        add_binary_tile(0, 1, 0);
        tile_regs_commit();
        out.pop_front(1);
        out.reserve_back(1);
        tile_regs_wait();
        pack_tile(0, out_cb);
        tile_regs_release();
        out.push_back(1);
    }
    cur.pop_front(count);
    factors.pop_front(rows);
}

// Tree merge: out = out * bcast(e_local) + child * bcast(e_child); consumes child and both factors.
template <uint32_t rows, uint32_t cols>
void k2d_out_merge(uint32_t out_cb, uint32_t e_local, uint32_t child_cb, uint32_t e_child) {
    constexpr uint32_t count = rows * cols;
    CircularBuffer out(out_cb), child(child_cb), local_factors(e_local), child_factors(e_child);
    out.wait_front(count);
    child.wait_front(count);
    local_factors.wait_front(rows);
    child_factors.wait_front(rows);
    pack_reconfig_data_format(out_cb);
    for (uint32_t tile = 0; tile < count; ++tile) {
        tile_regs_acquire();
        k2d_copy(out_cb, 0, 0);
        k2d_bcast(e_local, tile / cols, 1);
        mul_binary_tile_init();
        mul_binary_tile(0, 1, 0);
        k2d_copy(child_cb, tile, 1);
        k2d_bcast(e_child, tile / cols, 2);
        mul_binary_tile_init();
        mul_binary_tile(1, 2, 1);
        add_binary_tile_init();
        add_binary_tile(0, 1, 0);
        tile_regs_commit();
        out.pop_front(1);
        out.reserve_back(1);
        tile_regs_wait();
        pack_tile(0, out_cb);
        tile_regs_release();
        out.push_back(1);
    }
    child.pop_front(count);
    local_factors.pop_front(rows);
    child_factors.pop_front(rows);
}

// Final normalization: out *= bcast(reciprocal); consumes reciprocal.
template <uint32_t rows, uint32_t cols>
void k2d_scale_output(uint32_t out_cb, uint32_t reciprocal) {
    constexpr uint32_t count = rows * cols;
    CircularBuffer out(out_cb), scale(reciprocal);
    out.wait_front(count);
    scale.wait_front(rows);
    pack_reconfig_data_format(out_cb);
    for (uint32_t tile = 0; tile < count; ++tile) {
        tile_regs_acquire();
        k2d_copy(out_cb, 0, 0);
        k2d_bcast(reciprocal, tile / cols, 1);
        mul_binary_tile_init();
        mul_binary_tile(0, 1, 0);
        tile_regs_commit();
        out.pop_front(1);
        out.reserve_back(1);
        tile_regs_wait();
        pack_tile(0, out_cb);
        tile_regs_release();
        out.push_back(1);
    }
    scale.pop_front(rows);
}

// Stock correction_block with per-operand unpack configuration and per-output
// pack configuration: max CBs stay BF16 while sums and factors are FP32. The
// fused SFPU arithmetic (max, two exponentials, FP32 sum merge) is unchanged.
template <uint32_t scale_fp32, VectorMode vector_mode = VectorMode::C>
void k2d_correction_block(
    uint32_t cb_worker_max,
    uint32_t cb_worker_sum,
    uint32_t cb_cur_max,
    uint32_t cb_prev_max,
    uint32_t cb_cur_sum,
    uint32_t cb_prev_sum,
    uint32_t cb_exp_max_diff,
    uint32_t cb_exp_max_diff_2,
    uint32_t num_head_tiles) {
    CircularBuffer worker_max(cb_worker_max), worker_sum(cb_worker_sum), cur_max(cb_cur_max), prev_max(cb_prev_max),
        cur_sum(cb_cur_sum), prev_sum(cb_prev_sum), exp_diff(cb_exp_max_diff), exp_diff_2(cb_exp_max_diff_2);
    worker_max.wait_front(num_head_tiles);
    worker_sum.wait_front(num_head_tiles);
    prev_max.wait_front(num_head_tiles);
    prev_sum.wait_front(num_head_tiles);
    cur_max.reserve_back(num_head_tiles);
    cur_sum.reserve_back(num_head_tiles);
    exp_diff.reserve_back(num_head_tiles);
    exp_diff_2.reserve_back(num_head_tiles);
    constexpr uint32_t worker_sum_dst = (DST_ACCUM_MODE && DST_SYNC_MODE == DstSync::SyncHalf) ? 2 : 4;
    static_assert(
        worker_sum_dst < compute_kernel_lib::DEST_AUTO_LIMIT,
        "correction DST layout exceeds DEST capacity for this sync/accum mode");
    constexpr uint16_t scale_bf16 = scale_fp32 >> 16;
    for (uint32_t i = 0; i < num_head_tiles; i++) {
        tile_regs_acquire();
        k2d_copy(cb_prev_max, i, 0);
        k2d_copy(cb_worker_max, i, 1);
        k2d_copy(cb_prev_sum, i, 3);
        k2d_copy(cb_worker_sum, i, worker_sum_dst);
        exp_tile_init<EXP_APPROX_MODE>();
        MATH((fused_max_sub_exp_add_tile<vector_mode>(0, scale_bf16)));
        tile_regs_commit();
        tile_regs_wait();
        pack_reconfig_data_format(cb_exp_max_diff);
        pack_tile(0, cb_exp_max_diff);
        pack_reconfig_data_format(cb_exp_max_diff_2);
        pack_tile(1, cb_exp_max_diff_2);
        pack_reconfig_data_format(cb_cur_max);
        pack_tile(2, cb_cur_max);
        pack_reconfig_data_format(cb_cur_sum);
        pack_tile(3, cb_cur_sum);
        tile_regs_release();
        cur_max.push_back(1);
        cur_sum.push_back(1);
        exp_diff.push_back(1);
        exp_diff_2.push_back(1);
    }
    prev_sum.pop_front(num_head_tiles);
    worker_sum.pop_front(num_head_tiles);
}

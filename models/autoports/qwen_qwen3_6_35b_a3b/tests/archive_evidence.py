"""Archive closed text evidence deterministically; retain original local files.

Run only between device jobs after all evidence writers have exited. Binary
oracle/Tracy captures remain local; profiler CSVs and human reports are retained.
"""

import gzip
import hashlib
import io
import json
import os
import re
from pathlib import Path

PART_BYTES = 450000
MANIFEST_PART_PATTERN = re.compile(r"archive_manifest\.part[0-9]{3,}\.json")
IGNORE_START = "# BEGIN archived large originals (generated by archive_evidence.py)"
IGNORE_END = "# END archived large originals"
FROZEN_IGNORE_START = "# BEGIN archived immutable text originals (generated by archive_evidence.py)"
FROZEN_IGNORE_END = "# END archived immutable text originals"


def frozen_text_format_risks(source):
    """Select only frozen/generated evidence whose exact bytes hooks would alter.

    Ordinary Python, Markdown, JSON and arbitrary text remain subject to normal
    hooks. These suffixes denote immutable snapshots, raw diffs or disassembly.
    Detection follows the default whitespace/EOF hooks without rewriting bytes.
    """
    if not (source.suffix in (".snapshot", ".diff") or source.name.endswith(".disasm.txt")):
        return {}
    raw = source.read_bytes()
    if not raw or b"\0" in raw:
        return {}
    try:
        raw.decode("utf-8")
    except UnicodeDecodeError:
        return {}
    trailing = False
    for line in io.BytesIO(raw):
        body = line[:-2] if line.endswith(b"\r\n") else line[:-1] if line.endswith(b"\n") else line
        trailing |= body.rstrip() != body
    content = raw.rstrip(b"\r\n")
    ending = raw[len(content) :]
    eof = not content or ending not in (b"\n", b"\r\n", b"\r")
    return {"trailing_whitespace": trailing, "end_of_file": eof} if trailing or eof else {}


def frozen_source_pins(root):
    """Validate explicit reviewed historical exports before writing any archive.

    This map is not a source-extension exemption. Only exact pinned files under
    endurance are eligible; ordinary code and all active tests stay hook checked.
    """
    manifest = root / "endurance/archive_frozen_source_pins.json"
    if not manifest.exists():
        return {}
    if manifest.is_symlink():
        raise ValueError("Frozen source pin map must not be a symlink")

    def unique(pairs):
        result = {}
        for name, value in pairs:
            if name in result:
                raise ValueError(f"Duplicate frozen source pin: {name}")
            result[name] = value
        return result

    pins = json.loads(manifest.read_bytes(), object_pairs_hook=unique)
    if not isinstance(pins, dict):
        raise ValueError("Frozen source pins must be a path-to-SHA256 map")
    for name, expected in pins.items():
        relative = Path(name)
        if (
            relative.is_absolute()
            or relative.as_posix() != name
            or ".." in relative.parts
            or "\\" in name
            or len(relative.parts) < 2
            or relative.parts[0] != "endurance"
            or any(part in {"raw", "oracle_cache", "pytest"} for part in relative.parts)
            or relative.suffix not in {".py", ".cpp"}
        ):
            raise ValueError(f"Unsafe or out-of-scope frozen source pin: {name}")
        source = root / relative
        if source.is_symlink() or not source.is_file() or source.resolve() != root.resolve() / relative:
            raise ValueError(f"Missing or symlinked frozen source export: {name}")
        if not isinstance(expected, str) or not re.fullmatch(r"[0-9a-f]{64}", expected):
            raise ValueError(f"Invalid frozen source SHA256: {name}")
        if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
            raise ValueError(f"Frozen source SHA256 mismatch: {name}")
    return pins


def evidence_sources(root, fused, *, source_pins=None):
    if fused:
        source_pins = frozen_source_pins(root) if source_pins is None else source_pins
        # Include candidate sweeps and future evidence directories, not just the
        # original top-level logs/profile names. Never archive binary/raw trees.
        excluded = {"raw", "oracle_cache", "pytest"}
        sources = []
        for directory, children, files in os.walk(root):
            children[:] = sorted(name for name in children if name not in excluded)
            for name in sorted(files):
                source = Path(directory) / name
                relative = source.relative_to(root)
                if source.is_symlink() or not source.is_file():
                    continue
                if len(relative.parts) == 1 and MANIFEST_PART_PATTERN.fullmatch(name):
                    continue  # Generated manifest pieces are never evidence inputs.
                selected = (
                    source.suffix in (".log", ".csv")
                    or name.endswith("_perf_report.txt")
                    or (
                        relative.parts[0] == "watcher"
                        and source.suffix == ".txt"
                        and "generated" in relative.parts
                        and "watcher" in relative.parts[1:]
                    )
                    or (relative.parts[0] == "endurance" and name.endswith("_results.json"))
                    or (
                        source.suffix == ".json"
                        and name != "archive_manifest.json"
                        and source.stat().st_size > PART_BYTES
                    )
                    or (name == "op_topology.md" and source.stat().st_size > PART_BYTES)
                    or bool(frozen_text_format_risks(source))
                    or relative.as_posix() in source_pins
                )
                if selected:
                    sources.append(source)
        return sorted(sources)
    sources = list((root / "logs").glob("*.log"))
    sources += list((root / "watcher").rglob("*.log"))
    sources += list((root / "watcher").glob("*/generated/watcher/*.txt"))
    for directory in sorted((root / "tracy").glob("*")):
        if not directory.is_dir():
            continue
        sources += list(directory.glob("*.csv")) + list(directory.glob("*.log"))
    return sorted(set(sources))


def update_large_original_ignores(root, records):
    """Ignore exact archived large/generated paths; never add suffix-wide rules."""
    path = root / ".gitignore"
    original = path.read_text() if path.exists() else ""
    for start, end in (
        (IGNORE_START, IGNORE_END),
        (FROZEN_IGNORE_START, FROZEN_IGNORE_END),
        (
            IGNORE_START.replace("large originals", "large JSON originals"),
            IGNORE_END.replace("large originals", "large JSON originals"),
        ),
    ):
        if start in original:
            before, block = original.split(start, 1)
            _, after = block.split(end, 1)
            original = before.rstrip("\n") + "\n" + after.lstrip("\n")
    names = sorted(
        name
        for name, entry in records.items()
        if (name.endswith(".json") or Path(name).name == "op_topology.md")
        and not name.endswith(".provenance.json")
        and entry["bytes"] > PART_BYTES
    )

    # Anchored literal paths avoid ignoring unrelated evidence with the same name.
    def pattern(name):
        return "/" + "".join("\\" + char if char in "\\*?[]!# " else char for char in name)

    frozen_names = sorted(
        name
        for name, entry in records.items()
        if entry.get("immutable_text_format_risk") or entry.get("immutable_source_pin")
    )
    blocks = ["\n".join([IGNORE_START, *(pattern(name) for name in names), IGNORE_END])]
    if frozen_names:
        blocks.append("\n".join([FROZEN_IGNORE_START, *(pattern(name) for name in frozen_names), FROZEN_IGNORE_END]))
    path.write_text(original.rstrip("\n") + "\n\n" + "\n\n".join(blocks) + "\n")


def write_topology_archive_index(root, records):
    lines = [
        "# Archived full performance and operation tables",
        "",
        "Full performance reports and large generated operation tables are preserved losslessly; originals remain local. "
        "Compact timing tables from `summarize_perf.py` remain tracked as `fused_decoder.md` in each profile directory.",
        "",
        "The [archive manifest](archive_manifest.json) records original byte counts and SHA256. "
        "For a single archive, gzip-decompress it; for multipart archives, concatenate the linked parts in order, "
        "then gzip-decompress. Verify the restored text against the manifest SHA256.",
        "",
    ]
    for name, entry in sorted(records.items()):
        if Path(name).name != "op_topology.md" and not name.endswith("_perf_report.txt"):
            continue
        archives = entry.get("archive_parts", [entry.get("archive")])
        links = ", ".join(f"[{Path(part).name}]({part})" for part in archives)
        summary = next(
            (
                parent / "fused_decoder.md"
                for parent in Path(name).parents
                if (root / parent / "fused_decoder.md").exists()
            ),
            None,
        )
        summary_link = f" [Compact timing table]({summary.as_posix()})." if summary is not None else ""
        lines.append(f"- `{name}` ({entry['bytes']} bytes): {links}.{summary_link}")
    (root / "archived_topology.md").write_text("\n".join(lines) + "\n")


def write_archive_manifest(root, records, *, part_bytes=PART_BYTES):
    """Write a legacy map or bounded deterministic parts plus a small root index."""
    records = dict(sorted(records.items()))
    complete = (json.dumps({"files": records}, indent=2) + "\n").encode()
    active = set()
    if len(complete) <= part_bytes:
        index = complete
    else:
        header, footer = b'{\n  "files": {\n', b"\n  }\n}\n"
        chunks, fragments = [], []
        size = len(header) + len(footer)
        for name, entry in records.items():
            lines = json.dumps({name: entry}, indent=2).splitlines()[1:-1]
            fragment = "\n".join("  " + line for line in lines).encode()
            if len(header) + len(fragment) + len(footer) > part_bytes:
                raise ValueError(f"Single manifest record exceeds part limit: {name}")
            added = len(fragment) + (2 if fragments else 0)
            if fragments and size + added > part_bytes:
                chunks.append((header + b",\n".join(fragments) + footer, len(fragments)))
                fragments, size = [], len(header) + len(footer)
                added = len(fragment)
            fragments.append(fragment)
            size += added
        if fragments:
            chunks.append((header + b",\n".join(fragments) + footer, len(fragments)))
        parts = []
        for number, (payload, count) in enumerate(chunks):
            name = f"archive_manifest.part{number:03d}.json"
            path = root / name
            if path.is_symlink():
                raise ValueError(f"Refuse generated manifest symlink: {path}")
            path.write_bytes(payload)
            active.add(name)
            parts.append(
                dict(path=name, bytes=len(payload), sha256=hashlib.sha256(payload).hexdigest(), file_count=count)
            )
        index = (
            json.dumps(
                dict(manifest_format="partitioned-files-v1", file_count=len(records), manifest_parts=parts), indent=2
            )
            + "\n"
        ).encode()
        if len(index) > part_bytes:
            raise ValueError("Manifest root index exceeds part limit")
    (root / "archive_manifest.json").write_bytes(index)
    # Only exact reserved root filenames are generated parts. Never recurse,
    # follow symlinks, or remove similarly named notes/archives/evidence.
    for path in root.iterdir():
        if MANIFEST_PART_PATTERN.fullmatch(path.name) and path.name not in active:
            if path.is_file() and not path.is_symlink():
                path.unlink()


def archive_evidence(root, *, fused):
    source_pins = frozen_source_pins(root) if fused else {}
    records = {}
    for source in evidence_sources(root, fused, source_pins=source_pins):
        raw = source.read_bytes()
        name = source.relative_to(root).as_posix()
        if name in source_pins and hashlib.sha256(raw).hexdigest() != source_pins[name]:
            raise ValueError(f"Frozen source changed during archival: {name}")
        compressed = gzip.compress(raw, mtime=0)
        archive = source.with_suffix(source.suffix + ".gz")
        entry = {
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        }
        if name in source_pins:
            entry["immutable_source_pin"] = {
                "sha256": source_pins[name],
                "reason": "Reviewed historical source export; preserve measured bytes against formatting hooks.",
                "pin_manifest": "endurance/archive_frozen_source_pins.json",
            }
        if fused:
            risks = frozen_text_format_risks(source)
            if risks:
                entry["immutable_text_format_risk"] = risks
        if len(compressed) > PART_BYTES:
            parts = []
            for i, start in enumerate(range(0, len(compressed), PART_BYTES)):
                part = archive.with_name(archive.name + f".part{i:03d}")
                part.write_bytes(compressed[start : start + PART_BYTES])
                parts.append(str(part.relative_to(root)))
            entry["archive_parts"] = parts
            entry["restore"] = "Concatenate archive_parts in order, then gzip-decompress; SHA256 is of original text."
            archive.unlink(missing_ok=True)
        else:
            archive.write_bytes(compressed)
            entry["archive"] = str(archive.relative_to(root))
        # Re-archiving a file must not leave obsolete trailing parts from an
        # earlier, larger version beside the current manifest.
        active_parts = set(entry.get("archive_parts", []))
        for part in source.parent.glob(archive.name + ".part*"):
            if str(part.relative_to(root)) not in active_parts:
                part.unlink()
        records[str(source.relative_to(root))] = entry
    write_archive_manifest(root, records)
    if fused:
        update_large_original_ignores(root, records)
        write_topology_archive_index(root, records)
    print("ARCHIVED_CLOSED_TEXT_EVIDENCE", len(records))
    return records


def main():
    fused = os.environ.get("QWEN_DECODER") == "fused"
    root = Path(__file__).parents[1] / "doc" / ("fused_decoder" if fused else "functional_decoder")
    archive_evidence(root, fused=fused)


if __name__ == "__main__":
    main()

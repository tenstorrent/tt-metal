"""Recompute candidate PCC and collect measured timing/provenance from run logs."""

import json
from pathlib import Path
import torch
from models.autoports.qwen_qwen3_8_flash_next.tests.metrics import pcc_metrics


def main():
    torch.set_num_threads(8)
    root = Path(__file__).resolve().parents[1] / "doc/multichip_decoder"
    cache = Path("/home/vkovacevic/qwen38-flash/tt-metal-cache/qwen_qwen3_8_flash_next/multichip_benchmark_outputs")
    rows = []
    references = {}
    for source in root.glob("*.log"):
        for line in source.read_text(errors="replace").splitlines():
            if line.startswith('{"impl":'):
                try:
                    entry = json.loads(line)
                    references[entry["tag"]] = entry
                except (json.JSONDecodeError, KeyError):
                    pass
    for log in sorted(root.glob("*.log")):
        for line in log.read_text(errors="replace").splitlines():
            if not line.startswith('{"impl":'):
                continue
            try:
                data = json.loads(line)
            except json.JSONDecodeError:
                continue
            if "median_traced_decode_ms" not in data or data.get("profiler"):
                continue
            recorded = data.get("policy", {}).get("recorded", False)
            layer = data["layer"]
            reference = ("recorded_single_l" if recorded else "baseline_l") + str(layer)
            fields = ("batch", "prefill_length", "chunk_size", "position", "advance_position", "final_position")
            matched = [
                name
                for name, entry in references.items()
                if entry.get("impl") == "single"
                and entry.get("layer") == layer
                and not entry.get("profiler")
                and entry.get("policy", {}).get("recorded", False) == recorded
                and entry.get("policy", {}).get("recorded_tag", "recorded_inputs")
                == data.get("policy", {}).get("recorded_tag", "recorded_inputs")
                and all(entry.get(k) == data.get(k) for k in fields)
            ]
            if matched:
                reference = sorted(matched, key=lambda name: (name.startswith("final_"), name))[-1]
            refpath = cache / (reference + ".pt")
            output = Path(data["outputs"])
            row = dict(
                tag=data["tag"],
                impl=data["impl"],
                layer=layer,
                recorded=recorded,
                recorded_tag=data.get("policy", {}).get("recorded_tag", "recorded_inputs") if recorded else None,
                prefill_ms=data["median_prefill_host_ms"],
                decode_ms=data["median_traced_decode_ms"],
                prefill_length=data["prefill_length"],
                initial_position=data["position"],
                final_position=data["final_position"],
                advance_position=data["advance_position"],
                source_sha256=data["source_sha256"],
                tracking=data.get("tracking"),
                candidate=data.get("candidate"),
                log=str(log.relative_to(root)),
                output=str(output),
                reference=str(refpath),
            )
            candidate = data.get("candidate") or {}
            if candidate.get("family") in {"fused_AG_WO_direct_HC", "agmm"}:
                row["qualification"] = (
                    "rejected: native AGMM eight-slice metadata violates the TP4 worker-watcher invariant; see triage_watcher/AUTOTRIAGE.md"
                )
            control = references.get(reference, {})
            row["comparison_matched"] = (
                bool(control)
                and all(data.get(k) == control.get(k) for k in fields)
                and control.get("policy", {}).get("recorded_tag", "recorded_inputs")
                == data.get("policy", {}).get("recorded_tag", "recorded_inputs")
                and control.get("policy", {}).get("recorded", False) == recorded
            )
            if row["comparison_matched"] and refpath.exists() and output.exists():
                ref = torch.load(refpath, weights_only=True)
                actual = torch.load(output, weights_only=True)
                row["pcc"] = {
                    key: pcc_metrics(ref[key], value)["pcc"]
                    for key, value in actual.items()
                    if isinstance(value, torch.Tensor) and key in ref
                }
                row["pcc_pass"] = min(row["pcc"].values()) >= 0.995
            rows.append(row)
    (root / "experiment_summary.json").write_text(json.dumps(rows, indent=2) + "\n")
    lines = [
        "# Measured experiment ledger",
        "",
        "Generated by `tests/summarize_multichip_experiments.py`. PCC is recomputed from saved tensors.",
        "Only rows with the same inputs, position advancement, and source family are comparable.",
        "Initial single-prompt PCC is not a replacement for the boundary/stress gates.",
        "",
        "Traditional AGMM measurements are rejected by the TP4 worker-watcher invariant, even where numerical PCC passes. See [AutoTriage](triage_watcher/AUTOTRIAGE.md).",
        "",
        "| Tag | Layer | Inputs | Prefill ms | Decode ms | Prefill/decode PCC | Qualification note |",
        "|---|---:|---|---:|---:|---|---|",
    ]
    for r in rows:
        pcc = "/".join(f'{r.get("pcc", {}).get(k, float("nan")):.8f}' for k in ("prefill", "decode"))
        lines.append(
            f'| [{r["tag"]}]({r["log"]}) | {r["layer"]} | {"recorded" if r["recorded"] else "seeded"} | '
            f'{r["prefill_ms"]:.6f} | {r["decode_ms"]:.6f} | {pcc} | {"Native AGMM rejected" if r.get("qualification") else ""} |'
        )
    (root / "experiments.md").write_text("\n".join(lines) + "\n")
    print("EXPERIMENTS_SUMMARIZED", len(rows))


if __name__ == "__main__":
    main()

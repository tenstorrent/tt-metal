#!/usr/bin/env python3
"""mk_alloc_yamls.py: the suites of the staged allocator's device A/B on the P150 (SLOT_ALLOCATOR.md section 12.14;
staged against tier, user 2026-11-05: only the configs whose slot rows change, plus the 2D mesh, at 4352 and 3072 B).
Writes the yamls that do not exist yet into yamls/ here and every suite into yamls/alloc_manifest.json:
  suite -> {yaml, tests (per rank), ranks, env (extra env, both arms)}.
  2d_<P>    slotstudy/sls_2d_p150.yaml (1-hop E/W, N/S, bidir, 3-hop, merge, turn, multicast); 3072 B:
            slotalloc/yamls/sls_2d_p150_3072.yaml (mk_dyn_yamls.py)
  1d_<P>    slotstudy/sls_1d_p150.yaml (Linear); 3072 B: slotalloc/yamls/sls_1d_p150_3072.yaml
  ring_<P>  v4/exp_ring.yaml (Ring, no flow control); 3072 B: slotalloc/yamls/exp_ring_3072.yaml
  vc1_<P>   vc1/sls_vc1_all.yaml: the VC1 split (two 2x2 meshes, two ranks): multi-mesh sanity, intra-mesh rows,
            inter-mesh rows and the VC1 + VC0 mixes; 3072 B: slotalloc/yamls/sls_vc1_all_3072.yaml
  vc2_<P>   VC2 on (TT_METAL_ENABLE_FABRIC_VC2=1): exp_2d_4352.yaml's VC0 rows, plus pcs3's VC2 row alone (PcsVC2EW4352)
            and VC0 + VC2 on one link (PcsVC02bEW4352, scored by the link total); 3072 B: the same, converted
  ne_<P>    NeighborExchange: yamls/pvs_c1ne.yaml; 3072 B: converted
Conversion to 3072 B is mk_dyn_yamls.py's: every fabric_setup gets max_packet_size 3072, payloads above it are capped.
"""
import json
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
TREE = os.path.abspath(os.path.join(HERE, "../.."))
OUT = os.path.join(HERE, "yamls")
sys.path.insert(0, os.path.join(TREE, "fabric_exp/consolidation/slotalloc"))
import mk_dyn_yamls  # noqa: E402

SA = "fabric_exp/consolidation/slotalloc/yamls"
VC2 = "TT_METAL_ENABLE_FABRIC_VC2=1"


def n_tests(t):
    n = 1
    for v in (t.get("parametrization_params") or {}).values():
        n *= len(v) if isinstance(v, list) else 1
    return n


def count(path):
    return sum(n_tests(t) for t in yaml.safe_load(open(os.path.join(TREE, path)))["Tests"])


def write(name, header, text):
    path = os.path.join(OUT, f"{name}.yaml")
    open(path, "w").write("".join(f"# {line}\n" for line in header) + text)
    return os.path.relpath(path, TREE)


def to_3072(name, src):
    lines = open(os.path.join(TREE, src)).readlines()
    lines = [line for line in lines if not line.startswith("#")]
    return write(name, [f"Generated by mk_alloc_yamls.py from {src}: mk_dyn_yamls.py's conversion to 3072 B slots."],
                 "".join(mk_dyn_yamls.convert(lines, 3072)))


def main():
    os.makedirs(OUT, exist_ok=True)
    # VC2 on at 4352 B: the census 2D rows plus the two pcs3 VC2 rows, one launch
    tests = yaml.safe_load(open(os.path.join(TREE, "fabric_exp/exp_2d_4352.yaml")))["Tests"]
    for src in ("fabric_exp/pcs3/vc2ew4352.yaml", "fabric_exp/pcs3/vc02bew4352.yaml"):
        tests += yaml.safe_load(open(os.path.join(TREE, src)))["Tests"]
    pol = yaml.safe_load(open(os.path.join(TREE, "fabric_exp/exp_2d_4352.yaml")))["allocation_policies"]
    vc2_4352 = write("alloc_vc2_4352", [
        "Generated by mk_alloc_yamls.py: exp_2d_4352.yaml's tests, pcs3/vc2ew4352.yaml and pcs3/vc02bew4352.yaml in one",
        "launch; run with TT_METAL_ENABLE_FABRIC_VC2=1 (VC2 on for every test)."],
        yaml.safe_dump({"allocation_policies": pol, "Tests": tests}, sort_keys=False))
    suites = {
        "2d_4352": ("fabric_exp/slotstudy/sls_2d_p150.yaml", 1, ""),
        "2d_3072": (f"{SA}/sls_2d_p150_3072.yaml", 1, ""),
        "1d_4352": ("fabric_exp/slotstudy/sls_1d_p150.yaml", 1, ""),
        "1d_3072": (f"{SA}/sls_1d_p150_3072.yaml", 1, ""),
        "ring_4352": ("fabric_exp/v4/exp_ring.yaml", 1, ""),
        "ring_3072": (f"{SA}/exp_ring_3072.yaml", 1, ""),
        "vc1_4352": ("fabric_exp/vc1/sls_vc1_all.yaml", 2, ""),
        "vc1_3072": (f"{SA}/sls_vc1_all_3072.yaml", 2, ""),
        "vc2_4352": (vc2_4352, 1, VC2),
        "vc2_3072": (to_3072("alloc_vc2_3072", vc2_4352), 1, VC2),
        "ne_4352": ("fabric_exp/port_slots/yamls/pvs_c1ne.yaml", 1, ""),
        "ne_3072": (to_3072("alloc_ne_3072", "fabric_exp/port_slots/yamls/pvs_c1ne.yaml"), 1, ""),
    }
    manifest = {}
    for s, (y, ranks, env) in suites.items():
        if not os.path.exists(os.path.join(TREE, y)):
            sys.exit(f"no {y}")
        text = open(os.path.join(TREE, y)).read()
        if s.endswith("_3072") and "max_packet_size: 3072" not in text:
            sys.exit(f"{y} has no 3072 B slot")
        if "enable_flow_control" in text:
            sys.exit(f"{y} has flow-control rows (not on a LoudBox)")
        manifest[s] = {"yaml": y, "tests": count(y), "ranks": ranks, "env": env}
        print(f"{s:10} {manifest[s]['tests']:3} tests x{ranks} rank(s)  {y} {env}")
    json.dump(manifest, open(os.path.join(OUT, "alloc_manifest.json"), "w"), indent=1)


if __name__ == "__main__":
    main()

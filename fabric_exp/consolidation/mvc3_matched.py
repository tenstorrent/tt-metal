#!/usr/bin/env python3
"""mvc3_matched.py [PASS [SET ...]]: matched-count rows for the multi-VC rows on the VC1 split (coordinator/user, 2026-11-02: the
combined rate measured in one run, as consolidation/mk_mvc_matched.py does for VC0 + VC2 on one mesh).

Per set and size, every flow of the combination gets N_i = T / r_i packets, r_i its cycles per packet under contention
from pass PASS (default a) of mvc3_runs.sh (A sets: all three VCs, rates from rows T012m<i>; B sets: VC0 + VC1, rows
P01m<i>), so the senders finish together. The run's combined rate is then the link's: all packets over the longest
sender's cycles (build_multivc3.py, with each sender's finish gap). No launch delay: both processes launch after the
same barrier; their start skew is not measured and enters the combined rate as skew / T (T = 1.5e9 cycles, 1.1 s).
Writes fabric_exp/vc1/mvc3/mvc3_<set>_match.yaml (one test per size: the counts differ by size); mvc3_runs.sh runs it at
the start and at the end of each set when MATCH=1."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "report", "scripts"))
import build_multivc3 as b  # noqa: E402  (its log parser)
import mvc3_yamls as y  # noqa: E402  (flows and the yaml writer)

T = 1.5e9
P = sys.argv[1] if len(sys.argv) > 1 else "a"
SETS = sys.argv[2:] or ["A_d", "B_main", "B_new"]  # (A_v8 dropped: refused at -O3, job 479)
for s in SETS:
    three = s.startswith("A")
    rows = {}
    for g in ("base", "lag1", "lag0"):
        r = b.parse(f"mvc3{P}_{s}_{g}")
        if r is None:
            sys.exit(f"no pass {P} log for {s} {g}")
        rows.update(r[0])
    flows = [0, 1, 2] if three else [0, 1]
    tests, info = [], []
    for size in y.SIZES:
        cnt = {}
        for f in flows:
            row = f"T012m{f}" if three else f"P01m{f}"
            fl = rows[(s, row, size)]
            r_f = fl[f][1] / fl[f][0]
            cnt[f] = int(round(T / r_f / 1e3) * 1e3)
        t = y.test_yaml(f"MVC3_{s}_M{''.join(map(str, flows))}_s{size}", flows, cnt, three)
        tests.append(t.replace(f"size: {y.SIZES}", f"size: [{size}]"))
        info.append(f"{size} B: " + ", ".join(f"F{f} {cnt[f]} (r {T / cnt[f]:.1f})" for f in flows))
    p = os.path.join(y.OUT, f"mvc3_{s}_match.yaml")
    with open(p, "w") as fh:
        fh.write(f"# Generated by fabric_exp/consolidation/mvc3_matched.py from pass {P} (set {s}): counts N_i = {T:.1e} / "
                 "r_i so the senders finish together.\n# " + "; ".join(info) + "\n"
                 "allocation_policies:\n  receiver:\n    policy: RoundRobin\n    max_configs_per_core: 4\nTests:\n" +
                 "\n\n".join(tests) + "\n")
    print(s, "|", "; ".join(info))

#!/usr/bin/env python3
"""mk_dyn_yamls.py: P150 suites at another slot size for the dynamic slot allocator's A/B (SLOT_ALLOCATOR.md).

Derives fabric_exp/consolidation/slotalloc/yamls/<name>_<P>.yaml from an existing suite: every fabric_setup gets
`max_packet_size: P` (the fabric's slot is then P plus the header), and every payload size above P becomes P (lists
deduplicated, order kept). Rows, devices and counts are otherwise the source's. Line-based, so comments survive.

  mk_dyn_yamls.py [P]      (default 3072) writes the set below and prints each output with its test count
"""
import os
import re
import sys

TREE = "/home/aagarwal/tt-metal"
OUT = os.path.join(TREE, "fabric_exp/consolidation/slotalloc/yamls")
SOURCES = {
    "sls_2d_p150": "fabric_exp/slotstudy/sls_2d_p150.yaml",
    "sls_1d_p150": "fabric_exp/slotstudy/sls_1d_p150.yaml",
    "exp_ring": "fabric_exp/v4/exp_ring.yaml",
    "exp_torus_y": "fabric_exp/v4/exp_torus_y.yaml",
    "torusxy_2x4_sizes": "fabric_exp/torus/torusxy_2x4_sizes.yaml",
    "sls_vc1_all": "fabric_exp/vc1/sls_vc1_all.yaml",
}


def cap_list(text, p):
    seen, out = set(), []
    for v in (int(x) for x in re.findall(r"\d+", text)):
        v = min(v, p)
        if v not in seen:
            seen.add(v)
            out.append(v)
    return out


def convert(lines, p):
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m_setup = re.match(r"^(\s*)fabric_setup:\s*(\{.*\})?\s*$", line)
        m_inline = re.match(r"^(\s*size:\s*)\[([^\]]*)\](.*)$", line)
        m_scalar = re.match(r"^(\s*size:\s*)(\d+)(\s*(#.*)?)$", line)
        m_block = re.match(r"^(\s*)size:\s*$", line)
        if m_setup and m_setup.group(2):  # flow style: fabric_setup: {topology: Ring}
            body = m_setup.group(2)[1:-1].strip()
            out.append(f"{m_setup.group(1)}fabric_setup: {{{body}, max_packet_size: {p}}}\n")
        elif m_setup:
            out.append(line)
            nxt = lines[i + 1] if i + 1 < len(lines) else ""
            indent = re.match(r"^(\s*)", nxt).group(1)
            out.append(f"{indent}max_packet_size: {p}\n")
        elif m_inline:
            vals = cap_list(m_inline.group(2), p)
            out.append(f"{m_inline.group(1)}[{', '.join(map(str, vals))}]{m_inline.group(3)}\n")
        elif m_scalar:
            out.append(f"{m_scalar.group(1)}{min(int(m_scalar.group(2)), p)}{m_scalar.group(3)}\n")
        elif m_block:
            out.append(line)
            seen = set()
            while i + 1 < len(lines) and re.match(r"^\s*-\s*\d+\s*$", lines[i + 1]):
                i += 1
                item = re.match(r"^(\s*-\s*)(\d+)", lines[i])
                v = min(int(item.group(2)), p)
                if v not in seen:
                    seen.add(v)
                    out.append(f"{item.group(1)}{v}\n")
        else:
            out.append(line)
        i += 1
    return out


def main():
    p = int(sys.argv[1]) if len(sys.argv) > 1 else 3072
    os.makedirs(OUT, exist_ok=True)
    for name, src in SOURCES.items():
        lines = open(os.path.join(TREE, src)).readlines()
        if any("max_packet_size" in l for l in lines):
            sys.exit(f"{src} already sets max_packet_size")
        out = convert(lines, p)
        head = f"# Generated by mk_dyn_yamls.py {p} from {src}: max_packet_size {p}, payloads above {p} capped to it.\n"
        dst = os.path.join(OUT, f"{name}_{p}.yaml")
        open(dst, "w").write(head + "".join(out))
        print(f"{os.path.relpath(dst, TREE)}: {sum(1 for l in out if 'max_packet_size' in l)} fabric_setups")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""rxm4_yamls.py: the receiver multiple-of-4 sweep's suites at 3072 B slots (SLOT_ALLOCATOR.md §9; coordinator,
2026-11-03). Every row comes from an existing, validated suite; the only changes are fabric_setup.max_packet_size 3072
and payloads above 3072 capped to it. Writes fabric_exp/consolidation/slotalloc/yamls/:

  rxm4_2d_3072.yaml       exp_2d_4352.yaml's Mesh1HopEW write, Mesh1HopEWBidir write, Mesh3HopEW write + scatter,
                          MeshMulticast write; payload 3072 (5 tests)
  rxm4_meshval_3072.yaml  test_fabric_mesh_sanity_common.yaml's FlowControlMeshLowLatency (data-checked; the Linear test
                          is dropped: it does not use the 2D row)
  rxm4_ringval_3072.yaml  v4/val_ring_p150.yaml, all four tests (the no-flow-control ring rows validated on the P150)
  rxm4_ring_3072.yaml     val_ring_p150's FullRingUnicastDeadlockQuick only (its benchmark row, 1024 B)
"""
import copy
import os

import yaml

TREE = "/home/aagarwal/tt-metal"
OUT = os.path.join(TREE, "fabric_exp/consolidation/slotalloc/yamls")
P = 3072


def load(rel):
    return yaml.safe_load(open(os.path.join(TREE, rel)))


def cap_sizes(test):
    params = test.get("parametrization_params", {})
    if "size" in params:
        seen = []
        for s in params["size"]:
            s = min(int(s), P)
            if s not in seen:
                seen.append(s)
        params["size"] = seen
    if "size" in test.get("defaults", {}):
        test["defaults"]["size"] = min(int(test["defaults"]["size"]), P)
    test.setdefault("fabric_setup", {})["max_packet_size"] = P
    return test


def write(name, doc, source, note):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write(f"# Generated by rxm4_yamls.py from {source}: {note}\n")
        yaml.safe_dump(doc, f, sort_keys=False)
    print(f"{os.path.relpath(path, TREE)}: {[t['name'] for t in doc['Tests']]}")


def main():
    os.makedirs(OUT, exist_ok=True)
    src = load("fabric_exp/exp_2d_4352.yaml")
    keep = {
        "Mesh1HopEW": ["unicast_write"],
        "Mesh1HopEWBidir": ["unicast_write"],
        "Mesh3HopEW": ["unicast_write", "unicast_scatter_write"],
        "MeshMulticast": ["unicast_write"],
    }
    tests = []
    for t in src["Tests"]:
        if t["name"] in keep:
            t = cap_sizes(copy.deepcopy(t))
            t["parametrization_params"]["ntype"] = keep[t["name"]]
            t["parametrization_params"]["size"] = [P]
            tests.append(t)
    write("rxm4_2d_3072.yaml", {**{k: v for k, v in src.items() if k != "Tests"}, "Tests": tests},
          "fabric_exp/exp_2d_4352.yaml", "max_packet_size 3072, payload 3072, five rows")

    src = load("tests/tt_metal/tt_fabric/test_infra/test_yamls/test_fabric_mesh_sanity_common.yaml")
    tests = [cap_sizes(copy.deepcopy(t)) for t in src["Tests"] if t["name"] == "FlowControlMeshLowLatency"]
    write("rxm4_meshval_3072.yaml", {"Tests": tests}, "test_fabric_mesh_sanity_common.yaml",
          "the Mesh test, max_packet_size 3072, sizes capped to 3072")

    src = load("fabric_exp/v4/val_ring_p150.yaml")
    write("rxm4_ringval_3072.yaml", {"Tests": [cap_sizes(copy.deepcopy(t)) for t in src["Tests"]]},
          "fabric_exp/v4/val_ring_p150.yaml", "all tests, max_packet_size 3072")
    tests = [cap_sizes(copy.deepcopy(t)) for t in src["Tests"] if t["name"] == "FullRingUnicastDeadlockQuick"]
    write("rxm4_ring_3072.yaml", {"Tests": tests}, "fabric_exp/v4/val_ring_p150.yaml",
          "its benchmark row only, max_packet_size 3072")


if __name__ == "__main__":
    main()

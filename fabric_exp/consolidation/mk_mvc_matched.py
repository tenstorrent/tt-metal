#!/usr/bin/env python3
"""mk_mvc_matched.py: VC0 + VC2 rows with matched packet counts (user, 2026-11-02: measure the combined rate in one
run instead of summing two runs' per-VC rates).

For each router, slot setting and size, the VC2 count is set so both senders finish together:
N2 = N0 x (VC0's cycles/packet under contention) / (VC2's), from multivc_runs.sh passes a and b (vc02ew gives VC0's
rate, vc02bew VC2's). With both senders active for the whole run, the summary CSV (total bytes over the longer sender's
cycles) is the link's combined rate, measured directly. Writes pcs3/vc02m/<router>_<slots>_<size>.yaml.
  mk_mvc_matched.py [--routers R,...] [--slots S,...] [--passes P,...]   (defaults main_fw,v4rxg3 / default,v8 / a,b)
"""
import os
import re
import sys

FE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(FE, "results")
OUT = os.path.join(FE, "pcs3", "vc02m")
N0 = 4_000_000
PAT = re.compile(r"\((VC\d)\)(?: on device .*?:| with) (\d+) packets in (\d+) cycles")


def rate(label, vc):
    for line in open(os.path.join(R, f"{label}.log")):
        m = PAT.search(line)
        if m and m.group(1) == vc:
            return int(m.group(3)) / int(m.group(2))
    raise SystemExit(f"no {vc} line in {label}")


TEMPLATE = """# VC0 + VC2 with matched counts ({router}, slots {slots}, {size} B; generated by consolidation/mk_mvc_matched.py).
# VC0 {n0} packets, VC2 {n2}: VC0 / VC2 cycles per packet under contention {c0:.1f} / {c2:.1f} (multivc_runs.sh
# passes {passes}), so both senders finish together and the summary CSV is the link's combined rate.
allocation_policies:
  receiver:
    policy: RoundRobin
    max_configs_per_core: 4
Tests:
- name: PcsVC02M{size}
  benchmark_mode: true
  sync: false  # each sender times its own run
  fabric_setup:
    topology: Mesh
    use_vc2: true
  parametrization_params:
    ntype:
    - unicast_write
    size:
    - {size}
  defaults:
    ftype: unicast
    num_packets: {n0}
  senders:
  - device:
    - 0
    - 0
    vc_id: 0
    patterns:
    - num_packets: {n0}
      destination:
        device:
        - 0
        - 1
  - device:
    - 0
    - 0
    vc_id: 2
    patterns:
    - num_packets: {n2}
      destination:
        device:
        - 0
        - 1
"""

os.makedirs(OUT, exist_ok=True)
def opt(name, default):
    return sys.argv[sys.argv.index(name) + 1].split(",") if name in sys.argv else default


PASSES = opt("--passes", ["a", "b"])
for router in opt("--routers", ["main_fw", "v4rxg3"]):
    for slots in opt("--slots", ["default", "v8"]):
        for size in (256, 1024, 4352):
            c0 = sum(rate(f"mvc{p}_{router}_{slots}_vc02ew{size}", "VC0") for p in PASSES) / len(PASSES)
            c2 = sum(rate(f"mvc{p}_{router}_{slots}_vc02bew{size}", "VC2") for p in PASSES) / len(PASSES)
            n2 = round(N0 * c0 / c2, -3)
            path = os.path.join(OUT, f"{router}_{slots}_{size}.yaml")
            with open(path, "w") as f:
                f.write(TEMPLATE.format(router=router, slots=slots, size=size, n0=N0, n2=int(n2), c0=c0, c2=c2,
                                    passes=" and ".join(PASSES)))
            print(f"{path}: VC0 {N0}, VC2 {int(n2)} (c0 {c0:.1f}, c2 {c2:.1f})")

"""Writes tt_metal/hw/inc/experimental/gguf_level_tables.h: the GGUF codebook formats' level tables, from gguf-py's
grids through the LLK tests' level_table (tt_metal/tt-llk/tests/python_tests/helpers/gguf_records.py).

Usage: python3 scripts/gen_gguf_level_tables.py (needs numpy and gguf==0.19.0, as tt_metal/tt-llk/tests/requirements.txt).
"""

import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
# The module alone: the helpers package's __init__ needs the device test stack.
_spec = importlib.util.spec_from_file_location(
    "gguf_records", ROOT / "tt_metal/tt-llk/tests/python_tests/helpers/gguf_records.py"
)
gguf_records = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gguf_records)
FORMATS, level_table = gguf_records.FORMATS, gguf_records.level_table

OUT = ROOT / "tt_metal/hw/inc/experimental/gguf_level_tables.h"
# IQ1_M uses IQ1_S's grid.
TABLES = ("IQ2_XXS", "IQ2_XS", "IQ2_S", "IQ3_XXS", "IQ3_S", "IQ1_S")


def main():
    lines = [
        "// SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.",
        "//",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_gguf_level_tables.py; do not edit.",
        "// Level tables of the GGUF codebook formats for experimental::gguf::lookup_grid (gguf_page.h): grid entry ->",
        "// the level index of each of its elements.",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "// On the RISC-V cores the tables go with the code in L1: as .rodata they would land in a core's small local data",
        "// memory, which the 2 KiB and 4 KiB tables overflow. static, not inline: the JIT's LTO drops the section of an",
        "// inline variable.",
        "#if defined(__riscv)",
        '#define GGUF_LEVEL_TABLE_SECTION __attribute__((section(".text.gguf_levels")))',
        "#else",
        "#define GGUF_LEVEL_TABLE_SECTION",
        "#endif",
        "",
        "namespace experimental::gguf::levels {",
        "",
        "// clang-format off",
    ]
    for name in TABLES:
        fmt = FORMATS[name]
        table = level_table(fmt)
        assert len(table) == fmt.table_entries, name
        if lines[-1] == "};":
            lines.append("")
        lines.append(
            f"alignas(64) GGUF_LEVEL_TABLE_SECTION static constexpr std::uint16_t {name.lower()}[{len(table)}] = {{"
        )
        for i in range(0, len(table), 12):
            lines.append("    " + " ".join(f"0x{int(v):04x}," for v in table[i : i + 12]))
        lines += ["};"]
    lines += ["// clang-format on", "", "}  // namespace experimental::gguf::levels", ""]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()

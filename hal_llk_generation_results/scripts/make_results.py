#!/usr/bin/env python3
"""Builds RESULTS.md from the files in this folder only (runs/run*/ and perf/perf_summary_hal.json).
Usage (from the folder root):  python3 scripts/make_results.py [--out RESULTS.md]
Every number in RESULTS.md is read from a file named next to the table; nothing is typed in by hand."""
import argparse
import json
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLS = {"text bytes": "text", "TTI": "tti", "TT elfray": "tt_elfray", "TT linear": "tt_linear",
        "TT all paths": "tt_all", "unresolved": "unres", "TTI + TT all paths": "tti_tt"}


def avg_table(path):
    """'### Average per build' table of tt_tti_counts.md -> {(side, kernel): {col: value}}."""
    lines = path.read_text().splitlines()
    i = next(k for k, l in enumerate(lines) if l.strip().startswith("### Average per build"))
    rows, header = {}, None
    for l in lines[i + 1:]:
        if not l.startswith("|"):
            if header:
                break
            continue
        cells = [c.strip() for c in l.strip().strip("|").split("|")]
        if header is None:
            header = cells
            continue
        if set(cells[0]) <= {"-"}:
            continue
        rows[(cells[0], cells[1])] = {COLS[h]: float(c) for h, c in zip(header[2:], cells[2:]) if h in COLS}
    return rows


def meta(path):
    out = {}
    for l in path.read_text().splitlines():
        if "=" in l:
            k, v = l.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def counts(line):
    """'... 1660 passed, 20 skipped ...' -> (passed, failed)."""
    p = re.search(r"(\d+) passed", line)
    f = re.search(r"(\d+) failed", line)
    return (int(p.group(1)) if p else 0, int(f.group(1)) if f else 0)


def harness_checks(summary):
    """HAL test after reset, original baseline and dirty-state check from the harness SUMMARY.txt
    (Serbian or English harness output: the test block lines are recognised by 'passed')."""
    lines = summary.read_text().splitlines()
    i = next(k for k, l in enumerate(lines) if re.match(r"^\s+test_eltwise_binary\s", l) and "passed" in l)
    hal, _, orig = lines[i].partition("| original:")
    dirty = next(l for l in lines[i + 1:] if "passed" in l or "failed" in l)
    return {"hal": counts(hal), "original": counts(orig), "dirty": counts(dirty)}


def postcheck(path):
    res = []
    for l in path.read_text().splitlines():
        m = re.match(r"^(check\d_\w+)\.txt: exit (\d+), (.*)$", l)
        if m:
            res.append((m.group(1), int(m.group(2)), counts(m.group(3))))
    return res


def fmt(x):
    return f"{x:.1f}".rstrip("0").rstrip(".") if isinstance(x, float) else str(x)


def ratio(new, orig):
    return f"{new / orig:.2f}×"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "RESULTS.md"))
    a = ap.parse_args()
    perf = json.loads((ROOT / "perf" / "perf_summary_hal.json").read_text())
    runs = sorted(p.name[3:] for p in (ROOT / "runs").iterdir() if p.is_dir() and p.name.startswith("run"))
    R = {}
    for n in runs:
        d = ROOT / "runs" / f"run{n}"
        r = {"meta": meta(d / "harness_logs" / "run_meta.txt"),
             "checks": harness_checks(d / "harness_logs" / "SUMMARY.txt"),
             "post": postcheck(min((d / "postcheck").glob("checks_*.txt"))) if (d / "postcheck").is_dir() else [],
             "m2": json.loads((d / "metrics_v2.json").read_text()),
             "on": avg_table(d / "static_counts" / "assert_on" / "tt_tti_counts.md"),
             "off": avg_table(d / "static_counts" / "assert_off" / "tt_tti_counts.md"),
             "perf": perf.get(n)}
        R[n] = r

    keys = ["base_commit", "hal_commit", "docs_commit", "docs_invalid", "model", "claude_version", "timeout",
            "max_turns", "max_budget_usd", "tests", "sfpi_compiler"]
    first = R[runs[0]]["meta"]
    same = {k: first.get(k) for k in keys if all(R[n]["meta"].get(k) == first.get(k) for n in runs)}
    diff = [k for k in keys if k not in same]
    L = ["# HAL LLK generation: original vs HAL, per run", "",
         "Generated by `python3 scripts/make_results.py` from the files in `runs/` and `perf/` only.", "",
         "## Setup", "",
         "Task: a Claude Code agent writes the LLK functions used by tt-llk `test_eltwise_binary` (ELWADD only, "
         "`-k add`) from a signature-only spec, using only HAL (it knows HAL from its documentation; HAL source "
         "and the original LLKs are read-denied). All runs start from the same frozen test set.", "",
         "Identical in all runs (`runs/run*/harness_logs/run_meta.txt`):", ""]
    L += [f"- `{k}` = {v}" for k, v in same.items()]
    if diff:
        L += ["", "Not identical: " + ", ".join(f"`{k}`" for k in diff)]
    L += ["", "| Run | prompt file | date |", "|---|---|---|"]
    for n in runs:
        m = R[n]["meta"]
        L.append(f"| {n} | `{Path(m.get('prompt_file', '?')).name}` | {m.get('date', '?')[:10]} |")

    # 1. one line per run
    L += ["", "## 1. Original vs HAL, one line per run", "",
          "Static counts: average per build over the 10 builds of `-k add`, both sides compiled with LLK asserts "
          "OFF (`TT_LLK_DISABLE_ASSERTS=1`). Cycles: LLK perf test, L1→L1 cycles per tile, asserts off. "
          "Format: original vs HAL (HAL / original).", ""]
    for n in runs:
        o, h, p = R[n]["off"][("original", "sum")], R[n]["off"][("hal", "sum")], R[n]["perf"]
        cyc = (f"cycles/tile {p['l1']['orig']:.2f} vs {p['l1']['new']:.2f} ({p['l1']['ratio_median']:.2f}×)"
               if p else "cycles/tile: not measured")
        L.append(f"- **run{n}:** .text {fmt(o['text'])} vs {fmt(h['text'])} B ({ratio(h['text'], o['text'])}) | "
                 f"TTI {fmt(o['tti'])} vs {fmt(h['tti'])} | TT {fmt(o['tt_all'])} vs {fmt(h['tt_all'])} | {cyc}")

    # 2./3. static tables
    def static_table(mode, title, src):
        out = ["", title, "", f"Source: `runs/run*/static_counts/{src}/tt_tti_counts.md` (section 'Average per build').", "",
               "| Run | .text orig | .text HAL | HAL/orig | TTI orig | TTI HAL | TT orig | TT HAL | TTI+TT orig | TTI+TT HAL | unresolved orig / HAL |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        for n in runs:
            o, h = R[n][mode][("original", "sum")], R[n][mode][("hal", "sum")]
            out.append(f"| {n} | {fmt(o['text'])} | {fmt(h['text'])} | {ratio(h['text'], o['text'])} | {fmt(o['tti'])} | "
                       f"{fmt(h['tti'])} | {fmt(o['tt_all'])} | {fmt(h['tt_all'])} | {fmt(o['tti_tt'])} | {fmt(h['tti_tt'])} | "
                       f"{fmt(o['unres'])} / {fmt(h['unres'])} |")
        for prefix in ("7", "8"):
            grp = [n for n in runs if n.startswith(prefix)]
            if len(grp) >= 3:
                med = {c: statistics.median(R[n][mode][("hal", "sum")][c] for n in grp) for c in ("text", "tti", "tt_all", "tti_tt")}
                out.append(f"| HAL {grp[0]}–{grp[-1]} median | | {fmt(med['text'])} | | | {fmt(med['tti'])} | | "
                           f"{fmt(med['tt_all'])} | | {fmt(med['tti_tt'])} | |")
        return out

    L += static_table("off", "## 2. Code size and Tensix instructions, LLK asserts OFF (fair comparison)", "assert_off")
    L += static_table("on", "## 3. Same, LLK asserts ON (default test build; the numbers in earlier run reports)", "assert_on")
    L += ["", "Per-kernel rows (unpack / math / pack) are in the same files."]

    # 4. perf
    L += ["", "## 4. Cycles (LLK perf test `perf_eltwise_binary.py -k Elwadd`, 16 variants, asserts off)", "",
          "Source: `perf/perf_summary_hal.json` (median of 3 runs per variant, then median over variants; "
          "original measured on the same board in the same session). Raw perf data: `runs/run*/perf/`.", "",
          "| Run | board | orig L1→L1 | HAL L1→L1 | HAL/orig (min–max over variants) | variants faster | 4 functionally verified variants | unpack | math | pack |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for n in runs:
        p = R[n]["perf"]
        if not p:
            L.append(f"| {n} | not measured | | | | | | | | |")
            continue
        l1 = p["l1"]
        L.append(f"| {n} | {p.get('board', '?')} | {l1['orig']:.2f} | {l1['new']:.2f} | {l1['ratio_median']:.2f}× "
                 f"({l1['ratio_min']:.2f}–{l1['ratio_max']:.2f}) | {l1['faster_variants']}/{l1['n']} | "
                 f"{p['l1_cov']['ratio_median']:.2f}× | {p['unp']['ratio_median']:.2f}× | {p['math']['ratio_median']:.2f}× | "
                 f"{p['pack']['ratio_median']:.2f}× |")

    # 5. correctness and cost
    L += ["", "## 5. Correctness and agent cost", "",
          "Sources: harness `SUMMARY.txt` (HAL test after reset, dirty-state check = original right after HAL without reset), "
          "`postcheck/checks_*.txt` (reset→HAL, no reset→original, no reset→HAL, reset→HAL), `metrics_v2.json` "
          "(recomputed with `scripts/harness/metrics.py` v2 from the run transcript).", "",
          "| Run | harness HAL after reset | dirty check | postcheck 4 steps | agent min | cost $ | pytest commands | iterations | first full pass (iteration, min) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for n in runs:
        c, post, m2 = R[n]["checks"], R[n]["post"], R[n]["m2"]
        pc = (" / ".join(f"{p}" for _, _, (p, f) in post) + ("" if all(f == 0 and e == 0 for _, e, (_, f) in post) else " (FAIL)")
              if post else "not run yet")
        ffp = (m2.get("process", {}).get("first_full_pass") or {}).get("test_eltwise_binary_hal")
        ffp_s = f"{ffp['iteration']}, {ffp['elapsed_min']:.1f}" if ffp else "none"
        L.append(f"| {n} | {c['hal'][0]} passed, {c['hal'][1]} failed | {c['dirty'][0]} passed, {c['dirty'][1]} failed | {pc} | "
                 f"{m2['duration_min']:.1f} | {m2['cost_usd']:.2f} | {m2['pytest_runs_total']} | "
                 f"{m2.get('process', {}).get('iterations', '?')} | {ffp_s} |")
    L.append(f"\nOriginal test (harness baseline) in every run: "
             + ", ".join(f"{n}: {R[n]['checks']['original'][0]} passed" for n in runs) + ".")

    L += ["", "## 6. Limits (read before using the numbers)", "",
          "- Static counts are counts in the compiled code, not executed instructions. TT = stores proven to reach the "
          "Tensix instruction buffer on every path (static analysis); 'unresolved' stores could not be settled, so TT is "
          "an estimate. TTI and code size are the main static measures; TT is secondary.",
          "- The default test build compiles LLK asserts (`-DENABLE_LLK_ASSERT`) unless `TT_LLK_DISABLE_ASSERTS=1` "
          "(tt-llk `tests/python_tests/helpers/test_config.py`, ~line 553). Section 2 removes that effect from both sides.",
          "- The perf test does not check results. Only 4 of the 16 Elwadd perf variants have formats / dest_acc that the "
          "functional test (and therefore the agent) verified.",
          "- One kernel (eltwise add). 7a–7e are 5 repeats with `prompt-run6b.md`; 8a–8e are 5 repeats with "
          "`prompt-run6b-cfgcost.md` (adds a section on the instruction cost of per-tile code). No statistical test is "
          "applied between runs.",
          "- `harness_logs/SUMMARY.txt` of 7a–7e quotes metrics.py v1 numbers (first full pass, pytest runs); section 5 "
          "uses v2 (`metrics_v2.json`; `harness_logs/metrics.md` is its rendering), so iteration numbers can differ.",
          "- The harness of runs 7a–8a wrote its outputs in Serbian (team convention at the time). Their files in "
          "`runs/run*/harness_logs/` are English copies; `harness_logs/translation_check.txt` records for every file "
          "that its numbers are identical to the Serbian original and that no Serbian words are left. Runs 8b–8e used "
          "the English harness; their files are copied as they are."]
    no_pc = [n for n in runs if not R[n]["post"]]
    no_perf = [n for n in runs if not R[n]["perf"]]
    if no_pc or no_perf:
        L.append(f"- Not run yet: postcheck for {', '.join(no_pc) or 'none'}; perf for {', '.join(no_perf) or 'none'}.")
    Path(a.out).write_text("\n".join(L) + "\n")
    print(f"wrote {a.out} ({len(runs)} runs: {' '.join(runs)})")


if __name__ == "__main__":
    main()
